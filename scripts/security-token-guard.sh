#!/bin/bash
# Ищет секреты в том, что уходит в историю git.
#
# ЧТО БЫЛО НЕ ТАК С ПРЕЖНЕЙ ВЕРСИЕЙ (обе дыры проверены живым прогоном).
#
# 1. Она искала ТРИ имени переменных — INFISICAL_CLIENT_SECRET,
#    SUPABASE_SERVICE_KEY, REPLICATE_API_TOKEN — и только в форме `ИМЯ="...`.
#    Токен, записанный литералом без имени переменной, проходил насквозь:
#    подсунул строку вида `bot<цифры>:<35 символов>` — гвард сказал ОК.
#    А имя переменной как раз и не нужно, чтобы секрет работал.
#
# 2. Она исключала `*.md`, `CLAUDE.md` и `.claude/` — ровно те файлы, где в
#    этом репозитории секреты и оказались. Исключение снято.
#
# 3. Фолбэк на диапазон коммитов не срабатывал никогда:
#    `git diff --cached` возвращает 0 и при пустом выводе, поэтому `||` не
#    выполнялся. На pre-push, где ничего не проиндексировано, гвард
#    проверял ПУСТУЮ строку и всегда проходил. Режим теперь задаётся явно
#    аргументом, а не выводится из кода возврата.
#
# Ищем ФОРМУ секрета, а не его имя: форма — это то, что делает строку
# работающим ключом.
#
# Использование:
#   security-token-guard.sh staged   # pre-commit: проиндексированное
#   security-token-guard.sh range    # pre-push: коммиты, которых нет на origin
#
# Осознанное исключение помечается комментарием `secret-guard-ok: причина`
# НА ТОЙ ЖЕ СТРОКЕ. Здесь было написано «на той же или предыдущей» — но
# отсев делает `grep -v` по самим найденным строкам, предыдущую он не
# видит. Пометка строкой выше молча не работала: автор считал, что
# исключение поставлено, а гвард продолжал ругаться. Описание приведено
# к тому, что код действительно делает.

set -uo pipefail

MODE="${1:-staged}"

case "$MODE" in
  staged)
    DIFF="$(git diff --cached)"
    ;;
  range)
    upstream="$(git rev-parse --abbrev-ref --symbolic-full-name '@{upstream}' 2>/dev/null || true)"
    if [ -n "$upstream" ]; then
      DIFF="$(git diff "$upstream"...HEAD 2>/dev/null || true)"
    else
      # Новой ветки ещё нет на сервере — сравниваем с основной.
      base="$(git merge-base origin/main HEAD 2>/dev/null || true)"
      DIFF="$([ -n "$base" ] && git diff "$base"..HEAD 2>/dev/null || git diff --cached)"
    fi
    ;;
  *)
    echo "неизвестный режим: $MODE (ожидается staged или range)" >&2
    exit 2
    ;;
esac

# Только добавленные строки: удаление секрета из файла блокировать нельзя,
# иначе почистить утечку станет невозможно.
ADDED="$(printf '%s\n' "$DIFF" | grep '^+' | grep -v '^+++' || true)"
# Проверять нечего — это НЕ «проверка пройдена». Молчаливый ноль здесь уже
# однажды выдавал пустой прогон за зелёный, поэтому случай назван вслух.
if [ -z "$ADDED" ]; then
  echo "секрет-гвард ($MODE): добавленных строк нет — проверять нечего"
  exit 0
fi

# Формы реальных ключей. Каждая проверена на живом примере из этого проекта.
declare -a NAMES=(
  "Telegram bot token"
  "OpenAI / Anthropic key"
  "Fly.io API token"
  "Replicate token"
  "AWS access key"
  "JWT (Supabase service_role и подобные)"
  "Slack token"
  "GitHub token"
  "приватный ключ"
  "секрет в переменной"
  "машинная учётка Infisical"
  "ключ xAI"
  "ключ Fal.ai"
  "строка подключения с паролем"
  "подписывающий ключ Inngest"
  "ключ ElevenLabs"
)
declare -a PATTERNS=(
  '(^|[^0-9])[0-9]{8,10}:AA[A-Za-z0-9_-]{30,}'
  'sk-(ant-)?(proj-)?[A-Za-z0-9_-]{20,}'
  'fm[12]_[A-Za-z0-9+/=_-]{40,}'
  '\br8_[A-Za-z0-9]{30,}'
  '\bAKIA[0-9A-Z]{16}\b'
  'eyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}'
  'xox[baprs]-[A-Za-z0-9-]{10,}'
  'gh[pousr]_[A-Za-z0-9]{30,}'
  '-----BEGIN [A-Z ]*PRIVATE KEY-----'
  '(SECRET|TOKEN|API_KEY|PASSWORD|SERVICE_KEY|SERVICE_ROLE_KEY|CLIENT_SECRET)[A-Za-z_]*[[:space:]]*[=:][[:space:]]*["'"'"']?[A-Za-z0-9_/+=-]{16,}'
  '(INFISICAL_CLIENT_SECRET|clientSecret)[[:space:]]*[=:][[:space:]]*["'"'"']?[a-f0-9]{64}'
  'xai-[A-Za-z0-9]{40,}'
  # Ключ Fal.ai: UUID, двоеточие, 32 hex. Гвард этой формы не знал, и
  # рабочий FAL_KEY пролежал в src/__tests__/ai-reels-fal-integration.test.ts
  # незамеченным — нашла его сторонняя проверка, не эта. Шаблон проверен на
  # той самой строке: до правки гвард молчал, после — ловит.
  '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}:[0-9a-f]{32}'
  # Строка подключения с ВСТРОЕННЫМ паролем: схема, затем имя, двоеточие,
  # пароль и собака перед хостом. Пример намеренно НЕ записан литералом:
  # он совпадал бы с этим же правилом, и гвард ловил бы собственную
  # документацию (поймано на первом же прогоне -- совпадение было в
  # комментарии, не в шаблоне).
  # Этой формы гвард не знал, и рабочая строка Neon с паролем лежала в
  # src/inngest_app/functions/instagram/instagramScraper-v2.ts запасным
  # значением к NEON_DATABASE_URL. Нашла её перепись запасных значений, не
  # этот гвард. Требую пароль от 6 знаков, чтобы `https://host:80@` и прочие
  # редкие формы без пароля не поднимали ложную тревогу.
  '[a-z][a-z0-9+.-]*://[a-z0-9_.%-]+:[^@[:space:]\"'"'"'`/]{6,}@'
  # Подписывающий ключ Inngest: signkey-prod- или signkey-test- и 64 hex.
  # Этой формы не знал НИ ОДИН словарь репозитория -- ни этот гвард, ни
  # искалка по истории, ни искалка по базе, ни тест no-secrets-in-repo.
  # Поэтому «в репозитории нет новых секретов» горело зелёным при 14 файлах с
  # ключами, три из которых ПРОДОВЫЕ. Шаблон проверен на тех самых строках:
  # до правки все словари молчали, после -- ловят.
  'signkey-(prod|test)-[a-f0-9]{32,}'
  # Ключ ElevenLabs: sk_ и 40+ hex. Форму знал тест no-secrets-in-repo, а этот
  # гвард -- нет, единственное расхождение из 17 при обратной сверке. Разделитель
  # `_` отличает его от ключей OpenAI (`sk-`), а требование hex -- от Stripe.
  'sk_[a-f0-9]{40,}'
)

found=0
for i in "${!PATTERNS[@]}"; do
  # -e ОБЯЗАТЕЛЕН. Без него шаблон, начинающийся с дефиса
  # (-----BEGIN … PRIVATE KEY-----), разбирается grep как набор опций:
  # «grep: unrecognized option», код возврата 2. Правило про приватные ключи
  # не срабатывало НИ РАЗУ, и `|| true` этот отказ проглатывал — гвард
  # сообщал об успехе, не выполнив проверку. Ровно тот класс, ради которого
  # этот файл и переписывался.
  # Код возврата берём у ПЕРВОГО grep, а не у всего конвейера.
  #
  # Так было до этой правки — и не работало:
  #     hits="$(… | grep -nEi -e "$PATTERN" | grep -v 'secret-guard-ok')"
  #     rc=$?
  # `$?` после конвейера — это код ПОСЛЕДНЕЙ команды, то есть `grep -v`.
  # `pipefail` тут не спасает: он отдаёт код самой правой команды с ненулевым
  # кодом. Когда шаблон ломает grep (код 2), тот не печатает ничего, `grep -v`
  # получает пустой вход и выходит с 1 — самым правым ненулевым. Итог: rc=1,
  # проверка ниже не срабатывает, а сломавшееся правило засчитывается как
  # «секретов не найдено». Проверено живым прогоном на шаблоне `[`:
  # grep честно ругается «brackets not balanced», а rc приходит 1.
  # Это ровно тот молчаливый пропуск, ради которого файл и переписывали.
  #
  # Лечится тем, что `grep -v` вынесен из конвейера в отдельный шаг: в
  # конвейере остаются только `printf` (он не падает) и сам шаблонный grep,
  # и `pipefail` отдаёт именно его код. `PIPESTATUS` здесь НЕ годится —
  # присваивание из `$( … )` затирает массив, и `${PIPESTATUS[1]}` под `set -u`
  # падает с «unbound variable». Тоже проверено прогоном, а не рассуждением.
  raw="$(printf '%s\n' "$ADDED" | grep -nEi -e "${PATTERNS[$i]}")"
  rc=$?
  # Отсев заведомо не-секретов. Держим списком с объяснением: фильтр, про
  # который непонятно, что он выбрасывает, со временем выбросит настоящий ключ.
  #
  # 1. ИМЯ переменной, стоящее ЗНАЧЕНИЕМ. Строки вида
  #      secretKey: 'BOT_INNGEST_EVENT_KEY'
  #    правило «секрет в переменной» ловит, потому что слева secretKey, а
  #    справа 21 подходящий символ. Но справа — идентификатор в верхнем
  #    регистре с подчёркиваниями, то есть ИМЯ ключа, а не сам ключ. Настоящие
  #    ключи так не выглядят: в них есть строчные буквы или разделители.
  #    Отсеиваем ТОЛЬКО значение целиком из [A-Z0-9_] — одна строчная буква
  #    внутри, и строка снова считается подозрительной.
  hits="$(printf '%s\n' "$raw" \
    | grep -v 'secret-guard-ok' \
    | grep -vE "[=:][[:space:]]*[\"']?[A-Z][A-Z0-9_]{7,}[\"']?,?[[:space:]]*$")"
  # grep: 0 — нашёл, 1 — не нашёл, >=2 — сам сломался. Третий случай нельзя
  # молча считать чистотой.
  if [ "$rc" -ge 2 ]; then
    echo "❌ Проверка «${NAMES[$i]}» не смогла отработать (grep код $rc)."
    echo "   Это НЕ значит, что секретов нет — значит, их не искали."
    exit 2
  fi
  if [ -n "$hits" ]; then
    [ "$found" = "0" ] && echo "❌ Похоже на секрет в изменениях:" && echo
    found=1
    echo "  ${NAMES[$i]}:"
    # Значение НЕ печатаем целиком — вывод хука попадает в логи и историю
    # терминала. Достаточно показать начало, чтобы человек нашёл строку.
    printf '%s\n' "$hits" | head -3 | while IFS= read -r line; do
      echo "    ${line:0:60}…"
    done
    echo
  fi
done

if [ "$found" = "1" ]; then
  echo "Секрет в истории git необратим: он остаётся в объектах даже после"
  echo "правки файла, и его придётся отзывать, а не удалять."
  echo
  echo "Если совпадение ложное — допишите на строке: secret-guard-ok: причина"
  exit 1
fi

exit 0
