#!/bin/bash

# Скрипт синхронизации переменных окружения
# Синхронизирует .env файлы между различными окружениями

echo "🔄 Синхронизация переменных окружения..."

# Проверяем наличие .env файла
if [ ! -f ".env" ]; then
    echo "⚠️  Файл .env не найден, создаем базовый..."
    touch .env
fi

# Проверяем наличие .env.local файла
if [ ! -f ".env.local" ]; then
    echo "⚠️  Файл .env.local не найден, создаем базовый..."
    touch .env.local
fi

# Синхронизируем переменные из .env в .env.local (если нужно)
if [ -f ".env" ] && [ -f ".env.local" ]; then
    echo "✅ Файлы окружения найдены"
else
    echo "❌ Проблема с файлами окружения"
    exit 1
fi

echo "✅ Синхронизация окружения завершена"
