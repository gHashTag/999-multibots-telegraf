#!/bin/bash
# tri self — проверить саму оболочку: доедет ли каждая команда до своего хелпера.
#
# ЗАЧЕМ (форма 56). 16.09.2026 я перенёс семнадцать команд в `bin/tri` и
# проверил ровно то, что проверяется легко: `bash -n` — чисто, команд в
# разборе 46. Обе цифры были правдой, и ни одна команда не работала: блоки
# легли ПОСЛЕ `*)`, а ветка по умолчанию ловит всё, до чего дошли. Каждая из
# семнадцати печатала общую справку и выходила с нулём.
#
# Ноль — вот что делает такую поломку дорогой. Команда «отработала», разбор
# верный, синтаксис верный; неверна только достижимость, а её не видно ни
# одной из дешёвых проверок. Поэтому она проверяется здесь и по имени.
#
# Четыре вопроса, и все — про несовпадение двух списков, которые человек
# держит в голове раздельно и потому расходится:
#
#   1. что стоит ПОСЛЕ ветки `*)` — недостижимо, чем бы оно ни было
#   2. у какой команды нет строки в справке — её не найдут
#   3. какая строка справки обещает команду, которой нет — соврём человеку
#   4. какой хелпер назван, но не лежит в дереве — упадём при вызове
# ЗВАТЬ НАПРЯМУЮ, А НЕ ЧЕРЕЗ ТО, ЧТО ПРОВЕРЯЕШЬ.
#
# `tri self` — сама команда `tri`, и на обратной мутации это вылезло: стоило
# передвинуть `*)` вверх, как проверяющий уехал в недостижимые вместе с теми
# семнадцатью и напечатал общую справку. Сторож, который ломается ровно той
# поломкой, которую ищет, не находит ничего.
#
# Поэтому `tri doctor` зовёт ЭТОТ ФАЙЛ, а не команду:
#
#     bash "$ROOT/bin/helpers/self.sh" "$ROOT"
#
# Так проверено: при той же мутации прямой вызов называет все семнадцать
# поимённо и возвращает 1. Через диспетчер — 64 и справка.
set -u
ROOT="${1:?нужен корень репозитория}"
TRI="$ROOT/bin/tri"
[ -f "$TRI" ] || { echo "нет файла: $TRI"; exit 2; }

RC=0
say() { printf '%s\n' "$*"; }

# Разбор ведёт python: sed/awk здесь уже ошибались на вложенном `case`
# внутри `tg-as`, считая его ветки командами верхнего уровня.
TRI="$TRI" python3 - <<'PY' || RC=1
import io, os, re, sys

s = io.open(os.environ['TRI'], encoding='utf-8').read()
lines = s.split('\n')

# Ветки ВЕРХНЕГО уровня: ровно два пробела отступа. Вложенный `case` в
# `tg-as` идёт с шестью и в этот счёт не попадает -- в этом и смысл отступа.
# ВЕТКА МОЖЕТ НЕСТИ НЕСКОЛЬКО ИМЁН. Первая версия этого разбора читала
# только `имя)` и объявила `crm-ingest` и `crm-leads` пропавшими из разбора
# -- а они стоят в одной ветке `crm-ingest|crm-leads)`, и обе работают.
# Проверка соврала в самую дорогую сторону: послала чинить исправное.
top = re.compile(r'^  ([a-z][a-z0-9-]*(?:\|[a-z][a-z0-9-]*)*)\)')
star = re.compile(r'^  \*\)')
cases, star_at = {}, None
for i, l in enumerate(lines):
    if star.match(l) and star_at is None:
        star_at = i
    m = top.match(l)
    if m:
        for name in m.group(1).split('|'):
            cases.setdefault(name, i)

usage = {}
for l in lines:
    m = re.match(r'^  tri ([a-z][a-z0-9-]*)', l)
    if m:
        usage.setdefault(m.group(1), l.strip())

bad = False

# 1. НЕДОСТИЖИМОЕ. Единственная проверка здесь, которую нельзя получить
#    ни из синтаксиса, ни из числа команд.
if star_at is not None:
    after = sorted(n for n, i in cases.items() if i > star_at)
    if after:
        bad = True
        print('  🛑 стоят ПОСЛЕ ветки `*)` и потому недостижимы (%d):' % len(after))
        for n in after:
            print('       %s  — печатает справку и выходит с нулём' % n)
        print('       Перенести `*)` в самый конец: ветка по умолчанию — последняя.')
else:
    print('  ⚠️  ветки `*)` нет вовсе: неизвестная команда промолчит')

# 2 и 3. ДВА СПИСКА, КОТОРЫЕ ОБЯЗАНЫ СОВПАДАТЬ.
no_help = sorted(set(cases) - set(usage))
if no_help:
    bad = True
    print('  🛑 есть в разборе, нет в справке (%d): %s'
          % (len(no_help), ', '.join(no_help)))
    print('       Команда, которой нет в справке, не существует для человека.')

no_case = sorted(set(usage) - set(cases))
if no_case:
    bad = True
    print('  🛑 обещаны справкой, нет в разборе (%d): %s'
          % (len(no_case), ', '.join(no_case)))

# 4. НАЗВАННЫЕ ФАЙЛЫ. Хелпер, которого нет, падает в момент вызова -- то
#    есть у того, кто на него понадеялся.
root = os.path.dirname(os.path.dirname(os.environ['TRI']))
missing = sorted({h for h in re.findall(r'\$ROOT/(bin/helpers/[\w./-]+)', s)
                  if not os.path.exists(os.path.join(root, h))})
if missing:
    bad = True
    print('  🛑 названы, но не лежат в дереве (%d):' % len(missing))
    for h in missing:
        print('       %s' % h)

print()
print('  команд в разборе: %d; строк справки: %d; хелперов названо: %d'
      % (len(cases), len(usage),
         len(set(re.findall(r'\$ROOT/(bin/helpers/[\w./-]+)', s)))))
sys.exit(1 if bad else 0)
PY

if [ "$RC" = "0" ]; then
  say "  ✅ каждая команда достижима, названа в справке и её хелпер на месте"
else
  say
  say "  Проверка достижимости — не роскошь: \`bash -n\` и счётчик команд"
  say "  были ЗЕЛЕНЫ, когда ни одна из семнадцати не работала."
fi
exit $RC
