#!/bin/bash
# tri owners — состояние, общее на процесс там, где людей больше одного.
#
# ЗАЧЕМ (форма 29 в скилле blind-guards). Ферма держит ВСЕХ ботов в одном
# процессе, а `ADMIN_IDS` в проде называет пятерых. Модульная переменная в
# таком коде — это «одна на всех»:
#
#   crmProactive: ненажатая карточка ОДНОГО держала всех два часа
#   businessBotService: счётчики дня складывали клиентов разных владельцев,
#                       а /business показывал каждому чужие подключения
#
# Компилятор такого не видит: код верен, пока человек один. Здесь — триаж:
# что объявлено на уровне модуля и есть ли у него ключ. Судит человек, но
# СПИСОК он больше не собирает руками.
set -u
ROOT="${1:?нужен корень репозитория}"
WHERE="${2:-}"
cd "$ROOT" || exit 1

# АРГУМЕНТ, КОТОРЫЙ МОЛЧА ИГНОРИРУЮТ, ХУЖЕ ОТСУТСТВУЮЩЕГО.
#
# До 16.09.2026 команда принимала только корень и всегда обходила свой
# список каталогов. `tri owners <файл>` печатал отчёт по ВСЕМУ дереву, и
# выглядело это как ответ про файл: я прочитал чужое состояние как состояние
# `crm-tools.ts` и чуть не пошёл чинить не тот модуль. Теперь путь сужает
# обход, а несуществующий путь — это отказ, а не тихий обход всего.
DIRS="src/services src/helpers src/navigation apps/vibee-editor/render/src/agent"
if [ -n "$WHERE" ]; then
  if [ ! -e "$WHERE" ]; then
    echo "нет такого пути: $WHERE"
    exit 2
  fi
  DIRS="$WHERE"
fi
echo "── состояние на уровне модуля ──"
echo "   смотрю: $DIRS"
echo

# ПРОЧИТАННОЕ БОЛЬШЕ НЕ ПОКАЗЫВАЕМ.
#
# Первый прогон дал 28 «общих», из которых 26 честно процессные: флаги DDL,
# дедуп предупреждений, один слушатель на сервис. Список, где 26 из 28 —
# норма, читают один раз и перестают. Поэтому у каждого разобранного
# объявления в коде стоит строка `// owner-scope: <почему>` — она и есть
# протокол разбора, лежит рядом с кодом и видна в diff, если кто-то поменяет
# смысл переменной. Здесь такие просто не показываются, а считаются.
reviewed=0
shared=0
keyed=0
for d in $DIRS; do
  # -e, НЕ -d. С проверкой на каталог одиночный файл молча пропускался, и
  # команда печатала «неразобранного общего состояния нет» про файл, в
  # котором его пять штук. Чистый экран от пропущенного входа неотличим от
  # чистого экрана от чистого кода — и это худший из возможных ответов.
  [ -e "$d" ] || continue
  while IFS= read -r line; do
    f="${line%%:*}"
    rest="${line#*:}"
    n="${rest%%:*}"
    code="${line#*:*:}"
    # Разобранное: маркер на самой строке или в СПЛОШНОМ блоке комментариев
    # прямо над объявлением.
    #
    # Одной строки назад мало: разбор на три строки объяснения — обычное дело
    # в этом файле, и 16.09.2026 два честно процессных объявления так и
    # остались в списке «общих» с маркером тремя строками выше.
    #
    # Подъём кончается на первой строке, которая НЕ комментарий и не пустая,
    # поэтому новое объявление не может спрятаться под чужой пометкой: между
    # ними всегда стоит строка кода. Ровно на этом `tri promises` один раз
    # соврал «разобрано», когда смотрел на 15 строк вверх без такого правила.
    found_marker=0
    if echo "$code" | grep -q 'owner-scope:'; then found_marker=1; fi
    i=$((n - 1))
    while [ "$found_marker" = "0" ] && [ "$i" -ge 1 ]; do
      l=$(sed -n "${i}p" "$f" 2>/dev/null)
      case "$l" in
        *owner-scope:*) found_marker=1; break ;;
      esac
      t=$(printf '%s' "$l" | sed 's/^[[:space:]]*//')
      case "$t" in
        ''|'//'*|'*'*|'/*'*|'*/'*) ;;
        *) break ;;
      esac
      i=$((i - 1))
    done
    if [ "$found_marker" = "1" ]; then
      reviewed=$((reviewed + 1))
      continue
    fi
    # Постоянная величина, а не состояние: коллекция создана СРАЗУ с
    # содержимым и имя в ВЕРХНЕМ РЕГИСТРЕ. Такие ничего не накапливают.
    case "$code" in
      *"new Set(["*|*"new Map(["*|*">(["*)
        reviewed=$((reviewed + 1))
        continue
        ;;
    esac
    case "$code" in
      *"new Map<"*|*"new Map("*)
        keyed=$((keyed + 1))
        printf '  ключ есть  %s:%s\n             %s\n' "$f" "$n" "$(echo "$code" | sed 's/^ *//')"
        ;;
      *)
        shared=$((shared + 1))
        printf '  🛑 ОБЩЕЕ   %s:%s\n             %s\n' "$f" "$n" "$(echo "$code" | sed 's/^ *//')"
        ;;
    esac
  done < <(grep -arnE "^(let [a-zA-Z_]+|const [a-zA-Z_]+ *(:[^=]*)?= *(new (Map|Set)\(|new (Map|Set)<))" \
    "$d" --include='*.ts' 2>/dev/null | grep -v '\.test\.ts' | grep -viE "interval|timeout|logger|client\b")
done

echo
echo "  с ключом: $keyed; общих на процесс: $shared; разобрано ранее: $reviewed"
echo
if [ "$shared" = "0" ]; then
  echo "  ✅ неразобранного общего состояния нет"
  echo
fi
echo "  ВОПРОС К КАЖДОМУ: а если владельцев двое?"
echo "  «Ключ есть» — не оправдание: ключ должен быть ВЛАДЕЛЬЦЕМ, а не чатом,"
echo "  если факт относится к владельцу. Set без ключа — почти всегда общее."
echo "  Разобрал — поставь рядом строку:  // owner-scope: <почему>"
