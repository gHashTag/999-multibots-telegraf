"""
КОПИИ ДЛИНЫ КОДА ВХОДА У КЛИЕНТОВ.

Длина живёт на сервере (PAIRING.DIGITS) и уже менялась: с шести цифр на
восемь. Клиент, который держит её копию, разойдётся молча -- и разошёлся:
поле iOS обрезало ввод на шестой цифре, и вход в приложение не работал вовсе.

Комментарии снимаются ПЕРЕД поиском. Первая версия этой проверки нашла
объяснение в комментарии и объявила его нарушением -- рассказ о правиле не
есть нарушение правила, и путать их эта проверка уже не должна.
"""
import re
import sys

ПОДОЗРИТЕЛЬНОЕ = re.compile(
    r"count == \d+|prefix\(\d+\)|\d+ цифр|\d+-значн|\d-digit|six-digit|шестизначн",
    re.IGNORECASE,
)

найдено = False
for путь in sys.argv[1:]:
    try:
        текст = open(путь, encoding="utf-8").read()
    except OSError:
        print(f"  {путь}: файла нет -- проверка НЕ выполнена")
        найдено = True
        continue
    # Блочные и строчные комментарии заменяем пустыми строками, чтобы номера
    # строк остались настоящими.
    без = re.sub(r"/\*[\s\S]*?\*/", lambda m: "\n" * m.group(0).count("\n"), текст)
    без = re.sub(r"^\s*//.*$", "", без, flags=re.M)
    for н, строка in enumerate(без.split("\n"), 1):
        if "ЦифрКода" in строка:
            continue
        if ПОДОЗРИТЕЛЬНОЕ.search(строка):
            print(f"  {путь}:{н}: {строка.strip()[:90]}")
            найдено = True

print("" if найдено else "  копий нет -- длину знает только сервер")
