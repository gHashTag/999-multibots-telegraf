#!/bin/bash
# tri rehearse [ветка…] — слить всё в одноразовой копии и сказать, где сломается.
#
# ЗАЧЕМ. 17.09.2026 открытых PR накопилось шестнадцать, все мои, и владелец
# должен был пройти их подряд. Вопрос «сольются ли они друг с другом» до этой
# команды никто не задавал: каждый PR по отдельности значился MERGEABLE —
# против main, а не против соседа, который вольётся раньше.
#
# Первая репетиция: четыре конфликта из шестнадцати. Три из них — в `bin/tri`,
# потому что три ветки вставляли свою команду в ОДНО и то же место. Развёл
# вставки по разным якорям — стало ноль. Это работа на пять минут, которую
# иначе делал бы владелец, трижды, посреди ночи.
#
# ПОРЯДОК — ЧАСТЬ ОТВЕТА. Тот же набор в другом порядке дал восемь конфликтов
# вместо четырёх. Команда не ищет лучший порядок, она проверяет тот, который
# вы назвали: порядок придумывает человек, а репетиция говорит цену.
#
# НИЧЕГО НЕ МЕНЯЕТ. Копия одноразовая, ветки и main не трогаются.
set -u
ROOT="${1:?нужен корень репозитория}"
shift || true
cd "$ROOT" || exit 1

command -v gh >/dev/null 2>&1 || { echo "🛑 нет gh — вывода НЕ делаю."; exit 2; }
git fetch -q origin 2>/dev/null || true

# Без аргументов — порядок открытых PR, как их отдаёт gh: снизу вверх по номеру.
# Это НЕ рекомендация, а отправная точка: свой порядок передайте аргументами.
# --test: ПОСЛЕ СЛИЯНИЯ ПРОГНАТЬ ТЕСТЫ НА ОБЪЕДИНЁННОМ ДЕРЕВЕ.
#
# Репетиция без этого отвечает только на «сольётся ли», а зелёный PR по
# отдельности не обещает зелёное ПОСЛЕ слияния: main уходит вперёд, соседи
# добавляют своё, и ломается обычно не код, а реестры — список команд, набор
# видов события, перепись подписок.
#
# Стоит минут, поэтому не по умолчанию. 17.09.2026 прогон по четырнадцати
# веткам дал 2020 тестов рендера и 1202 бота, все зелёные, и `tri self` на
# объединённом дереве увидел 60 команд при 60 строках справки — то есть шесть
# веток, каждая регистрировавшая свою команду, собрались в связную оболочку.
WITH_TESTS=0
case "${1:-}" in
  --test) WITH_TESTS=1; shift ;;
esac

LIST="$*"
if [ -z "$LIST" ]; then
  LIST=$(gh pr list --state open --limit 40 --json number,headRefName,baseRefName \
    -q '.[] | select(.baseRefName == "main") | .headRefName' 2>/dev/null)
fi
[ -n "$LIST" ] || { echo "🛑 нечего репетировать — вывода НЕ делаю."; exit 2; }

W="$(mktemp -d)/rehearse"
cleanup() {
  git -C "$ROOT" worktree remove --force "$W" >/dev/null 2>&1
  git -C "$ROOT" worktree prune >/dev/null 2>&1
  rm -rf "$(dirname "$W")"
}
trap cleanup EXIT
git worktree prune >/dev/null 2>&1
git worktree add -q --detach "$W" origin/main 2>/dev/null || {
  echo "🛑 не смог создать одноразовую копию — репетицию НЕ провожу."
  exit 2
}
# `cd ... || exit` — ЦЕЛИКОМ ЛАДОНЬ НА ЭТОЙ СТРОКЕ.
# Без неё сценарий продолжает работу в ТЕКУЩЕЙ копии, и «репетиция» сливает
# шестнадцать веток в ваш рабочий main. Так и вышло в первый раз; спасло
# только то, что ничего не было отправлено.
cd "$W" || { echo "🛑 копия не открылась — репетицию НЕ провожу."; exit 2; }

OK=0; BAD=0; CONF=""
for b in $LIST; do
  [ -z "$b" ] && continue
  if git merge --no-edit --no-ff "origin/$b" >/dev/null 2>&1; then
    OK=$((OK + 1)); printf '  ✅ %s\n' "$b"
  else
    BAD=$((BAD + 1)); printf '  🛑 %s:\n' "$b"
    git diff --name-only --diff-filter=U | sed 's/^/       /'
    # ПОКАЗАТЬ СПОРНОЕ МЕСТО, А НЕ ТОЛЬКО ИМЯ ФАЙЛА.
    #
    # Имя файла говорит «тут будет больно» и ничего больше. А спор почти
    # всегда виден в пяти строках, и по ним сразу ясно, спор ли это вообще:
    # две ветки, заменяющие ОДНУ строку разными дополнениями, — это не
    # разногласие, а соседство, и разрешается оно объединением, не выбором.
    git diff --diff-filter=U 2>/dev/null | python3 -c '
import re, sys
# КОММЕНТАРИИ НЕ СПОРЯТ. Их в этом репозитории больше, чем кода, и в спорном
# куске они забивают собой ту единственную строку, ради которой всё читается.
skip = re.compile(r"^\s*(\*|//|/\*|#)")
shown = 0
for line in sys.stdin:
    if shown >= 10:
        break
    body = line[2:].rstrip() if line[:2] in ("++", "+ ") else None
    if body is None or not body.strip() or skip.match(body):
        continue
    print("         " + body[:78])
    shown += 1
'
    CONF="$CONF $b"
    git merge --abort 2>/dev/null
  fi
done

echo
echo "  слилось подряд: $OK, конфликтов: $BAD"
if [ "$BAD" -gt 0 ]; then
  echo "  разбирать:$CONF"
  echo
  echo "  Конфликт в ОДНОМ файле у нескольких веток — обычно не спор по сути,"
  echo "  а одно и то же место вставки. Разведите вставки по разным якорям и"
  echo "  прогоните снова: это дешевле, чем разрешать одно и то же трижды."
  exit 1
fi
echo "  ✅ весь порядок проходит без единого конфликта."
[ "$WITH_TESTS" = "1" ] || exit 0

# Копия одноразовая и без node_modules: связываем с рабочими, не копируя.
echo
echo "── тесты на ОБЪЕДИНЁННОМ дереве ──"
ln -s "$ROOT/node_modules" "$W/node_modules" 2>/dev/null
ln -s "$ROOT/apps/vibee-editor/render/node_modules" \
      "$W/apps/vibee-editor/render/node_modules" 2>/dev/null
RC=0
(cd "$W/apps/vibee-editor/render" && npx vitest run --reporter=dot 2>&1 |
  grep -E '^ +(Tests|Test Files) |FAIL ' | sed 's/^/  рендер:/') || RC=1
(cd "$W" && npx vitest run src/__tests__/services/ src/__tests__/bot/ \
  --reporter=dot 2>&1 | grep -E '^ +(Tests|Test Files) |FAIL ' |
  sed 's/^/  бот:/') || RC=1
(cd "$W" && node scripts/orphan-events.cjs >/dev/null 2>&1 &&
  echo "  шлюз событий: ✅" || { echo "  шлюз событий: 🛑"; RC=1; })
exit $RC
