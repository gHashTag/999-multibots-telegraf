#!/bin/bash
# tri landing — доедет ли работа этой ветки до main, и что застрянет вместе с ней.
#
# ЗАЧЕМ (форма 34). Восемнадцать витков подряд я писал инструменты и складывал
# их в ветку, которая на 132 коммита позади origin/main. Проверено 16.09.2026:
# ПЯТЬ помощников `tri` — mutate, wired, promises, owners, clock — существуют
# ТОЛЬКО там. Ни один человек и ни один следующий виток крона их не увидит,
# пока ветка не сольётся, а слиться она не может, пока в неё не влит main.
#
# Ветка не жалуется. `git status` про это молчит, тесты зелены, PR открыт и
# выглядит живым. Расхождение — единственная поломка в этом репозитории,
# которая растёт сама и ничего не печатает. Поэтому её надо печатать.
#
# ЧИСЛО СЧИТАЕТ КОМАНДА, А НЕ ГЛАЗ. Первый замер конфликтов в этот же день
# дал 84 файла — я сосчитал `tail -n +3`, а `git merge-tree --name-only`
# после списка имён печатает ещё и свой рассказ про Auto-merging. Честных
# конфликтов было 20. Разница между «84» и «20» — это разница между «трогать
# нельзя» и «работа на один виток», то есть ровно то решение, ради которого
# считают. Разбор здесь останавливается на первой пустой строке.
set -u
ROOT="${1:?нужен корень репозитория}"
BASE="${2:-origin/main}"
cd "$ROOT" || exit 1

BR="$(git rev-parse --abbrev-ref HEAD)"
echo "── ветка: $BR ──"

# Свежесть базы. Без fetch числа описывают вчерашний main и врут в сторону
# «всё хорошо» — а ошибаться надо в другую.
if git fetch --quiet origin "${BASE#origin/}" 2>/dev/null; then
  echo "  база обновлена: $BASE"
else
  echo "  ⚠️  fetch не прошёл — числа ниже по локальной копии $BASE, возможно вчерашней"
fi

git rev-parse --verify --quiet "$BASE" >/dev/null || {
  echo "  нет такой базы: $BASE"
  exit 2
}

if [ "$(git rev-parse HEAD)" = "$(git rev-parse "$BASE")" ]; then
  echo "  это и есть $BASE — ехать некуда."
  exit 0
fi

read -r BEHIND AHEAD <<<"$(git rev-list --left-right --count "$BASE"...HEAD)"
echo "  впереди $BASE: $AHEAD; позади: $BEHIND"

# СКОЛЬКО ИЗ «ВПЕРЕДИ» ДЕЙСТВИТЕЛЬНО ЗАСТРЯЛО.
#
# Коммит может уже быть в main другим хешем — через PR, cherry-pick, чужую
# правку того же места. `git cherry` сверяет patch-id, а не хеши: «+» — того
# нет наверху, «−» — то же изменение уже там. Без этой поправки цифра
# «впереди» пугает больше, чем следует.
STRANDED=$(git cherry "$BASE" HEAD 2>/dev/null | grep -c '^+' || true)
ALREADY=$(git cherry "$BASE" HEAD 2>/dev/null | grep -c '^-' || true)
echo "  из них действительно нет в $BASE: ${STRANDED:-0} (уже наверху другим хешем: ${ALREADY:-0})"

# ФАЙЛЫ, КОТОРЫХ НАВЕРХУ НЕТ ВОВСЕ. Это и есть «застрявшее» в самом буквальном
# смысле: не спорные строки, а целые файлы, живущие в одной ветке.
ONLY=$(git diff --name-status "$BASE"...HEAD | awk '$1=="A"{print $2}')
ONLY_N=$(printf '%s' "$ONLY" | grep -c . || true)
if [ "${ONLY_N:-0}" != "0" ]; then
  echo
  echo "  файлов есть только здесь: $ONLY_N"
  TOOLS=$(printf '%s\n' "$ONLY" | grep -E '^(bin/|scripts/|\.claude/)' || true)
  if [ -n "$TOOLS" ]; then
    echo "  из них инструментов и памяти (их не увидит ни человек, ни следующий виток):"
    printf '%s\n' "$TOOLS" | sed 's/^/    · /'
  fi
fi

# КОНФЛИКТЫ — СУХИМ ПРОГОНОМ, НИЧЕГО НЕ ТРОГАЯ НА ДИСКЕ.
MT="$(mktemp)"
trap 'rm -f "$MT"' EXIT
git merge-tree --write-tree --name-only HEAD "$BASE" > "$MT" 2>/dev/null
MT_RC=$?
# Первая строка — oid дерева, дальше имена, дальше пустая строка и рассказ
# про Auto-merging. Останавливаемся на пустой строке — см. шапку.
CONFL=$(awk 'NR==1{next} /^$/{exit} {print}' "$MT")
CN=$(printf '%s' "$CONFL" | grep -c . || true)

echo
# КОДЫ ВОЗВРАТА merge-tree: 0 — чисто, 1 — конфликты, БОЛЬШЕ — сам не смог.
#
# Первая версия считала «всё, что не ноль» конфликтами и напечатала бы
# «конфликтов: 0 файлов» с пустым списком там, где команда просто упала на
# неверной ссылке. Ноль, полученный от сломанного замера, — это форма 35 в
# другой одежде: инструмент не падает, он соглашается.
if [ "$MT_RC" = "0" ]; then
  echo "  ✅ слияние $BASE сюда пройдёт без конфликтов"
elif [ "$MT_RC" = "1" ] && [ "${CN:-0}" != "0" ]; then
  echo "  конфликтов при слиянии $BASE сюда: $CN файлов"
  printf '%s\n' "$CONFL" | sed 's/^/    · /'
else
  echo "  ⚠️  merge-tree не смог посчитать (код $MT_RC) — про конфликты НИЧЕГО не известно"
fi

echo
if [ "${BEHIND:-0}" -gt 30 ]; then
  echo "  🛑 Ветка отстала на $BEHIND. Слитая КАК ЕСТЬ, она везёт наверх старые"
  echo "     копии файлов, которые main с тех пор менял, — то есть откат чужой"
  echo "     работы под видом своей. Сначала влить $BASE сюда, потом просить merge."
  echo "     Новое — резать отдельной веткой ОТ $BASE, а не класть сюда."
  exit 1
fi
echo "  ветка близко к $BASE — можно предлагать к слиянию."
