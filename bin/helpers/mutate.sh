#!/bin/bash
# Обратная мутация одной командой: сломать нарочно, прогнать тесты, вернуть.
#
# ЗАЧЕМ. Главная проверка этого проекта — не «тесты зелёные», а «упадёт ли
# тест, если сломать то, что он якобы сторожит». За последние циклы так
# нашлись три сторожа, которые не умели падать вовсе: поддельный пул отвечал
# по имени таблицы, а условие запроса было удалено; целая функция отключалась
# от вызывающего, и всё оставалось зелёным — дважды.
#
# Делалось это руками десятки раз: cp в /tmp, sed, прогон, cp назад. Дороже
# всего стоит ошибка ровно на «cp назад» — мутация уезжает в коммит. Поэтому
# возврат здесь в ловушке EXIT: он случится и когда тесты упали, и когда
# прервали по Ctrl-C.
#
# tri mutate <файл> <было> <стало> -- <команда тестов>
set -u

F="${1:-}"
FROM="${2:-}"
TO="${3:-}"
shift 3 2>/dev/null || true
[ "${1:-}" = "--" ] && shift

if [ -z "$F" ] || [ -z "$FROM" ] || [ $# -eq 0 ]; then
  echo 'tri mutate <файл> <было> <стало> -- <команда тестов>'
  echo 'пример: tri mutate src/a.ts "if (!face)" "if (false)" -- npx vitest run a.test.ts'
  exit 2
fi
[ -f "$F" ] || { echo "нет файла: $F"; exit 2; }

# ПРОВЕРКА НАЛИЧИЯ — НЕ grep. `grep -qF` разбивает образец по переводам
# строк и говорит «есть», если нашлась ЛЮБАЯ из них. Для многострочного
# образца это ложное «да»: замена ниже ни во что не попадает, файл остаётся
# прежним, тесты зеленеют — и команда печатает «мутация выжила» про
# мутацию, которой не было. 16.09.2026 так и вышло на блоке из четырёх
# строк: сторож был настоящий, а инструмент сказал обратное.
MUT_FILE="$F" MUT_FROM="$FROM" python3 - <<'CHECK' || exit 2
import io, os, sys
s = io.open(os.environ['MUT_FILE'], encoding='utf-8').read()
if os.environ['MUT_FROM'] not in s:
    sys.stderr.write('в файле нет такого куска:\n%s\n' % os.environ['MUT_FROM'])
    sys.exit(1)
CHECK

# СНАЧАЛА УБЕДИТЬСЯ, ЧТО ТЕСТЫ ЗЕЛЁНЫЕ БЕЗ МУТАЦИИ.
#
# Без этого шага команда врёт в самую дорогую сторону: она судит по коду
# возврата, а падение может быть от чего угодно — опечатки в пути к тесту,
# неверной версии node, чужой красноты в том же файле. 16.09.2026 так и
# вышло: «мутация убита» напечаталось там, где мутация на самом деле прошла
# незамеченной, и сторожа, которого нет, я чуть не записал в отчёт.
echo "— проверяю, что тесты зелёные ДО мутации —"
if ! "$@" >/dev/null 2>&1; then
  echo
  echo "🛑 Тесты падают и БЕЗ мутации. Сначала почините прогон:"
  echo "   $*"
  echo "   Иначе любая мутация будет засчитана убитой, чем бы она ни была."
  exit 2
fi

BAK="$(mktemp)"
cp "$F" "$BAK"
restore() {
  cp "$BAK" "$F"
  rm -f "$BAK"
  echo "— файл возвращён —"
}
trap restore EXIT

MUT_FILE="$F" MUT_FROM="$FROM" MUT_TO="$TO" python3 - <<'PY'
import io, os
p = os.environ['MUT_FILE']
s = io.open(p, encoding='utf-8').read()
io.open(p, 'w', encoding='utf-8').write(
    s.replace(os.environ['MUT_FROM'], os.environ['MUT_TO'], 1)
)
PY

# И ПОСЛЕ ЗАМЕНЫ — ЧТО ФАЙЛ ДЕЙСТВИТЕЛЬНО ИЗМЕНИЛСЯ. Вторая страховка от
# того же самого: «было» равно «стало», лишний пробел, замена вхолостую.
if cmp -s "$BAK" "$F"; then
  echo
  echo "🛑 Файл НЕ изменился: замена ни во что не попала."
  echo "   Прогон засчитал бы «мутация выжила» без всякой мутации."
  exit 2
fi

echo "— мутация внесена, гоню тесты —"
if "$@"; then
  echo
  echo "🛑 МУТАЦИЯ ВЫЖИЛА. Тест не сторожит то, что вы думали."
  echo "   Нужен случай, который падает именно на этой подмене."
  exit 1
fi
echo
echo "✅ мутация убита — сторож настоящий"
exit 0
