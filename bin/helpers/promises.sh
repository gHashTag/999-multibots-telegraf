#!/bin/bash
# tri promises — обещания в тексте, за которыми стоит число из другого файла.
#
# ЗАЧЕМ (форма 30 в скилле blind-guards). Бот говорит человеку «молчу 30
# минут», «30 дней не трогаем», «стартовые токены есть». Число живёт в другой
# константе, часто в ДРУГОМ сервисе, и фраза — единственное, что связывает его
# с человеком. Поменяли константу — бот продолжает обещать прошлогоднее, и
# звучит это правдоподобно: неверная команда даёт тишину, неверный срок — нет.
#
# Три таких пары нашлись руками за три витка. Инструмент ищет их сразу.
#
# Разобранное помечается строкой `promise-checked: <чем держится>` рядом — и
# больше не показывается, а считается. Тот же приём, что у `tri owners`:
# список, где норма — 26 из 28, читают один раз и перестают.
set -u
ROOT="${1:?нужен корень репозитория}"
cd "$ROOT" || exit 1

# ── tri promises --defaults ────────────────────────────────────────────────
#
# ЧАСТЬ ОБЕЩАНИЙ ПРОВЕРЯЕТСЯ МАШИНОЙ.
#
# Общий список — 82 фразы — разбирается только глазами. Но одна их порода
# проверяется целиком: «(по умолчанию N)» в описании параметра инструмента и
# запасной вариант в обработчике того же инструмента. Эту фразу читает МОДЕЛЬ,
# и разойтись они могут молча — поменяли запасной вариант, а описание осталось
# и продолжает рассказывать про старое поведение.
#
# ЧЕСТНОСТЬ ЭТОЙ СВЕРКИ СТОИЛА ОДНОЙ ПЕРЕДЕЛКИ. Первая версия искала запасной
# вариант ПО ВСЕМУ файлу и выдала пять «расхождений» — все пять оказались
# ложными: она хватала первое попавшееся число, из другого инструмента. Теперь
# ищет только ПОСЛЕ фразы и в пределах шестидесяти строк, то есть внутри того
# же объекта. Инструмент, показывающий пять несуществующих поломок, хуже, чем
# отсутствие инструмента: по нему пойдут проверять (форма 95).
if [ "${2:-}" = "--defaults" ] || [ "${1:-}" = "--defaults" ]; then
  python3 - <<'PYEOF'
import re, subprocess, sys

PROMISE = re.compile(r'по умолчанию\s+(\d+)')
KEY = re.compile(r"\s*([a-z_][a-z0-9_]*)\s*:\s*\{")
WINDOW = 60

files = subprocess.run(['git', 'ls-files', '*.ts'],
                       capture_output=True, text=True).stdout.split()
rows = []
for f in files:
    if '.test.' in f or '/node_modules/' in f:
        continue
    try:
        lines = open(f, encoding='utf-8').read().splitlines()
    except Exception:
        continue
    for i, l in enumerate(lines):
        m = PROMISE.search(l)
        if not m:
            continue
        promised = int(m.group(1))
        name = None
        for j in range(i, max(-1, i - 6), -1):
            k = KEY.match(lines[j])
            if k:
                name = k.group(1)
                break
        if not name:
            continue
        after = '\n'.join(lines[i:i + WINDOW])
        pats = [rf"\b{re.escape(name)}\b[^\n]{{0,80}}\?\?\s*(\d+)",
                rf"\b{re.escape(name)}\b[^\n]{{0,80}}\|\|\s*(\d+)",
                rf"\b{re.escape(name)}\b[\s\S]{{0,160}}?:\s*(\d+)\b"]
        found = None
        for p in pats:
            mm = re.search(p, after)
            if mm:
                found = int(mm.group(1))
                break
        rows.append((f, i + 1, name, promised, found))

if not rows:
    print('🛑 ни одной фразы «по умолчанию N» — вывода НЕ делаю.')
    sys.exit(2)
bad = [r for r in rows if r[4] is not None and r[4] != r[3]]
ok = [r for r in rows if r[4] == r[3]]
none = [r for r in rows if r[4] is None]
print(f'обещанных умолчаний: {len(rows)}')
print(f'  сошлось с кодом:        {len(ok)}')
print(f'  РАЗОШЛОСЬ:              {len(bad)}')
print(f'  запасной вариант не рядом (судить нельзя): {len(none)}')
for f, ln, n, p, a in bad:
    print(f'  🛑 {f}:{ln}  {n}: обещано {p}, рядом {a}')
if none:
    print()
    print('  «Не рядом» — не находка: умолчание может жить в другой функции,')
    print('  а число в описании быть телефоном или идентификатором. Судить о')
    print('  них можно только глазами.')
if bad:
    print()
    print('  Описание параметра читает МОДЕЛЬ. Разойдясь, оно рассказывает ей')
    print('  про поведение, которого больше нет. Лучше всего строить фразу ИЗ')
    print('  постоянной — тогда расхождение невозможно, а не ловится тестом.')
    sys.exit(1)
print()
print('  ✅ ни одно обещанное умолчание не разошлось с кодом.')
PYEOF
  exit $?
fi


DIRS="src/navigation src/services src/handlers apps/vibee-editor/render/src/agent"
# Число с единицей ВНУТРИ строки с кириллицей: срок, цена, количество.
UNITS='минут|мин\.|часа|часов|дней|дня|суток|недел|токен|звёзд|звезд|⭐|раз'
# И ОТДЕЛЬНО — числа в ОПИСАНИЯХ ИНСТРУМЕНТОВ, у которых единицы может не быть.
#
# Форма 31: `crm_ingest_chats` обещал модели «максимум 200», а зажим допускал
# 2000 — вдесятеро меньше, чем просил владелец. Эта команда ту находку
# ПРОПУСТИЛА: «диалогов» нет в списке единиц, и строка не попала в выборку,
# а счётчик показывал ноль неразобранного. Ноль, который врёт, — то же самое,
# что ложное «разобрано»: вопрос закрыт, и никто не вернётся.
DESC='(по умолчанию|максимум|не более|до) [0-9]+'

echo "── обещания числом ──"
echo
open=0
checked=0
while IFS= read -r line; do
  [ -z "$line" ] && continue
  f="${line%%:*}"
  rest="${line#*:}"
  n="${rest%%:*}"
  # СТРОКА БЕЗ НОМЕРА — ЭТО НЕ СТРОКА ФАЙЛА, А СООБЩЕНИЕ grep О СЕБЕ.
  #
  # Форма 35. `grep` без -a на файле с одним управляющим байтом печатает
  # "Binary file X matches" вместо совпадений. Дальше `$((n - 1))` считает
  # это арифметикой, находит там слово и падает с "unbound variable" — но
  # это ЛУЧШЕЕ из двух зол: до -a такой файл просто выпадал из выборки, и
  # счётчик писал «не разобрано: 0», ни разу его не прочитав.
  case "$n" in
    '' | *[!0-9]*)
      echo "  ⚠️  grep ответил не строкой файла, а про себя: $line" >&2
      continue
      ;;
  esac
  # СМОТРИМ ВВЕРХ — НО ДО ПЕРВОЙ НАСТОЯЩЕЙ СТРОКИ КОДА.
  #
  # Пометка стоит над строкой, а между ними бывает закрытие блочного
  # комментария и голова выражения (`const caption = is_ru`). Одной строки
  # назад мало.
  #
  # ПЕРВАЯ ВЕРСИЯ СМОТРЕЛА НА 15 СТРОК ВВЕРХ — и проверено обратной мутацией:
  # новое обещание, дописанное под ЧУЖОЙ пометкой, исчезало из списка. То
  # есть инструмент начинал врать «разобрано» — хуже, чем шум, который он
  # убирал. Теперь подъём кончается на первой строке, которая не комментарий,
  # не пустая и не голова того же выражения (одна такая допускается).
  seen_code=0
  found=0
  i=$((n - 1))
  while [ "$i" -ge 1 ] && [ $((n - i)) -le 12 ]; do
    l=$(sed -n "${i}p" "$f" 2>/dev/null)
    case "$l" in
      *promise-checked:*) found=1; break ;;
    esac
    t=$(printf '%s' "$l" | sed 's/^[[:space:]]*//')
    case "$t" in
      ''|'//'*|'*'*|'/*'*|'*/'*) ;;
      *)
        seen_code=$((seen_code + 1))
        [ "$seen_code" -ge 2 ] && break
        ;;
    esac
    i=$((i - 1))
  done
  if [ "$found" = "1" ]; then
    checked=$((checked + 1))
    continue
  fi
  open=$((open + 1))
  printf '  %s:%s\n     %s\n' "$f" "$n" "$(echo "${line#*:*:}" | sed 's/^ *//' | cut -c1-96)"
done < <(
  for d in $DIRS; do
    [ -d "$d" ] || continue
    # -a: ЧИТАТЬ ДАЖЕ ТО, ЧТО grep СЧЁЛ ДВОИЧНЫМ.
    #
    # На origin/main в tools.ts лежит один настоящий байт 0x00 — разделитель
    # в хеше, записанный байтом вместо '\0'. Из-за него grep объявляет
    # ДВОИЧНЫМ весь файл: 2888 строк реестра инструментов агента не видит ни
    # одна проверка на shell. Байт чинится отдельно, но инструмент не должен
    # слепнуть от одного байта в чужом файле.
    grep -arnE "['\"\`][^'\"\`]*[а-яё][^'\"\`]*([0-9]+ ?($UNITS)|$DESC)" "$d" --include='*.ts' 2>/dev/null |
      grep -v '\.test\.ts' | grep -viE '^\S+: *(//|\*)' | grep -v 'promise-checked' |
      grep -v 'logger\.\|console\.'  # журнал -- не обещание человеку
  done
)

echo
echo "  не разобрано: $open; разобрано ранее: $checked"
if [ "$open" = "0" ]; then
  echo
  echo "  ✅ каждое обещание числом связано с тем, что его держит"
fi
echo
echo "  ВОПРОС К КАЖДОМУ: что должно быть верно, чтобы эта фраза осталась правдой?"
echo "  Ответ — утверждение теста. Разобрал — поставь рядом строку:"
echo "     // promise-checked: <тест или константа, которая её держит>"
