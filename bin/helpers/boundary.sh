#!/bin/bash
# tri boundary — держат ли инструменты агента своё обещание не отправлять.
#
# ЗАЧЕМ. Всё устройство продавца стоит на одной фразе: НИЧЕГО НЕ УХОДИТ К
# ЧЕЛОВЕКУ БЕЗ НАЖАТИЯ ВЛАДЕЛЬЦА. В коде эта гарантия живёт не в одном месте,
# а в девятнадцати описаниях инструментов — и описание читает МОДЕЛЬ, решая,
# что ей можно.
#
# До 17.09.2026 её не проверял никто. Сверить недолго, а цена ошибки — чужому
# человеку уходит сообщение, которого владелец не видел.
#
# ДВЕ РАЗНЫЕ КЛЯТВЫ, И ПРОВЕРКИ У НИХ РАЗНЫЕ. Первая версия этой команды их
# смешала и выдала восемь «нарушений», из которых все восемь были ложью:
#
#   «НЕ ОТПРАВЛЯЕТ СРАЗУ — proposal»  → ОБЯЗАН звать propose()
#   «ЧИТАЮЩИЙ, ничего не отправляет»  → ОБЯЗАН не звать отправку вовсе
#
# Читающему инструменту звать propose незачем, и требовать этого — значит
# отправить человека проверять шестнадцать исправных мест.
set -u
ROOT="${1:?нужен корень репозитория}"
cd "$ROOT" || exit 1

python3 - <<'PYEOF'
import re, glob, sys

# Всё, чем инструмент реально отправляет сообщение от имени человека.
SEND = re.compile(
    r'\bc\.sendMessage\(|\bc\.sendFile\(|sendToTelegram\(|'
    r'\.invoke\(\s*new\s+Api\.messages\.Send'
)
PROPOSAL = re.compile(r'НЕ ОТПРАВЛЯЕТ СРАЗУ|возвращает proposal|: proposal')
READONLY = re.compile(r'ЧИТАЮЩИЙ|ничего не отправля|только чтение')
# Хвост инструмента: имя, описание, параметры и обработчик умещаются в это
# окно во всех нынешних файлах. Шире — начнёт цеплять соседний инструмент.
WINDOW = 140

files = [f for f in sorted(glob.glob('apps/vibee-editor/render/src/agent/*.ts'))
         if not f.endswith('.test.ts')]
if not files:
    print('🛑 не нашёл ни одного файла инструментов — вывода НЕ делаю.')
    sys.exit(2)

prop = read = 0
broken = []
for p in files:
    lines = open(p, encoding='utf-8').read().splitlines()
    for i, l in enumerate(lines):
        m = re.match(r"\s*name:\s*'([a-z_0-9]+)',", l)
        if not m:
            continue
        name = m.group(1)
        block = '\n'.join(lines[i:i + WINDOW])
        head = block[:700]
        if PROPOSAL.search(head):
            prop += 1
            if not re.search(r'\bpropose\(', block):
                broken.append(('обещает подтверждение, но не готовит его', name, p, i + 1))
        elif READONLY.search(head):
            read += 1
            if SEND.search(block):
                broken.append(('клянётся только читать, но отправляет', name, p, i + 1))

if prop + read == 0:
    print('🛑 ни один инструмент не обещает ни того, ни другого.')
    print('   Либо формулировки сменились, либо я смотрю не туда — вывода НЕ делаю.')
    sys.exit(2)

print(f'обещают подтверждение владельца: {prop}')
print(f'клянутся только читать:          {read}')
if not broken:
    print()
    print('  ✅ граница держится: ни один инструмент не нарушил своего обещания.')
    print('     Это то самое свойство, на котором стоит весь продавец:')
    print('     ничего не уходит человеку без нажатия владельца.')
    sys.exit(0)
print()
for why, name, p, ln in broken:
    print(f'  🛑 {name}: {why}')
    print(f'     {p}:{ln}')
print()
print('  Описание читает МОДЕЛЬ. Разойдясь с кодом, оно разрешает ей то,')
print('  чего продукт не разрешает, — и обнаружится это на живом человеке.')
sys.exit(1)
PYEOF
