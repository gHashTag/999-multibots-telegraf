#!/bin/bash
# tri scan — сторожа, которые ОБХОДЯТ дерево, а не импортируют его.
#
# ЗАЧЕМ. Ворота перед push зовут `vitest related`, а тот выбирает тесты по
# ГРАФУ ИМПОРТОВ. Сторож, который читает исходники через fs (их в репозитории
# 419) и тем более обходит каталог целиком, не связан с кодом ни одним
# импортом — его невозможно выбрать по графу, и он не запускается вовсе.
#
# Чем это кончилось 16.09.2026: `callbackNumberParseRegistry` — реестр
# «каждое место, где число берётся из callback, прочитано человеком» —
# краснел с коммита ace97435b и пережил несколько push подряд. Два новых
# места CRM просто не были в нём записаны, и никто об этом не узнал.
#
# Здесь запускаются ровно обходчики (readdirSync): их 72 на оба дерева, они
# идут 8 секунд и сегодня зелены все. Малый, быстрый и полный набор — такой
# можно ставить в ворота, не рискуя заблокировать чужой чистый push.
set -u
ROOT="${1:?нужен корень репозитория}"
cd "$ROOT" || exit 1

BOT=$(grep -rln "readdirSync" src/__tests__ 2>/dev/null | tr '\n' ' ')
R=apps/vibee-editor/render
REN=$(cd "$R" && grep -rln "readdirSync" --include='*.test.ts' . 2>/dev/null |
  grep -v node_modules | tr '\n' ' ')

# Слова разбиваются намеренно: это СПИСОК файлов, и кавычки вокруг него
# превратили бы его в одно имя. Скрипт исполняется bash-ем, а не zsh, поэтому
# работает обычное разбиение, и никакого `${=VAR}` здесь не нужно.
status=0
if [ -n "${BOT// /}" ]; then
  echo "── обходчики дерева: бот ──"
  # shellcheck disable=SC2086
  npx vitest run $BOT 2>&1 | tail -5
  [ "${PIPESTATUS[0]}" = "0" ] || status=1
fi
if [ -n "${REN// /}" ]; then
  echo
  echo "── обходчики дерева: рендер ──"
  cd "$R" || exit 1
  # shellcheck disable=SC2086
  npx vitest run $REN 2>&1 | tail -5
  [ "${PIPESTATUS[0]}" = "0" ] || status=1
fi
if [ "$status" = "0" ]; then
  echo
  echo "✅ обходчики дерева зелены — реестры и переписи прочитаны"
fi
exit $status
