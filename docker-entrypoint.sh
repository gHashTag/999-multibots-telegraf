#!/bin/sh

# ====================================
# DOCKER ENTRYPOINT ДЛЯ TELEGRAM БОТОВ
# ====================================
# Автоматически устанавливает вебхуки при запуске контейнера

set -e

echo "======================================"
echo "🚀 ЗАПУСК TELEGRAM BOT FARM"
echo "======================================"

# 1. Проверяем переменные окружения
echo "📍 Проверка конфигурации..."
echo "   ORIGIN: ${ORIGIN:-не установлен}"
echo "   NODE_ENV: ${NODE_ENV:-production}"

# 2. Ждём пока приложение запустится
echo "⏳ Ожидание запуска приложения..."
sleep 5

# 3. Запускаем основное приложение в фоне
echo "🤖 Запуск ботов..."
node dist/index.js &
APP_PID=$!

# 4. Ждём пока все боты инициализируются
echo "⏳ Инициализация ботов (15 секунд)..."
sleep 15

# 5. Устанавливаем вебхуки
echo "🔗 Установка вебхуков..."
if [ -f "scripts/setup-webhooks-correct.js" ]; then
    node scripts/setup-webhooks-correct.js || echo "⚠️ Не все вебхуки установлены успешно"
else
    echo "⚠️ Скрипт установки вебхуков не найден"
fi

echo "======================================"
echo "✅ BOT FARM ЗАПУЩЕН!"
echo "======================================"

# 6. Держим процесс активным
wait $APP_PID