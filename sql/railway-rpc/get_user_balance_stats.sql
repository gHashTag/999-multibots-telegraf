-- =============================================================================
--  get_user_balance_stats(p_user_telegram_id text, p_bot_name text)
--  Порт функции из облачного Supabase в Railway Postgres (Postgres-NFrq).
-- =============================================================================
--
--  ЧИТАТЬ ЦЕЛИКОМ ПЕРЕД ТЕМ, КАК «ПОЧИНИТЬ» ЭТОТ ФАЙЛ.
--
--  Эта функция НЕ возвращает статистику. Никогда не возвращала. Ниже — не
--  недоделка и не заглушка: это точное воспроизведение живого поведения
--  облачной функции, снятое с неё измерением. В облаке она сломана, и порт
--  сломан ровно так же и по той же причине.
--
-- -----------------------------------------------------------------------------
--  ЧТО ИЗМЕРЕНО (источник истины — живой облачный Supabase, PostgREST)
-- -----------------------------------------------------------------------------
--
--  Тела функции нет НИГДЕ в исходниках: `grep -rn get_user_balance_stats sql/`
--  даёт только `get_user_balance_stats_optimized` (другая функция, другая
--  сигнатура, она работает). Строки 'Invalid telegram_id format' нет ни в
--  одном блобе за всю историю git. Поэтому единственный источник — наблюдаемый
--  вывод живой функции.
--
--  Прозвонены ВСЕ 759 реальных пар (telegram_id, bot_name) из payments_v2
--  (629 различных telegram_id) плюс матрица краевых случаев.
--
--  Результат: 759 из 759 → HTTP 404, SQLSTATE 42883
--      message: operator does not exist: text = bigint
--      hint:    No operator matches the given name and argument types.
--               You might need to add explicit type casts.
--      detail:  null
--
--  Ни одна реальная пара не вернула статистику. Ноль исключений.
--
--  Достижимы ровно ДВА исхода:
--
--   1. p_user_telegram_id НЕ приводится к bigint
--      → нормальный возврат (HTTP 200), jsonb:
--        {"error": "Invalid telegram_id format", "details": "<SQLERRM>"}
--      Ловятся ОБА класса ошибок приведения:
--        22P02 invalid_text_representation
--              details = 'invalid input syntax for type bigint: "abc"'
--        22003 numeric_value_out_of_range
--              details = 'value "9223372036854775808" is out of range for type bigint'
--
--   2. p_user_telegram_id приводится к bigint (любое значение, включая
--      несуществующего пользователя, отрицательное, ' 144022504 ',
--      '+144022504', '000144022504', 9223372036854775807)
--      → исключение 42883. Функция до данных не доходит.
--
--  Проверка типа — это ПРОСТОЙ `::bigint`, а не регулярка: ' 144022504 ',
--  '+144022504', '-5' и '000144022504' проходят приведение (и падают в 42883),
--  а `^\d+$` их бы отверг. '12.0' и '1e3' не проходят — как и положено bigint.
--
--  ОБРАБОТЧИК ИСКЛЮЧЕНИЙ ловит и 22P02, и 22003, но НЕ ловит 42883. Значит
--  `WHEN OTHERS` вокруг ВСЕГО тела исключён (он проглотил бы 42883), и
--  `WHEN invalid_text_representation` в одиночку тоже исключён (он пропустил бы
--  22003). Остаётся: узкий блок вокруг самого приведения. Ниже — он.
--
--  ТИП ВОЗВРАТА — jsonb, а не json. Различитель — форматирование:
--      json_build_object  → {"error" : "...", "details" : "..."}   (пробел С ДВУХ сторон)
--      jsonb_build_object → {"error": "...", "details": "..."}     (пробел ТОЛЬКО справа)
--  Облако отдаёт вторую форму. Для сравнения: работающая
--  get_user_balance_stats_optimized отдаёт ПЕРВУЮ форму, то есть она RETURNS json,
--  а эта — RETURNS jsonb. Это разные функции, написанные разными руками.
--
--  p_bot_name НЕ ВЛИЯЕТ НИ НА ЧТО. Проверено на 'neuro_blogger_bot',
--  несуществующем 'NoSuchBot_xyz', '', '  ', '%' и SQL NULL при валидном
--  telegram_id — все шесть дают идентичный 42883. Падение происходит раньше,
--  чем bot_name мог бы быть использован. Фильтрует ли он что-нибудь в
--  «задуманной» версии — УСТАНОВИТЬ НЕВОЗМОЖНО.
--
-- -----------------------------------------------------------------------------
--  ЕДИНСТВЕННОЕ ИЗМЕРЕННОЕ РАСХОЖДЕНИЕ С ОБЛАКОМ (не скрыто, читать)
-- -----------------------------------------------------------------------------
--
--  Railway — PostgreSQL 18.6. Облако — PostgreSQL 15 или ниже. Начиная с
--  PG16 функция ввода bigint принимает недесятичные литералы (0x/0X, 0o, 0b)
--  и подчёркивания-разделители. Из-за этого расходятся ровно такие входы:
--
--    вход                 облако (PG<=15)                    Railway (PG18)
--    '0x10'               error-jsonb                        42883
--    '0X10' '0xFF'        error-jsonb                        42883
--    '0o20'               error-jsonb                        42883
--    '0b101'              error-jsonb                        42883
--    '1_000'              error-jsonb                        42883
--    '1_4_4_0_2_2_5_0_4'  error-jsonb                        42883
--    '-0x10' '+0x10'      error-jsonb                        42883
--
--  '0x' и '0b' (префикс без цифр) отвергаются ОБЕИМИ — совпадают.
--
--  Расхождение создаёт ПЛАТФОРМА, а не тело функции. Что в облаке стоит
--  именно голое `::bigint`, а не собственная проверка, доказывается текстом
--  details: 'invalid input syntax for type bigint: "0x10"' — это дословное
--  сообщение парсера bigint самого Postgres. Рукописная проверка выдала бы
--  своё сообщение. То есть облако не отвергает hex — его отвергает PG15.
--
--  Guard здесь СОЗНАТЕЛЬНО НЕ ДОБАВЛЕН. Чтобы закрыть расхождение, пришлось бы
--  написать эмуляцию парсера целых PG15 (разрешить пробельные символы и знак,
--  запретить 0x/0o/0b/подчёркивания, сохранить оба текста SQLERRM — и 22P02,
--  и 22003). Это код, которого в облаке доказуемо НЕТ, и он завёл бы
--  собственные ошибки в углах, которые никто не измерял. Telegram ID всегда
--  приходит десятичными цифрами, поэтому на реальном трафике расхождение
--  недостижимо: все 759 реальных пар совпали побайтово.
--
--  Если однажды паритет на мусорном вводе станет важен — закрывать его надо
--  осознанно и с тестами на обе ветки SQLERRM, а не молча.
--
-- -----------------------------------------------------------------------------
--  ПОЧЕМУ 42883 ВОСПРОИЗВОДИТСЯ САМ, БЕЗ ИМИТАЦИИ
-- -----------------------------------------------------------------------------
--
--  Схемы облака и Railway в этой части совпадают побайтово:
--      payments_v2.telegram_id  bigint
--      users.telegram_id        text     <-- вот он, разъезд типов
--
--  Тело приводит текстовый параметр к bigint, а потом сравнивает bigint с
--  ТЕКСТОВОЙ колонкой. Postgres не имеет оператора `text = bigint` и падает на
--  этапе планирования этого оператора — при КАЖДОМ вызове, для любых данных.
--
--  Ниже стоит ровно то же сравнение на тех же типах. Ошибка не подделана
--  через RAISE: она возникает по той же причине, что и в облаке, и потому
--  совпадает по SQLSTATE, message, hint и пустому detail.
--
--  С какой стороны разъезд — установить снаружи НЕЛЬЗЯ. Порядок операндов в
--  сообщении (`text = bigint`, текст слева) одинаково допускает
--      users.telegram_id (text) = v_telegram_id (bigint)
--  и
--      p_user_telegram_id (text) = payments_v2.telegram_id (bigint).
--  Оба варианта дают побайтово одинаковую ошибку. Выбран первый; наблюдаемой
--  разницы между ними нет.
--
-- -----------------------------------------------------------------------------
--  ЧЕГО В ЭТОМ ФАЙЛЕ НЕТ И ПОЧЕМУ
-- -----------------------------------------------------------------------------
--
--  Здесь НЕТ «успешной» ветки со статистикой. Форма этого ответа неизвестна:
--  функция никогда её не отдавала, в исходниках её нет, и единственный
--  вызывающий код (src/utils/statsDebugger.ts, строки ~174 и ~340) зовёт её с
--  параметром `user_telegram_id` — такого параметра у живой функции нет, так
--  что приложение получает PGRST202 «функция не найдена» и до тела не доходит
--  вообще. Контракта потребителя тоже не существует.
--
--  Интерфейс UserBalanceStats в src/core/supabase/getUserBalance.ts
--  (balance_rub, total_xtr_purchased, service_usage_details и т.д.) —
--  это НЕ описание этой функции. Он не подтверждён ни одним наблюдением:
--  ни одно из его полей ни разу не было получено из БД. Заполнить его
--  «похожими» суммами из payments_v2 значило бы выдумать контракт и выдать
--  выдумку за перенос.
--
--  Если статистика нужна на деле — берите get_user_balance_stats_optimized
--  (p_telegram_id bigint, ...): она в облаке РАБОТАЕТ, её тело лежит в
--  sql/balance_functions.sql, и её форму можно переносить, а не угадывать.
--
-- =============================================================================

BEGIN;

CREATE OR REPLACE FUNCTION public.get_user_balance_stats(
  p_user_telegram_id text,
  p_bot_name         text
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
  v_telegram_id bigint;
  v_result      jsonb;
BEGIN
  -- Ветка 1. Узкий блок вокруг приведения: ловит и 22P02, и 22003.
  -- Обработчик намеренно НЕ растянут на всё тело — иначе он проглотил бы
  -- 42883 из ветки 2, и порт разошёлся бы с облаком.
  BEGIN
    v_telegram_id := p_user_telegram_id::bigint;
  EXCEPTION
    WHEN OTHERS THEN
      RETURN jsonb_build_object(
        'error',   'Invalid telegram_id format',
        'details', SQLERRM
      );
  END;

  -- Ветка 2. Тот самый разъезд типов: users.telegram_id — text,
  -- v_telegram_id — bigint. Оператора `text = bigint` в Postgres нет,
  -- поэтому здесь всегда поднимается 42883 — ровно как в облаке.
  --
  -- НЕ «чинить» это приведением типов. Пока облачная функция сломана,
  -- починка здесь означала бы, что порт ведёт себя иначе, чем оригинал,
  -- и вернула бы наверх статистику, форма которой не выведена ниоткуда.
  -- Чинить надо ОБЕ базы разом и с явно заданной формой ответа.
  SELECT to_jsonb(u.*)
    INTO v_result
    FROM public.users u
   WHERE u.telegram_id = v_telegram_id;

  -- Недостижимо, пока users.telegram_id остаётся text. Стоит здесь как
  -- предохранитель: если кто-то поменяет тип колонки, функция не начнёт
  -- молча отдавать наверх непроверенную форму ответа, а скажет об этом.
  RAISE EXCEPTION
    'get_user_balance_stats: форма успешного ответа не выведена — облачная функция её никогда не возвращала (SQLSTATE 42883 на всех 759 реальных парах). См. заголовок sql/railway-rpc/get_user_balance_stats.sql'
    USING ERRCODE = 'feature_not_supported';

  RETURN v_result;
END;
$$;

COMMENT ON FUNCTION public.get_user_balance_stats(text, text) IS
  'Побитовый порт сломанной облачной функции. Валидный telegram_id -> SQLSTATE 42883 (operator does not exist: text = bigint), как в облаке на 759/759 реальных пар. Невалидный -> jsonb {"error":"Invalid telegram_id format","details":<SQLERRM>}. Форма успешного ответа не выведена: она не наблюдалась ни разу. Для рабочей статистики: get_user_balance_stats_optimized.';

COMMIT;
