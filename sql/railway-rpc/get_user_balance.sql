-- =============================================================================
--  get_user_balance(user_telegram_id text) -> numeric
--  Порт функции из облачного Supabase в Railway Postgres (Postgres-NFrq).
-- =============================================================================
--
--  ЧИТАТЬ ЦЕЛИКОМ ПЕРЕД ТЕМ, КАК «ПОПРАВИТЬ» ФОРМУЛУ.
--
--  Эта функция решает, сколько у человека денег. Ошибка в ней в любую сторону
--  неотличима от кражи. Ниже — не «похожая» формула, а та, что снята
--  измерением с живой облачной функции и сошлась с ней ПОБАЙТОВО на всех
--  629 плательщиках.
--
-- -----------------------------------------------------------------------------
--  ОТКУДА ВЗЯТО ТЕЛО
-- -----------------------------------------------------------------------------
--
--  Тела функции нет НИГДЕ в исходниках. `grep -rn get_user_balance sql/` даёт
--  только `get_user_balance_stats_optimized` (другая функция, другая формула —
--  см. раздел «РАСХОЖДЕНИЕ С get_user_balance_stats_optimized»). Единственный
--  источник истины — наблюдаемое поведение живой функции через PostgREST.
--
--  Метод: облачный RPC — оракул, таблица payments_v2 — данные.
--
--  ПРЕДВАРИТЕЛЬНО ПРОВЕРЕНО, что данные совпадают. Все 17139 строк payments_v2
--  выкачаны из облака и сравнены со строками на Railway по id и по колонкам
--  telegram_id, type, category, status, stars, amount, is_test,
--  is_system_payment, bot_name, transaction_context, currency. Расхождений
--  НОЛЬ, лишних строк с обеих сторон НОЛЬ. Значит любое несовпадение
--  результата — это формула, а не данные. Таблица статична: последняя
--  оплата 2026-08-27, счётчик 17139 не менялся за всё время замера.
--
-- -----------------------------------------------------------------------------
--  ЧТО ИЗМЕРЕНО
-- -----------------------------------------------------------------------------
--
--  1. Прозвонены ВСЕ 629 различных telegram_id из payments_v2. Порт и облако
--     сравнивались не по числу, а по СЫРОМУ ТЕКСТУ ответа PostgREST.
--     Результат: 629 из 629 совпали посимвольно, включая масштаб ('0' против
--     '0.00' — см. п.4). Повторный независимый прогон на 80 случайных
--     плательщиках: 80 из 80.
--
--  2. Возвращается СКАЛЯР numeric, не строка и не объект. Дробная часть —
--     ровно та, что даёт сумма numeric(12,2): 592 пользователя получили два
--     знака, округления до целого нет (195848267.69, -4994.00). Отрицательные
--     значения отдаются как есть — 6 пользователей с минусом, greatest(...,0)
--     нет (вариант с обрезкой разошёлся бы на 6 из 629).
--
--  3. Пользователь без строк и telegram_id, которого нет вообще: возвращается
--     0, а НЕ NULL и не ошибка. Проверено на 0, -1, 1, 999999999999,
--     ±9223372036854775807 и на 8 реальных telegram_id из users без оплат.
--     NULL в аргументе тоже даёт 0.
--
--  4. Ноль приходит В ДВУХ РАЗНЫХ ТЕКСТОВЫХ ФОРМАХ, и это выдаёт структуру
--     запроса. 37 пользователей, у которых ЕСТЬ строки в payments_v2, но ВСЕ
--     они PENDING, получают '0' (масштаб 0), а не '0.00'. Так бывает только
--     если строки отсеяны ДО агрегата: sum() по пустому множеству даёт NULL,
--     и его подменяет целочисленный литерал COALESCE(..., 0). Пользователь с
--     хотя бы одной COMPLETED-строкой получает '0.00' — масштаб приходит от
--     numeric(12,2). Поэтому `status = 'COMPLETED'` стоит в WHERE, а не
--     внутри CASE, и литерал в COALESCE — именно 0, а не 0.00.
--
--  5. PENDING исключены. Это не догадка по одному примеру:
--       - 72 пользователя из 629 получили бы другое число, если бы PENDING
--         учитывались;
--       - у 144022504 висит 85 PENDING-строк на 1 035 300 звёзд, и облако
--         отдаёт 195848267.69 — ровно сумму без них;
--       - 37 пользователей с ТОЛЬКО PENDING-строками получают 0.
--
--  6. Единственная строка type='BONUS' (id 15265, telegram_id 289259562,
--     10000.00 звёзд, COMPLETED) НЕ учитывается. Проверено адресно: облако
--     отдаёт для 289259562 ровно 159105.00 — сумму БЕЗ этих 10000.
--     С ними было бы 169105.00. Отсюда `ELSE 0` в CASE.
--
--  7. REFUND прибавляется со знаком ПЛЮС. Если REFUND вычитать — разойдутся
--     11 из 629; если игнорировать — тоже 11 из 629.
--
--  8. Колонка category НЕ участвует. Фильтр category='REAL' разошёлся бы на
--     332 пользователях из 629: MONEY_INCOME/BONUS (464 строки, 1 527 381.69
--     звёзд) входит в баланс наравне с REAL.
--
--  9. Считается колонка stars, не amount. Вариант на amount разошёлся бы
--     на 343 пользователях из 629.
--
--  10. НЕ фильтруется ничего из: is_test (иначе разошлись бы 113 из 629 —
--      тестовые строки ВХОДЯТ в баланс), is_system_payment (7 из 629),
--      currency (75 из 629), bot_name (58 пользователей имеют COMPLETED-строки
--      более чем от одного бота и сходятся без фильтра по боту — параметра
--      бота у функции и нет).
--
--  11. Таблица users не читается ВООБЩЕ.
--       - 278 из 629 плательщиков вообще отсутствуют в users, и облако всё
--         равно отдаёт им ненулевой баланс (проверено адресно на трёх:
--         1456255940, 727608416, 5877944848 → 100.00). Джойна с users нет.
--       - Дубликаты telegram_id в users на баланс не влияют. Из ~35 дублей
--         только у ОДНОГО есть оплаты — 289259562 (2 строки в users,
--         7 в payments_v2). Облако отдаёт 159105.00, то есть однократную
--         сумму; джойн размножил бы её вдвое (318210.00). Это единственный
--         возможный тест на дубли — других дублирующихся плательщиков нет.
--       - Колонки balance в users не существует вовсе, брать баланс оттуда
--         не из чего.
--
--  12. Аргумент приводится к bigint именно так: `user_telegram_id::bigint`.
--      Ошибка облака на мусоре — 22P02 `invalid input syntax for type bigint:
--      "..."`, на переполнении — 22003 `value "..." is out of range for type
--      bigint`. Приведение через ::numeric исключено: '144022504.0' падает
--      с 22P02. Сравнение через telegram_id::text исключено: тогда мусор
--      возвращал бы 0, а не падал. Пробелы, табы, переводы строк, ведущий '+'
--      и ведущие нули облако принимает — ровно как штатный text->bigint.
--
-- -----------------------------------------------------------------------------
--  ЕДИНСТВЕННОЕ ИЗВЕСТНОЕ РАСХОЖДЕНИЕ ПОРТА С ОБЛАКОМ (и почему это не формула)
-- -----------------------------------------------------------------------------
--
--  Матрица краевых случаев: 35 совпадений из 37. Разошлись ровно два входа:
--
--      '144_022_504'  облако -> 22P02        порт (PG18) -> 195848267.69
--      '0x10'         облако -> 22P02        порт (PG18) -> 0
--
--  Это НЕ разница тел функций, а разница ВЕРСИЙ Postgres. Подчёркнутые
--  разделители и литералы 0x/0o/0b в text->integer появились в PostgreSQL 16.
--  Облако отвергает все четыре формы ('0x10', '0b101', '0o17', '1_0'), то есть
--  под ним Postgres <= 15; Railway — PostgreSQL 18.6 и принимает все четыре
--  ('0x10'::bigint = 16). Любое тело с `::bigint` на PG18 ведёт себя так же.
--
--  Практического следа у этого нет: telegram_id всегда десятичный. Если
--  когда-нибудь потребуется побайтовая совместимость и по мусорному вводу —
--  добавлять НЕ подмену типа, а явную проверку перед приведением
--  (`user_telegram_id !~ '^\s*[+-]?[0-9]+\s*$'` -> RAISE с ERRCODE '22P02'
--  и тем же текстом). Намеренно не сделано: это была бы уже не перенесённая
--  функция, а надстройка над ней.
--
-- -----------------------------------------------------------------------------
--  ЧТО ОСТАЛОСЬ НЕДОКАЗАННЫМ
-- -----------------------------------------------------------------------------
--
--  1. Статус FAILED. В payments_v2 НОЛЬ строк со status='FAILED' — ни в
--     облаке, ни на Railway. Поэтому снаружи НЕЛЬЗЯ отличить
--     `status = 'COMPLETED'` от `status <> 'PENDING'`. Взят первый вариант:
--     он строже и не может завысить баланс. Если строки FAILED когда-нибудь
--     появятся, поведение порта и облака может разъехаться — и проверить это
--     будет можно только тогда.
--
--  2. Типы SUBSCRIPTION_PURCHASE, SUBSCRIPTION_RENEWAL, REFERRAL, SYSTEM.
--     Они есть в enum operation_type, но в данных их НОЛЬ строк. Как их
--     считает облако — неизвестно. Здесь они попадают в `ELSE 0`, то есть
--     не влияют на баланс. Это выведено по аналогии с BONUS (единственным
--     проверенным «прочим» типом), а не измерено.
--
--  3. Округление до 2 знаков. `ROUND(..., 2)` неотличимо от его отсутствия:
--     все stars имеют numeric(12,2), сумма всегда ровно два знака. Отсутствие
--     округления до ЦЕЛОГО доказано (63 из 629 разошлись бы).
--
--  4. LANGUAGE (sql или plpgsql), VOLATILE/STABLE/IMMUTABLE, SECURITY
--     DEFINER/INVOKER, SET search_path и GRANT'ы — снаружи не наблюдаемы.
--     Взято: LANGUAGE sql, STABLE, SECURITY INVOKER (по умолчанию). Проверить
--     доступ роли anon не удалось: переменная SUPABASE_SERVICE_KEY на сервисе
--     пуста, ключа роли anon нет. Если на Railway перед базой встанет
--     PostgREST с RLS — грант и, возможно, SECURITY DEFINER придётся добавить
--     осознанно, это решение развёртывания, а не перенос.
--
--  5. Строки платежей на Railway и в облаке сравнены по 11 колонкам, а не по
--     всем 27. Не сравнивались, в частности, description, metadata,
--     payment_date, cost. На формулу баланса они не влияют (доказано тем, что
--     формула сходится), но утверждать полную идентичность таблиц по этому
--     замеру нельзя.
--
-- -----------------------------------------------------------------------------
--  РАСХОЖДЕНИЕ С get_user_balance_stats_optimized (ВАЖНО, НЕ БАГ ЭТОГО ФАЙЛА)
-- -----------------------------------------------------------------------------
--
--  В sql/balance_functions.sql лежит ДРУГАЯ формула баланса:
--      income(REAL) + income(BONUS) - outcome(REAL)
--  Она не знает про REFUND и не вычитает MONEY_OUTCOME с category='BONUS'.
--  На текущих данных две функции расходятся на 12 пользователях из 629,
--  суммарно на 1483.68 звезды. Здесь воспроизведена именно живая
--  get_user_balance. Который из двух ответов «правильный» с точки зрения
--  бизнеса — этим замером не решается и решаться не должно.
--
-- =============================================================================

BEGIN;

CREATE OR REPLACE FUNCTION public.get_user_balance(user_telegram_id text)
RETURNS numeric
LANGUAGE sql
STABLE
AS $fn$
  SELECT COALESCE(
           SUM(
             CASE p.type
               WHEN 'MONEY_INCOME'  THEN  p.stars
               WHEN 'REFUND'        THEN  p.stars
               WHEN 'MONEY_OUTCOME' THEN -p.stars
               ELSE 0
             END
           ),
           0
         )
  FROM public.payments_v2 p
  WHERE p.telegram_id = user_telegram_id::bigint
    AND p.status = 'COMPLETED';
$fn$;

COMMENT ON FUNCTION public.get_user_balance(text) IS
  'Баланс в звёздах = SUM(MONEY_INCOME + REFUND - MONEY_OUTCOME) по payments_v2 при status=COMPLETED; type=BONUS, PENDING и category не учитываются, is_test/is_system_payment учитываются. Нет строк -> 0 (не NULL). Порт живой облачной функции: совпал побайтово на 629/629 плательщиках. Недоказано: поведение на status=FAILED и на типах SUBSCRIPTION_*/REFERRAL/SYSTEM — таких строк в данных нет. См. заголовок sql/railway-rpc/get_user_balance.sql';

COMMIT;
