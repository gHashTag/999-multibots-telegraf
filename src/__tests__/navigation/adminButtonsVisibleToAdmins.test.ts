import { describe, it, expect, vi, beforeEach } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'

/**
 * АДМИНСКИЕ КНОПКИ НЕ ВИДЕЛ НИКТО — ВКЛЮЧАЯ САМОГО ВЛАДЕЛЬЦА.
 *
 * Владелец жаловался, что кнопки в боте не работают. Аудит показал, что все
 * восемь кнопок главного меню исправны, а настоящая поломка глубже: в обоих
 * построителях клавиатуры стояло безусловное
 *
 *     if (item.adminOnly) continue
 *
 * без единой проверки «а ты админ?». То есть «🎬 ИИ Рилс» и «🔍 Парсинг
 * Instagram» не рисовались НИКОМУ и никогда, хотя их обработчики
 * зарегистрированы и срабатывают, если набрать название текстом.
 *
 * Это не «скрыто от посторонних», а «спрятано от собственного владельца» —
 * ровно тот признак, на который он и жаловался: кнопки нет на экране, значит
 * она «не работает».
 *
 * Проверка читает исходник, потому что сломано было РЕШЕНИЕ о показе, а не
 * функция: юнит-тест на построитель клавиатуры прошёл бы и со старым кодом,
 * если не знать, чего именно в списке не хватает.
 */
const КОРЕНЬ = path.join(__dirname, '..', '..', '..')
const читать = (о: string) => fs.readFileSync(path.join(КОРЕНЬ, о), 'utf8')

/** Исходник без комментариев: закрепляем поведение, а не рассказ о нём. */
const безКомментариев = (s: string) =>
  s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

const КЛАВИАТУРА = безКомментариев(читать('src/navigation/helpers/menuKeyboard.ts'))

describe('админский пункт скрыт от не-админа, а не от всех', () => {
  it('нет безусловного отбрасывания adminOnly', () => {
    expect(КЛАВИАТУРА).not.toMatch(/if\s*\(\s*item\.adminOnly\s*\)/)
  })

  it('обе версии построителя спрашивают про админа', () => {
    /*
     * Версии две — синхронная и асинхронная, — и меню «Профиля» зовёт именно
     * вторую. Починить одну означало бы оставить половину пользователей без
     * кнопок и не узнать об этом.
     */
    const вхождений = КЛАВИАТУРА.match(/item\.adminOnly && !админ/g) || []
    expect(вхождений.length).toBe(2)
  })

  it('список админов ОДИН и уже существующий', () => {
    // Второй список админов разошёлся бы с первым — вопрос только когда.
    expect(КЛАВИАТУРА).toContain("import { isAdmin } from '@/middleware/adminOnly'")
    expect(КЛАВИАТУРА).not.toContain('ADMIN_IDS_ARRAY')
  })
})

describe('isAdmin отвечает по списку, а не всем подряд', () => {
  beforeEach(() => vi.resetModules())

  it('в списке — да, вне списка — нет', async () => {
    vi.doMock('@/config', () => ({ ADMIN_IDS_ARRAY: [144022504, 352374518] }))
    const { isAdmin } = await import('@/middleware/adminOnly')
    expect(isAdmin(144022504)).toBe(true)
    expect(isAdmin(999)).toBe(false)
    // Ноль — то, во что превращается отсутствующий ctx.from.id. Он не должен
    // случайно оказаться админом.
    expect(isAdmin(0)).toBe(false)
  })
})

describe('одна сцена — одна регистрация', () => {
  const РЕГИСТРАЦИЯ = безКомментариев(
    читать('src/navigation/registerCommands.ts')
  )

  it('neuroPhotoWizard больше не регистрируется рядом со своей V2', () => {
    /*
     * Обе сцены объявлены под ОДНИМ id ('neuro_photo', ModeEnum.NeuroPhoto).
     * У Telegraf карта сцен last-write-wins, поэтому V2 молча затенял V1: в
     * работе всегда был только V2, а регистрация V1 создавала впечатление,
     * что живы обе.
     *
     * Поведение не меняется — побеждал V2 и раньше. Убрана иллюзия выбора.
     */
    /*
     * Якорь — САМА функция регистрации, а не первое совпадение имени сцены.
     *
     * Сначала окно бралось от первого `subscriptionScene,`, а он встречается
     * в списке ИМПОРТОВ, за сотни строк до регистрации. Проверка читала не тот
     * список: мутация, вернувшая двойную регистрацию, её не уронила. Поймано
     * этой самой мутацией — то есть тест сторожил не то, что обещал.
     */
    const начало = РЕГИСТРАЦИЯ.indexOf('export function createStage')
    expect(начало).toBeGreaterThan(0)
    const списокСцен = РЕГИСТРАЦИЯ.slice(начало, начало + 3000)
    expect(списокСцен).toContain('neuroPhotoWizardV2,')
    expect(списокСцен).not.toMatch(/^\s*neuroPhotoWizard,\s*$/m)
  })

  it('обе версии по-прежнему объявлены под одним id — иначе повод исчез', () => {
    // Если кто-то разведёт id, эта проверка напомнит перечитать решение выше.
    expect(читать('src/scenes/neuroPhotoWizardV2/index.ts')).toContain(
      "'neuro_photo'"
    )
    expect(читать('src/scenes/neuroPhotoWizard/index.ts')).toContain(
      'ModeEnum.NeuroPhoto'
    )
  })
})
