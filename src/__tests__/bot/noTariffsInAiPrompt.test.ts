import { describe, it, expect } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'

/**
 * ПЕРВЫЙ ЭКРАН НЕ ПРОДАЁТ ТОГО, ЧЕГО НЕТ.
 *
 * Каждому новому человеку бот отвечал: «выберите тарифный план: Free (3
 * фото/день), Basic (299₽), Pro (699₽) или Studio (1999₽)». Владелец: «у нас
 * нет тарифов, мы перепродаём токены с наценкой 200% и зарабатываем на
 * создании рилсов и контент-плана».
 *
 * Модель это не выдумала — так было написано в её системной подсказке. То
 * есть продукт звал платить за несуществующее с самого первого сообщения.
 * Это хуже опечатки: человек уходит, не найдя обещанного, и уходит с
 * ощущением обмана.
 *
 * ЦЕНЫ В ПОДСКАЗКЕ НЕ НАЗЫВАЮТСЯ. Они считаются из себестоимости провайдеров
 * и наценки (billing-shared.ts) и меняются вместе с прайсами; вписанное сюда
 * руками число разошлось бы с кассой молча — ровно так и появились тарифы,
 * которые пришлось убирать.
 */
const КОРЕНЬ = path.join(__dirname, '..', '..', '..')
const ПОДСКАЗКА = (() => {
  const исходник = fs.readFileSync(
    path.join(КОРЕНЬ, 'src/navigation/registerCommands.ts'),
    'utf8'
  )
  const начало = исходник.indexOf("role: 'system'")
  expect(начало).toBeGreaterThan(0)
  // Берём только строковые литералы подсказки, без окружающих комментариев:
  // рассказ о снятых тарифах ДОЛЖЕН остаться в коде и не должен ронять тест.
  const кусок = исходник.slice(начало, начало + 2000)
  return (кусок.match(/'[^']*'/g) || []).join(' ')
})()

describe('системная подсказка ИИ-ответчика', () => {
  it('не называет ни одного тарифа', () => {
    for (const слово of [
      'Тарифы',
      'тарифный план',
      'Basic',
      'Pro (',
      'Studio',
    ]) {
      expect(ПОДСКАЗКА).not.toContain(слово)
    }
  })

  it('не называет цен — они живут в прайсе, а не в тексте', () => {
    // Любое число рублей или «₽» здесь означает цену, вписанную руками.
    expect(ПОДСКАЗКА).not.toMatch(/\d+\s*₽/)
    expect(ПОДСКАЗКА).not.toMatch(/299|699|1999/)
  })

  it('называет настоящую модель: токены, а не подписка', () => {
    expect(ПОДСКАЗКА).toMatch(/токен/i)
    expect(ПОДСКАЗКА).toMatch(/звёзд/i)
    // И прямо говорит, что подписок нет: молчание об этом человек читает как
    // «просто не нашёл, где купить».
    expect(ПОДСКАЗКА).toMatch(/тарифов и подписок НЕТ/)
  })

  it('запрещает выдумывать цену и баланс', () => {
    /*
     * Модель, спрошенная «сколько стоит видео», охотно называет число. Оно
     * будет неверным: цена считается из себестоимости и наценки в момент
     * запуска. Названная неверная цена — это обещание, за которое платит
     * владелец.
     */
    expect(ПОДСКАЗКА).toMatch(/не выдумывай/)
  })
})
