/**
 * Bot API 9.0 replaced `BusinessConnection.can_reply` with `rights.can_reply`
 * (BusinessBotRights). Reading only the old field yields `undefined` on every
 * connection Telegram sends today, which the reply path treats as "cannot
 * reply" -- so every business DM was dropped. Accept both shapes.
 */
export function canReplyOf(connection: BusinessConnection): boolean {
  return connection.rights?.can_reply === true || connection.can_reply === true
}

/**
 * The registry is process memory: after a redeploy it is empty, and Telegram
 * only sends `business_connection` when the link changes, not on restart. A
 * business_message from an unknown connection id is resolved through
 * getBusinessConnection and cached exactly like a live update would be.
 */
async function lookupConnection(
  connId: string,
  bot: Telegraf<any>
): Promise<ConnectionInfo | undefined> {
  try {
    const fetched = (await (bot.telegram as any).callApi(
      'getBusinessConnection',
      { business_connection_id: connId }
    )) as BusinessConnection
    handleBusinessConnection(fetched)
    return connections.get(connId)
  } catch (error) {
    logger.warn('[Business] getBusinessConnection failed', {
      connId,
      error: error instanceof Error ? error.message : String(error),
    })
    return undefined
  }
}

/**
 * CONNECTION ID -> WHEN ITS CORRESPONDENCE IMPORT LAST STARTED (ms).
 *
 * It used to be a `Set` the guard ADDED TO BEFORE doing the work, and never
 * restored on failure. Proven live: an owner connected their account, the
 * one-shot import of their whole correspondence timed out against the 170 s
 * ceiling `callTool` imposes (modelSwitch.ts:70) while walking
 * {limit: 2000, depth: 500}, the catch warned, and the flag stayed set for the
 * life of the process. Within a process `handleBusinessConnection` runs for a
 * given id at most once more, so that was the only second chance there was:
 * the owner then used a CRM that silently had no history in it, and nobody was
 * told. Every "the bot doesn't remember our conversations" report traces here.
 *
 * The same file already had the correct shape 330 lines below --
 * `notifyOwnerOfLead` deletes its guard key in the catch. The two now agree.
 *
 * A timestamp rather than a boolean so a process that stays up for weeks is not
 * poisoned by one bad day either: a SUCCESSFUL import is not repeated inside
 * INGEST_REPEAT_AFTER_MS, and after it the walk may refresh. This is NOT the
 * 5-second debounce of navigation/registerCommands.ts: that is a double-tap
 * guard, this is a once-per-connection import.
 */
const ingestStartedAt = new Map<string, number>()
export const INGEST_REPEAT_AFTER_MS = 6 * 60 * 60 * 1000

/**
 * How long a walk that outlived our wait is left alone. Long enough for a real
 * 2000-dialog import to finish, short enough that a render which died mid-walk
 * gets tried again the same hour rather than the next day.
 */
export const INGEST_RETRY_AFTER_TIMEOUT_MS = 30 * 60 * 1000

async function mirrorExchange(
  owner: number,
  lead: number,
  name: string,
  messages: Array<{ msg_id: number; at: number; out: boolean; text: string }>
): Promise<void> {
  try {
    const { mirrorDm } = await import('@/services/modelSwitch')
    const r = await mirrorDm(String(owner), String(lead), name, messages)
    if (!r.ok) {
      logger.warn('[Business] DM not mirrored', { lead, error: r.error })
    }
  } catch (error) {
    logger.warn('[Business] DM mirror threw', {
      lead,
      error: error instanceof Error ? error.message : String(error),
    })
  }
}

/**
 * May the correspondence import run for this connection now? Yes when it has
 * never run, when the last attempt FAILED (the catch gave the claim back), or
 * when the last successful walk is older than INGEST_REPEAT_AFTER_MS. Prunes
 * expired entries on the way so the map cannot grow without bound.
 */
export function shouldIngest(connId: string, now = Date.now()): boolean {
  for (const [id, at] of ingestStartedAt)
    if (now - at > INGEST_REPEAT_AFTER_MS) ingestStartedAt.delete(id)
  return !ingestStartedAt.has(connId)
}

async function ingestOnConnect(owner: string, connId: string): Promise<void> {
  try {
    const { ingestChats } = await import('@/services/modelSwitch')
    const r = await ingestChats(owner)
    logger.info('[Business] correspondence ingested on connect', {
      connId,
      owner,
      people: r.people,
      new: r.messages_new,
      zep: r.zep_mirrored,
    })
  } catch (error) {
    /*
     * A TIMEOUT IS NOT A FAILURE, AND THIS IS THE ONE THAT ALWAYS TIMES OUT.
     *
     * The walk asked for here is `limit: 2000, depth: 500` -- every dialog the
     * account has, five hundred messages deep, each dialog its own MTProto
     * round trip plus a Postgres write plus a Zep mirror. The render's own
     * module says it "takes minutes". The client budget is 170 seconds. So the
     * abort is the expected end of a healthy import, arriving while the render
     * is still walking -- nothing over there was cancelled (no signal reaches a
     * tool handler), and the history does land.
     *
     * Releasing the claim here made that worse than cosmetic: the next business
     * event started a SECOND full 2000-dialog walk on top of the first. Three
     * pages a day for one owner (17:54, 21:35, 01:22) were three of these.
     *
     * So the claim is kept -- but re-dated to expire in
     * INGEST_RETRY_AFTER_TIMEOUT_MS instead of six hours, because a render that
     * died mid-walk must not lock the import out for the rest of the day.
     */
    if (renderIsStillWorking(error)) {
      ingestStartedAt.set(
        connId,
        Date.now() - INGEST_REPEAT_AFTER_MS + INGEST_RETRY_AFTER_TIMEOUT_MS
      )
      logger.info('[Business] correspondence import still walking', {
        connId,
        owner,
        waited: error instanceof Error ? error.message : String(error),
      })
      return
    }
    /*
     * THE GUARD IS RELEASED FIRST, so the next connection event for this id
     * gets a real second chance. Marking the ATTEMPT instead of the SUCCESS is
     * what made this failure permanent for the life of the process.
     */
    ingestStartedAt.delete(connId)
    /*
     * AND IT PAGES. An import that silently does not happen is worse than one
     * that visibly fails: this is our machinery failing, not a customer doing
     * anything, so by the house rule it belongs on the owner's phone. The
     * transport's fingerprint throttle (alertThrottle.ts, 10 min) keeps a
     * flapping render from turning this into a flood.
     */
    logger.error('[Business] ingest on connect failed', {
      connId,
      owner,
      error: error instanceof Error ? error.message : String(error),
    })
  }
}

/**
 * THE LINK AND THE BUTTON AT ONCE -- but only when the client asked to pay.
 *
 * A Stars invoice link in the answer opens the payment sheet when tapped;
 * a button under the message makes that one tap obvious. The answer carries
 * a link only after the person themselves asked to pay or buy (the agent's
 * prompt forbids offering first), so the button never appears uninvited.
 */
export function payButton(reply: string): { text: string; url: string } | null {
  const row = payRow(reply)
  if (!row) return null
  const b = row[0] as { text: string; url?: string }
  return b.url ? { text: b.text, url: b.url } : null
}

// --- Handlers ---

export function handleBusinessConnection(connection: BusinessConnection): void {
  if (connection.is_enabled) {
    connections.set(connection.id, {
      userId: connection.user.id,
      ownerChatId: connection.user_chat_id ?? connection.user.id,
      canReply: canReplyOf(connection),
      connectedAt: connection.date,
    })
    logger.info('[Business] Connection established', {
      connectionId: connection.id,
      userId: connection.user.id,
      canReply: canReplyOf(connection),
    })
    /*
     * THE MEMORY STARTS NOW. The owner connected their account so the bot
     * answers their clients as them; before the first answer the agent must
     * know the history. Every dialog, deep, into Postgres and Zep -- once
     * per connection per process, in the background.
     */
    if (shouldIngest(connection.id)) {
      // Claimed BEFORE the work only so two events arriving together cannot
      // start two walks; `ingestOnConnect` gives the claim back if it fails.
      ingestStartedAt.set(connection.id, Date.now())
      void ingestOnConnect(String(connection.user.id), connection.id)
    }
  } else {
    connections.delete(connection.id)
    logger.info('[Business] Connection disabled', {
      connectionId: connection.id,
      userId: connection.user.id,
    })
  }
}

export async function handleBusinessMessage(
  msg: BusinessMessage,
  bot: Telegraf<any>,
  botUsername: string
): Promise<void> {
  const connId = msg.business_connection_id
  const conn = connections.get(connId) ?? (await lookupConnection(connId, bot))

  if (!conn || !conn.canReply) {
    logger.warn('[Business] No active connection or cannot reply', { connId })
    return
  }

  const chatId = msg.chat.id
  const senderName = msg.from?.first_name || msg.chat.first_name || 'User'
  const chatKey = `${connId}:${chatId}`
  const sendAsOwner = (text: string, extra: Record<string, unknown> = {}) =>
    bot.telegram.sendMessage(chatId, text, {
      ...extra,
      business_connection_id: connId,
    } as any)

  // Telegram's own away/greeting messages and the bot's outgoing messages come
  // through the same stream; answering them would loop.
  if (msg.is_from_offline || msg.sender_business_bot) return

  // The owner typed in this chat themselves: hand the conversation to them.
  if (msg.from?.id === conn.userId) {
    ownerTakeoverUntil.set(chatKey, Date.now() + OWNER_TAKEOVER_MS)
    logger.info('[Business] Owner replied manually, AI paused', {
      connId,
      chatId,
    })
    return
  }
  const pausedUntil = ownerTakeoverUntil.get(chatKey) ?? 0
  if (pausedUntil > Date.now()) {
    ensureToday()
    stats.takeoverSkipped++
    logger.info('[Business] Owner takeover active, AI silent', {
      connId,
      chatId,
    })
    return
  }
  ownerTakeoverUntil.delete(chatKey)

  void notifyOwnerOfLead(msg, conn, bot, chatKey)

  // Media: copy it to the owner's own chat first (they asked to SEE what the
  // customer sends), then either answer the caption through the LLM or answer
  // the bare media with a service offer. Never a dead end.
  const media = customerMedia(msg)
  let plan: AgentMessagePlan | null = null
  if (media) {
    ensureToday()
    stats.mediaRelayed++
    await relayMediaToOwner(msg, media, conn, bot)
    /*
     * THE AGENT KEEPS, SEES AND HEARS THE FILE.
     *
     * Measured 2026-09-13: this branch re-sent the file to the owner, told
     * the model "[the client sent a photo]" and dropped the bytes -- a
     * description of a file, never the file. Now the same helper the bot
     * chat uses fetches it once through the token-bearing link, puts it on
     * OUR shelf and hands back marker lines the provider can open; the
     * shelf URLs are indexed per client (media library). The Telegram link
     * is used inside `buildAgentTurn` and never stored or logged.
     *
     * One message = one turn. The bot chat's album buffer is NOT reused
     * here: a business album arrives as separate updates too, but each part
     * is relayed and answered on its own, so a part that never comes does
     * not cost the client a reply.
     */
    plan = await buildAgentTurn(bot.telegram as unknown as FileFetcher, [msg])
    if (plan.stored.length) {
      rememberClientMediaQuietly(
        String(conn.userId),
        String(chatId),
        'business',
        mediaItemsFrom(plan, msg.caption ?? null)
      )
    }
  }

  const caption = msg.caption?.trim()
  const markers = plan?.stored.map(s => s.line) ?? []
  // With a stored file the note is a human-readable prefix above the marker
  // lines; when every file was refused, the caption travels the way it
  // always did, so the client still gets an answer to their words.
  const text =
    msg.text ??
    (media && markers.length
      ? [`${media.note}.`, caption, ...markers].filter(Boolean).join('\n')
      : media && caption
        ? `[${media.note}] ${caption}`
        : undefined)
  if (!text) {
    ensureToday()
    stats.nonTextDropped++
    logger.info('[Business] Non-text message', {
      connId,
      chatId,
      kind: media?.field ?? 'other',
    })
    if (media) {
      const card = SERVICE_CARDS.find(c => c.key === media.card)
      try {
        // Why the file did not make it (too big, did not download) and the
        // service offer, in ONE message: two would read as nagging.
        const said = plan?.refusal
          ? `${plan.refusal}\n\n${media.reply}`
          : media.reply
        await sendAsOwner(said, {
          reply_markup: {
            inline_keyboard: [
              [
                {
                  text: '🚀 Открыть в боте',
                  url: card
                    ? deepLink(botUsername, card)
                    : `https://t.me/${botUsername}?start=${LEAD_START_PARAM}`,
                },
              ],
            ],
          },
        })
      } catch (error) {
        logger.warn('[Business] Media reply failed', {
          error: error instanceof Error ? error.message : String(error),
          connId,
          chatId,
        })
      }
    }
    return
  }

  const flightKey = String(chatId)
  if (businessReplyInFlight.has(flightKey)) {
    logger.info('[Business] Reply already in flight — dropping duplicate', {
      connId,
      chatId,
    })
    return
  }
  businessReplyInFlight.add(flightKey)

  try {
    const messages = buildBusinessMessages(text, senderName, botUsername)

    void bot.telegram
      .sendChatAction(chatId, 'typing', {
        business_connection_id: connId,
      } as any)
      .catch(() => undefined)

    const reply = await answerClient(String(chatId), text, () =>
      chatWithAI(messages, undefined, {
        telegramId: String(chatId),
        botName: `business_${botUsername}`,
      })
    )

    const pay = payButton(reply)
    const keyboard = {
      reply_markup: {
        inline_keyboard: [
          ...(pay ? [[pay]] : []),
          [
            {
              text: '🚀 Открыть в боте',
              url: replyButtonUrl(botUsername, text),
            },
          ],
        ],
      },
    }
    // Telegram refuses a text over 4096 characters outright: the answer is
    // split, and the keyboard rides on the LAST chunk.
    const parts = разбитьДлинное(reply) // cyrillic-ok: pre-existing helper name
    let sentAsOwner: { message_id?: number } | undefined
    for (let i = 0; i < parts.length; i++) {
      const last = i === parts.length - 1
      sentAsOwner = (await sendAsOwner(parts[i], last ? keyboard : {})) as
        | { message_id?: number }
        | undefined
    }

    /*
     * THE EXCHANGE GOES INTO THE MEMORY AT ONCE: their message and the
     * answer, with Telegram's own ids, so the next question is answered
     * from a memory that already has this one. Best effort, off the path.
     */
    void mirrorExchange(conn.userId, chatId, senderName, [
      { msg_id: msg.message_id, at: msg.date, out: false, text },
      ...(sentAsOwner?.message_id
        ? [
            {
              msg_id: sentAsOwner.message_id,
              at: Math.floor(Date.now() / 1000),
              out: true,
              text: reply,
            },
          ]
        : []),
    ])

    ensureToday()
    stats.messagesHandled++
    stats.uniqueUsers.add(String(chatId))

    logger.info('[Business] Reply sent', { connId, chatId })
  } catch (error) {
    logger.error('[Business] Failed to reply', {
      error: error instanceof Error ? error.message : String(error),
      connId,
      chatId,
    })
  } finally {
    businessReplyInFlight.delete(flightKey)
  }
}

/**
 * Re-send a customer's media into the owner's own chat with the bot, captioned
 * with who sent it and from which chat. file_ids are bot-scoped, so the id
 * from the business update is valid for the owner's chat too. Non-fatal: on
 * failure the owner gets a text pointer to the chat instead.
 */
async function relayMediaToOwner(
  msg: BusinessMessage,
  media: CustomerMedia,
  conn: ConnectionInfo,
  bot: Telegraf<any>
): Promise<void> {
  const name = escapeHtml(
    sanitizeSenderName(msg.from?.first_name || msg.chat.first_name)
  )
  const caption = msg.caption?.trim()
  const html =
    `📎 ${media.label} от <b>${name}</b> (chat ${msg.chat.id})` +
    (caption ? `\n«${escapeHtml(caption.slice(0, 500))}»` : '') +
    `\nОткрыть чат: tg://user?id=${msg.chat.id}`
  try {
    if (media.method === 'sendVideoNote') {
      await bot.telegram.sendVideoNote(conn.ownerChatId, media.fileId)
      await bot.telegram.sendMessage(conn.ownerChatId, html, {
        parse_mode: 'HTML',
      })
    } else {
      await (bot.telegram as any)[media.method](
        conn.ownerChatId,
        media.fileId,
        {
          caption: html,
          parse_mode: 'HTML',
        }
      )
    }
    logger.info('[Business] Media relayed to owner', {
      kind: media.field,
      chatId: msg.chat.id,
    })
  } catch (error) {
    logger.warn('[Business] Media relay failed, sending a pointer instead', {
      kind: media.field,
      error: error instanceof Error ? error.message : String(error),
    })
    try {
      await bot.telegram.sendMessage(
        conn.ownerChatId,
        `${html}\n(переслать сам файл не удалось — откройте чат)`,
        { parse_mode: 'HTML' }
      )
    } catch (inner) {
      logger.warn('[Business] Media pointer failed too', {
        error: inner instanceof Error ? inner.message : String(inner),
      })
    }
  }
}

/**
 * Tell the owner about a customer once per chat per UTC day, in the owner's own
 * private chat with the bot (NOT through the business connection, which would
 * post into the customer's chat). Fire-and-forget: a failed notification never
 * blocks the reply. The dedup map is process memory and resets on redeploy.
 */
async function notifyOwnerOfLead(
  msg: BusinessMessage,
  conn: ConnectionInfo,
  bot: Telegraf<any>,
  chatKey: string
): Promise<void> {
  const day = todayKey()
  if (leadNotifiedOn.get(chatKey) === day) return
  leadNotifiedOn.set(chatKey, day)
  try {
    // The menu under the notification: who this is, take over, prepare a
    // reply, later, refuse -- for an owner who is an admin of this bot (a
    // farm owner outside ADMIN_IDS would press buttons nobody answers).
    const menu = ADMIN_IDS_ARRAY.includes(Number(conn.userId))
      ? dmLeadMenu(msg.chat.id)
      : undefined
    await bot.telegram.sendMessage(
      conn.ownerChatId,
      buildLeadNotification(msg),
      {
        parse_mode: 'HTML',
        ...(menu ? { reply_markup: menu.reply_markup } : {}),
      }
    )
    ensureToday()
    stats.leadsNotified++
    logger.info('[Business] Owner notified of a lead', { chatKey })
  } catch (error) {
    leadNotifiedOn.delete(chatKey)
    logger.warn('[Business] Owner lead notification failed', {
      error: error instanceof Error ? error.message : String(error),
      chatKey,
    })
  }
}

// --- Raw middleware (Telegraf 4.16.3 doesn't support business events natively) ---

export function createBusinessMiddleware(bot: Telegraf<any>) {
  bot.use(async (ctx: any, next: () => Promise<void>) => {
    const update = ctx.update

    if (update.business_connection) {
      handleBusinessConnection(update.business_connection as BusinessConnection)
      return
    }

    if (update.business_message) {
      // botInfo is filled by launch(), after this middleware is registered:
      // read the username per message or the sales prompt names an empty bot.
      await handleBusinessMessage(
        update.business_message as BusinessMessage,
        bot,
        bot.botInfo?.username || ''
      )
      return
    }

    return next()
  })
}

