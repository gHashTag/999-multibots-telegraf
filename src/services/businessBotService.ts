/**
 * What the agent is told about a sticker: its emoji, and whether it moves.
 * An animated sticker is gzipped Lottie and a video one is WebM -- neither can
 * be looked at, so the emoji the sender picked is the meaning that travels.
 */
export function stickerNote(sticker: BusinessMessage['sticker']): string {
  const moving = sticker?.is_animated
    ? 'анимированный стикер'
    : sticker?.is_video
      ? 'видеостикер'
      : 'стикер'
  const emoji = sticker?.emoji?.trim()
  return `Клиент прислал ${moving}${emoji ? ` ${emoji}` : ''}`
}

/** A sticker whose bytes are a picture a vision model can look at. */
function isStaticSticker(msg: BusinessMessage): boolean {
  return Boolean(
    msg.sticker && !msg.sticker.is_animated && !msg.sticker.is_video
  )
}

interface CustomerMedia extends MediaKind {
  fileId: string
}

export function customerMedia(msg: BusinessMessage): CustomerMedia | undefined {
  for (const kind of MEDIA_KINDS) {
    const value = msg[kind.field]
    if (!value) continue
    const fileId = Array.isArray(value)
      ? value[value.length - 1]?.file_id
      : (value as { file_id?: string }).file_id
    if (!fileId) continue
    if (kind.field === 'sticker')
      return { ...kind, fileId, note: stickerNote(msg.sticker) }
    return { ...kind, fileId }
  }
  return undefined
}
const LEAD_START_PARAM = 'dm'

export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

/** The button under every AI reply: the service the customer asked about, or the bot itself. */
export function replyButtonUrl(botUsername: string, text: string): string {
  const card = matchCards(text)[0]
  return card
    ? deepLink(botUsername, card)
    : `https://t.me/${botUsername}?start=${LEAD_START_PARAM}`
}

export function buildLeadNotification(
  msg: BusinessMessage,
  o: { assistantOff?: boolean } = {}
): string {
  const name = escapeHtml(
    sanitizeSenderName(msg.from?.first_name || msg.chat.first_name)
  )
  const username = msg.from?.username
    ? ` (@${escapeHtml(msg.from.username)})`
    : ''
  const preview = escapeHtml((msg.text || msg.caption || '').slice(0, 200))
  const body = preview ? `\n«${preview}»` : '\n(сообщение без текста)'
  return (
    `🆕 Новый клиент в вашей личке: <b>${name}</b>${username}${body}\n\n` +
    `Открыть чат: tg://user?id=${msg.chat.id}\n` +
    (o.assistantOff
      ? `🔕 Этот клиент попросил выключить автоответы — ассистент здесь молчит, отвечаете только вы.`
      : `Ответите сами — я замолчу в этом чате на 30 минут.`)
  )
}

