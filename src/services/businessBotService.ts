interface CustomerMedia extends MediaKind {
  fileId: string
}

export function customerMedia(msg: BusinessMessage): CustomerMedia | undefined {
  for (const kind of MEDIA_KINDS) {
    const value = msg[kind.field]
    if (!value) continue
    const fileId = Array.isArray(value)
      ? value[value.length - 1]?.file_id
      : (value as { file_id?: string }).file_id
    if (fileId) return { ...kind, fileId }
  }
  return undefined
}
const LEAD_START_PARAM = 'dm'

export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

/** The button under every AI reply: the service the customer asked about, or the bot itself. */
export function replyButtonUrl(botUsername: string, text: string): string {
  const card = matchCards(text)[0]
  return card
    ? deepLink(botUsername, card)
    : `https://t.me/${botUsername}?start=${LEAD_START_PARAM}`
}

export function buildLeadNotification(msg: BusinessMessage): string {
  const name = escapeHtml(
    sanitizeSenderName(msg.from?.first_name || msg.chat.first_name)
  )
  const username = msg.from?.username
    ? ` (@${escapeHtml(msg.from.username)})`
    : ''
  const preview = escapeHtml((msg.text || msg.caption || '').slice(0, 200))
  const body = preview ? `\n«${preview}»` : '\n(сообщение без текста)'
  return (
    `🆕 Новый клиент в вашей личке: <b>${name}</b>${username}${body}\n\n` +
    `Открыть чат: tg://user?id=${msg.chat.id}\n` +
    `Ответите сами — я замолчу в этом чате на 30 минут.`
  )
}

interface DailyStats {
  date: string
  messagesHandled: number
  uniqueUsers: Set<string>
  leadsNotified: number
  nonTextDropped: number
  mediaRelayed: number
  takeoverSkipped: number
}

let stats: DailyStats = {
  date: todayKey(),
  messagesHandled: 0,
  uniqueUsers: new Set(),
  leadsNotified: 0,
  nonTextDropped: 0,
  mediaRelayed: 0,
  takeoverSkipped: 0,
}

function todayKey(): string {
  return new Date().toISOString().slice(0, 10)
}

function ensureToday(): void {
  const key = todayKey()
  if (stats.date !== key) {
    stats = {
      date: key,
      messagesHandled: 0,
      uniqueUsers: new Set(),
      leadsNotified: 0,
      nonTextDropped: 0,
      mediaRelayed: 0,
      takeoverSkipped: 0,
    }
  }
}

