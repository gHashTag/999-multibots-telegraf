interface ConnectionInfo {
  userId: number
  /** Private chat with the owner (user_chat_id); lead notifications go here, never through the connection. */
  ownerChatId: number
  canReply: boolean
  connectedAt: number
}

const connections = new Map<string, ConnectionInfo>()

// Per-sender single-flight: while a reply is being generated for a chat,
// drop further messages from it so one sender cannot spawn many concurrent
// (paid, ~30s) LLM predictions. Added on entry, removed in finally — bounded
// to the set of chats with a reply currently in flight.
const businessReplyInFlight = new Set<string>()

/** Owner replied manually in a chat: the AI stays silent there until this time (ms). */
export const OWNER_TAKEOVER_MS = 30 * 60 * 1000
const ownerTakeoverUntil = new Map<string, number>()

/**
 * The owner takes a client's chat over from a button ("🤫 Отвечу сам"):
 * the AI stays quiet there for `ms`, exactly as when the owner types in it.
 * Returns how many connections were paused.
 */
export function pauseAiFor(
  chatId: number | string,
  ms = OWNER_TAKEOVER_MS,
  ownerUserId?: number
): number {
  let paused = 0
  for (const [connId, conn] of connections) {
    if (ownerUserId !== undefined && conn.userId !== ownerUserId) continue
    ownerTakeoverUntil.set(`${connId}:${chatId}`, Date.now() + ms)
    paused += 1
  }
  return paused
}

