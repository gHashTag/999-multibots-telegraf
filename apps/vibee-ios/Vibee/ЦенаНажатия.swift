import Foundation

/**
 * Сколько спишут за одно нажатие — С УЧЁТОМ ДЛИТЕЛЬНОСТИ.
 *
 * Экран показывал цену СЕКУНДЫ и сравнивал с ней остаток. Для видео это
 * неверно вдвойне: длительность выбрана на том же экране, то есть точная сумма
 * известна — и не считалась.
 *
 * Замер: 100 токенов, `kling/v3-turbo` (36/с), 10 с. Кнопка активна и
 * подписана «· 36/с», человек жмёт, ждёт — и получает 402 «нужно 360, есть
 * 100». Это ровно тот отказ ПОСЛЕ нажатия, ради устранения которого проверка
 * до нажатия и появилась.
 *
 * Для липсинка длительность неизвестна: её задаёт готовая озвучка, а не
 * человек. Там `секунды` = nil, сумма честно не называется, и подпись остаётся
 * «за секунду» — обещать точное число, которого не знаем, хуже, чем назвать
 * единицу измерения.
 */
struct ЦенаНажатия: Equatable {
  /// Что списать сейчас. nil — сумма неизвестна (посекундная работа без
  /// заданной длительности).
  let всего: Int?
  /// Цена одной секунды, если работа посекундная.
  let заСекунду: Int?

  var посекундная: Bool { заСекунду != nil }


  /// Как называется то, за что берут: «с» у секунд, «1000 зн.» у знаков.
  let мераПодпись: String?

  /**
   * Один расчёт вместо частных случаев.
   *
   * Сначала здесь была только посекундность. Когда озвучка стала считаться за
   * тысячу знаков, соблазн был добавить второй флаг — и получить третью
   * ветку на третьей единице. Множитель и его название общие: экран знает,
   * ЧЕМ мерить, из ответа сервера, а не из своего перечисления.
   */
  static func посчитать(
    единица: Int?,
    мера: String?,
    множитель: Int?
  ) -> ЦенаНажатия {
    guard let единица else {
      return ЦенаНажатия(всего: nil, заСекунду: nil, мераПодпись: nil)
    }
    guard let мера else {
      return ЦенаНажатия(всего: единица, заСекунду: nil, мераПодпись: nil)
    }
    guard let множитель, множитель > 0 else {
      // Меру знаем, количество нет — называем цену меры, а не выдуманную сумму.
      return ЦенаНажатия(всего: nil, заСекунду: единица, мераПодпись: мера)
    }
    return ЦенаНажатия(
      всего: единица * множитель,
      заСекунду: единица,
      мераПодпись: мера
    )
  }

  /// Подпись на кнопке. «· 360» когда сумма известна, «· 36/с» когда нет.
  var подпись: String? {
    if let всего { return "· \(всего)" }
    if let заСекунду, let мераПодпись { return "· \(заСекунду)/\(мераПодпись)" }
    if let заСекунду { return "· \(заСекунду)" }
    return nil
  }
}

/**
 * Секунды из подписи чипа длительности: «6s» → 6, «10s» → 10.
 *
 * Возвращает nil, а не единицу: nil означает «не знаем», и на нём подпись
 * честно переключается на цену секунды. Подстановка единицы назвала бы сумму
 * в шесть раз меньше настоящей.
 */
func секундыИзДлительности(_ подпись: String) -> Int? {
  let цифры = подпись.prefix { $0.isNumber }
  guard let n = Int(цифры), n > 0 else { return nil }
  return n
}
