import Foundation

/**
 * ШАБЛОНЫ СЦЕНАРИЯ — сохранённые настройки, которые не надо выставлять заново.
 *
 * В вебе это есть с самого начала (`player/src/pages/Script.tsx`,
 * `scriptTemplatesAtom`), в приложении не было. Разница видна тому, кто
 * пользуется обоими: на телефоне четыре выбора — длительность, ниша, стиль,
 * язык — приходится повторять при каждом запуске.
 *
 * Хранение и правила ОТДЕЛЕНЫ от экрана намеренно: экран в тестах не поднять,
 * а именно в правилах живут случаи, которые ломают чужую работу — пустое имя,
 * повтор, удаление не того.
 */
struct ШаблонСценария: Codable, Identifiable, Equatable {
  let id: String
  let имя: String
  let ниша: String
  let стиль: String
  let секунды: Int
  let язык: String

  /// Что видно в строке под именем: те же значения, только коротко.
  var сводка: String { "\(ниша) · \(стиль) · \(секунды)с" }
}

enum ХранилищеШаблонов {
  /// Ключ в UserDefaults. Меняешь — старые шаблоны исчезают у всех, поэтому
  /// он назван один раз и здесь.
  static let ключ = "vibee.шаблоныСценария"

  /**
   * Добавить шаблон. Возвращает НОВЫЙ список, а не меняет старый на месте:
   * так правило проверяется значением, а не наблюдением за состоянием.
   *
   * - Пустое имя (и имя из одних пробелов) шаблона НЕ создаёт: строка без
   *   подписи в списке неотличима от соседней, и человек удалит не ту.
   * - Повтор имени ЗАМЕЩАЕТ прежний, а не заводит второй. Два «Утро» с
   *   разными настройками — это выбор вслепую.
   */
  static func добавить(
    _ шаблоны: [ШаблонСценария],
    имя: String,
    ниша: String,
    стиль: String,
    секунды: Int,
    язык: String,
    id: String
  ) -> [ШаблонСценария] {
    let чистое = имя.trimmingCharacters(in: .whitespacesAndNewlines)
    guard !чистое.isEmpty else { return шаблоны }
    let новый = ШаблонСценария(
      id: id, имя: чистое, ниша: ниша, стиль: стиль, секунды: секунды, язык: язык
    )
    if let место = шаблоны.firstIndex(where: {
      $0.имя.caseInsensitiveCompare(чистое) == .orderedSame
    }) {
      var копия = шаблоны
      копия[место] = новый
      return копия
    }
    return шаблоны + [новый]
  }

  /// Удалить по id, а не по имени и не по позиции: имена повторяются после
  /// правки, позиции съезжают при удалении соседа.
  static func удалить(_ шаблоны: [ШаблонСценария], id: String) -> [ШаблонСценария] {
    шаблоны.filter { $0.id != id }
  }

  /// Прочитать из хранилища. Испорченные данные дают ПУСТОЙ список, а не сбой:
  /// экран генерации не должен падать из-за старого формата шаблона.
  static func прочитать(_ настройки: UserDefaults = .standard) -> [ШаблонСценария] {
    guard let данные = настройки.data(forKey: ключ) else { return [] }
    return (try? JSONDecoder().decode([ШаблонСценария].self, from: данные)) ?? []
  }

  static func записать(
    _ шаблоны: [ШаблонСценария], в настройки: UserDefaults = .standard
  ) {
    guard let данные = try? JSONEncoder().encode(шаблоны) else { return }
    настройки.set(данные, forKey: ключ)
  }
}

/**
 * СОВЕТЫ ПО СЦЕНАРИЮ — те же четыре, что в вебе.
 *
 * Взяты дословно из `player/src/pages/Script.tsx`, а не написаны заново: две
 * витрины, советующие разное, хуже одной, не советующей ничего.
 */
enum СоветыСценария {
  static let все = [
    "Зацепка в первые 1–3 секунды",
    "3 ключевых пункта и призыв в конце",
    "60–120 слов на 30 секунд",
    "Смена кадра каждые 3–5 секунд",
  ]
}
