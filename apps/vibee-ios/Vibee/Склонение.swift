import Foundation

/**
 * Число с существительным в нужном падеже.
 *
 * ЖИЛО `private` ВНУТРИ `TimelineView`. Стоило показать цену в списке
 * моделей — и на экране появилось «1 токенов»: тот же дефект, что уже
 * чинили в таймлайне («1 дорожек»), только в новом месте. Запертый в одном
 * экране помощник не мешает написать вторую такую же ошибку — он лишь
 * мешает её НЕ написать.
 *
 * Русский требует три формы. Подстановка `\(n) токенов` согласуется только
 * с 5–20, а единица — самый частый случай и в таймлайне (одна дорожка), и
 * в прайсе (модели по 1 токену).
 *
 * 11–14 — исключение: одиннадцать, а не «одиннадцать токен», поэтому сотня
 * отбрасывается до проверки десятков.
 */
func склонение(_ n: Int, _ одна: String, _ две: String, _ пять: String) -> String {
  let сто = abs(n) % 100
  let десять = сто % 10
  let форма: String
  if сто >= 11 && сто <= 14 { форма = пять }
  else if десять == 1 { форма = одна }
  else if десять >= 2 && десять <= 4 { форма = две }
  else { форма = пять }
  return "\(n) \(форма)"
}
