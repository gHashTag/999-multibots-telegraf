// MARK: - Разбор hex

extension Color {
  /**
   * Цвет из hex-строки веба.
   *
   * Принимает ровно тот формат, в котором значение записано в CSS —
   * «#00ff88». Так значение в Swift буквально совпадает со значением в
   * CSS посимвольно, и сверка глазами не требует пересчёта в доли единицы.
   * Пересчёт — это ровно то место, где в прошлый раз завёлся второй зелёный:
   * `Color(red: 0.29, green: 0.87, blue: 0.50)` рядом с системным `.green`.
   */
  init(вебHex: UInt32) {
    self.init(
      .sRGB,
      red: Double((вебHex >> 16) & 0xFF) / 255,
      green: Double((вебHex >> 8) & 0xFF) / 255,
      blue: Double(вебHex & 0xFF) / 255,
      opacity: 1
    )
  }
}

