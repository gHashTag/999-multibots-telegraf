   * ═══════════════════════════════════════════════════════════════════
   * ГЛАВНОЕ, ЧТО НАДО ЗНАТЬ ПРО ЭТОТ ШРИФТ: В НЁМ НЕТ КИРИЛЛИЦЫ.
   * ═══════════════════════════════════════════════════════════════════
   *
   * Замер, а не догадка. Таблица `cmap` файла Outfit-Regular.ttf несёт 360
   * символов, из диапазона U+0400–04FF — НОЛЬ. Тот же ответ у Google Fonts:
   * `css2?family=Outfit:wght@400` отдаёт ровно два `@font-face`, latin и
   * latin-ext (U+0000-00FF и U+0100-02BA…), кириллического подмножества у
   * семейства не существует вовсе.
   *
   * ЧТО ИЗ ЭТОГО СЛЕДУЕТ. Интерфейс приложения русский, значит БОЛЬШИНСТВО
   * подписей как рисовалось системным шрифтом, так и будет: и iOS, и
   * браузер подставляют недостающие глифы из следующего шрифта списка.
   * Outfit виден на латинице, цифрах и знаках — «@username», счётчики,
   * даты, названия моделей.
   *
   * И ЭТО НЕ ОБХОД ЗАДАЧИ, А ЕЁ ТОЧНОЕ ИСПОЛНЕНИЕ. В вебе происходит
   * ровно то же самое: `'Outfit', -apple-system, …` — кириллица там падает
   * на системный шрифт по тому же правилу. Совпасть с вебом — значит
   * повторить и запасную ветку, а не выдумать «русский Outfit», которого в
   * вебе нет.
   *
   * ПОЧЕМУ ЧЕТЫРЕ НАЧЕРТАНИЯ, А НЕ ВОСЕМЬ. Каждое — ~75 КБ в бандле.
   * Приложение просит ровно четыре веса: обычный по умолчанию, `.medium`,
   * `.semibold`, `.bold`. Веб грузит 300-800, но 300 и 800 в приложении не
   * запрашивает никто (`grep '\.font('` по каталогу Vibee), а платить за
   * них весом бандла пришлось бы всем.
   */
  enum Шрифт {

    /**
     * PostScript-имя файла под запрошенный вес.
     *
     * Имена сняты из таблицы `name` самих файлов, а не придуманы:
     * nameID 6 = Outfit-Regular / Outfit-Medium / Outfit-SemiBold /
     * Outfit-Bold. Важно, что берётся именно PostScript-имя: семейство
     * (nameID 1) у Medium и SemiBold — «Outfit Medium» и «Outfit SemiBold»,
     * отдельные семейства, поэтому `Font.custom("Outfit").weight(.medium)`
     * дал бы Regular с синтетическим утолщением, а не настоящее начертание.
     *
     * Незавезённые веса сводятся к ближайшему завезённому осознанно:
     * тонкие — к Regular, сверхжирные — к Bold. Вызовов с такими весами
     * сейчас нет ни одного, но функция обязана быть полной.
     */
    private static func лицо(_ вес: Font.Weight) -> String {
      switch вес {
      case .ultraLight, .thin, .light, .regular: return "Outfit-Regular"
      case .medium: return "Outfit-Medium"
      case .semibold: return "Outfit-SemiBold"
      case .bold, .heavy, .black: return "Outfit-Bold"
      default: return "Outfit-Regular"
      }
    }

    /**
     * ЗАПАСНОЙ ПУТЬ: шрифт не подключён — молча берём системный.
     *
     * Файл может не попасть в бандл (забыли ресурс цели), может не попасть
     * в `UIAppFonts` (забыли Info.plist), может оказаться битым. Во всех
     * трёх случаях `UIFont(name:size:)` возвращает nil, и это ЕДИНСТВЕННАЯ
     * честная проверка: наличие файла на диске ничего не доказывает, пока
     * система его не зарегистрировала.
     *
     * Проверяются все четыре лица, а не одно: набор, где половина файлов
     * доехала, дал бы разнобой начертаний вместо ровного отката.
     *
     * Ленивая статическая переменная считается один раз и потокобезопасно
     * (Swift разворачивает её в dispatch_once).
     */
    static let подключён: Bool = {
      ["Outfit-Regular", "Outfit-Medium", "Outfit-SemiBold", "Outfit-Bold"]
        .allSatisfy { UIFont(name: $0, size: 12) != nil }
    }()

    /**
     * Базовый кегль семантического стиля при СТАНДАРТНОМ размере текста.
     *
     * Спрашиваем систему, а не пишем таблицу из одиннадцати чисел руками:
     * числа Apple меняет между версиями, а `preferredFontDescriptor`
     * всегда отвечает актуальными. Явный `.large` обязателен — без него
     * вернётся кегль С УЧЁТОМ текущей настройки Dynamic Type, а он ниже
     * умножается на неё ещё раз через `relativeTo:`, и текст у людей с
     * крупным шрифтом раздувался бы квадратично.
     */
    private static func базовыйКегль(_ стиль: Font.TextStyle) -> CGFloat {
      let системный: UIFont.TextStyle
      switch стиль {
      case .largeTitle: системный = .largeTitle
      case .title: системный = .title1
      case .title2: системный = .title2
      case .title3: системный = .title3
      case .headline: системный = .headline
      case .subheadline: системный = .subheadline
      case .callout: системный = .callout
      case .footnote: системный = .footnote
      case .caption: системный = .caption1
      case .caption2: системный = .caption2
      default: системный = .body
      }
      return UIFontDescriptor.preferredFontDescriptor(
        withTextStyle: системный,
        compatibleWith: UITraitCollection(preferredContentSizeCategory: .large)
      ).pointSize
    }

    /**
     * Текст семантического стиля. Замена `.font(.footnote)` и родни.
     *
     * `relativeTo:` — не украшение: без него подписи перестают слушаться
     * системной настройки размера текста, и экран, который сегодня читаем
     * человеку со слабым зрением, завтра станет нечитаем. Ровно поэтому
     * экраны и жили на семантических стилях; переход на свою гарнитуру
     * обязан это сохранить, а не разменять на красоту.
     */
    static func стиль(_ с: Font.TextStyle, _ вес: Font.Weight = .regular) -> Font {
      guard подключён else { return .system(с).weight(вес) }
      return .custom(лицо(вес), size: базовыйКегль(с), relativeTo: с)
    }

    /**
     * Текст ЖЁСТКИМ кеглем — там, где число требует веб.
     *
     * `относительно:` оставлен: даже фиксированный кегль масштабируется от
     * своего стиля, иначе четыре таких места превратились бы в четыре
     * нечитаемых пятна при крупном системном шрифте.
     */
    static func кегль(
      _ размер: CGFloat,
      _ вес: Font.Weight = .regular,
      относительно: Font.TextStyle = .body
    ) -> Font {
      guard подключён else {
        return .system(size: размер, weight: вес)
      }
      return .custom(лицо(вес), size: размер, relativeTo: относительно)
    }

    /**
     * Моноширинный — ОСТАЁТСЯ СИСТЕМНЫМ, и это не недоделка.
     *
     * У Outfit моноширинного начертания не существует. Таймкоды, координаты
     * и код входа набраны моноширинным ради того, чтобы цифры не прыгали
     * при смене значения; пропорциональный Outfit эту задачу ломает. Веб в
     * тех же местах поступает так же — `font-family: ui-monospace, …`
     * (PropertiesPanel.css:108,197, ChatAssets.css:76), то есть уходит с
     * Outfit на системный моноширинный.
     */
    static func моно(_ с: Font.TextStyle, _ вес: Font.Weight = .regular) -> Font {
      .system(с, design: .monospaced).weight(вес)
    }

    /// То же, но кеглем-числом: поле ввода кода набрано 34 pt.
    static func моно(_ размер: CGFloat, _ вес: Font.Weight = .regular) -> Font {
      .system(size: размер, weight: вес, design: .monospaced)
    }

    /**
     * Кегль ОДИНОКОГО ЗНАЧКА (SF Symbols) — тоже системный, намеренно.
     *
     * `Image(systemName:)` — глиф системного шрифта, и никакой другой
     * гарнитурой он не рисуется: значков в Outfit нет ни одного. `.font()`
     * на картинке задаёт не гарнитуру, а РАЗМЕР символа, и пропускать этот
     * размер через метрики чужого шрифта значит менять габариты иконок без
     * повода — а часть из них здесь ещё и служит целью нажатия.
     *
     * Функция существует, чтобы это решение было видно в месте вызова:
     * `.font(Тема.Шрифт.значок(.title3))` читается как выбор, а голое
     * `.font(.title3)` — как недоделанная замена.
     *
     * Подписи РЯДОМ со значком (`Label`, VStack с текстом) под это правило
     * НЕ попадают: там буквы, и они идут через `стиль`.
     */
    static func значок(_ с: Font.TextStyle, _ вес: Font.Weight = .regular) -> Font {
      .system(с).weight(вес)
    }

    /// То же для значка с кеглем, заданным числом.
    static func значок(_ размер: CGFloat, _ вес: Font.Weight = .regular) -> Font {
      .system(size: размер, weight: вес)
    }

    /**
     * То же для UIKit: полосе вкладок облик задаётся `UIFont`, а не `Font`.
     *
     * Оговорка честности: все пять подписей вкладок русские, значит видимого
     * эффекта здесь сегодня НЕТ — глифы всё равно придут из системного
     * шрифта. Строка стоит, чтобы источник гарнитуры был один: подписи
     * латиницей или цифрами (а они появятся) не должны разъезжаться с
     * остальным приложением.
     */
    static func uiKit(_ размер: CGFloat, _ вес: Font.Weight = .regular) -> UIFont {
      let системныйВес: UIFont.Weight
      switch вес {
      case .medium: системныйВес = .medium
      case .semibold: системныйВес = .semibold
      case .bold, .heavy, .black: системныйВес = .bold
      default: системныйВес = .regular
      }
      return UIFont(name: лицо(вес), size: размер)
        ?? .systemFont(ofSize: размер, weight: системныйВес)
    }
  }

