   * потому, что описывает не поведение, а ту же сверку с вебом: все четыре
   * кнопки профиля построены ОДИНАКОВО, и «одинаково» стоит записать один
   * раз, а не повторить в двух экранах.
   *
   *   `.profile-files__cta`        Profile.css:1561-1568
   *   `.profile-skills__add`       Profile.css:1601-1612
   *   `.profile-skills__save`      Profile.css:1737-1745
   *   `.profile-skills__install`   Profile.css:1760-1771
   *
   * У всех четырёх `border-radius: 999px`, `border: 1px solid` и `color`,
   * равный цвету рамки. Заливка либо `transparent` (:1608, :1767), либо
   * золото на 10% (:1741).
   *
   * ПОЧЕМУ НЕ СПЛОШНАЯ ЗАЛИВКА АКЦЕНТОМ, как у зелёной кнопки в `Кнопка`.
   * Потому что на золоте читается только чёрный — см. `Профиль.наЗолоте`.
   * Веб развилку «инвертировать подпись или нет» решил третьим способом:
   * не заливать вовсе.
   *
   * Чего это стоит, посчитано по СНЯТОМУ КАДРУ, а не по задуманным числам:
   * заливка кнопки на скриншоте вышла #1e1a05 (золото 10% поверх #050505),
   * и золотой текст на ней даёт 12.42:1. Меньше, чем 14.97:1 у чёрного на
   * сплошном золоте, — и это осознанный размен: 12.4 проходит AAA (порог
   * 7:1) вдвое, зато инверсия подписи и второе правило «какой текст на
   * какой заливке» исчезают совсем.
   */
  struct ПилюляПрофиля: ButtonStyle {
    let цвет: Color
    /// `rgba(255,215,0,0.1)` — Profile.css:1741, либо `.clear` для
    /// `background: transparent` (:1608, :1767).
    let заливка: Color
    /// Кнопка входа тянется во всю ширину, кнопка «Выйти» — по содержимому.
    var воВсюШирину = false

    func makeBody(configuration: Configuration) -> some View {
      configuration.label
        .font(Шрифт.стиль(.subheadline, .medium))
        .foregroundStyle(цвет)
        /**
         * Высота задаётся ВНУТРИ стиля, а не снаружи кнопки.
         *
         * Снаружи `.frame` растягивает контейнер, а подложку рисует стиль по
         * размеру своего содержимого — так на кнопке входа уже вышло 34.3 pt
         * вместо 44 при формально правильном внешнем frame. Здесь frame
         * стоит ДО `.background`, поэтому заливку получает уже растянутое.
         * Проверено на кадре: рамка занимает строки 773..904 из 2622 при
         * масштабе 3x, то есть ровно 44.00 pt.
         */
        .frame(maxWidth: воВсюШирину ? .infinity : nil, minHeight: Кнопка.высота)
        .padding(.horizontal, Отступ.md)
        .background(заливка, in: Capsule())
        .overlay(Capsule().strokeBorder(цвет, lineWidth: Профиль.толщинаГраницы))
        .opacity(configuration.isPressed ? 0.6 : 1)
    }
  }

