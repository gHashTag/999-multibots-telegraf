  /**
   * ЧЕСТНЫЙ СПИСОК НЕСОВПАДЕНИЙ.
   *
   * Здесь лежит то, чему в вебе не нашлось источника. Значения оставлены
   * ровно такими, какими были в Swift, и НЕ подогнаны под похожие вебовские
   * — подгонка превратила бы замер в догадку.
   *
   * Собраны в одном месте по единственной причине: пока они были разбросаны
   * литералами по девяти файлам, «нет источника» было не отличить от
   * «источник есть, просто никто не искал».
   */
  enum БезИсточника {
    /**
     * Цвета типов дорожек таймлайна.
     *
     * Искал: `grep -rn 'track-color\|clip-color'` по player/src — ноль;
     * components/Timeline/Timeline.css и styles.css задают только
     * `--text-muted`/`--text-muted-light` для подписей, но НИ ОДНОГО цвета
     * на тип дорожки. Веб-таймлайн не красит клипы по типу вовсе.
     *
     * Следствие, которое стоит назвать: `видео` = #4ADE80 — ВТОРОЙ зелёный
     * в приложении, отличный от акцента #00ff88, и они попадают на один
     * экран редактора. Свести их было бы правкой на глаз, поэтому не свожу.
     */
    static let дорожкаВидео = Color(вебHex: 0x4ADE80)
    static let дорожкаЗвук = Color(вебHex: 0xFABF3D)
    static let дорожкаКартинка = Color(вебHex: 0x73B5FA)
    static let дорожкаТекст = Color(вебHex: 0xD999FA)
    static let дорожкаПрочее = Color(white: 0.7)

    /**
     * Подпись на цветном клипе: почти-чёрный с тёплым уклоном.
     *
     * В вебе клипы по типу не красятся (см. выше), поэтому и текста на
     * цветной заливке там нет — сравнивать не с чем. Значение сохранено:
     * оно решает реальную задачу контраста на светлой насыщенной заливке.
     */
    static let текстНаКлипе = Color(вебHex: 0x14120F)

    /**
     * Кегль поля ввода кода: 34 pt.
     *
     * Экрана входа по шестизначному коду в вебе НЕТ — веб узнаёт человека по
     * подписи Telegram и ничего не спрашивает. Ближайшие 34px в
     * pages/Blog.css:26 — это заголовок блога, другая роль; брать оттуда
     * число значило бы совпасть цифрой и разойтись смыслом.
     */
    static let кегльКодаВхода: CGFloat = 34

    /**
     * Кегль иконок правого столбца ленты: 26 pt.
     *
     * В вебе размер иконок экшн-бара задан не в CSS, а пропом React
     * `size={…}` в components/Panels/FeedPanel.tsx, и для кнопок лайка,
     * звезды и звука единого значения там нет — соседние элементы идут с 12,
     * 14, 24 и 32. Одного числа, с которым можно совпасть, не существует.
     */
    static let кегльИконокЛенты: CGFloat = 26
  }
