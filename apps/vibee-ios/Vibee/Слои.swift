import Foundation
import SwiftUI

/**
 * Что уже сделано для ролика — и во что это собирается.
 *
 * ЗАЧЕМ. Вкладка «ИИ» умела пять шагов и не помнила ни одного: сгенерировал
 * озвучку — ссылка показалась и пропала при переключении вида. Собрать ролик
 * из этого было нельзя в принципе, потому что собирать было не из чего:
 * результаты нигде не накапливались.
 *
 * Здесь они накапливаются и превращаются в `Composition` — тот самый тип, на
 * котором уже работают таймлайн и рендер. Новый формат не выдумывается: слои
 * ложатся на существующие дорожки (`video`, `image`, `audio`, `text`), иначе
 * редактор получил бы то, чего не понимает.
 *
 * ОДИН ЭКЗЕМПЛЯР НА ПРИЛОЖЕНИЕ. Накопитель переживает переключение вкладок —
 * в этом весь смысл: человек уходит из «ИИ» в «Редактор» и должен застать там
 * свои слои, а не пустой холст.
 */
@MainActor
final class Слои: ObservableObject {
  static let общие = Слои()
  private init() {}

  struct Слой: Identifiable, Equatable {
    let id = UUID().uuidString
    /// Дорожка редактора: video | image | audio | text.
    let дорожка: String
    let подпись: String
    /// Ссылка на файл. У текста её нет — он и есть содержимое.
    let ссылка: String?
    let текст: String?
  }

  @Published private(set) var слои: [Слой] = []

  /// Композиция, ждущая редактора. Он забирает её и обнуляет — иначе
  /// повторный заход подменял бы уже правленый проект старой сборкой.
  @Published var готоваяКомпозиция: Composition?

  var пусто: Bool { слои.isEmpty }

  func добавить(дорожка: String, подпись: String, ссылка: String? = nil, текст: String? = nil) {
    слои.append(Слой(дорожка: дорожка, подпись: подпись, ссылка: ссылка, текст: текст))
  }

  func убрать(_ id: String) { слои.removeAll { $0.id == id } }
  func очистить() { слои.removeAll() }

  /// Человеческое имя дорожки. Порядок тот же, что в `дорожки`.
  static func имяДорожки(_ т: String) -> String {
    switch т {
    case "video": return "Видео"
    case "image": return "Картинки"
    case "audio": return "Звук"
    default: return "Текст"
    }
  }

  /// Порядок дорожек сверху вниз — как в любом монтажном столе:
  /// картинка выше звука, видео выше картинки.
  static let дорожки = ["video", "image", "audio", "text"]

  /**
   * Собрать композицию для редактора.
   *
   * ДЛИТЕЛЬНОСТЬ БЕРЁТСЯ ОТ ОЗВУЧКИ, а если её нет — по пять секунд на клип.
   * Это не догадка о вкусах: в вертикальном ролике длину задаёт голос, под
   * него подрезают картинку. Считать наоборот значило бы обрезать речь на
   * полуслове.
   *
   * Клипы кладутся ПОДРЯД внутри дорожки, а не друг на друга: наложение —
   * осознанное решение монтажёра, и делать его за него нельзя. Разложить их
   * по очереди — предсказуемо и легко поправить в самом редакторе.
   */
  func композиция(fps: Int = 30) -> Composition {
    let наКлип = 5 * fps
    var tracks: [Track] = []

    for тип in Self.дорожки {
      let свои = слои.filter { $0.дорожка == тип }
      guard !свои.isEmpty else { continue }
      let tid = "track-\(тип)"
      var кадр = 0
      var клипы: [Clip] = []
      for с in свои {
        клипы.append(
          Clip(
            id: с.id, trackId: tid, name: с.подпись,
            startFrame: кадр, durationInFrames: наКлип, url: с.ссылка
          )
        )
        кадр += наКлип
      }
      tracks.append(Track(id: tid, type: тип, name: Self.имяДорожки(тип), items: клипы))
    }

    return Composition(fps: fps, width: 1080, height: 1920, tracks: tracks)
  }
}
