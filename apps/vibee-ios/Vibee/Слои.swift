import Foundation
import SwiftUI

/**
 * Что уже сделано для ролика — и во что это собирается.
 *
 * ЗАЧЕМ. Вкладка «ИИ» умела пять шагов и не помнила ни одного: сгенерировал
 * озвучку — ссылка показалась и пропала при переключении вида. Собрать ролик
 * из этого было нельзя в принципе, потому что собирать было не из чего:
 * результаты нигде не накапливались.
 *
 * Здесь они накапливаются и превращаются в `Composition` — тот самый тип, на
 * котором уже работают таймлайн и рендер. Новый формат не выдумывается: слои
 * ложатся на существующие дорожки (`video`, `image`, `audio`, `text`), иначе
 * редактор получил бы то, чего не понимает.
 *
 * ОДИН ЭКЗЕМПЛЯР НА ПРИЛОЖЕНИЕ. Накопитель переживает переключение вкладок —
 * в этом весь смысл: человек уходит из «ИИ» в «Редактор» и должен застать там
 * свои слои, а не пустой холст.
 */
@MainActor
final class Слои: ObservableObject {
  static let общие = Слои()
  private init() { загрузить() }

  struct Слой: Identifiable, Equatable {
    let id = UUID().uuidString
    /// Дорожка редактора: video | image | audio | text.
    let дорожка: String
    let подпись: String
    /// Ссылка на файл. У текста её нет — он и есть содержимое.
    let ссылка: String?
    let текст: String?
    let таймированныеПодписи: [TimedCaption]?
  }

  @Published private(set) var слои: [Слой] = []

  /**
   * ИСТОРИЯ ВСЕГО СГЕНЕРИРОВАННОГО — на диске, а не в памяти.
   *
   * До неё каждый ассет жил ровно до перезапуска приложения. Человек платил
   * за озвучку, закрывал приложение — и платил ещё раз за ту же фразу,
   * потому что найти прежнюю было негде. Для продукта, где каждый шаг стоит
   * денег, это худший вид потери: не сломанная функция, а сожжённые деньги
   * без следа.
   *
   * Хранится РЯДОМ С НАСТРОЙКАМИ приложения (Application Support), а не в
   * кэше: кэш система вправе очистить когда угодно, и она это делает.
   * Ассеты — не кэш, их нельзя пересоздать бесплатно.
   */
  @Published private(set) var история: [Актив] = []

  struct Актив: Identifiable, Codable, Equatable {
    var id = UUID().uuidString
    var дорожка: String
    /**
     * КАКОЙ ШАГ это сделал: «видео», «липсинк», «фото», «голос», «сценарий».
     *
     * Дорожки монтажа на это не отвечают: и «Видео», и «Липсинк» кладут
     * результат на дорожку `video`, поэтому история, отфильтрованная по
     * дорожке, показывала на «Липсинке» ролик, сделанный на «Видео». Человек
     * мог взять чужой результат, думая, что это его липсинк.
     *
     * Необязательное: записи, сделанные до этого поля, вида не знают, и
     * подставлять им догадку нельзя — по дорожке `video` не отличить одно от
     * другого. Такие показываются везде, где показывались раньше.
     */
    var вид: String?
    var подпись: String
    var ссылка: String?
    var текст: String?
    /// Когда сделано. Строкой ISO — читается глазами в файле и не зависит
    /// от того, как Codable сегодня сериализует Date.
    var когда: String
    var таймированныеПодписи: [TimedCaption]?
  }

  /// Композиция, ждущая редактора. Он забирает её и обнуляет — иначе
  /// повторный заход подменял бы уже правленый проект старой сборкой.
  @Published var готоваяКомпозиция: Composition?

  var пусто: Bool { слои.isEmpty }

  func добавить(
    дорожка: String,
    вид: String? = nil,
    подпись: String,
    ссылка: String? = nil,
    текст: String? = nil,
    таймированныеПодписи: [TimedCaption]? = nil
  ) {
    слои.append(
      Слой(
        дорожка: дорожка,
        подпись: подпись,
        ссылка: ссылка,
        текст: текст,
        таймированныеПодписи: таймированныеПодписи
      )
    )
    // В историю кладём ТО ЖЕ САМОЕ и сразу: если записывать только при
    // выходе, потеряем всё при падении — а падение как раз тот случай,
    // когда человек ищет, за что заплатил.
    запомнить(
      дорожка: дорожка,
      вид: вид,
      подпись: подпись,
      ссылка: ссылка,
      текст: текст,
      таймированныеПодписи: таймированныеПодписи
    )
  }

  private func запомнить(
    дорожка: String,
    вид: String?,
    подпись: String,
    ссылка: String?,
    текст: String?,
    таймированныеПодписи: [TimedCaption]?
  ) {
    история.insert(
      Актив(
        дорожка: дорожка, вид: вид, подпись: подпись, ссылка: ссылка,
        текст: текст,
        когда: ISO8601DateFormatter().string(from: Date()),
        таймированныеПодписи: таймированныеПодписи
      ),
      at: 0  // Свежее сверху: искать почти всегда будут последнее.
    )
    сохранить()
  }

  /// Взять готовый ассет в текущий ролик. Ничего не генерирует и не платит.
  func взятьВРолик(_ id: String) {
    guard let а = история.first(where: { $0.id == id }) else { return }
    слои.append(
      Слой(
        дорожка: а.дорожка,
        подпись: а.подпись,
        ссылка: а.ссылка,
        текст: а.текст,
        таймированныеПодписи: а.таймированныеПодписи
      )
    )
  }

  func забытьИзИстории(_ id: String) {
    история.removeAll { $0.id == id }
    сохранить()
  }

  // MARK: - Диск

  private static var файл: URL? {
    try? FileManager.default.url(
      for: .applicationSupportDirectory, in: .userDomainMask,
      appropriateFor: nil, create: true
    ).appendingPathComponent("vibee-история.json")
  }

  private func сохранить() {
    guard let f = Self.файл, let d = try? JSONEncoder().encode(история) else { return }
    try? d.write(to: f, options: .atomic)
  }

  /// Читается ОДИН раз при создании: см. `init`.
  private func загрузить() {
    guard let f = Self.файл, let d = try? Data(contentsOf: f),
          let сп = try? JSONDecoder().decode([Актив].self, from: d)
    else { return }
    история = сп
  }

  func убрать(_ id: String) { слои.removeAll { $0.id == id } }
  func очистить() { слои.removeAll() }

  /// Человеческое имя дорожки. Порядок тот же, что в `дорожки`.
  static func имяДорожки(_ т: String) -> String {
    switch т {
    case "video": return "Видео"
    case "image": return "Картинки"
    case "audio": return "Звук"
    default: return "Текст"
    }
  }

  /// Порядок дорожек сверху вниз — как в любом монтажном столе:
  /// картинка выше звука, видео выше картинки.
  static let дорожки = ["video", "image", "audio", "text"]

  /**
   * Собрать композицию для редактора.
   *
   * ДЛИТЕЛЬНОСТЬ БЕРЁТСЯ ОТ ОЗВУЧКИ, а если её нет — по пять секунд на клип.
   * Это не догадка о вкусах: в вертикальном ролике длину задаёт голос, под
   * него подрезают картинку. Считать наоборот значило бы обрезать речь на
   * полуслове.
   *
   * Клипы кладутся ПОДРЯД внутри дорожки, а не друг на друга: наложение —
   * осознанное решение монтажёра, и делать его за него нельзя. Разложить их
   * по очереди — предсказуемо и легко поправить в самом редакторе.
   */
  func композиция(fps: Int = 30) -> Composition {
    let наКлип = 5 * fps
    var tracks: [Track] = []
    var timedCaptions: [TimedCaption] = []

    for тип in Self.дорожки {
      let свои = слои.filter { $0.дорожка == тип }
      guard !свои.isEmpty else { continue }
      let tid = "track-\(тип)"
      var кадр = 0
      var клипы: [Clip] = []
      for с in свои {
        if тип == "audio", let captions = с.таймированныеПодписи {
          let offsetMs = Int((Double(кадр) / Double(fps) * 1000).rounded())
          timedCaptions.append(contentsOf: captions.map { $0.offset(by: offsetMs) })
        }
        клипы.append(
          Clip(
            id: с.id, trackId: tid, name: с.подпись,
            startFrame: кадр, durationInFrames: наКлип, url: с.ссылка
          )
        )
        кадр += наКлип
      }
      tracks.append(Track(id: tid, type: тип, name: Self.имяДорожки(тип), items: клипы))
    }

    return Composition(
      fps: fps,
      width: 1080,
      height: 1920,
      tracks: tracks,
      captions: timedCaptions.isEmpty ? nil : timedCaptions
    )
  }
}
