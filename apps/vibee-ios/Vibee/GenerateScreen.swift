  /**
   * Отдельная сессия с ДЛИННЫМ таймаутом.
   *
   * `URLSession.shared` ждёт ответа 60 секунд. Замеренное время генерации —
   * 60 с у видео и 66 с у картинки, то есть на общей сессии картинка падала
   * бы по таймауту ВСЕГДА, а видео — через раз, и выглядело бы это как
   * «сервер не отвечает» при полностью исправном сервере.
   */
  private static let долгая: URLSession = {
    let c = URLSessionConfiguration.default
    c.timeoutIntervalForRequest = 300
    c.timeoutIntervalForResource = 600
    return URLSession(configuration: c)
  }()

  /// Ответ сервера, приведённый к трём исходам: ссылка, отказ, обрыв.
  private struct Ответ {
    var ссылка: String?
    var текст: String?
    var озвучка: String?
    var обложка: String?
    var кадры: [String] = []
    var подписи: [String] = []
    var таймированныеПодписи: [TimedCaption] = []
    var провайдер: String?
    var отказ: String?
  }

  private func позвать(_ путь: String, _ тело: [String: Any]) async -> Ответ {
    /**
     * ЗАПРОС СОБИРАЕТСЯ ЗАНОВО ПЕРЕД КАЖДОЙ ПОПЫТКОЙ.
     *
     * Заголовки берутся из `Identity` в момент сборки, а не один раз: после
     * обновления сессии токен ДРУГОЙ, и повтор со старым заголовком получил
     * бы тот же 401. Тонкость, которую легко потерять, вынеся сборку выше.
     */
    func собрать() -> URLRequest {
      var r = URLRequest(url: API.base.appendingPathComponent(путь))
      r.httpMethod = "POST"
      r.setValue("application/json", forHTTPHeaderField: "Content-Type")
      // Личность — тем же способом, что в AgentChatView. Без неё сервер
      // отвечает 401, и до генерации дело не доходит вовсе.
      for (k, v) in Identity.headers() { r.setValue(v, forHTTPHeaderField: k) }
      r.httpBody = try? JSONSerialization.data(withJSONObject: тело)
      return r
    }

    do {
      var (data, resp) = try await Self.долгая.data(for: собрать())

      /**
       * ОДНА ПОПЫТКА ОБНОВИТЬ ПРОТУХШУЮ СЕССИЮ — как в `API.отправить`.
       *
       * Access живёт десять минут, а экран генерации открыт дольше: набрать
       * тему, выбрать модель, посмотреть цены — и токен уже мёртв. Без этой
       * ветки человек получал «unauthorized: session rejected: expired»,
       * держа на руках живой refresh, и единственным выходом выглядел
       * повторный вход по коду из бота.
       *
       * Проверено на себе: вошёл, потратил десять минут на выбор модели,
       * нажал «Сгенерировать» — и получил ровно этот отказ.
       *
       * Повтор РОВНО ОДИН. Если и он ответил 401, сессии действительно нет,
       * и об этом надо сказать, а не крутить цикл на протухшем refresh.
       */
      if (resp as? HTTPURLResponse)?.statusCode == 401,
         await Identity.refreshSession() {
        (data, resp) = try await Self.долгая.data(for: собрать())
      }
      let o = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any] ?? [:]
      let код = (resp as? HTTPURLResponse)?.statusCode ?? 0

      /**
       * Показываем СЛОВА СЕРВЕРА, а не «ошибка генерации».
       *
       * Сервер здесь необычно разговорчив: он сам объясняет, что ключ
       * ElevenLabs — это идентификатор, а не ключ, и что баланс fal.ai
       * исчерпан. Заменить это на своё общее сообщение значит выбросить
       * готовую диагностику и заставить человека гадать.
       */
      if let e = o["error"] as? String {
        let деталь = o["detail"] as? String
        return Ответ(отказ: деталь.map { "\(e): \($0)" } ?? e)
      }
      guard (200...299).contains(код) else {
        return Ответ(отказ: "Сервер ответил \(код) без объяснения")
      }
      // Сценарий отвечает словами: voiceover, подписи и описания кадров.
      // Ищем их ДО ссылки, иначе успешный ответ был бы объявлен непонятным.
      if let голос = o["voiceover"] as? String {
        let подписи = (o["captions"] as? [String] ?? []).map { "• \($0)" }
        let кадры = (o["broll_prompts"] as? [String] ?? []).map { "• \($0)" }
        var части = [голос]
        if !подписи.isEmpty { части.append("\nПодписи:\n" + подписи.joined(separator: "\n")) }
        if !кадры.isEmpty { части.append("\nКадры:\n" + кадры.joined(separator: "\n")) }
        if let обложка = o["cover_prompt"] as? String {
          части.append("\nОбложка:\n\(обложка)")
        }
        return Ответ(
          текст: части.joined(separator: "\n"),
          озвучка: голос,
          обложка: o["cover_prompt"] as? String,
          кадры: o["broll_prompts"] as? [String] ?? [],
          подписи: o["captions"] as? [String] ?? [],
          провайдер: o["provider"] as? String
        )
      }
      guard let url = o["url"] as? String else {
        return Ответ(отказ: "Сервер ответил \(код), но ссылки в ответе нет")
      }
      let timedCaptions = (o["timed_captions"] as? [[String: Any]] ?? [])
        .compactMap { row -> TimedCaption? in
          guard
            let text = row["text"] as? String,
            !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
            let start = (row["startMs"] as? NSNumber)?.intValue,
            let end = (row["endMs"] as? NSNumber)?.intValue,
            start >= 0,
            end > start
          else { return nil }
          let timestamp = (row["timestampMs"] as? NSNumber)?.intValue ?? start
          return TimedCaption(
            text: text,
            startMs: start,
            endMs: end,
            timestampMs: timestamp,
            confidence: (row["confidence"] as? NSNumber)?.doubleValue
          )
        }
      return Ответ(
        ссылка: url,
        таймированныеПодписи: timedCaptions,
        провайдер: o["provider"] as? String
      )
    } catch {
      /**
       * СНАЧАЛА СПРОСИТЬ, НЕ ГОТОВО ЛИ УЖЕ.
       *
       * Обрыв связи не значит, что генерации не было. Провайдеру уже
       * заплачено, файл уже в хранилище — потеряна только наша сторона
       * разговора. Сервер с недавних пор заводит задание ДО вызова
       * провайдера, и результат оседает там независимо от того, дослушали
       * мы ответ или нет.
       *
       * Поэтому на любом сетевом отказе идём в /api/generate/jobs. Если
       * ответ уже лежит — показываем его, а не сообщение об ошибке. Сказать
       * «не дошло» о том, что дошло и оплачено, — худший вид неправды: он
       * заставляет человека заплатить второй раз.
       */
      if let спасённое = await API.последнееЗадание(вид: вид.видЗадания) {
        return Ответ(ссылка: спасённое.url, провайдер: спасённое.provider)
      }
      return Ответ(отказ: "Не дошло до сервера: \(error.localizedDescription)")
    }
  }

  private func сгенерировать() async {
    ошибка = nil
    результат = nil
    идёт = true
    прошло = 0
    let часы = Task {
      while !Task.isCancelled {
        try? await Task.sleep(nanoseconds: 1_000_000_000)
        if Task.isCancelled { return }
        прошло += 1
      }
    }
    defer {
      часы.cancel()
      идёт = false
      // Списание уже произошло на сервере — перечитываем, а не вычитаем сами:
      // своя арифметика разойдётся с сервером на первом же возврате средств.
      Task { баланс = try? await API.баланс() }
    }

    let тело: [String: Any]
    if вид == .сценарий {
      /**
       * У СЦЕНАРИЯ СВОЁ ТЕЛО, И БЕЗ ЭТОЙ ВЕТКИ КНОПКА НЕ РАБОТАЛА БЫ.
       *
       * Здесь было две ветки — видео и «всё остальное», — и сценарий попадал
       * во вторую. Она шлёт `prompt`, ширину, высоту и модель `fal-ai/flux/dev`,
       * то есть запрос на КАРТИНКУ. Маршрут `generate-script` ждёт `topic` и
       * ответил бы «topic is required». Список моделей на экране был бы, цена
       * была бы, а кнопка возвращала бы отказ — ровно то притворство, которое
       * мы уже вычищали из этой вкладки.
       *
       * Модель шлётся выбранная, а не зашитая: на экране их четыре, у каждой
       * своя цена и свой провайдер, и выбор человека обязан доезжать до
       * сервера. Сервер всё равно сверяет имя со своим списком.
       */
      тело = [
        "topic": промпт,
        "language": "Russian",
        "model": модельДляСервера,
        // Формат совпадает с запасным значением сервера («30 seconds») —
        // строка подставляется в промпт LLM буквально, а не парсится.
        "duration": "\(длительностьСценарияСек) seconds",
      ]
    } else if вид == .звук {
      /**
       * У ОЗВУЧКИ СВОЁ ТЕЛО. Без него она никогда не работала из приложения:
       * звук попадал в ветку «всё остальное» и уходил запросом КАРТИНКИ, а
       * маршрут ждёт `text` и падал с «Cannot read properties of undefined
       * (reading 'substring')» — внутренней ошибкой JS, которую видел человек.
       * Форма была известна рядом: `телоПроверки` шлёт ровно это.
       */
      тело = [
        "text": промпт, "voice_id": "sarah", "speed": 1,
        "model": модельДляСервера,
      ]
    } else if вид == .аватар {
      /**
       * АВАТАРУ НУЖНЫ ФАЙЛЫ, А НЕ ОПИСАНИЕ, и берёт он их из пройденных шагов.
       *
       * Липсинк оживляет КОНКРЕТНОЕ фото КОНКРЕТНЫМ голосом: `image_url` и
       * `audio_url`. Он тоже падал в ветку картинки — третий случай одной
       * ошибки, после сценария и звука.
       *
       * Ссылки берутся из накопителя слоёв: в этом и выгода конвейера — шаг
       * работает потому, что до него сделали голос и образ. Если их нет,
       * честнее сказать это ДО отправки, чем платить за неполный запрос.
       */
      тело = [
        "audio_url": Слои.общие.слои.last { $0.дорожка == "audio" }?.ссылка ?? "",
        "image_url": Слои.общие.слои.last { $0.дорожка == "image" }?.ссылка ?? "",
        "resolution": "480p", "aspect_ratio": соотношение,
        "model": модельДляСервера,
      ]
    } else if вид == .видео {
      тело = [
        "model": модельДляСервера,
        "prompt": промпт,
        "duration": длительность,
        "aspect_ratio": соотношение,
      ]
    } else {
      let (ш, в) = размер(соотношение)
      тело = ["model": модельДляСервера, "prompt": промпт, "width": ш, "height": в]
    }

    let о = await позвать(вид.путь, тело)
    if let отказ = о.отказ {
      ошибка = отказ
    } else if let t = о.текст {
      // Слой в общий накопитель: без этого результат жил до переключения
      // вкладки и собрать из него ролик было не из чего.
      Слои.общие.добавить(дорожка: "text", подпись: "Сценарий", текст: t)
      результат = Результат(
        текст: t, провайдер: о.провайдер, видео: false,
        озвучка: о.озвучка, обложка: о.обложка, кадры: о.кадры,
        подписи: о.подписи
      )
    } else if let s = о.ссылка, let u = URL(string: s) {
      Слои.общие.добавить(
        дорожка: дорожкаСлоя,
        подпись: вид.подпись,
        ссылка: s,
        таймированныеПодписи: о.таймированныеПодписи
      )
      результат = Результат(ссылка: u, провайдер: о.провайдер, видео: вид == .видео)
    } else {
      ошибка = "Сервер вернул ссылку, которую не удалось разобрать"
    }
  }

  /// Спросить сервер про неработающий вид и показать его собственный ответ.
  private func перепроверить() async {
    ошибка = nil
    результат = nil
    идёт = true
    defer { идёт = false }

    let о = await позвать(вид.путь, вид.телоПроверки)
    if let отказ = о.отказ {
      ошибка = "Сервер сейчас отвечает так — \(отказ)"
    } else {
      // Причина отпала: сервер ответил успехом. Говорим об этом прямо, иначе
      // человек так и будет верить заглушке.
      ошибка = "Сервер только что ответил успехом — причина отпала. "
        + "Форму для этого вида ещё не включили в приложении."
    }
  }

  /// Сервер сам выводит соотношение из ширины и высоты (h/w ≥ 1.7 → 9:16),
  /// поэтому шлём размеры, а не строку: иначе он округлит не туда.
  private func размер(_ соотношение: String) -> (Int, Int) {
    switch соотношение {
    case "16:9": return (1792, 1024)
    case "1:1": return (1024, 1024)
    default: return (1024, 1792)
    }
  }
