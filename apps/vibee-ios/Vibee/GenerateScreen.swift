         * там дефект тот же, числом чуть мягче: замер пользователя это
         * подтвердил на «Выберите модель».
         *
         * Правильно отключённая кнопка не гасит СВОИ ЖЕ цвета до
         * нечитаемости — она берёт цвета, которые и без того рассчитаны на
         * тусклое состояние: `Тема.Цвет.поверхность` и `текстПриглушённый`
