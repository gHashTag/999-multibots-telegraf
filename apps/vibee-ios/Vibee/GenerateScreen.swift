      } label: {
        HStack(spacing: Тема.Отступ.sm) {
          if идёт {
            ProgressView().tint(Тема.Кнопка.основнаяТекст)
            Text("Идёт \(прошло) с")
          } else {
            Image(systemName: "sparkles")
            Text("Сгенерировать")
              .accessibilityIdentifier("ии.кнопка.текст")
          }
        }
        .font(Тема.Шрифт.стиль(.headline, .semibold))
        // Высота явная: 44 — минимум касания (index.css:47).
        .frame(maxWidth: .infinity, minHeight: Тема.Кнопка.высота)
        /**
         * ДВА ЯВНЫХ ЦВЕТА ВМЕСТО ОДНОЙ НЕПРОЗРАЧНОСТИ.
         *
         * Было `.opacity(0.45)` на всей кнопке — чёрный текст на ярком
         * зелёном, оба разом притушены к чёрному фону экрана. Замер по
         * формуле WCAG: 3.67:1 при минимуме 4.5:1. Дело не в величине 0.45 —
         * дело в самой механике. У `наАкценте` (чёрный) контраст рассчитан
         * НА ПОЛНУЮ яркость зелёного; стоит увести оба цвета к общему чёрному
         * фону экрана, и расстояние между ними схлопывается быстрее, чем
         * кажется на глаз, потому что оба тянутся к одной точке.
         *
         * Раньше это чинили только для «идёт запрос» (# 1667) — но та же
         * непрозрачность стояла и на «нет описания»/«модель не в строю», и
         * там дефект тот же, числом чуть мягче: замер пользователя это
         * подтвердил на «Выберите модель».
         *
         * Правильно отключённая кнопка не гасит СВОИ ЖЕ цвета до
         * нечитаемости — она берёт цвета, которые и без того рассчитаны на
         * тусклое состояние: `Тема.Цвет.поверхность` и `текстПриглушённый`
         * уже используются по всему экрану как раз для «сейчас неактивно»
         * (невыбранный вид, невыбранная модель) и там контраст проверен.
         */
        .background(
          нельзяЗапускать && !идёт ? Тема.Цвет.поверхность : Тема.Кнопка.основнаяФон,
          in: RoundedRectangle(cornerRadius: Тема.Радиус.md)
