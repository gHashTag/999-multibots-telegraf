  private func содержимоеЧасти(_ р: Результат) -> String {
    switch частьСценария {
    case .озвучка:
      var к = [р.озвучка ?? "—"]
      // Подписи — тайминги озвучки, поэтому живут с ней, а не отдельной
      // вкладкой: отдельной их нет и в вебе.
      if !р.подписи.isEmpty {
        к.append("\nПодписи:\n" + р.подписи.map { "• \($0)" }.joined(separator: "\n"))
      }
      return к.joined(separator: "\n")
    case .обложка:
      return р.обложка ?? "Сервер не прислал промпт обложки."
    case .броль:
      return р.кадры.isEmpty
        ? "Сервер не прислал описания кадров."
        : р.кадры.map { "• \($0)" }.joined(separator: "\n")
    }
  }

  @ViewBuilder private func показ(_ r: Результат) -> some View {
    let р = r
    VStack(alignment: .leading, spacing: 10) {
      /**
       * СЦЕНАРИЙ ПОКАЗЫВАЕТСЯ ПО ЧАСТЯМ, как в вебе (`script-output-tabs`).
       *
       * Части приходят с сервера отдельными полями и УЖЕ хранятся отдельно —
       * `озвучка`, `обложка`, `кадры` питают кнопки «Дальше». А на экран
       * выводились одной склеенной строкой: «текст, Подписи:, Кадры:,
       * Обложка:» подряд. Прочитать в ней промпт обложки можно, найти —
       * трудно, а решение о трате принимают именно по нему.
       *
       * Три вкладки — те же, что в вебе: Озвучка · Обложка · B-Roll.
       * Подписи остаются с озвучкой: это её тайминги, а не отдельная работа.
       */
      if р.озвучка != nil || р.обложка != nil || !р.кадры.isEmpty {
        частиСценария(р)
      } else if let текст = р.текст {
        // Текст выделяемый: сценарий пишут, чтобы его скопировать.
        Text(текст)
          .font(Тема.Шрифт.стиль(.callout))
          .textSelection(.enabled)
          .fixedSize(horizontal: false, vertical: true)
          .frame(maxWidth: .infinity, alignment: .leading)
          .padding(12)
          .background(Тема.Цвет.поверхность, in: RoundedRectangle(cornerRadius: Тема.Радиус.lg))
      } else if let ссылка = р.ссылка, р.видео {
        VideoPlayer(player: AVPlayer(url: ссылка))
          .frame(height: 380)
          .clipShape(RoundedRectangle(cornerRadius: Тема.Радиус.lg))
      } else if let ссылка = р.ссылка {
        AsyncImage(url: ссылка) { фаза in
          switch фаза {
          case .success(let картинка):
            картинка.resizable().scaledToFit()
          case .failure:
            // Ссылка на картинку подписанная и живёт сутки. Молчать о том,
            // что она протухла, значит показать пустой прямоугольник.
            Text("Картинка не загрузилась: ссылка сервера уже недействительна.")
              .font(Тема.Шрифт.стиль(.footnote)).foregroundStyle(Тема.Цвет.текстПриглушённый).padding()
          default:
            ProgressView().frame(height: 200).frame(maxWidth: .infinity)
          }
        }
        .clipShape(RoundedRectangle(cornerRadius: Тема.Радиус.lg))
      }

      if let п = р.провайдер {
        // Кто РЕАЛЬНО сделал. Не то же самое, что было заказано: и видео, и
        // картинка сегодня уходят в запасной Replicate.
        Text("Сделал: \(п)")
          .font(Тема.Шрифт.моно(.caption))
          .foregroundStyle(Тема.Цвет.текстПриглушённый)
      }
      /**
       * ЧЕК — СКОЛЬКО ЭТО СТОИЛО И СКОЛЬКО ОСТАЛОСЬ.
       *
       * Экран называл сумму РОВНО в одном месте: подписью под погашенной
       * кнопкой, «не хватит токенов: нужно 20, есть 16». То есть остаток
       * видел лишь тот, кому его уже не хватало, — та же дыра, которую мы
       * чинили у цены, теперь у баланса. Успех показывал «Сделал: kie/…» и
       * файл, а списание оставалось невидимым.
       *
       * Цифры БЕРУТСЯ ИЗ ОТВЕТА, а не считаются здесь. Своя арифметика
       * («было минус цена») разошлась бы с сервером на первом же возврате
       * средств и на первой посекундной генерации: длительность звука
       * приложение узнаёт позже сервера.
       *
       * `осталось` может не прийти (владельцу списывают ноль, и остатка в
       * ответе нет) — тогда говорим только про списание, а не подставляем
       * старое число из `баланс`: оно относится к моменту ДО генерации.
       */
      if let списано = р.списано {
        // Сама строка — в `Чек.swift`: внутри `body` её не проверить иначе как
        // настоящей генерацией за настоящие токены.
        Text(чекСтрокой(списано: списано, осталось: р.осталось))
          .font(Тема.Шрифт.моно(.caption))
          .foregroundStyle(Тема.Цвет.текстПриглушённый)
      }
      /**
       * ЧТО ДЕЛАТЬ ДАЛЬШЕ — ПРЯМО ЗДЕСЬ, А НЕ «догадайтесь сами».
       *
       * До этих кнопок сценарий был тупиком: текст пришёл, и человек оставался
       * с вопросом «и куда это?». Чтобы озвучить, надо было выделить нужный
       * кусок, запомнить его, переключить вкладку и вставить руками — и то же
       * для обложки и для каждого кадра. Продукт умел все шаги и не соединял
       * ни одного.
       *
       * Кнопки переносят ИМЕННО ту часть, которая нужна следующему шагу:
       * озвучке — voiceover, картинке — cover_prompt, видео — первый кадр.
       * Текст кладётся в поле, а не отправляется молча: следующий шаг стоит
       * денег, и человек должен увидеть, что именно уйдёт, и успеть поправить.
       */
      if r.текст != nil, r.озвучка != nil || r.обложка != nil || !r.кадры.isEmpty {
        VStack(alignment: .leading, spacing: 8) {
          Text("Дальше")
            .font(Тема.Шрифт.стиль(.subheadline, .semibold))
            .foregroundStyle(Тема.Цвет.текстПриглушённый)

          /**
           * КНОПКА НА КАЖДЫЙ КУСОК, А НЕ НА ПЕРВЫЙ ПОПАВШИЙСЯ.
           *
           * Здесь стояло `кадры.first` — предлагался один кадр, а остальные
           * два молча выбрасывались. Ролик из трёх планов было не собрать: на
           * таймлайне взялся бы один слой там, где сценарий описал три.
           *
           * Подписи добавляются СРАЗУ как текстовые слои: генерировать их не
           * надо, они уже написаны, и им место на дорожке текста. Кнопка
           * «сгенерировать подпись» была бы предложением заплатить за то,
           * что уже лежит в ответе.
           *
           * Ряд переносится (`FlowLayout` через `LazyVGrid` с адаптивной
           * колонкой): кнопок теперь пять-шесть, и горизонтальная лента
           * прятала бы половину за краем — ту же ошибку мы уже разбирали
           * с лентой видов.
           */
          LazyVGrid(
            columns: [GridItem(.adaptive(minimum: 150), spacing: 8)],
            alignment: .leading, spacing: 8
          ) {
            if let о = r.озвучка { шагДальше("Озвучить", "waveform", .звук, о) }
            if let об = r.обложка { шагДальше("Обложка", "photo", .картинка, об) }
            ForEach(Array(r.кадры.enumerated()), id: \.offset) { i, кадр in
              шагДальше("Кадр \(i + 1)", "film", .видео, кадр)
            }
            if !r.подписи.isEmpty {
              Button {
                for п in r.подписи {
                  Слои.общие.добавить(дорожка: "text", вид: вид.rawValue, подпись: п, текст: п)
                }
              } label: {
                Label("Подписи · \(r.подписи.count)", systemImage: "textformat")
                  .font(Тема.Шрифт.стиль(.footnote, .medium))
                  .padding(.vertical, 8).padding(.horizontal, 12)
                  .frame(minHeight: 44)
                  .background(Тема.Цвет.поверхность, in: Capsule())
                  .contentShape(Capsule())
              }
              .buttonStyle(.plain)
              .tint(Тема.Цвет.акцент)
            }
          }
        }
        .padding(.top, 4)
      }

      // Делимся тем, что есть: файлом — ссылкой, сценарием — самим текстом.
      // Ссылки у текста нет, и подпись «поделиться ссылкой» над сценарием
      // обещала бы не то.
      if let ссылка = р.ссылка {
        ShareLink(item: ссылка) {
          Label("Поделиться ссылкой", systemImage: "square.and.arrow.up")
            .font(Тема.Шрифт.стиль(.subheadline, .medium))
        }
        .tint(Тема.Цвет.акцент)
      } else if let текст = р.текст {
        ShareLink(item: текст) {
          Label("Поделиться сценарием", systemImage: "square.and.arrow.up")
            .font(Тема.Шрифт.стиль(.subheadline, .medium))
        }
        .tint(Тема.Цвет.акцент)
      }
    }
  }

