        .foregroundStyle(
          нельзяЗапускать && !идёт ? Тема.Цвет.текстПриглушённый : Тема.Кнопка.основнаяТекст
        )
      }
      .buttonStyle(.plain)
      .disabled(нельзяЗапускать)
      /*
       * ОПОЗНАВАТЕЛЬ НА САМОЙ КНОПКЕ, а не только на её частях.
       *
       * SwiftUI склеивает доступность подписи кнопки: внутренние `Text` не
       * видны проверке как отдельные элементы, и `ии.кнопка.цена` найти было
       * нельзя. Подпись кнопки целиком («Сгенерировать · 216») читается, и
       * именно её видит человек.
       */
      .accessibilityIdentifier("ии.кнопка")

