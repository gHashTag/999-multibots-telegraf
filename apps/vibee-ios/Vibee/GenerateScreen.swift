  @State private var результат: Результат?
  @State private var ошибка: String?

  /**
   * Вид генерации.
   *
   * Пять, а не четыре: `/generate/script` — такая же страница вкладки «ИИ» в
   * вебе, как остальные, просто сломанная. Спрятать её значило бы починить
   * список, а не продукт: человек, искавший сценарии, решил бы, что их
   * выпилили.
   */
  enum Вид: String, CaseIterable, Identifiable {
    /**
     * ПОРЯДОК — ЭТО ПОРЯДОК РАБОТЫ, а не история появления вкладок.
     *
     * Было `видео, картинка, звук, аватар, сценарий`: сценарий последним,
     * хотя с него всё начинается. Человек открывал вкладку на «Видео» и
     * оставался с вопросом, откуда взять описание — а инструмент, который
     * его пишет, лежал за краем прокрутки.
     *
     * Теперь список читается как шаги ролика: сценарий → голос → образы →
     * оживление → съёмка. `CaseIterable` отдаёт их в этом же порядке, и
     * лента вкладок наверху становится картой процесса.
     */
    case сценарий, звук, картинка, аватар, видео, редактор

    /// Как этот вид называется в заданиях на сервере. Имена намеренно
    /// перечислены, а не выведены из rawValue: сервер знает их по-английски,
    /// и молчаливое совпадение сломалось бы при первом переименовании.
    var видЗадания: String {
      switch self {
      case .видео: return "video"
      case .редактор: return "script"
      case .картинка: return "image"
      case .звук: return "audio"
      case .аватар: return "lipsync"
      case .сценарий: return "script"
      }
    }

    var id: String { rawValue }

    var подпись: String {
      switch self {
      case .видео: return "Видео"
      case .редактор: return "Редактор"
      // «Фото» и «Голос» — так они названы в вебе (app.t27.ai/generate/*).
      // Разные слова для одного и того же в двух клиентах — это два разных
      // продукта в глазах человека, который пользуется обоими.
      case .картинка: return "Фото"
      case .звук: return "Голос"
      // Шаг называется тем, что делает: он оживляет фото голосом. «Аватар»
      // в этом продукте уже занят — так зовётся дорожка монтажа и
      // категория ассетов, то есть ТИП МЕДИА, а не шаг.
      case .аватар: return "Липсинк"
      case .сценарий: return "Сценарий"
      }
    }

    var значок: String {
      switch self {
      case .видео: return "film"
      case .редактор: return "square.stack.3d.up"
      case .картинка: return "photo"
      // ЗНАЧКИ СНЯТЫ С app.t27.ai, а не подобраны по смыслу.
      //
      // У голоса там МИКРОФОН, а не звуковая волна: волна — это про то, что
      // уже записано, микрофон — про то, что сейчас произнесут. Шаг делает
      // второе.
      case .звук: return "mic"
      // У аватара там УЛЫБКА, а не человек с камерой: оживляют лицо, и
      // значок про лицо, а не про съёмочный прибор.
      case .аватар: return "face.smiling"
      case .сценарий: return "text.alignleft"
      }
    }

    var путь: String {
      switch self {
      case .видео: return "api/generate/video"
      // У редактора нет своего маршрута: он ничего не генерирует.
      case .редактор: return ""
      case .картинка: return "api/generate/image"
      case .звук: return "api/generate/audio"
      case .аватар: return "api/generate/lipsync"
      case .сценарий: return "api/ai/generate-script"
      }
    }

    /**
     * Почему вид не работает СЕГОДНЯ. `nil` — работает.
     *
     * Текст пересказывает ответ сервера, а не догадку. Дата стоит намеренно:
     * причина может отпасть без единой правки в приложении (доложили баланс,
     * заменили ключ), и тогда фраза «проверено тогда-то» честнее, чем вечное
     * «не работает». Для этого же рядом стоит кнопка перепроверки: она
     * спрашивает сервер прямо сейчас и показывает его собственный ответ.
     */
    /**
     * Тот же вид в терминах каталога KieAI. `nil` — своих моделей нет.
     *
     * У СЦЕНАРИЯ ТЕПЕРЬ СВОИ МОДЕЛИ, И ЭТО ВАЖНОЕ ОТЛИЧИЕ ОТ ПРЕЖНЕГО.
     * Здесь стояло `case .видео, .сценарий: return .видео`, и вкладка
     * показывала Kling и Grok Imagine — модели, которые снимают ролик, а не
     * пишут текст. Заимствованный список ещё и убеждал проверку живости,
     * что всё в порядке, пряча настоящую поломку.
     *
     * Подставлять чужой вид нельзя по-прежнему. Разница в том, что у
     * сценария появились собственные модели: три чат-модели KieAI,
     * проверенные не «отвечает ли», а той самой задачей — им отправили
     * системный запрос маршрута и разобрали ответ как JSON с voiceover,
     * cover_prompt, broll_prompts и captions.
     */
    var видКаталога: Модель.Вид? {
      switch self {
      case .видео: return .видео
      // Редактор моделей не выбирает — он собирает уже сделанное.
      case .редактор: return nil
      case .картинка: return .картинка
      case .звук: return .звук
      case .аватар: return .липсинк
      case .сценарий: return .сценарий
      }
    }

    var неготовность: String? {
      /**
       * KieAI СНИМАЕТ неготовность, и это не поблажка, а замер.
       *
       * Три вида были объявлены сломанными по вине ОДНОГО провайдера каждый:
       * озвучка — из-за подменённого ELEVENLABS_API_KEY, липсинк — из-за
       * нулевого баланса fal.ai, сценарий — из-за отсутствующего ключа xAI.
       * Всё это верно и всё это больше не единственный путь: те же задачи
       * идут через KieAI, чей ключ работает и чьи модели проверены живым
       * перебором.
       *
       * Поэтому вид считается сломанным, только если у него НЕТ ни одной
       * живой модели в каталоге. Оставить прежний текст значило бы врать
       * человеку о продукте, который умеет больше, чем о себе говорит.
       */
      let естьЖивые = видКаталога.map { !КаталогKie.поВиду($0).filter(\.живая).isEmpty } ?? false
      if естьЖивые { return nil }

      switch self {
      // Редактор не «неготов»: он ничего не просит у провайдеров.
      case .видео, .картинка, .редактор:
        return nil
      case .звук:
        return """
          Сервер отвечает 500 и сам называет причину: в переменной \
          ELEVENLABS_API_KEY лежит не ключ, а его идентификатор — настоящий \
          начинается с «sk_». ElevenLabs на такой отвечает 400. Чинится \
          заменой переменной на сервере, а не в приложении.
          """
      case .аватар:
        return """
          Сервер отвечает 500 словами fal.ai: «User is locked. Reason: \
          Exhausted balance». Аккаунт заблокирован из-за нулевого баланса — \
          липсинк идёт через очередь fal.ai. Чинится пополнением, а не кодом.
          """
      case .сценарий:
        return """
          Сервер отвечает 500: «xAI API key not configured». Переменной с \
          ключом xAI у сервиса рендера нет вовсе — проверено по списку \
          переменных, а не по коду. Чинится добавлением ключа.
          """
      }
    }

    /// Минимальное тело для перепроверки: только чтобы услышать сервер.
    var телоПроверки: [String: Any] {
      switch self {
      // Редактору нечего перепроверять: он не ходит на сервер.
      case .редактор:
        return [:]
      case .звук:
        return ["text": "проверка", "voice_id": "Russian_ReliableMan", "speed": 1]
      case .аватар:
        return [
          "audio_url": "https://example.com/a.mp3",
          "image_url": "https://example.com/i.jpg",
          "resolution": "480p", "aspect_ratio": "9:16",
        ]
      case .сценарий:
        return [
          "topic": "проверка", "niche": "lifestyle",
          "style": "dynamic", "duration": 15, "language": "ru",
        ]
      case .видео, .картинка:
        return [:]
      }
    }
  }

  /**
   * Что вернулась генерация. У сценария это ТЕКСТ, а не файл.
   *
   * Раньше здесь была обязательная `ссылка`, и это молча закрывало путь
   * любому виду, который возвращает слова: разбор ответа заканчивался
   * фразой «ссылки в ответе нет», хотя сервер прислал готовый сценарий.
   */
  struct Результат {
    var ссылка: URL?
    var текст: String?
    var провайдер: String?
    var видео: Bool
    /**
     * ЧАСТИ СЦЕНАРИЯ ОТДЕЛЬНО, А НЕ ТОЛЬКО СКЛЕЕННЫМ ТЕКСТОМ.
     *
     * Ответ маршрута сценария УЖЕ устроен как задание для конвейера:
     * `voiceover` — это то, что надо озвучить, `cover_prompt` — обложка,
     * `broll_prompts` — кадры. Склеив всё в одну строку для показа, мы
     * теряли ровно эту структуру, и сценарий упирался в тупик: человек
     * прочитал текст — и дальше некуда, хотя следующий шаг уже написан.
     */
    var озвучка: String?
    var обложка: String?
    var кадры: [String] = []
    var подписи: [String] = []
    var таймированныеПодписи: [TimedCaption] = []
    /// Чек этой генерации. Кнопка обещает цену ВЫБРАННОЙ модели до нажатия,
    /// но у посекундных видов сумма зависит от длительности, которой
    /// приложение заранее не знает: назвать её может только ответ.
    var списано: Int?
    var осталось: Int?
  }

