        .foregroundStyle(
          нельзяЗапускать && !идёт ? Тема.Цвет.текстПриглушённый : Тема.Кнопка.основнаяТекст
        )
      }
      .buttonStyle(.plain)
      .disabled(нельзяЗапускать)

      /**
       * Причина названа, а не оставлена на догадку.
       *
       * Погашенная кнопка без объяснения — самый частый способ выглядеть
       * поломкой: человек видит, что нажать нельзя, и не знает, что сделать.
