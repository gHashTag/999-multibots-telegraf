import PhotosUI
import SwiftUI

/**
 * Вкладка «ИИ» целиком нативная. Это был ПОСЛЕДНИЙ `WebScreen` в приложении.
 *
 * ПОЧЕМУ ВЕБ ЗДЕСЬ НЕ РАБОТАЛ В ПРИНЦИПЕ, а не «работал хуже». Веб-клиент
 * подписывает запросы к маршрутам генерации заголовком `X-Telegram-Init-Data`, и
 * берёт он его из `window.Telegram.WebApp.initData`. Внутри нашего WKWebView
 * этого объекта нет и быть не может: подпись выдаёт Telegram своему WebView, а
 * не чужому. То есть страница открывалась, форма рисовалась, кнопка нажималась
 * — и каждый запрос уходил без личности и получал 401. Ровно тот молчаливый
 * отказ, который в этом приложении уже вычищали в ленте и в агенте.
 *
 * Нативный экран берёт личность из `Identity.headers()` — тем же способом, что
 * AgentChatView. Сервер понимает её третьей веткой в `authenticate()`
 * (`Authorization: Bearer`), и никакой правки на сервере для этого не нужно.
 *
 * ЧТО ЗДЕСЬ ИЗМЕРЕНО, А НЕ ВЫВЕДЕНО ИЗ КОДА. Все пять видов генерации
 * простуканы живыми запросами к проду 28.08.2026 с серверным ключом:
 *
 *   POST /api/generate/video   → 200, ссылка на .mp4, 60 с     РАБОТАЕТ
 *   POST /api/generate/image   → 200, ссылка на картинку, 66 с РАБОТАЕТ
 *   POST /api/generate/audio   → 500, испорченный ключ ElevenLabs
 *   POST /api/generate/lipsync → 500, исчерпан баланс fal.ai
 *   POST /api/ai/generate-script → 500, ключа xAI нет в переменных сервиса
 *
 * Поэтому форма есть ровно у двух видов. У остальных трёх — заглушка с
 * НАЗВАННОЙ причиной и кнопкой перепроверки, а не кнопка, которая молча
 * не работает.
 */
struct GenerateScreen: View {
  /// Открываемся на СЦЕНАРИИ: это первый шаг, а не пятый.
  @State private var вид: Вид = .сценарий
  @State private var промпт = ""
  @State private var длительность = "5s"
  /**
   * Длительность СЦЕНАРИЯ — отдельная величина от `длительность` видео.
   *
   * У видео это ограничение конкретного клипа KieAI («6s»/«10s» — то, что
   * умеет модель). У сценария это ЦЕЛЬ ДЛЯ ТЕКСТА: сервер вставляет число
   * прямо в промпт LLM — `Create a {duration} {style} video script about…»
   * (render-server.ts:8248) — и результат реально короче или длиннее.
   * Раньше приложение это поле вообще не отправляло, и сервер молча ставил
   * свои «30 seconds» по умолчанию — выбора не было, хотя разница между
   * 15-секундным TikTok и полуторaминутным Reels для сценария огромна.
   *
   * Пресеты — не выдумка: 15 / 30 / 60 — стандартные отметки TikTok и
   * YouTube Shorts, 90 — верхняя граница формата Reels. Кто снимает не по
   * шаблону, вводит своё числом.
   */
  @State private var длительностьСценарияСек = 30
  @State private var свояДлительность = false
  @State private var соотношение = "9:16"
  /**
   * ГОЛОС И СКОРОСТЬ — ВЫБОР, А НЕ КОНСТАНТА.
   *
   * Приложение слало жёстко зашитые «sarah» и 1. В вебе это выбор из трёх
   * голосов и регулятор скорости, то есть половина настроек озвучки в
   * приложении просто отсутствовала: человек, привыкший к вебу, не находил
   * их и считал, что тут «другой продукт».
   */
  /**
   * НИША, СТИЛЬ И ЯЗЫК — НАСТРОЙКИ, КОТОРЫЕ МЕНЯЮТ РЕЗУЛЬТАТ.
   *
   * Сервер принимает `niche` и `style` и подставляет их в промпт модели
   * (`in the ${niche} niche`), а приложение слало ОДНУ тему: две настройки
   * веба до генерации не доходили вовсе. Язык был зашит «Russian» — человек,
   * которому нужен английский сценарий, получить его не мог.
   */
  @State private var ниша = "Другое"
  @State private var стиль = "Обучающий"
  @State private var языкСценария = "Русский"
  /// Сохранённые шаблоны сценария. Читаются один раз при появлении экрана.
  @State private var шаблоны: [ШаблонСценария] = []
  @State private var сохраняемШаблон = false
  @State private var имяШаблона = ""
  /**
   * ВЫБРАННЫЙ ГОЛОС — ИДЕНТИФИКАТОР ПРОВАЙДЕРА, а не витринное имя.
   *
   * Было `"Sarah"`, и на сервер уходило `голос.lowercased()` — строка,
   * которой нет ни у одного провайдера. Тот, кто реально читает текст
   * (Replicate minimax), её отбрасывал и говорил голосом по умолчанию: выбор
   * не менял ничего, а каждая попытка стоила как новая.
   *
   * Значение по умолчанию — русский голос: приложение русскоязычное, а список
   * ElevenLabs был английским целиком.
   */
  @State private var голос = "Russian_ReliableMan"
  /// Голоса приходят с `/api/voices`. Запасные — до первого ответа и при
  /// обрыве сети; они настоящие и уходят провайдеру дословно.
  @State private var голоса: [API.Голос] = [
    API.Голос(id: "Russian_ReliableMan", name: "Максим — уверенный", category: "ru"),
    API.Голос(id: "Russian_BrightHeroine", name: "Алиса — звонкая", category: "ru"),
    API.Голос(id: "English_Wiselady", name: "Wise Lady", category: "en"),
  ]
  @State private var скорость = "1.0"
  /// Ссылка на загруженный исходник. Пока её нет, модель правки не пустим.
  @State private var исходник: String?
  @State private var выбранное: PhotosPickerItem?
  @State private var идётЗагрузка = false
  @State private var ошибкаЗагрузки: String?
  /**
   * Выбранная модель KieAI. `nil` — человек ещё не выбирал.
   *
   * Умолчание НЕ ставится молча: подставить первую живую значит решить за
   * человека, чем генерировать, и списать деньги на модель, которую он не
   * называл. Пока не выбрано — кнопка не нажимается и говорит почему.
   */
  @State private var модель: Модель?
  @ObservedObject private var слои = Слои.общие
  @State private var открытьРедактор = false

  /// Берём у самого вида: одно определение вместо двух расходящихся.
  private var видКаталога: Модель.Вид? { вид.видКаталога }

  /// The paid web boundary is deliberately narrow: show only models whose
  /// request shapes are implemented and server-allowlisted end to end.
  private var доступныеМодели: [Модель] {
    guard let kind = видКаталога else { return [] }
    /**
     * УСЛОВИЯ ОДНИ — те же, что у сервера, и проверяются по каталогу.
     *
     * Здесь стоял набор имён списком, а рядом — второй такой же. Две записи
     * одной правды в одном файле: смена допущенной модели требовала править
     * обе, и первая же правка развела бы их. Теперь имён нет вовсе: и экран,
     * и сервер отбирают по одинаковым признакам самой модели — живая,
     * оценена, не опасная.
     */
    if вид == .сценарий || вид == .редактор { return КаталогKie.поВиду(kind) }
    return КаталогKie.поВиду(kind).filter { сервернаяOK($0) }
  }

  /**
   * ЕДИНСТВЕННАЯ МОДЕЛЬ НА ВИД, КОТОРУЮ ПРОПУСКАЕТ СЕРВЕР.
   *
   * Дословно из `render/src/agent/kie-web-provider.ts` (`KIE_WEB_MODEL`).
   * Сервер сверяет присланное с этим списком и на любое другое отвечает
   * 500 «Kie.ai model is not enabled for <вид>».
   *
   * ЗАЧЕМ ЭТО ЗДЕСЬ. Каталог на устройстве знает 48 моделей KieAI, из них 45
   * помечены живыми — и все они предлагались на выбор. Но «живая» означает
   * «KieAI её выполняет», а не «наш сервер её пропустит»: за этой границей
   * тратятся настоящие деньги, поэтому там намеренно стоит по одной
   * проверенной модели на вид. Человек выбирал одну из сорока пяти, платил
   * вниманием за выбор и получал 500 ПОСЛЕ нажатия.
   *
   * Шлюз не открываем — он защитный. Убираем ложное обещание выбора.
   */
  /**
   * ЧТО СЕРВЕР ДОПУСКАЕТ К ОПЛАТЕ — уже не одна модель на вид.
   *
   * Здесь стояло по одному имени: сервер выполнял четыре модели из сорока
   * восьми, а каталог показывал сорок пять живых. Теперь сервер допускает всё,
   * что живое, оценено провайдером и не помечено опасным
   * (`KIE_WEB_MODELS` в kie-web-provider.ts) — а значит и приложению незачем
   * держать список: условия те же самые и проверяются по каталогу на месте.
   *
   * `опасная` не показываем НИКОГДА: `grok-imagine/image-to-video` создаёт
   * платное задание даже на пустой запрос.
   * `ценаUSD == nil` не показываем тоже: сумму до нажатия назвать нечем, а
   * сервер такую модель отвергнет.
   */
  private func сервернаяOK(_ м: Модель) -> Bool {
    if вид == .сценарий { return true }
    // `входИзвне` — модель просит картинку/видео/звук, которых экран не шлёт.
    // Показывать её значит обещать работу, которой не будет: сервер такую
    // модель к оплате не допускает (kie-web-provider.ts, ПОЛЯ_МАРШРУТА).
    return м.живая && !м.опасная && м.ценаUSD != nil && !м.входИзвне
  }

  private var модельДляСервера: String {
    guard let id = модель?.id else { return "" }
    return вид == .сценарий ? id : "kie/\(id)"
  }

  /// На какую дорожку редактора ложится результат этого вида.
  /// Аватар — тоже видео: на выходе ролик с губами, а не отдельная сущность.
  private var дорожкаСлоя: String {
    switch вид {
    case .видео, .аватар: return "video"
    case .картинка: return "image"
    case .звук: return "audio"
    case .сценарий, .редактор: return "text"
    }
  }

  /// Что писать в поле — своими словами для каждого вида.
  private var подсказкаПоля: String {
    switch вид {
    case .видео: return "Кот прыгает через лужу в неоне…"
    case .сценарий: return "Тема ролика: утренний кофе…"
    // Своя подсказка КАЖДОМУ виду, а не «остальным». В поле для озвучки
    // висело «Красный куб на белом столе» — описание картинки там, где
    // ждут слова для голоса.
    case .звук: return "Текст, который надо произнести…"
    case .аватар: return "Возьмём голос и образ из прошлых шагов"
    case .редактор: return ""
    case .картинка: return "Красный куб на белом столе…"
    }
  }

  /**
   * Одна причина, названная словами, вместо булева «нельзя».
   *
   * Порядок проверок — от самой поправимой к самой внешней: сначала то, что
   * человек может сделать сам, и лишь потом то, чего он изменить не может.
   * Обратный порядок сообщал бы про приостановку провайдера тому, кто просто
   * не заполнил описание.
   */
  /// Имя операции в прайсе сервера (`TOKEN_PRICES`) для текущего вида.
  /// Редактор ничего не генерирует — у него цены нет.
  private var операцияЦены: String? {
    switch вид {
    case .сценарий: return nil  // сценарий не тарифицируется отдельно
    case .звук: return "audio_generate"
    case .картинка: return "image_generate"
    case .видео: return "video_generate"
    case .аватар: return "lipsync_generate"
    case .редактор: return nil
    }
  }

  /**
   * Загрузить выбранное фото и запомнить ссылку.
   *
   * Ссылка сбрасывается ПЕРЕД загрузкой: иначе при неудачной замене осталась
   * бы старая, и человек отправил бы в работу не тот файл, который видит
   * выбранным. Отказ показывается словами — молчаливый провал выглядит как
   * «кнопка не нажимается».
   */
  private func загрузитьИсходник(_ элемент: PhotosPickerItem) async {
    идётЗагрузка = true
    ошибкаЗагрузки = nil
    исходник = nil
    defer { идётЗагрузка = false }
    do {
      guard let данные = try await элемент.loadTransferable(type: Data.self) else {
        ошибкаЗагрузки = "Не удалось прочитать фото"
        return
      }
      // Тип и расширение — по виду файла: сервер кладёт их в S3 как есть, и
      // ролик с именем .jpg провайдер отвергнет по типу, не по содержимому.
      let видео = модель?.видИсходника == "видео"
      исходник = try await API.положитьФайл(
        данные,
        имя: "source-\(Int(Date().timeIntervalSince1970))." + (видео ? "mp4" : "jpg"),
        тип: видео ? "video/mp4" : "image/jpeg"
      )
    } catch {
      ошибкаЗагрузки = "Загрузка не удалась: \(error.localizedDescription)"
    }
  }

  private var почемуНельзяЗапускать: String? {
    if идёт { return nil }
    guard let м = модель else { return "Выберите модель" }
    if !м.живая { return м.почемуНельзя }
    if промпт.isEmpty { return "Нужно описание" }
    // Модель правки без исходника — заявка, которую сервер соберёт как null.
    // Сказать об этом ДО нажатия честнее, чем показать отказ после.
    if м.нуженИсходник && исходникИлиПодстава == nil {
      let что = м.видИсходника == "видео" ? "видео" : "фото"
      return идётЗагрузка ? "Файл загружается" : "Нужно \(что)"
    }
    /*
     * ЛИПСИНКУ НУЖЕН ЗВУК, А НЕ ТОЛЬКО ФОТО.
     *
     * Проверка выше спрашивает ОДИН исходник — тот, что называет
     * `видИсходника`. У липсинка их два: контракт `omnihuman-1-5` перечисляет
     * `image_url` И `audio_url`, а маршрут отвергает запрос без звука.
     *
     * Звук берётся из пройденных шагов (`Слои`), и у пришедшего сразу на эту
     * вкладку их нет — ссылка уходила ПУСТОЙ строкой. Ровно это уже чинили
     * для фотографии в соседней строке; для звука не починили, и выглядело
     * это как «липсинк не работает», хотя работать было не с чем.
     */
    if вид == .аватар, звукИзШагов == nil {
      return "Сначала озвучка: сделайте её на вкладке «Голос»"
    }
    /**
     * ХВАТИТ ЛИ ТОКЕНОВ — СПРАШИВАЕМ ДО НАЖАТИЯ.
     *
     * Раньше это выяснялось ПОСЛЕ: человек выбирал модель, жал, ждал сервер и
     * получал «не хватает токенов: нужно 20, есть 16». Отказ верный, момент
     * негодный — решение о покупке принимают до траты времени, а не после.
     *
     * Цена берётся из ответа сервера, не из таблицы в приложении: своя копия
     * разошлась бы с прайсом на первой же правке, и мы бы обещали доступное
     * там, где сервер откажет.
     *
     * Пока баланс не загружен (`nil`) — НЕ мешаем. Неизвестность это не
     * «нельзя»: сервер всё равно проверит, а гасить кнопку на догадке значит
     * запрещать оплаченное.
     */
    /*
     * ЦЕНА БЕРЁТСЯ У ВЫБРАННОЙ МОДЕЛИ, а не у вида работы.
     *
     * По виду мы называли среднюю сумму, а списывают цену модели. Замер
     * показал расхождение в ОБЕ стороны: за картинку обещали 1 при списании 8
     * (отказ после нажатия), за видео обещали 20 при списании 5 — то есть
     * гасили кнопку тому, кому денег хватало.
     */
    /*
     * СВЕРЯЕМ С ПОЛНОЙ СУММОЙ, А НЕ С ЦЕНОЙ СЕКУНДЫ.
     *
     * Сравнение с единицей пропускало вперёд того, кому хватало на секунду и
     * не хватало на ролик: кнопка активна, отказ после нажатия.
     */
    /*
     * С ОСВОБОЖДЁННОГО НЕ СПИСЫВАЮТ — И НЕ ЗАПРЕЩАЕМ.
     *
     * Проверка кармана гасила кнопку у владельца, с которого сервер не берёт
     * ничего: единственный счёт без списаний оказался единственным без права
     * работать.
     */
    if баланс?.exempt == true { return nil }
    if let оп = операцияЦены, let б = баланс,
       let цена = сколькоСпишут.всего ?? б.цена(оп, модель: модельДляСервера),
       б.balance < цена
    {
      /**
       * У ПОСЕКУНДНЫХ ОПЕРАЦИЙ ЦЕНА — ЗА СЕКУНДУ, И ОБ ЭТОМ НАДО СКАЗАТЬ.
       *
       * Липсинк сервер считает как `3 × ceil(длительность звука)`
       * (`billedSeconds`, render-server.ts). Замер: трёхсекундная озвучка
       * стоила 9 при цене 3 — и отказ «нужно 9, есть 7» пришёл там, где
       * приложение, сравнив остаток с тройкой, обещало бы «хватит».
       *
       * Длительности будущего звука приложение не знает, поэтому обещать
       * точную сумму НЕ МОЖЕТ и не будет. Оно говорит цену за секунду и
       * запрещает только заведомо невозможное — когда не хватает даже на
       * одну. Соврать «хватит» и получить отказ после нажатия хуже, чем
       * честно назвать единицу измерения.
       */
      return (б.perSecond ?? []).contains(оп)
        ? "не хватит: \(цена) за секунду звука, есть \(б.balance)"
        : "не хватит токенов: нужно \(цена), есть \(б.balance)"
    }
    return nil
  }


  /// Сколько спишут за одно нажатие. `nil` — цены нет (сценарий) или баланс
  /// ещё не пришёл: молчать честнее, чем показать сумму по умолчанию.
  private var ценаНажатия: Int? {
    /*
     * ПОКА МОДЕЛЬ НЕ ВЫБРАНА — ЦЕНЫ НЕТ.
     *
     * Без этой проверки `модельДляСервера` отдаёт пустую строку, цена модели
     * не находится, и кнопка показывала цену ВИДА. На «Аватаре» это «6/с»
     * при том, что OmniHuman стоит 54/с — девятикратная разница, названная
     * до того, как человек вообще что-то выбрал.
     *
     * Замечено на скриншоте собственной вчерашней правки: кнопка была
     * погашена подписью «Выберите модель», и число рядом с ней я принял за
     * безобидное.
     */
    guard модель != nil, let оп = операцияЦены, let б = баланс else { return nil }
    return б.цена(оп, модель: модельДляСервера)
  }

  /**
   * Полная цена нажатия: единица × длительность там, где длительность известна.
   *
   * Раньше экран называл и сверял с остатком цену СЕКУНДЫ. Для видео это
   * неверно вдвойне — длительность выбрана на этом же экране. Замер: 100
   * токенов, kling/v3-turbo (36/с), 10 с — кнопка активна, подпись «· 36/с»,
   * а после нажатия 402 «нужно 360, есть 100».
   */
  private var сколькоСпишут: ЦенаНажатия {
    let мера = баланс?.мера(операцияЦены ?? "", модель: модель == nil ? nil : модельДляСервера)
    return ЦенаНажатия.посчитать(
      единица: ценаНажатия,
      мера: мера,
      /*
       * Количество известно там, где его задаёт ЧЕЛОВЕК: длительность у
       * видео и длина текста у озвучки. У липсинка длину определяет готовая
       * озвучка — там `nil`, и подпись честно называет цену секунды.
       */
      множитель: {
        switch мера {
        case "с":
          /*
           * ЧИП НЕ НАЗЫВАЕТ ДЛИНУ ТАМ, ГДЕ ЕЁ ЗАДАЁТ ФАЙЛ.
           *
           * У `topaz/video-upscale` контракт просит готовый ролик, и чип
           * «6с/10с» до провайдера не доходит: сборщик входа оставляет только
           * поля контракта. Экран всё равно множил — и обещал 96 или 160 за
           * один и тот же файл, а сервер теперь считает по замеру. Обещать
           * число, которого не знаем, хуже, чем назвать цену секунды.
           */
          guard вид == .видео, !(баланс?.поЗамеруФайла(модельДляСервера) ?? false)
          else { return nil }
          return секундыИзДлительности(длительность)
        case "1000 зн.":
          // utf16.count, а НЕ count: сервер считает `text.length` в JS, то
          // есть единицы UTF-16, а Swift `count` — графемы. Эмодзи весит одну
          // графему и две единицы: кнопка обещала 24, счёт брал 48.
          return промпт.isEmpty ? nil : (промпт.utf16.count + 999) / 1000
        default: return nil
        }
      }()
    )
  }

  /**
   * Цена КОНКРЕТНОЙ модели в списке — чтобы сравнивать до выбора.
   *
   * Раньше сравнить было нечем: цена появлялась только на кнопке, то есть
   * уже ПОСЛЕ выбора, и чтобы сопоставить две модели, надо было выбрать
   * одну, прокрутить вниз, вернуться и выбрать другую.
   *
   * `nil`, если провайдер цены не назвал (тогда строка так и скажет) или
   * баланс ещё не пришёл — второе временно и молчания заслуживает.
   */
  private func ценаМодели(_ м: Модель) -> Int? {
    guard let оп = операцияЦены, м.ценаUSD != nil else { return nil }
    return баланс?.цена(оп, модель: "kie/\(м.id)")
  }

  /// Цена посекундной работы — это цена СЕКУНДЫ, и подпись обязана это сказать.
  /// Без «/с» человек умножит на длительность сам и ошибётся в свою пользу.
  private var посекундная: Bool {
    guard let оп = операцияЦены, let б = баланс else { return false }
    return б.посекундная(оп, модель: модель == nil ? nil : модельДляСервера)
  }

  /// Посекундна ли КОНКРЕТНАЯ строка списка. По виду работы это не узнать:
  /// у видео восемь моделей из двенадцати берут за секунду, остальные за ролик.
  private func посекундная(_ м: Модель) -> Bool {
    guard let оп = операцияЦены, let б = баланс else { return false }
    return б.посекундная(оп, модель: "kie/\(м.id)")
  }

  /// Готовая озвучка из пройденных шагов. `nil` — её нет, и липсинку нечего
  /// класть на губы: пустая ссылка доедет до сервера и вернётся отказом.
  /// Выбранный файл. Подстава существует ради проверок, стоящих ПОСЛЕ
  /// фотографии: без неё экран останавливался на «Нужно фото», и тест
  /// звуковой проверки проходил, даже когда самой проверки не было.
  private var исходникИлиПодстава: String? {
    исходник ?? ПодставаДляПроверки.фото
  }

  private var звукИзШагов: String? {
    if let свой = ПодставаДляПроверки.звук { return свой }
    let ссылка = Слои.общие.слои.last { $0.дорожка == "audio" }?.ссылка
    return (ссылка?.isEmpty ?? true) ? nil : ссылка
  }

  private var нельзяЗапускать: Bool {
    идёт || почемуНельзяЗапускать != nil
