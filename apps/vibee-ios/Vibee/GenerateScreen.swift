import AVKit
import SwiftUI

/**
 * Вкладка «ИИ» целиком нативная. Это был ПОСЛЕДНИЙ `WebScreen` в приложении.
 *
 * ПОЧЕМУ ВЕБ ЗДЕСЬ НЕ РАБОТАЛ В ПРИНЦИПЕ, а не «работал хуже». Веб-клиент
 * подписывает запросы к маршрутам генерации заголовком `X-Telegram-Init-Data`, и
 * берёт он его из `window.Telegram.WebApp.initData`. Внутри нашего WKWebView
 * этого объекта нет и быть не может: подпись выдаёт Telegram своему WebView, а
 * не чужому. То есть страница открывалась, форма рисовалась, кнопка нажималась
 * — и каждый запрос уходил без личности и получал 401. Ровно тот молчаливый
 * отказ, который в этом приложении уже вычищали в ленте и в агенте.
 *
 * Нативный экран берёт личность из `Identity.headers()` — тем же способом, что
 * AgentChatView. Сервер понимает её третьей веткой в `authenticate()`
 * (`Authorization: Bearer`), и никакой правки на сервере для этого не нужно.
 *
 * ЧТО ЗДЕСЬ ИЗМЕРЕНО, А НЕ ВЫВЕДЕНО ИЗ КОДА. Все пять видов генерации
 * простуканы живыми запросами к проду 28.08.2026 с серверным ключом:
 *
 *   POST /api/generate/video   → 200, ссылка на .mp4, 60 с     РАБОТАЕТ
 *   POST /api/generate/image   → 200, ссылка на картинку, 66 с РАБОТАЕТ
 *   POST /api/generate/audio   → 500, испорченный ключ ElevenLabs
 *   POST /api/generate/lipsync → 500, исчерпан баланс fal.ai
 *   POST /api/ai/generate-script → 500, ключа xAI нет в переменных сервиса
 *
 * Поэтому форма есть ровно у двух видов. У остальных трёх — заглушка с
 * НАЗВАННОЙ причиной и кнопкой перепроверки, а не кнопка, которая молча
 * не работает.
 */
struct GenerateScreen: View {
  /// Открываемся на СЦЕНАРИИ: это первый шаг, а не пятый.
  @State private var вид: Вид = .сценарий
  @State private var промпт = ""
  @State private var длительность = "5s"
  /**
   * Длительность СЦЕНАРИЯ — отдельная величина от `длительность` видео.
   *
   * У видео это ограничение конкретного клипа KieAI («6s»/«10s» — то, что
   * умеет модель). У сценария это ЦЕЛЬ ДЛЯ ТЕКСТА: сервер вставляет число
   * прямо в промпт LLM — `Create a {duration} {style} video script about…»
   * (render-server.ts:8248) — и результат реально короче или длиннее.
   * Раньше приложение это поле вообще не отправляло, и сервер молча ставил
   * свои «30 seconds» по умолчанию — выбора не было, хотя разница между
   * 15-секундным TikTok и полуторaминутным Reels для сценария огромна.
   *
   * Пресеты — не выдумка: 15 / 30 / 60 — стандартные отметки TikTok и
   * YouTube Shorts, 90 — верхняя граница формата Reels. Кто снимает не по
   * шаблону, вводит своё числом.
   */
  @State private var длительностьСценарияСек = 30
  @State private var свояДлительность = false
  @State private var соотношение = "9:16"
  /**
   * Выбранная модель KieAI. `nil` — человек ещё не выбирал.
   *
   * Умолчание НЕ ставится молча: подставить первую живую значит решить за
   * человека, чем генерировать, и списать деньги на модель, которую он не
   * называл. Пока не выбрано — кнопка не нажимается и говорит почему.
   */
  @State private var модель: Модель?
  @ObservedObject private var слои = Слои.общие
  @State private var открытьРедактор = false

  /// Берём у самого вида: одно определение вместо двух расходящихся.
  private var видКаталога: Модель.Вид? { вид.видКаталога }

  /// The paid web boundary is deliberately narrow: show only models whose
  /// request shapes are implemented and server-allowlisted end to end.
  private var доступныеМодели: [Модель] {
    guard let kind = видКаталога else { return [] }
    /**
     * СПИСОК ОДИН — `пропускаетСервер`, а не своя копия рядом.
     *
     * Здесь стоял ВТОРОЙ набор тех же четырёх имён, отдельным `switch`. Две
     * записи одной правды в одном файле: смена разрешённой модели требовала
     * править обе, и первая же правка развела бы их — экран предлагал бы
     * модель, которую шлюз тут же отверг бы как «сервер не подключил».
     * Ровно та ошибка, от которой этот шлюз и заводился.
     */
    if вид == .сценарий || вид == .редактор { return КаталогKie.поВиду(kind) }
    guard let разрешена = Self.пропускаетСервер[вид] else { return [] }
    return КаталогKie.поВиду(kind).filter { $0.id == разрешена }
  }

  /**
   * ЕДИНСТВЕННАЯ МОДЕЛЬ НА ВИД, КОТОРУЮ ПРОПУСКАЕТ СЕРВЕР.
   *
   * Дословно из `render/src/agent/kie-web-provider.ts` (`KIE_WEB_MODEL`).
   * Сервер сверяет присланное с этим списком и на любое другое отвечает
   * 500 «Kie.ai model is not enabled for <вид>».
   *
   * ЗАЧЕМ ЭТО ЗДЕСЬ. Каталог на устройстве знает 48 моделей KieAI, из них 45
   * помечены живыми — и все они предлагались на выбор. Но «живая» означает
   * «KieAI её выполняет», а не «наш сервер её пропустит»: за этой границей
   * тратятся настоящие деньги, поэтому там намеренно стоит по одной
   * проверенной модели на вид. Человек выбирал одну из сорока пяти, платил
   * вниманием за выбор и получал 500 ПОСЛЕ нажатия.
   *
   * Шлюз не открываем — он защитный. Убираем ложное обещание выбора.
   */
  static let пропускаетСервер: [Вид: String] = [
    .картинка: "google/nano-banana",
    .видео: "grok-imagine/text-to-video",
    .звук: "elevenlabs/text-to-speech-multilingual-v2",
    .аватар: "infinitalk/from-audio",
  ]

  /// Выполнит ли сервер эту модель. У сценария своя ветка — там KieAI не при чём.
  private func сервернаяOK(_ м: Модель) -> Bool {
    if вид == .сценарий { return true }
    return Self.пропускаетСервер[вид] == м.id
  }

  private var модельДляСервера: String {
    guard let id = модель?.id else { return "" }
    return вид == .сценарий ? id : "kie/\(id)"
  }

  /// На какую дорожку редактора ложится результат этого вида.
  /// Аватар — тоже видео: на выходе ролик с губами, а не отдельная сущность.
  private var дорожкаСлоя: String {
    switch вид {
    case .видео, .аватар: return "video"
    case .картинка: return "image"
    case .звук: return "audio"
    case .сценарий, .редактор: return "text"
    }
  }

  /// Что писать в поле — своими словами для каждого вида.
  private var подсказкаПоля: String {
    switch вид {
    case .видео: return "Кот прыгает через лужу в неоне…"
    case .сценарий: return "Тема ролика: утренний кофе…"
    // Своя подсказка КАЖДОМУ виду, а не «остальным». В поле для озвучки
    // висело «Красный куб на белом столе» — описание картинки там, где
    // ждут слова для голоса.
    case .звук: return "Текст, который надо произнести…"
    case .аватар: return "Возьмём голос и образ из прошлых шагов"
    case .редактор: return ""
    case .картинка: return "Красный куб на белом столе…"
    }
  }

  /**
   * Одна причина, названная словами, вместо булева «нельзя».
   *
   * Порядок проверок — от самой поправимой к самой внешней: сначала то, что
   * человек может сделать сам, и лишь потом то, чего он изменить не может.
   * Обратный порядок сообщал бы про приостановку провайдера тому, кто просто
   * не заполнил описание.
   */
  /// Имя операции в прайсе сервера (`TOKEN_PRICES`) для текущего вида.
  /// Редактор ничего не генерирует — у него цены нет.
  private var операцияЦены: String? {
    switch вид {
    case .сценарий: return nil  // сценарий не тарифицируется отдельно
    case .звук: return "audio_generate"
    case .картинка: return "image_generate"
    case .видео: return "video_generate"
    case .аватар: return "lipsync_generate"
    case .редактор: return nil
    }
  }

  private var почемуНельзяЗапускать: String? {
    if идёт { return nil }
    guard let м = модель else { return "Выберите модель" }
    if !м.живая { return м.почемуНельзя }
    if промпт.isEmpty { return "Нужно описание" }
    /**
     * ХВАТИТ ЛИ ТОКЕНОВ — СПРАШИВАЕМ ДО НАЖАТИЯ.
     *
     * Раньше это выяснялось ПОСЛЕ: человек выбирал модель, жал, ждал сервер и
     * получал «не хватает токенов: нужно 20, есть 16». Отказ верный, момент
     * негодный — решение о покупке принимают до траты времени, а не после.
     *
     * Цена берётся из ответа сервера, не из таблицы в приложении: своя копия
     * разошлась бы с прайсом на первой же правке, и мы бы обещали доступное
     * там, где сервер откажет.
     *
     * Пока баланс не загружен (`nil`) — НЕ мешаем. Неизвестность это не
     * «нельзя»: сервер всё равно проверит, а гасить кнопку на догадке значит
     * запрещать оплаченное.
     */
    if let оп = операцияЦены, let б = баланс, let цена = б.цена(оп),
       б.balance < цена
    {
      return "не хватит токенов: нужно \(цена), есть \(б.balance)"
    }
    return nil
  }

  private var нельзяЗапускать: Bool {
    идёт || почемуНельзяЗапускать != nil
  }
  @State private var идёт = false
  /// Остаток и цены с сервера. nil — ещё не спросили; отличать от нуля
  /// обязательно, иначе на секунду показали бы «не хватит» всем подряд.
  @State private var баланс: API.Баланс?
  @State private var прошло = 0
  @State private var результат: Результат?
  @State private var ошибка: String?

  /**
   * Вид генерации.
   *
   * Пять, а не четыре: `/generate/script` — такая же страница вкладки «ИИ» в
   * вебе, как остальные, просто сломанная. Спрятать её значило бы починить
   * список, а не продукт: человек, искавший сценарии, решил бы, что их
   * выпилили.
   */
  enum Вид: String, CaseIterable, Identifiable {
    /**
     * ПОРЯДОК — ЭТО ПОРЯДОК РАБОТЫ, а не история появления вкладок.
     *
     * Было `видео, картинка, звук, аватар, сценарий`: сценарий последним,
     * хотя с него всё начинается. Человек открывал вкладку на «Видео» и
     * оставался с вопросом, откуда взять описание — а инструмент, который
     * его пишет, лежал за краем прокрутки.
     *
     * Теперь список читается как шаги ролика: сценарий → голос → образы →
     * оживление → съёмка. `CaseIterable` отдаёт их в этом же порядке, и
     * лента вкладок наверху становится картой процесса.
     */
    case сценарий, звук, картинка, аватар, видео, редактор

    /// Как этот вид называется в заданиях на сервере. Имена намеренно
    /// перечислены, а не выведены из rawValue: сервер знает их по-английски,
    /// и молчаливое совпадение сломалось бы при первом переименовании.
    var видЗадания: String {
      switch self {
      case .видео: return "video"
      case .редактор: return "script"
      case .картинка: return "image"
      case .звук: return "audio"
      case .аватар: return "lipsync"
      case .сценарий: return "script"
      }
    }

    var id: String { rawValue }

    var подпись: String {
      switch self {
      case .видео: return "Видео"
      case .редактор: return "Редактор"
      // «Фото» и «Голос» — так они названы в вебе (app.t27.ai/generate/*).
      // Разные слова для одного и того же в двух клиентах — это два разных
      // продукта в глазах человека, который пользуется обоими.
      case .картинка: return "Фото"
      case .звук: return "Голос"
      case .аватар: return "Аватар"
      case .сценарий: return "Сценарий"
      }
    }

    var значок: String {
      switch self {
      case .видео: return "film"
      case .редактор: return "square.stack.3d.up"
      case .картинка: return "photo"
      // ЗНАЧКИ СНЯТЫ С app.t27.ai, а не подобраны по смыслу.
      //
      // У голоса там МИКРОФОН, а не звуковая волна: волна — это про то, что
      // уже записано, микрофон — про то, что сейчас произнесут. Шаг делает
      // второе.
      case .звук: return "mic"
      // У аватара там УЛЫБКА, а не человек с камерой: оживляют лицо, и
      // значок про лицо, а не про съёмочный прибор.
      case .аватар: return "face.smiling"
      case .сценарий: return "text.alignleft"
      }
    }

    var путь: String {
      switch self {
      case .видео: return "api/generate/video"
      // У редактора нет своего маршрута: он ничего не генерирует.
      case .редактор: return ""
      case .картинка: return "api/generate/image"
      case .звук: return "api/generate/audio"
      case .аватар: return "api/generate/lipsync"
      case .сценарий: return "api/ai/generate-script"
      }
    }

    /**
     * Почему вид не работает СЕГОДНЯ. `nil` — работает.
     *
     * Текст пересказывает ответ сервера, а не догадку. Дата стоит намеренно:
     * причина может отпасть без единой правки в приложении (доложили баланс,
     * заменили ключ), и тогда фраза «проверено тогда-то» честнее, чем вечное
     * «не работает». Для этого же рядом стоит кнопка перепроверки: она
     * спрашивает сервер прямо сейчас и показывает его собственный ответ.
     */
    /**
     * Тот же вид в терминах каталога KieAI. `nil` — своих моделей нет.
     *
     * У СЦЕНАРИЯ ТЕПЕРЬ СВОИ МОДЕЛИ, И ЭТО ВАЖНОЕ ОТЛИЧИЕ ОТ ПРЕЖНЕГО.
     * Здесь стояло `case .видео, .сценарий: return .видео`, и вкладка
     * показывала Kling и Grok Imagine — модели, которые снимают ролик, а не
     * пишут текст. Заимствованный список ещё и убеждал проверку живости,
     * что всё в порядке, пряча настоящую поломку.
     *
     * Подставлять чужой вид нельзя по-прежнему. Разница в том, что у
     * сценария появились собственные модели: три чат-модели KieAI,
     * проверенные не «отвечает ли», а той самой задачей — им отправили
     * системный запрос маршрута и разобрали ответ как JSON с voiceover,
     * cover_prompt, broll_prompts и captions.
     */
    var видКаталога: Модель.Вид? {
      switch self {
      case .видео: return .видео
      // Редактор моделей не выбирает — он собирает уже сделанное.
      case .редактор: return nil
      case .картинка: return .картинка
      case .звук: return .звук
      case .аватар: return .липсинк
      case .сценарий: return .сценарий
      }
    }

    var неготовность: String? {
      /**
       * KieAI СНИМАЕТ неготовность, и это не поблажка, а замер.
       *
       * Три вида были объявлены сломанными по вине ОДНОГО провайдера каждый:
       * озвучка — из-за подменённого ELEVENLABS_API_KEY, липсинк — из-за
       * нулевого баланса fal.ai, сценарий — из-за отсутствующего ключа xAI.
       * Всё это верно и всё это больше не единственный путь: те же задачи
       * идут через KieAI, чей ключ работает и чьи модели проверены живым
       * перебором.
       *
       * Поэтому вид считается сломанным, только если у него НЕТ ни одной
       * живой модели в каталоге. Оставить прежний текст значило бы врать
       * человеку о продукте, который умеет больше, чем о себе говорит.
       */
      let естьЖивые = видКаталога.map { !КаталогKie.поВиду($0).filter(\.живая).isEmpty } ?? false
      if естьЖивые { return nil }

      switch self {
      // Редактор не «неготов»: он ничего не просит у провайдеров.
      case .видео, .картинка, .редактор:
        return nil
      case .звук:
        return """
          Сервер отвечает 500 и сам называет причину: в переменной \
          ELEVENLABS_API_KEY лежит не ключ, а его идентификатор — настоящий \
          начинается с «sk_». ElevenLabs на такой отвечает 400. Чинится \
          заменой переменной на сервере, а не в приложении.
          """
      case .аватар:
        return """
          Сервер отвечает 500 словами fal.ai: «User is locked. Reason: \
          Exhausted balance». Аккаунт заблокирован из-за нулевого баланса — \
          липсинк идёт через очередь fal.ai. Чинится пополнением, а не кодом.
          """
      case .сценарий:
        return """
          Сервер отвечает 500: «xAI API key not configured». Переменной с \
          ключом xAI у сервиса рендера нет вовсе — проверено по списку \
          переменных, а не по коду. Чинится добавлением ключа.
          """
      }
    }

    /// Минимальное тело для перепроверки: только чтобы услышать сервер.
    var телоПроверки: [String: Any] {
      switch self {
      // Редактору нечего перепроверять: он не ходит на сервер.
      case .редактор:
        return [:]
      case .звук:
        return ["text": "проверка", "voice_id": "sarah", "speed": 1]
      case .аватар:
        return [
          "audio_url": "https://example.com/a.mp3",
          "image_url": "https://example.com/i.jpg",
          "resolution": "480p", "aspect_ratio": "9:16",
        ]
      case .сценарий:
        return [
          "topic": "проверка", "niche": "lifestyle",
          "style": "dynamic", "duration": 15, "language": "ru",
        ]
      case .видео, .картинка:
        return [:]
      }
    }
  }

  /**
   * Что вернулась генерация. У сценария это ТЕКСТ, а не файл.
   *
   * Раньше здесь была обязательная `ссылка`, и это молча закрывало путь
   * любому виду, который возвращает слова: разбор ответа заканчивался
   * фразой «ссылки в ответе нет», хотя сервер прислал готовый сценарий.
   */
  struct Результат {
    var ссылка: URL?
    var текст: String?
    var провайдер: String?
    var видео: Bool
    /**
     * ЧАСТИ СЦЕНАРИЯ ОТДЕЛЬНО, А НЕ ТОЛЬКО СКЛЕЕННЫМ ТЕКСТОМ.
     *
