  @ViewBuilder private var форма: some View {
    VStack(alignment: .leading, spacing: 14) {
      Text("Что сгенерировать")
        .font(Тема.Шрифт.стиль(.subheadline, .medium))
        .foregroundStyle(Тема.Цвет.текстПриглушённый)

      // Подсказка показывает, ЧТО именно ждут в этом поле. Для сценария
      // это тема ролика, а не описание кадра: «красный куб на белом столе»
      // сбивал бы с толку в поле, куда просят тему.
      TextField(подсказкаПоля, text: $промпт, axis: .vertical)
        // Опознаватели СТАБИЛЬНЫ и не зависят от языка подписи: тест,
        // ищущий «Сгенерировать» по видимому тексту, ломается от правки
        // копирайта, а это правка, которую делают не глядя на тесты.
        .accessibilityIdentifier("ии.промпт")
      .textFieldStyle(.plain)
      .lineLimit(3...6)
      .padding(12)
      .background(Тема.Цвет.поверхность, in: RoundedRectangle(cornerRadius: Тема.Радиус.xl))

      /*
       * Чип длительности — только там, где длину задаём МЫ. У модели, которой
       * шлют готовый ролик, он ничего не менял: в запрос не попадал, а счёт
       * умножал. Настройка, ни на что не влияющая, — это обещание не того.
       */
      if вид == .видео,
         !(баланс?.поЗамеруФайла(модельДляСервера) ?? false),
         баланс?.полеДоходит("duration", модель: модельДляСервера) ?? true {
        строкаВыбора("Длительность", ["6s", "10s"], $длительность)
      }
      if вид == .сценарий {
        выборДлительностиСценария
      }
      // У сценария нет кадра: на выходе текст, а не картинка. Показывать
      // выбор 9:16 для сценария — предлагать настройку, которая ни на что
      // не влияет, и этим обещать не то.
      // Перечисление ПОЛОЖИТЕЛЬНОЕ: у этих видов есть изображение на выходе.
      // Было `!= .сценарий` — исключение «все, кроме одного» ошибается при
      // каждом новом виде, и на вкладке «Звук» висел выбор 9:16 для того, у
      // чего картинки нет вовсе.
      /*
       * ЧИП — ТОЛЬКО ПОД ПОЛЕ, КОТОРОЕ ДОЕДЕТ ДО ПРОВАЙДЕРА.
       *
       * Перечисление видов было верно наполовину: у десяти видеомоделей из
       * двенадцати контракт — один `prompt`, и `aspect_ratio` сборщик входа
       * срезает молча. Человек выбирал 9:16 для рилса и получал то, что
       * модель решила сама.
       *
       * Список полей приходит с сервера — там же, где живёт сам сборщик.
       */
      if [.видео, .картинка, .аватар].contains(вид),
         баланс?.полеДоходит("aspect_ratio", модель: модельДляСервера) ?? true {
        строкаВыбора("Кадр", ["9:16", "16:9", "1:1"], $соотношение)
      }

      /*
       * Настройки озвучки — только на «Голосе». У остальных видов голоса и
       * скорости нет, и показывать их значило бы предлагать настройку,
       * которая ни на что не влияет.
       */
      if вид == .сценарий {
        чипыВыбора("Ниша", КаталогСценария.ниши, $ниша)
        чипыВыбора("Стиль", КаталогСценария.стили, $стиль)
        строкаВыбора("Язык", ["Русский", "English"], $языкСценария)
        шаблоныСценария
        советыСценария
      }

      if вид == .звук {
        /*
         * ЧИПЫ, А НЕ СЕГМЕНТЫ: голосов теперь тринадцать, и сегментированный
         * переключатель на трёх вариантах был рассчитан на выдуманную тройку.
         * Показываем ИМЯ, отправляем ИДЕНТИФИКАТОР — разошлись бы они, и
         * выбор снова перестал бы доходить.
         */
        чипыВыбораПоИмени(
          "Голос",
          голоса.map { (значение: $0.id, подпись: $0.name) },
          $голос
        )
        строкаВыбора("Скорость", ["0.75", "1.0", "1.25"], $скорость)
      }

      /**
       * ИСХОДНИК — ТОЛЬКО ТАМ, ГДЕ ЕГО ПРОСЯТ.
       *
       * Пять моделей правки были в каталоге и не работали НИКОГДА: строка
       * честно писала «нужно: фото», а послать его было нечем — выбора файла
       * на экране не существовало. Показывать поле всем подряд не стоит: у
       * «Seedream 5 Lite — картинка» исходника нет и быть не должно.
       */
      if модель?.нуженИсходник == true {
        VStack(alignment: .leading, spacing: 8) {
          Text("Исходник")
            .font(Тема.Шрифт.стиль(.caption))
            .foregroundStyle(Тема.Цвет.текстПриглушённый)

          /*
           * ВИД ФАЙЛА — ПО КОНТРАКТУ МОДЕЛИ, а не по вкладке.
           *
           * На «Видео» рядом стоят `kling/v2-1-pro`, который оживляет
           * КАРТИНКУ, и `topaz/video-upscale`, который увеличивает готовый
           * РОЛИК. Один общий выбор фотографий предложил бы половине списка
           * работу, которая не сработает.
           */
          PhotosPicker(
            selection: $выбранное,
            matching: модель?.видИсходника == "видео" ? .videos : .images
          ) {
            HStack(spacing: Тема.Отступ.sm) {
              Image(systemName: исходник == nil ? "photo.badge.plus" : "checkmark.circle.fill")
              Text(
                идётЗагрузка
                  ? "Загружаю…"
                  : исходник == nil
                    ? (модель?.видИсходника == "видео" ? "Выбрать видео" : "Выбрать фото")
                    : (модель?.видИсходника == "видео"
                      ? "Видео готово — заменить" : "Фото готово — заменить")
              )
              .accessibilityIdentifier("ии.исходник.кнопка")
            }
            .font(Тема.Шрифт.стиль(.subheadline))
            .frame(maxWidth: .infinity, minHeight: Тема.Кнопка.высота)
            .background(Тема.Цвет.поверхность)
            .foregroundStyle(исходник == nil ? Тема.Цвет.текст : Тема.Цвет.акцент)
            .clipShape(RoundedRectangle(cornerRadius: 8))
          }
          .disabled(идётЗагрузка)

          if let о = ошибкаЗагрузки {
            // Молчаливый провал загрузки выглядит как «кнопка не нажимается».
            Text(о)
              .font(Тема.Шрифт.стиль(.caption))
              .foregroundStyle(Тема.Цвет.предупреждение)
              .fixedSize(horizontal: false, vertical: true)
          }
        }
        .onChange(of: выбранное) { _, новое in
          guard let новое else { return }
          Task { await загрузитьИсходник(новое) }
        }
      }

      /**
       * Модель НЕ предлагается, и это не упрощение.
       *
       * Измерено: у видео путь через MCP падает всегда и запрос уходит в
       * запасной Replicate/seedance независимо от выбранной модели (пустое
       * тело без поля `model` тоже вернуло 200 и ролик). У картинок FAL
       * отвечает «баланс исчерпан», и запрос так же уходит в
       * Replicate/flux-schnell — какую бы из семи моделей ни выбрали.
       *
       * Выпадающий список из семи имён, ни одно из которых сегодня ни на что
       * не влияет, — это и есть мёртвая кнопка, только выглядящая богато.
       * Вместо неё показываем ФАКТИЧЕСКОГО исполнителя: сервер называет его
       * в поле `provider` ответа, и он попадает под результат.
       */
      /**
       * Выбор модели ПЕРЕД кнопкой, а не после.
       *
       * Порядок несёт смысл: сначала чем генерируем, потом что. Обратный
       * порядок приводит к тому, что человек пишет описание и только затем
       * узнаёт, что нужная модель приостановлена.
       *
       * Показаны только модели выбранного вида: сорок четыре строки списком
       * — это не выбор, а поиск.
       */
      VStack(alignment: .leading, spacing: 4) {
        Text("Модель")
          .font(Тема.Шрифт.стиль(.caption))
          .foregroundStyle(Тема.Цвет.текстПриглушённый)

        ForEach(доступныеМодели) { м in
          СтрокаМоделиKie(
            модель: м, выбрана: модель?.id == м.id, пропускает: сервернаяOK(м),
            ценаТокенов: ценаМодели(м),
            посекундная: посекундная(м),
            бесплатно: операцияЦены == nil && м.живая
          ) {
            модель = м
            if вид == .видео && длительность == "5s" { длительность = "6s" }
          }
        }
      }

      историяДляВида

      Button {
