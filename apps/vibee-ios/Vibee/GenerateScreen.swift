          .font(Тема.Шрифт.стиль(.caption))
          .foregroundStyle(Тема.Цвет.текстПриглушённый)
      }

      if идёт {
        /**
         * Ожидание НАЗВАНО, потому что оно ненормально длинное.
         *
         * Сервер отвечает одним синхронным ответом: ни очереди, ни опроса
