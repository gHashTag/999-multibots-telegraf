          .foregroundStyle(Тема.Цвет.текстПриглушённый)
          // Опознаватель нужен, чтобы причину читал ТЕСТ, а не только глаз:
          // денежные отказы проверялись до сих пор одними тестами логики.
          .accessibilityIdentifier("ии.причина")
      }

      if идёт {
        /**
