import Foundation

/**
 * Строка чека под готовым результатом: сколько СПИСАЛИ и сколько ОСТАЛОСЬ.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ, а не строкой внутри вью. Внутри `body` её нельзя
 * ни запустить, ни проверить: UI-тест до неё не доберётся без живой генерации,
 * то есть без списания настоящих токенов, а сборка про текст не знает ничего.
 * Здесь же три случая проверяются мгновенно — и они не гипотетические:
 * согласование числа уже ломалось дважды в этом же приложении («1 дорожек» в
 * таймлайне, «1 токенов» в прайсе), оба раза на единице.
 *
 * Формы слова — через общий `склонение`, а не своей веткой: третья копия того
 * же правила разошлась бы с первыми двумя.
 *
 * - Parameter осталось: `nil` — сервер остатка не назвал (владельцу списывают
 *   ноль, и `осталось` в ответе нет). Тогда про остаток МОЛЧИМ. Подставить
 *   сюда последнее известное значение баланса нельзя: оно относится к моменту
 *   ДО генерации и назовёт остаток, которого уже нет.
 */
func чекСтрокой(списано: Int, осталось: Int?) -> String {
  let сумма = склонение(списано, "токен", "токена", "токенов")
  guard let осталось else { return "Списано \(сумма)" }
  return "Списано \(сумма) · осталось \(осталось)"
}
