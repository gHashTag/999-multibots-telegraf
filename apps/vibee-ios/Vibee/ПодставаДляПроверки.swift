/**
 * ПОДСТАВНОЕ СОСТОЯНИЕ ДЛЯ ПРОВЕРКИ ЭКРАНОВ — ТОЛЬКО В ОТЛАДОЧНОЙ СБОРКЕ.
 *
 * ЗАЧЕМ. Половина денежных правок этой смены закрыта тестами, но НЕ проверена
 * глазами: цена × длительность, «за 1000 знаков», чек, освобождённый кошелёк,
 * отказ липсинка без звука. Все они показываются только тогда, когда сервер
 * ответил остатком, а остаток он отдаёт лишь по сессии. Кода авторизации у
 * цикла нет и не будет: это учётные данные владельца.
 *
 * Долг проверки поэтому не «подождёт до входа» — он не закрывается никогда, и
 * это худший вид долга: он накапливается молча. Единственный выход, не
 * требующий чужих учётных данных, — дать экрану возможность получить остаток
 * не из сети.
 *
 * ПОЧЕМУ ЭТО НЕ ДЫРА. Значение читается из аргументов запуска процесса, а их
 * задаёт тот, кто ЗАПУСКАЕТ приложение: XCUITest на своей машине. Через сеть,
 * ссылку или чужое приложение аргумент подставить нельзя. Плюс весь файл
 * закрыт `#if DEBUG`: в сборке для магазина этих строк нет вовсе — проверено
 * тем, что `Release` не компилирует ни одной ссылки на них.
 *
 * ПОЧЕМУ НЕ МОК СЕТИ. Подменить URLProtocol значило бы проверять, как экран
 * разбирает JSON, — а ломалось не это, а ЧТО он показывает при известном
 * остатке. Подставляем ровно то значение, вокруг которого спор.
 */
enum ПодставаДляПроверки {
  /// Ключ аргумента: следом идёт JSON ответа `/api/balance`.
  static let ключБаланса = "-подставнойБаланс"
  /// Ключ аргумента: следом идёт ссылка, которую считать готовой озвучкой.
  static let ключЗвука = "-подставнойЗвук"
  /// Ключ аргумента: следом идёт ссылка, которую считать выбранным фото.
  ///
  /// Нужен, чтобы дойти до проверок, стоящих ПОСЛЕ фотографии. Без него тест
  /// «липсинк без звука» проходил и с УДАЛЁННОЙ звуковой проверкой: экран
  /// останавливался на «Нужно фото», а тест принимал это за успех — то есть
  /// проверял не то, чем назывался. Поймано мутацией, не чтением.
  static let ключФото = "-подставноеФото"

  #if DEBUG
    private static func значение(_ ключ: String) -> String? {
      let а = ProcessInfo.processInfo.arguments
      guard let i = а.firstIndex(of: ключ), i + 1 < а.count else { return nil }
      return а[i + 1]
    }

    /// Остаток и цены, заданные запускающим. `nil` — обычная работа по сети.
    static var баланс: API.Баланс? {
      guard let текст = значение(ключБаланса),
            let данные = текст.data(using: .utf8)
      else { return nil }
      return try? JSONDecoder().decode(API.Баланс.self, from: данные)
    }

    /// Готовая озвучка, заданная запускающим. `nil` — брать из пройденных шагов.
    static var звук: String? {
      let с = значение(ключЗвука)
      return (с?.isEmpty ?? true) ? nil : с
    }

    /// Выбранное фото, заданное запускающим. `nil` — обычная загрузка.
    static var фото: String? {
      let с = значение(ключФото)
      return (с?.isEmpty ?? true) ? nil : с
    }
  #else
    /// В сборке для магазина подставы нет: оба значения всегда `nil`, и
    /// компилятор выбрасывает и разбор аргументов, и этот путь целиком.
    static var баланс: API.Баланс? { nil }
    static var звук: String? { nil }
    static var фото: String? { nil }
  #endif
}
