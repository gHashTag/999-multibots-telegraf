import SwiftUI

/**
 * Профиль целиком нативный.
 *
 * ЧТО ЗДЕСЬ БЫЛО. `WebScreen(path: "/profile")` под секцией входа. И он
 * ГАРАНТИРОВАННО показывал не профиль: веб узнаёт человека по подписи
 * Telegram, а у WKWebView внутри приложения её нет и не будет. Сначала
 * вкладка молча показывала ленту, потом — экран «профиль не открыть».
 * Оба варианта одинаково бесполезны, просто второй честнее.
 *
 * ЧТО ИЗМЕНИЛОСЬ. Приложение знает свой telegram_id — сервер называет его в
 * ответ на обмен кода. Этого достаточно: имя, аватар и ролики берутся теми же
 * маршрутами, которыми пользуется веб. Никакой подписи для них не нужно —
 * профиль публичный, и это правильно: чужой профиль тоже должен открываться.
 *
 * ПАЛИТРА ЗДЕСЬ СВОЯ — `Тема.Профиль`, а не общая `Тема.Цвет`.
 *
 * Экран был зелёным целиком: чёрный фон #000000, акцент #00ff88 на отметке
 * входа и на @имени. В вебе профиль так не выглядит — у него отдельный scope
 * `.profile-page` с матовым чёрным фоном, кремовым текстом и ЗОЛОТЫМ акцентом.
 * Значения и адреса строк лежат в `Тема.Профиль`, палитра приехала раньше
 * экрана (PR #967) и до этой правки не была вызвана ни разу.
 *
 * ЧЕСТНО ПРО ЗЕЛЁНЫЙ: из Profile.css он никуда не делся. Пересчитано, а не
 * прикинуто — `grep -c 'vibee-amber'` даёт 27 строк против 19 золотых. Файл
 * в двух поколениях, и граница видна по номерам: 26 зелёных из 27 лежат ВЫШЕ
 * :1111, а 17 золотых из 19 — НИЖЕ, внутри блока `.profile-page`, который и
 * переопределяет фоны. Единственный зелёный ниже границы — :1187,
 * `.profile-page__error-home`, кнопка страницы ошибки; такой у нативного
 * экрана нет. Так что «профиль в вебе золотой» — упрощение. Точнее: золотое
 * НОВОЕ поколение, и берём мы его.
 *
 * ПРО ЧИТАЕМОСТЬ. Золото под текстом сплошной заливкой не идёт нигде — ни
 * здесь, ни в вебе. Замер: белый на #ffd700 даёт 1.40:1, то есть повторил бы
 * ровно ту жалобу, из-за которой на зелёных кнопках стоит чёрный текст.
 * Вместо заливки — вебовская связка «золотая рамка + заливка 10% + золотой
 * текст». По снятому кадру: золотая подпись на фоне страницы 14.53:1,
 * на заливке кнопки 12.42:1, тёплый красный «Выйти» 7.34:1, кремовый текст
 * на плитке 14.78:1. Белых пикселей в содержимом экрана не осталось вовсе —
 * единственные #ffffff на скриншоте это часы в строке состояния.
 */
/**
 * Плитка пакета — ОТДЕЛЬНЫМ типом, и строки считаются вне тела.
 *
 * Три витка этот раздел не собирался. Компилятор сообщал про `Binding` и про
 * присваивание там, где идёт чтение, — и то и другое было капитуляцией вывода
 * типов, а не диагнозом. Настоящий ответ («unable to type-check in reasonable
 * time») появился только после упрощения. Детонатор — склейка `String(x) + " ★"`
 * посреди цепочки модификаторов: перегруженный обобщённый `+` даёт
 * комбинаторный перебор.
 *
 * Отсюда форма: свой тип, строки в отдельных `private var`, фон и рамка тоже
 * вынесены. Это не украшение кода, а условие его компиляции.
 */
private struct ПлиткаПакета: View {
  let пакет: API.TokenPack

  private var числоТокенов: String { String(пакет.токенов) }
  private var цена: String { String(пакет.звёзд) + " ★" }
  private var подпись: String {
    String(пакет.токенов) + " токенов за " + String(пакет.звёзд) + " звёзд"
  }

  var body: some View {
    VStack(spacing: 2) {
      Text(числоТокенов)
        .font(Тема.Шрифт.стиль(.title3, .bold))
        .foregroundStyle(Тема.Профиль.акцент)
      // Звезда — валюта Telegram, а не украшение: для VoiceOver подпись
      // проговаривает её словом, иначе читается как «звёздочка».
      Text(цена)
        .font(Тема.Шрифт.стиль(.caption2))
        .foregroundStyle(Тема.Профиль.текстПриглушённый)
    }
    .frame(maxWidth: .infinity, minHeight: 44)
    .padding(.vertical, 10)
    .background(фон)
    .overlay(рамка)
    .accessibilityElement(children: .ignore)
    .accessibilityLabel(подпись)
  }

  private var фон: some View {
    RoundedRectangle(cornerRadius: Тема.Профиль.радиусКарточки)
      .fill(Тема.Профиль.поверхность)
  }

  private var рамка: some View {
    RoundedRectangle(cornerRadius: Тема.Профиль.радиусКарточки)
      .strokeBorder(
        Тема.Профиль.границаЗаметная,
        lineWidth: Тема.Профиль.толщинаГраницы
      )
  }
}

struct ProfileScreen: View {
  @State private var профиль: API.Profile?
  @State private var ролики: [API.Template] = []
  @State private var грузим = true
  @State private var ошибка: String?
  /// Растёт при входе и выходе — по нему перезагружаются данные.
  @State private var версия = 0
  @State private var пакеты: [API.TokenPack] = []
  /// nil — ещё не спросили. Отличать от нуля обязательно: ноль это ответ,
  /// nil это отсутствие ответа, и на экране они значат разное.
  @State private var остаток: Int?
  /// Визитка человека. `nil` — её просто нет, и это обычный случай.
  @State private var soul: String?
  @State private var soulРазвёрнут = false
  /// Ролики агента, ждущие одобрения. Пусто — их правда нет.
  @State private var ожидают: [API.Ожидающий] = []
  /// id того, который сейчас публикуется: кнопка не должна нажиматься дважды.
  @State private var публикую: Int?
  @State private var ошибкаОдобрения: String?
  /// Контент-план: то, чем человек и агент обмениваются работой.
  @State private var план: [API.ЦельПлана] = []
  /// id карточки, статус которой сейчас меняется.
  @State private var меняюСтатус: Int?
  @State private var ошибкаПлана: String?

  var body: some View {
    ScrollView {
      VStack(alignment: .leading, spacing: Тема.Отступ.lg) {
        доступ

        if Identity.telegramId != nil {
          if грузим {
            ProgressView()
              .tint(Тема.Профиль.акцент)
              .frame(maxWidth: .infinity)
              .padding(.vertical, Тема.Отступ.xl)
          } else if let ошибка {
            подпись(ошибка)
          } else if let профиль {
            шапка(профиль)
            // Счётчики СРАЗУ под шапкой, как в вебе (ProfileHeader.tsx): там
            // они часть шапки, и человек читает их одним движением сверху
            // вниз. Перенести их ниже токенов значило бы сделать «тот же
            // экран» с другим порядком чтения.
            счётчики(профиль)
            // SOUL сразу за счётчиками — тот же порядок чтения, что в вебе
            // (Profile.tsx: шапка → счётчики → SOUL → вкладки).
            карточкаSoul
            токены
            /*
             * ПОДКЛЮЧЕНИЕ TELEGRAM — там же, где в вебе: во вкладке «Агент»,
             * рядом с входом. Это и есть то, ЧЕМ агент будет пользоваться, и
             * читается оно как продолжение одной мысли, а не как отдельная
             * настройка, до которой ещё надо додуматься.
             *
             * Показываем ТОЛЬКО вошедшим: подключать чужую переписку
             * неопознанному человеку нечего, а форма, которая всё равно
             * ответит 401, — обещание без покрытия.
             */
            if Identity.telegramId != nil {
              ConnectTelegramView()
            }
            /*
             * ЖДУТ ОДОБРЕНИЯ — НАД «Роликами», а не под ними.
             *
             * В вебе этот раздел стоит сразу за «Шаблонами» (ProfileTabs.tsx:
             * templates → pending), и порядок там осмысленный: сначала то, что
             * ТРЕБУЕТ ДЕЙСТВИЯ, потом то, что просто лежит.
             *
             * Здесь то же: сделанное агентом ждёт решения, и прятать его под
             * ленту своих роликов значило бы, что человек до него не долистает.
             */
            ждутОдобрения
            /*
             * ПЛАН — ниже одобрения, выше роликов.
             *
             * В вебе порядок вкладок: шаблоны → ждут одобрения → план. Тот же
             * смысл: сперва то, что требует решения СЕЙЧАС, потом то, чем
             * живёшь дальше, и только потом готовое.
             */
            карточкаПлана
            сетка
          }
        }
      }
      .padding(Тема.Отступ.md)
    }
    // #050505, а не #000000 общей темы: Profile.css:1114 и :1122.
    .background(Тема.Профиль.фон)
    .task(id: версия) { await загрузить() }
  }

  // MARK: - Куски

  /**
   * Секция доступа СВЕРХУ и всегда.
   *
   * Соблазн был спрятать её после входа. Но «выйти» — единственное действие,
   * которое человек ищет именно в профиле, и прятать его за раскрывающийся
   * блок значит прятать единственную кнопку, ради которой сюда заходят.
   */
  @ViewBuilder private var доступ: some View {
    if Identity.hasSession {
      HStack {
        Label("Вы вошли", systemImage: "checkmark.shield")
          .font(Тема.Шрифт.стиль(.subheadline, .medium))
          // Золото вместо зелёного: акцент нового профиля — Profile.css:555.
          .foregroundStyle(Тема.Профиль.акцент)
        Spacer()
        Button {
          Task {
            await Identity.logout()
            профиль = nil
            ролики = []
            версия += 1
          }
        } label: {
          Text("Выйти")
        }
        /**
         * Тёплый #ff6b6b, а не общий #ef4444 — почему именно так, расписано
         * у самого токена `Тема.Профиль.красный`.
         *
         * Форма — та же пилюля, что у остальных кнопок профиля, и БЕЗ
         * заливки: у трёх из четырёх вебовских кнопок `background`
         * прозрачный (Profile.css:1608, :1767, и заливка на :1616 только
         * под курсором). Контраст на кадре: 7.34:1.
         */
        .buttonStyle(Тема.Пилюля(цвет: Тема.Профиль.красный, заливка: .clear))
      }
    } else {
      VStack(alignment: .leading, spacing: Тема.Отступ.карточкаЛенты) {
        Label("Нужен вход", systemImage: "exclamationmark.shield")
          .font(Тема.Шрифт.стиль(.subheadline, .medium))
          /**
           * ЗОЛОТО, А НЕ `Цвет.предупреждение` #eab308.
           *
           * Прежний #eab308 и золото #ffd700 — два почти одинаковых жёлтых,
           * и после этой правки они попадали бы на один экран: отметка
           * состояния одним, кнопка входа под ней — другим. Ровно такую пару
           * Theme.swift уже фиксирует как дефект на двух зелёных таймлайна.
           * Вебовского источника у этой строки нет — экрана «нужен вход» в
           * вебе не существует, — поэтому свожу к акценту профиля, а не
           * держу второй жёлтый ради статусной семантики.
           */
          .foregroundStyle(Тема.Профиль.акцент)
        SignInView { версия += 1 }
      }
    }
  }

  /**
   * Раздел исчезает целиком, когда сервер вернул пусто: это либо выключенная
   * продажа (флаг `включено`), либо отказ. Пустой раздел ПРО ДЕНЬГИ пугает
   * сильнее, чем его отсутствие — человек решает, что у него что-то сгорело.
   */
  @ViewBuilder private var токены: some View {
    if !пакеты.isEmpty {
      VStack(alignment: .leading, spacing: 8) {
        HStack(alignment: .firstTextBaseline) {
          Text("Токены")
            .font(Тема.Шрифт.стиль(.subheadline, .semibold))
            .foregroundStyle(Тема.Профиль.текст)
          Spacer()
          /**
           * ОСТАТОК РЯДОМ С ПАКЕТАМИ, и это не украшение.
           *
           * Здесь были только пакеты «10 / 50 / 150» — цены на ПОКУПКУ. Своего
           * числа на экране не было вовсе, и витрину читали как счёт: «у меня
           * же есть на балансе». Узнать правду можно было единственным
           * способом — нажать «Сгенерировать» и получить отказ, уже выбрав
           * модель и дождавшись сервера.
           *
           * Пока не загрузилось — не пишем ноль. Ноль здесь означал бы
           * «у вас пусто», то есть враньё на секунду раньше правды.
           */
          if let б = остаток {
            Text("есть \(б)")
              .font(Тема.Шрифт.стиль(.subheadline, .semibold))
              .foregroundStyle(Тема.Цвет.акцент)
              .accessibilityIdentifier("профиль.баланс")
          } else {
            ProgressView().controlSize(.mini)
          }
        }
        HStack(spacing: Тема.Профиль.просветСетки) {
          ForEach(пакеты) { пакет in
            ПлиткаПакета(пакет: пакет)
          }
        }
      }
    }
  }

  private func шапка(_ p: API.Profile) -> some View {
    HStack(alignment: .top, spacing: Тема.Отступ.пузырьЧата) {
      // AsyncImage, а не своя загрузка: система сама кеширует, отменяет при
      // уходе с экрана и не держит картинку в памяти дольше нужного.
      AsyncImage(url: p.avatar_url.flatMap(URL.init(string:))) { фаза in
        if let img = фаза.image {
          img.resizable().scaledToFill()
        } else {
          // #0d0d0c — `--bg-elevated` профиля, Profile.css:1123
          Тема.Профиль.поверхность
        }
      }
      .frame(width: 72, height: 72)
      .clipShape(Circle())
      .overlay(
        Circle().strokeBorder(
          Тема.Профиль.границаЗаметная, lineWidth: Тема.Профиль.толщинаГраницы
        )
      )

      VStack(alignment: .leading, spacing: Тема.Отступ.xs) {
        Text(p.display_name ?? p.username)
          /**
           * ВЕС 700, А НЕ 600.
           *
           * `.profile-header__name { font-weight: 700 }` — Profile.css:225,
           * и правило веса ниже по файлу не перебивается: в блоке
           * `@media (max-width: 480px)` меняется только кегль
           * (Profile.css:1322-1324). Стоял `.semibold`, то есть 600 —
           * ближайший сосед, отличающийся ровно на одну ступень; такое
           * расхождение глазом не ловится и живёт годами.
           *
           * Кегль оставлен семантическим `.title3`: система раскрывает его
           * в 20 pt при обычном размере текста — ровно те 1.25rem, которые
           * веб даёт на 402 pt (Profile.css:1323). Число совпало, а
           * масштабирование под Dynamic Type сохранилось.
           */
          .font(Тема.Шрифт.стиль(.title3, .bold))
          // Кремовый #e6e0d2, а не белый: Profile.css:1640, :1702, :1908.
          .foregroundStyle(Тема.Профиль.текст)
        Text("@\(p.username)")
          .font(Тема.Шрифт.стиль(.subheadline))
          .foregroundStyle(Тема.Профиль.акцент)
        if let bio = p.bio, !bio.isEmpty {
          Text(bio)
            .font(Тема.Шрифт.стиль(.footnote))
            .foregroundStyle(Тема.Профиль.текстВторичный)
            .fixedSize(horizontal: false, vertical: true)
        }
      }
      Spacer(minLength: 0)
    }
  }

  /**
   * СЧЁТЧИКИ — ТЕ ЖЕ ПЯТЬ, В ТОМ ЖЕ ПОРЯДКЕ, ЧТО В ВЕБЕ.
   *
   * Владелец 07.09.2026: «страницы профиля должны совпадать по логике и
   * дизайну — сайт и в мобиле».
   *
   * Порядок и подписи взяты из `ProfileHeader.tsx:65-71`: подписчики,
   * подписки, видео, просмотры, лайки. Порядок здесь — не вкусовщина: человек,
   * привыкший к вебу, читает вторую колонку как «подписки», и переставленные
   * местами числа он не перепроверяет, а запоминает неверно.
   *
   * Сокращение тысяч повторяет `ProfileHeader.tsx:58-62` (1.2K, 3.4M) —
   * иначе одно и то же число выглядит на двух экранах по-разному.
   */
  @ViewBuilder private func счётчики(_ p: API.Profile) -> some View {
    HStack(spacing: 0) {
      счётчик(p.followers_count, "ПОДПИСЧИКИ")
      счётчик(p.following_count, "ПОДПИСКИ")
      счётчик(p.templates_count, "ВИДЕО")
      счётчик(p.total_views, "ПРОСМОТРЫ")
      счётчик(p.total_likes, "ЛАЙКИ")
    }
  }

  @ViewBuilder private func счётчик(_ значение: Int?, _ подпись: String) -> some View {
    VStack(spacing: Тема.Отступ.xs) {
      Text(кратко(значение ?? 0))
        .font(Тема.Шрифт.стиль(.subheadline, .bold))
        .foregroundStyle(Тема.Профиль.текст)
      Text(подпись)
        .font(Тема.Шрифт.стиль(.caption2))
        .foregroundStyle(Тема.Профиль.текстПриглушённый)
        // Одна строка на подпись: «ПРОСМОТРЫ», перенесённое пополам, ломает
        // ряд по высоте, и пять колонок перестают читаться как один ряд.
        .lineLimit(1)
        .minimumScaleFactor(0.7)
    }
    .frame(maxWidth: .infinity)
  }

  /** 1234 → «1.2K», 3400000 → «3.4M». Ровно как `formatNumber` в вебе. */
  private func кратко(_ n: Int) -> String {
    if n >= 1_000_000 {
      return String(format: "%.1fM", Double(n) / 1_000_000)
    }
    if n >= 1000 {
      return String(format: "%.1fK", Double(n) / 1000)
    }
    return String(n)
  }

  /**
   * SOUL.md — ВИЗИТКА, А НЕ ИСХОДНИК MARKDOWN.
   *
   * Владелец 07.09.2026: «страницы профиля должны совпадать по логике и
   * дизайну». В вебе эта карточка есть (`SoulCard.tsx`), на телефоне её не
   * было вовсе — при том что сервер отдаёт текст тем же адресом.
   *
   * Разбирается ровно то подмножество, которым SOUL и написан: заголовки двух
   * уровней и абзацы — как в вебе (`SoulCard.tsx:44-68`). Полный markdown сюда
   * не тянется: в SOUL нет таблиц и ссылок, а вместе с ними пришла бы
   * возможность выполнить чужую разметку на нашем экране.
   *
   * Свёртка до шести строк и подписи «Читать целиком» / «Свернуть» взяты
   * оттуда же (`СТРОК_В_ПРЕВЬЮ = 6`): человек, знающий веб, ищет ту же кнопку
   * на том же месте.
   */
  @ViewBuilder private var карточкаSoul: some View {
    if let текст = soul {
      let строки = текст.components(separatedBy: "\n")
      let длинный = строки.count > Self.строкВПревью
      let показать = soulРазвёрнут || !длинный
        ? строки
        : Array(строки.prefix(Self.строкВПревью))

      VStack(alignment: .leading, spacing: Тема.Отступ.xs) {
        Text("SOUL.md")
          .font(Тема.Шрифт.стиль(.subheadline, .semibold))
          .foregroundStyle(Тема.Профиль.текстПриглушённый)

        ForEach(Array(показать.enumerated()), id: \.offset) { _, строка in
          строкаSoul(строка)
        }

        if длинный {
          Button {
            withAnimation(.easeInOut(duration: 0.2)) { soulРазвёрнут.toggle() }
          } label: {
            Text(soulРазвёрнут ? "Свернуть" : "Читать целиком")
              .font(Тема.Шрифт.стиль(.footnote, .medium))
              .foregroundStyle(Тема.Профиль.акцент)
          }
          .buttonStyle(.plain)
          // 44 pt — минимальная цель касания: кнопка из одной строки текста
          // иначе не нажимается пальцем с первого раза.
          .frame(minHeight: 44, alignment: .leading)
        }
      }
      .frame(maxWidth: .infinity, alignment: .leading)
    }
  }

  /** Шесть строк превью — ровно как `СТРОК_В_ПРЕВЬЮ` в вебе. */
  private static let строкВПревью = 6

  @ViewBuilder private func строкаSoul(_ строка: String) -> some View {
    let чистая = строка.trimmingCharacters(in: .whitespaces)
    if чистая.isEmpty {
      // Пустая строка — это ПРОБЕЛ между блоками, а не текст: в вебе она
      // рисуется отдельным элементом (`soul-card__gap`).
      Color.clear.frame(height: Тема.Отступ.xs)
    } else if чистая.hasPrefix("## ") {
      Text(String(чистая.dropFirst(3)))
        .font(Тема.Шрифт.стиль(.subheadline, .semibold))
        .foregroundStyle(Тема.Профиль.текст)
    } else if чистая.hasPrefix("# ") {
      Text(String(чистая.dropFirst(2)))
        .font(Тема.Шрифт.стиль(.headline, .bold))
        .foregroundStyle(Тема.Профиль.текст)
    } else {
      Text(чистая)
        .font(Тема.Шрифт.стиль(.footnote))
        .foregroundStyle(Тема.Профиль.текстВторичный)
        .fixedSize(horizontal: false, vertical: true)
    }
  }

