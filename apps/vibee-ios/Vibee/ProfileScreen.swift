   *
   * Владелец 07.09.2026: паритет профиля. До этого план был доступен на
   * телефоне ТОЛЬКО через просьбу агенту в чате: человек мог попросить
   * спланировать ролики и не увидеть ни составленного плана, ни возможности
   * отметить вышедшее.
