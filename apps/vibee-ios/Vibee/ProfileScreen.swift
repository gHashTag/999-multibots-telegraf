  // MARK: - Загрузка

  private func загрузить() async {
    guard let id = Identity.telegramId else {
      грузим = false
      return
    }
    грузим = true
    ошибка = nil
    do {
      let p = try await API.profile(telegramId: id)
      профиль = p
      // Ролики грузим ВТОРЫМ запросом и не роняем из-за них весь экран:
      // профиль без списка полезен, список без профиля — нет.
      ролики = (try? await API.userTemplates(username: p.username)) ?? []
      // SOUL — третьим и так же необязательно: профиль без визитки полезен,
      // визитка без профиля бессмысленна.
      soul = try? await API.soul(username: p.username)
      // Список ожидающих — тоже необязательно: профиль без него полезен.
      ожидают = (try? await API.ожидаютОдобрения()) ?? []
      // План — тоже необязательно: профиль без него полезен.
      план = (try? await API.планПрочитать()) ?? []
      пакеты = await API.tokenPacks()
      // Остаток НЕ обязателен для экрана: без входа его нет, и профиль обязан
      // открыться всё равно. Поэтому отдельной попыткой и без throw наружу.
      остаток = try? await API.баланс().balance
    } catch {
      /*
       * ПРИЧИНА НАЗЫВАЕТСЯ СВОИМИ СЛОВАМИ, А НЕ ПРЯЧЕТСЯ ЗА «НЕ ЗАГРУЗИЛСЯ».
       *
       * Отсутствие @имени — не сбой, а обычное состояние нового человека:
       * сервер честно отвечает 200 с пустым именем. Приписка «Профиль не
       * загрузился» превращала это в поломку и отправляла искать несуществующую
       * причину — ту же ошибку я месяцем раньше чинил в вебе.
       */
      if let своя = error as? API.ПрофильError {
        ошибка = своя.errorDescription
      } else {
        ошибка = "Профиль не загрузился: \(error.localizedDescription)"
      }
    }
    грузим = false
  }
