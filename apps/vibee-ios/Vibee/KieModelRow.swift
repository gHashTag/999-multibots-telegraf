import SwiftUI

/// Строка выбора: живые нажимаются, приостановленные видны и объяснены.
struct СтрокаМоделиKie: View {
  let модель: Модель
  let выбрана: Bool
  /**
   * Пропустит ли эту модель сервер.
   *
   * Поле добавлялось вместе с вызывающим кодом, но на свежий `main` доехала
   * только половина: `GenerateScreen` передавал `пропускает:`, а структура
   * его уже не принимала — `main` не собирался вовсе. Половина парной правки,
   * потерянная при переносе, выглядит как чужая ошибка ровно до тех пор, пока
   * не посмотришь, кто автор обеих.
   */
  var пропускает: Bool = true
  let нажать: () -> Void

  var body: some View {
    Button(action: нажать) {
      HStack(spacing: 12) {
        VStack(alignment: .leading, spacing: 3) {
          Text(модель.название)
            .font(Тема.Шрифт.стиль(.subheadline))
            .foregroundStyle(
              модель.живая && пропускает ? Тема.Цвет.текст : Тема.Цвет.текстПриглушённый
            )

          if let причина = модель.почемуНельзя {
            Text(причина)
              .font(Тема.Шрифт.стиль(.caption))
              .foregroundStyle(Тема.Цвет.предупреждение)
              .fixedSize(horizontal: false, vertical: true)
          } else {
            Text("нужно: \(модель.требует)")
              .font(Тема.Шрифт.стиль(.caption))
              .foregroundStyle(Тема.Цвет.текстПриглушённый)
          }
        }

        Spacer(minLength: 8)

        // Цена справа: человек решает «стоит ли», а не «что это». Молчание
        // здесь означало, что цену узнают уже по списанию.
        if let ценник = модель.ценник {
          Text(ценник)
            .font(Тема.Шрифт.стиль(.caption))
            .foregroundStyle(Тема.Цвет.текстПриглушённый)
            .multilineTextAlignment(.trailing)
            .fixedSize(horizontal: false, vertical: true)
        } else if !пропускает {
          // Причина словами: «недоступна» без объяснения читается как
          // поломка, и человек жмёт снова.
          Text("сервер не подключил")
            .font(Тема.Шрифт.стиль(.caption2))
            .foregroundStyle(Тема.Цвет.текстПриглушённый)
        } else if модель.живая {
          // Не молчим и об отсутствии: «—» честнее пустоты, из которой
          // человек заключит, что бесплатно.
          Text("цену не назвали")
            .font(Тема.Шрифт.стиль(.caption))
            .foregroundStyle(Тема.Цвет.текстПриглушённый.opacity(0.7))
        }

        if выбрана && модель.живая {
          Image(systemName: "checkmark").foregroundStyle(Тема.Цвет.акцент)
        }
      }
      .padding(.vertical, 10)
      .padding(.horizontal, 14)
      // 44pt — минимальная цель касания в HIG; две мелкие подписи дают меньше.
      .frame(minHeight: 44)
      .frame(maxWidth: .infinity, alignment: .leading)
      // Как в вебе: РАМКА, а не заливка, и радиус 8 вместо 10.
      .overlay(
        RoundedRectangle(cornerRadius: 8)
          .strokeBorder(
            выбрана ? Тема.Цвет.акцент : Color.clear, lineWidth: 1.5
          )
      )
      /**
       * БЕЗ ЭТОЙ СТРОКИ НАЖИМАЛИСЬ ТОЛЬКО БУКВЫ.
       *
       * SwiftUI считает попаданием лишь НАРИСОВАННОЕ, а фон невыбранной
       * строки — `Color.clear`, то есть не нарисован ничем. Поэтому живой
       * зоной оставались глифы названия и подписи, а вся пустота между ними
       * и справа от них — а это большая часть строки — нажатий не принимала.
       *
       * Отсюда и вся странность, которую я списывал на свою неточность:
       * ручные тапы по координатам «мазали», XCUITest находил элемент и
       * жал по его центру — ровно в пустоту между названием и ценой, — и
       * «Выберите модель» не исчезало. Ошибка выглядела как промах, а была
       * дырой в области нажатия.
       *
       * Выбранная строка попадалась легче невыбранной, потому что у неё фон
       * НЕ прозрачный. Асимметрия, которую невозможно заподозрить, пока не
       * посмотришь на hit-testing.
       *
       * У вкладок видов сверху ровно от этого стоит `.contentShape(Capsule())`
       * — приём в этом файле уже знали, до строки моделей он не дошёл.
       */
      .contentShape(RoundedRectangle(cornerRadius: 10))
    }
    .buttonStyle(.plain)
    .disabled(!модель.живая || !пропускает)
    // Опознаватель НА КНОПКЕ, а не на обёртке снаружи: XCUITest находил
    // внешний контейнер, его тап не доходил до Button, и тест падал ровно
    // так же, как падали мои ручные тапы по координатам.
    .accessibilityIdentifier("ии.модель.\(модель.id)")
  }
}
