/// Видео во весь экран, без контролов.
///
/// `VideoPlayer` из SwiftUI показывает системные контролы и вписывает кадр
/// целиком — по краям остаются поля. В вертикальной ленте нужно обратное:
/// кадр заполняет экран, обрезаясь по длинной стороне, и ничего не мешает
/// смотреть. Это ровно то, ради чего слой берётся напрямую: `resizeAspectFill`
/// у `AVPlayerLayer` — то самое поведение, которое в вебе изображают через
/// `object-fit: cover`, только без промежуточного слоя.
struct PlayerLayerView: UIViewRepresentable {
  let player: AVPlayer

  func makeUIView(context: Context) -> PlayerHostView {
    let v = PlayerHostView()
    v.playerLayer.player = player
    v.playerLayer.videoGravity = .resizeAspectFill
    v.backgroundColor = UIColor(Тема.Цвет.фон)
    return v
  }

  func updateUIView(_ v: PlayerHostView, context: Context) {
    if v.playerLayer.player !== player { v.playerLayer.player = player }
  }
}

/// Слой обязан быть слоем самого view: иначе он не растягивается за ним и
/// при повороте или смене размера остаётся прежнего размера.
final class PlayerHostView: UIView {
  override static var layerClass: AnyClass { AVPlayerLayer.self }
  var playerLayer: AVPlayerLayer { layer as! AVPlayerLayer }
}

/**
 * Ремикс: рецепт → правка слов → рендер → ссылка.
 *
 * ЧТО ЗДЕСЬ ПРАВЯТ. Рилс в этом сервисе — это JSON `{compositionId, props}`, а
 * не набор дорожек: замер прода 2026-09-03 показал у всех 25 свежих записей
 * ленты пустые `assets` и `tracks` (`"[]"`, два символа) и весь ролик в
 * `props`. Поэтому ремикс — это правка пропсов и повторная сборка ТОЙ ЖЕ
 * композиции, а не открытие таймлайна. Редактор здесь был бы враньём: двигать
 * в нём нечего.
 *
 * ПОЧЕМУ ЭКРАН НЕ ЗАКРЫВАЕТСЯ САМ. Ни один отказ не уводит человека и не
 * закрывает экран: уход читается как «получилось». Каждый исход — рецепт не
 * взят, композиция неизвестна, рендер упал, задание потеряно, ожидание
 * затянулось — доходит сюда текстом и, если повтор осмыслен, кнопкой повтора.
 *
 * ПОЧЕМУ ФАЙЛ ТОТ ЖЕ. Экран достижим только из ленты и живёт её данными
 * (`API.Template`), а `Vibee.xcodeproj` перечисляет исходники поимённо —
 * новый файл потребовал бы правки самого проекта ради одного экрана.
 */
struct RemixView: View {
  let template: API.Template
  /// Закрыть. Зовётся ТОЛЬКО по решению человека — см. комментарий выше.
  let закрыть: () -> Void

  @State private var шаг: Шаг = .берёмРецепт
  @State private var рецепт: API.Рецепт?
  @State private var поля: [Поле] = []
  /// renderId. Нужен, чтобы «спросить ещё раз» шло к ТОМУ ЖЕ заданию, а не
  /// заводило второе: каждый рендер занимает сервер на минуты.
  @State private var задание: String?
  @State private var процент = 0
  @State private var прошло = 0
  @State private var часы: Task<Void, Never>?
  @State private var работа: Task<Void, Never>?
  /// Плеер результата держим в состоянии: новый `AVPlayer` на каждой
  /// перерисовке сбрасывал бы воспроизведение на начало.
  @State private var плеер: AVPlayer?

  enum Шаг {
    case берёмРецепт
    case правка
    case рендер
    case готово(URL)
    case отказ(String, Повтор)
  }

  /// Что осмысленно повторить после этого отказа. `нечего` — когда повторять
  /// нечего, и рисовать кнопку значило бы предложить бессмысленное действие.
  enum Повтор: Equatable { case рецепт, рендер, состояние, нечего }

  /// Одно правимое поле рецепта. `id` — ключ пропса: двух одинаковых ключей в
  /// JSON-объекте не бывает, значит отдельный идентификатор был бы выдумкой.
  struct Поле: Identifiable {
    let id: String
    let подпись: String
    var значение: String
  }

  var body: some View {
    ZStack {
      Тема.Цвет.фон.ignoresSafeArea()
      VStack(alignment: .leading, spacing: 0) {
        шапка
        Divider().overlay(Тема.Цвет.граница)
        ScrollView {
          VStack(alignment: .leading, spacing: Тема.Отступ.md) {
            содержимое
          }
          .padding(Тема.Отступ.md)
          .frame(maxWidth: .infinity, alignment: .leading)
        }
      }
    }
    .task { await взятьРецепт() }
    // Экран закрыли — сеть и часы обязаны остановиться вместе с ним: иначе
    // опрос стучится к серверу ещё десять минут после того, как его никто
    // не ждёт.
    //
    // `плеер?.pause()` — не мелочь: `AVPlayer` не останавливается оттого, что
    // его view исчез, и звук готового ролика продолжал бы идти поверх ленты.
    // Это ровно та жалоба «закрыл, а слышно», от которой карточка ленты
    // защищается своим `onDisappear`.
    .onDisappear {
      часы?.cancel()
      работа?.cancel()
      плеер?.pause()
    }
  }

  // MARK: - Куски

  private var шапка: some View {
    HStack(alignment: .top, spacing: Тема.Отступ.sm) {
      VStack(alignment: .leading, spacing: 2) {
        Text("Ремикс")
          .font(Тема.Шрифт.стиль(.headline, .semibold))
          .foregroundStyle(Тема.Цвет.текст)
        Text(template.name)
          .font(Тема.Шрифт.стиль(.caption))
          .foregroundStyle(Тема.Цвет.текстПриглушённый)
          .lineLimit(1)
      }
      Spacer(minLength: 0)
      Button("Закрыть") { закрыть() }
        .font(Тема.Шрифт.стиль(.subheadline, .medium))
        .foregroundStyle(Тема.Цвет.акцент)
        // Высота ЯВНАЯ: у текстовой кнопки она иначе собирается из кегля и
        // выходит около 20 pt — тот же дефект, что описан в `КнопкаДействия`.
        .frame(minWidth: Тема.Касание.минимум, minHeight: Тема.Касание.минимум)
        .contentShape(Rectangle())
    }
    .padding(.horizontal, Тема.Отступ.md)
    .padding(.top, Тема.Отступ.sm)
  }

  @ViewBuilder private var содержимое: some View {
    switch шаг {
    case .берёмРецепт:
      ожидание("Берём рецепт ролика…")
    case .правка:
      форма
    case .рендер:
      ходРаботы
    case .готово(let ссылка):
      результат(ссылка)
    case .отказ(let текст, let повтор):
      отказ(текст, повтор)
    }
  }

  @ViewBuilder private var форма: some View {
    Text("Слова ваши, всё остальное переносится из оригинала.")
      .font(Тема.Шрифт.стиль(.subheadline, .medium))
      .foregroundStyle(Тема.Цвет.текст)

    // Пустая форма без объяснения читается как не догрузившийся экран. Такое
    // возможно у рецепта, где текста нет вовсе (одни списки и ссылки), — и
    // сказать об этом честнее, чем показать пустоту с кнопкой.
    if поля.isEmpty {
      плашка(
        значок: "text.badge.xmark",
        цвет: Тема.Цвет.предупреждение,
        текст: "В этом рецепте нет ни одного текстового поля — править нечего. "
          + "Собрать копию всё равно можно."
      )
    }

    ForEach($поля) { $п in
      VStack(alignment: .leading, spacing: 6) {
        Text(п.подпись)
          .font(Тема.Шрифт.стиль(.caption))
          .foregroundStyle(Тема.Цвет.текстПриглушённый)
        // `axis: .vertical` + растущий предел строк: заголовок в этих
        // рецептах бывает длиной в предложение, а однострочное поле
        // показывало бы человеку кусок собственного текста.
        TextField(п.подпись, text: $п.значение, axis: .vertical)
          .textFieldStyle(.plain)
          .font(Тема.Шрифт.стиль(.subheadline))
          .lineLimit(1...6)
          .padding(12)
          .background(Тема.Цвет.поверхность, in: RoundedRectangle(cornerRadius: Тема.Радиус.xl))
      }
    }

    /**
     * Что уезжает НЕТРОНУТЫМ — названо поимённо.
     *
     * В рецепте есть поля, которые текстом не правят: списки (`tags`,
     * `plates`), ссылки на постер и видео-медальон, служебные ручки громкости.
     * Промолчать о них значило бы дать человеку думать, что он видит весь
     * ролик целиком, — а потом получить чужую картинку и чужие плашки в своём
     * ремиксе и не понять, откуда они.
     */
    if !переносится.isEmpty {
      Text("Без изменений переносится: \(переносится.joined(separator: ", "))")
        .font(Тема.Шрифт.стиль(.caption))
        .foregroundStyle(Тема.Цвет.текстПриглушённый)
    }
    if let р = рецепт {
      Text("Композиция: \(р.compositionId)")
        .font(Тема.Шрифт.моно(.caption))
        .foregroundStyle(Тема.Цвет.текстПриглушённый)
    }

    /**
     * Про публикацию говорим ДО нажатия, а не после.
     *
     * Мы намеренно не шлём серверу `userInfo` — с ним рендер сам публикует
     * ролик в общую ленту (render-server.ts:2130-2146). Человек, нажавший
     * «собрать», не просил публиковать; но и молча оставить его в неведении
     * нельзя: «а где мой ролик» — такой же плохой исход, как неожиданная
     * публикация.
     */
    плашка(
      значок: "eye.slash",
      цвет: Тема.Цвет.предупреждение,
      текст: "Ролик соберётся только для вас: в общую ленту он не попадёт. "
        + "Публикация — отдельное решение, и в приложении её пока нет."
    )

    Button {
      работа?.cancel()
      работа = Task { await собрать() }
    } label: {
      HStack(spacing: Тема.Отступ.sm) {
        Image(systemName: "wand.and.stars")
        Text("Собрать ролик")
      }
      .font(Тема.Шрифт.стиль(.headline, .semibold))
      .frame(maxWidth: .infinity, minHeight: Тема.Кнопка.высота)
      .background(Тема.Кнопка.основнаяФон, in: RoundedRectangle(cornerRadius: Тема.Радиус.md))
      .foregroundStyle(Тема.Кнопка.основнаяТекст)
    }
    .buttonStyle(.plain)
  }

  private var ходРаботы: some View {
    VStack(alignment: .leading, spacing: Тема.Отступ.sm) {
      HStack(spacing: Тема.Отступ.sm) {
        ProgressView().tint(Тема.Цвет.акцент)
        // Проценты показываем ТОЛЬКО когда сервер их прислал: «0 %» на
        // задании, которое ещё стоит в очереди, читается как «не двигается».
        Text(процент > 0 ? "Собираем: \(процент)% · \(прошло) с" : "Собираем: \(прошло) с")
          .font(Тема.Шрифт.стиль(.subheadline, .medium))
          .foregroundStyle(Тема.Цвет.текст)
          .monospacedDigit()
      }
      /**
       * Ожидание НАЗВАНО, как и в генерации: молчащий спиннер на минуты
       * неотличим от зависшего приложения. Числа здесь нет намеренно — в
       * отличие от генерации (замеренные 50–70 с) время рендера зависит от
       * длины ролика и загрузки сервера, и обещать секунды было бы выдумкой.
       */
      Text("Сервер рисует ролик кадр за кадром — это минуты, а не секунды.")
        .font(Тема.Шрифт.стиль(.footnote))
        .foregroundStyle(Тема.Цвет.текстПриглушённый)
      /**
       * Цена закрытия названа заранее.
       *
       * Задание живёт в памяти процесса рендера (`renderJobs`), списка своих
       * рендеров сервер не отдаёт, и `renderId` есть только здесь. Закрыв
       * экран, человек теряет ссылку навсегда — об этом честнее предупредить,
       * чем потом объяснять.
       */
      Text("Если закрыть экран, сервер дорендерит, но ссылку взять будет "
           + "негде: списка своих рендеров он не отдаёт.")
        .font(Тема.Шрифт.стиль(.caption))
        .foregroundStyle(Тема.Цвет.текстПриглушённый)
    }
  }

  @ViewBuilder private func результат(_ ссылка: URL) -> some View {
    if let плеер {
      VideoPlayer(player: плеер)
        .frame(height: 420)
        .clipShape(RoundedRectangle(cornerRadius: Тема.Радиус.lg))
        .onAppear { плеер.play() }
    } else {
      // Не тупик: ссылка ниже рабочая, и человек это видит словами, а не
      // упирается в пустой прямоугольник.
      Text("Ролик готов, но проигрыватель не создался. Ссылка ниже рабочая.")
        .font(Тема.Шрифт.стиль(.footnote))
        .foregroundStyle(Тема.Цвет.текстПриглушённый)
    }

    Text("Готово за \(прошло) с.")
      .font(Тема.Шрифт.стиль(.subheadline, .medium))
      .foregroundStyle(Тема.Цвет.текст)
      .monospacedDigit()

    // Ссылка ВРЕМЕННАЯ в обоих случаях: подписанная ссылка хранилища живёт
    // семь суток, а запасная — на самом рендер-сервере — до перезапуска
    // сервиса. Различать их на экране незачем, а умалчивать нельзя.
    Text("Ролик не опубликован в ленту — это только ваша ссылка, и она "
         + "временная. Сохраните ролик, если он нужен надолго.")
      .font(Тема.Шрифт.стиль(.caption))
      .foregroundStyle(Тема.Цвет.текстПриглушённый)

    ShareLink(item: ссылка) {
      Label("Поделиться ссылкой", systemImage: "square.and.arrow.up")
        .font(Тема.Шрифт.стиль(.subheadline, .medium))
        .frame(maxWidth: .infinity, minHeight: Тема.Кнопка.высота)
    }
    .tint(Тема.Цвет.акцент)
  }

  @ViewBuilder private func отказ(_ текст: String, _ повтор: Повтор) -> some View {
    плашка(значок: "xmark.octagon", цвет: Тема.Цвет.ошибка, текст: текст)

    if повтор != .нечего {
      Button {
        работа?.cancel()
        работа = Task { await повторить(повтор) }
      } label: {
        Text(названиеПовтора(повтор))
          .font(Тема.Шрифт.стиль(.subheadline, .medium))
          .frame(maxWidth: .infinity, minHeight: Тема.Кнопка.высота)
          .background(Тема.Цвет.поверхность, in: RoundedRectangle(cornerRadius: Тема.Радиус.md))
          .foregroundStyle(Тема.Цвет.текст)
      }
      .buttonStyle(.plain)
    }
  }

