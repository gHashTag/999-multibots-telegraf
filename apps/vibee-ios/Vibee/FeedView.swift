  /// Ключи рецепта, которые форма не показывает: они уедут как есть.
  private var переносится: [String] {
    guard let р = рецепт else { return [] }
    let правим = Set(поля.map(\.id))
    return р.props.keys.filter { !правим.contains($0) }.sorted()
  }

  private func названиеПовтора(_ п: Повтор) -> String {
    switch п {
    case .рецепт: return "Взять рецепт ещё раз"
    case .рендер: return "Вернуться к словам"
    case .состояние: return "Спросить сервер ещё раз"
    case .нечего: return ""
    }
  }

  // MARK: - Работа

  @MainActor
  private func взятьРецепт() async {
    шаг = .берёмРецепт
    do {
      let р = try await API.рецептРемикса(templateId: template.id)
      рецепт = р
      поля = Self.поляИз(р.props)
      шаг = .правка
    } catch {
      // Повторять осмысленно: 401 после обновления сессии, обрыв связи и
      // временный отказ сервера лечатся вторым нажатием. Отсутствующая
      // композиция — нет, и там кнопки не будет.
      var что = Повтор.рецепт
      if let e = error as? API.RemixError, case .безКомпозиции = e { что = .нечего }
      шаг = .отказ(error.localizedDescription, что)
    }
  }

  @MainActor
  private func собрать() async {
    guard let р = рецепт else {
      шаг = .отказ("Рецепт потерялся до отправки. Возьмите его заново.", .рецепт)
      return
    }

    /**
     * Правки НАКЛАДЫВАЕМ на исходные пропсы, а не собираем объект из полей.
     *
     * Всё, чего в форме нет — списки `tags` и `plates`, постер, видео в
     * медальоне, громкости, титры, — обязано доехать нетронутым. Собери мы
     * новый объект из семи строк, ремикс потерял бы половину ролика и
     * отчитался бы успехом; а у части пропсов схема на сервере ещё и
     * обязательная (`TrinityBlogReel.tsx:77-91`), так что рендер упал бы уже
     * после минуты ожидания.
     */
    var props = р.props
    for п in поля { props[п.id] = п.значение }

    прошло = 0
    процент = 0
    шаг = .рендер
    запуститьЧасы()
    do {
      let id = try await API.начатьРендер(
        API.Рецепт(compositionId: р.compositionId, props: props))
      задание = id
      await ждать(id)
    } catch {
      часы?.cancel()
      if Task.isCancelled { return }
      шаг = .отказ(error.localizedDescription, .рендер)
    }
  }

  /**
   * Ждать готовности опросом, а не по SSE.
   *
   * `/render/:id/status` умеет отдавать поток, но личность в нём принимается
   * только подписью мини-аппа через `?initData=` — Bearer в строке запроса он
   * не читает. Для сессии приложения это тупик, а обычный GET с заголовком
   * работает. Раз в две секунды: сервер обновляет процент по кадрам, чаще
   * спрашивать нечего.
   *
   * Предел — десять минут. Он здесь не потому, что сервер обещал уложиться:
   * общего срока у задания нет вовсе. Это граница, после которой честнее
   * спросить человека, ждать ли дальше, чем крутить спиннер молча.
   */
  @MainActor
  private func ждать(_ id: String) async {
    var попыток = 0
    while попыток < 300 {
      попыток += 1
      try? await Task.sleep(for: .seconds(2))
      if Task.isCancelled { return }

      do {
        let с = try await API.состояниеРендера(задание: id)
        if Task.isCancelled { return }
        процент = с.процент

        switch с.статус {
        case "completed":
          часы?.cancel()
          guard let ссылка = с.ссылка else {
            // «Готово» без ссылки — не успех. Заливка в хранилище могла
            // упасть; спросить ещё раз дешевле, чем рендерить заново.
            шаг = .отказ(
              "Сервер говорит «готово», но ссылки на файл в ответе нет.",
              .состояние)
            return
          }
          плеер = AVPlayer(url: ссылка)
          шаг = .готово(ссылка)
          return

        case "failed":
          часы?.cancel()
          // Слова сервера, а не своё «не получилось»: он называет и
          // непонятый проп, и нехватку памяти — готовая диагностика.
          шаг = .отказ(
            "Сервер не собрал ролик: \(с.отказ ?? "причину он не назвал")",
            .рендер)
          return

        default:
          continue
        }
      } catch {
        if Task.isCancelled { return }
        часы?.cancel()
        // Задание потеряно — повторять ОПРОС бессмысленно, его больше нет;
        // осмысленно вернуться к словам и собрать заново.
        var что = Повтор.состояние
        if let e = error as? API.RemixError, case .заданиеПотеряно = e { что = .рендер }
        шаг = .отказ(error.localizedDescription, что)
        return
      }
    }

    часы?.cancel()
    шаг = .отказ(
      "Рендер идёт дольше десяти минут. Сервер может всё ещё считать — общего "
        + "срока у задания нет, — а может и потерять его при перезапуске.",
      .состояние)
  }

  @MainActor
  private func повторить(_ п: Повтор) async {
    switch п {
    case .рецепт:
      await взятьРецепт()
    case .рендер:
      /**
       * Возврат К СЛОВАМ, а не немедленный повтор рендера.
       *
       * Причиной отказа могли быть сами пропсы — сервер разбирает их схемой и
       * падает на непонятом поле. Молча отправить те же слова второй раз
       * значит потратить ещё минуты ожидания на тот же отказ.
       */
      if рецепт != nil { шаг = .правка } else { await взятьРецепт() }
    case .состояние:
      guard let id = задание else {
        шаг = .отказ("Спрашивать не о чем: номер задания потерян.", .рендер)
        return
      }
      шаг = .рендер
      запуститьЧасы()
      await ждать(id)
    case .нечего:
      break
    }
  }

  /// Секундомер. `прошло` НЕ обнуляется здесь: при возобновлении опроса счёт
  /// должен продолжиться, иначе ожидание на экране выглядит короче, чем было.
  @MainActor
  private func запуститьЧасы() {
    часы?.cancel()
    часы = Task {
      while !Task.isCancelled {
        try? await Task.sleep(for: .seconds(1))
        if Task.isCancelled { return }
        прошло += 1
      }
    }
  }

  // MARK: - Какие поля показывать

  /**
   * Подписи к пропсам, которые человек правит осмысленно.
   *
   * Набор взят из схемы `TrinityBlogReel.tsx:70-157` и подтверждён живой
   * записью ленты 2026-09-03: у неё в `props` ровно `url, tags, year, title,
   * lesson, plates, dateline, subtitle, invariant, posterUrl, avatarVideo`.
   * Витрина мини-аппа (`templates/registry.ts:105-112`) показывает шесть из
   * них — те же самые, плюс титры.
   *
   * Ключ, которого здесь нет, всё равно попадёт в форму, если его значение —
   * строка: подписью станет само имя поля. Так рецепт чужой композиции не
   * останется без правки только потому, что мы о нём не знали.
   */
  private static let подписи: [String: String] = [
    "title": "Заголовок",
    "subtitle": "Подзаголовок",
    "dateline": "Дата и время чтения",
    "lesson": "Вывод",
    "invariant": "Инвариант",
    "url": "Адрес",
    "year": "Год",
  ]

  /// Порядок — как в самом ролике, а не по алфавиту: человек правит текст
  /// сверху вниз ровно в том порядке, в каком он появляется на экране.
  private static let порядок = [
    "title", "subtitle", "dateline", "lesson", "invariant", "url", "year",
  ]

  /**
   * Строки, которые правкой НЕ являются.
   *
   * `lang` переключает только служебные надписи шаблона и ничего не переводит;
   * остальные — адреса файлов. Дать их текстовым полем значит предложить
   * сломать ссылку опечаткой и получить ролик без картинки. Они уедут как
   * есть, и об этом сказано строкой «без изменений переносится».
   */
  private static let служебные: Set<String> = [
    "lang", "posterUrl", "avatarVideo", "voiceover", "music", "thumbnailUrl",
  ]

  /**
   * Поля из пропсов: только строки и только не служебные.
   *
   * Числа, списки и вложенные объекты полем не становятся НИКОГДА. Дать
   * `plates` или `captions` одной строкой значило бы предложить человеку
   * править JSON руками, а первая же опечатка сломала бы рецепт молча — в
   * форме он выглядел бы обычным текстом.
   */
  private static func поляИз(_ props: [String: Any]) -> [Поле] {
    let строки = props
      .compactMapValues { $0 as? String }
      .filter { !служебные.contains($0.key) }
    let известные = порядок.filter { строки[$0] != nil }
    let прочие = строки.keys.filter { !порядок.contains($0) }.sorted()
    return (известные + прочие).compactMap { ключ in
      строки[ключ].map {
        Поле(id: ключ, подпись: подписи[ключ] ?? ключ, значение: $0)
      }
    }
  }
