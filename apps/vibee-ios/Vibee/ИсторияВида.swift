import Foundation

/**
 * Что показать на вкладке из общей истории.
 *
 * ДОРОЖКА МОНТАЖА НЕ ОТВЕЧАЕТ НА ЭТОТ ВОПРОС. «Видео» и «Липсинк» кладут
 * результат на одну дорожку `video`, поэтому отбор по дорожке показывал на
 * «Липсинке» ролик, сделанный на «Видео» — и человек мог взять чужой
 * результат, думая, что это его липсинк. Замечено на скриншоте обхода вкладок.
 *
 * Записи без вида сделаны до появления поля. Их не выбрасываем и не
 * приписываем наугад: по дорожке `video` одно от другого не отличить.
 * Показываем там же, где показывали раньше — потерять оплаченное хуже, чем
 * показать лишнее.
 */
enum ИсторияВида {
  static func отобрать(
    _ история: [Слои.Актив],
    вид: String,
    дорожка: String
  ) -> [Слои.Актив] {
    история.filter { а in
      if let свой = а.вид { return свой == вид }
      return а.дорожка == дорожка
    }
  }
}
