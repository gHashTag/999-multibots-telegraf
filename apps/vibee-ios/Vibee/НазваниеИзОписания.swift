import Foundation

/**
 * Название работы — из описания, а не из вида.
 *
 * В истории и на дорожках монтажа стояло родовое «Фото», «Видео», «Голос».
 * Три генерации подряд давали три строки «Фото», отличимые только временем:
 * чтобы понять, какая из них нужна, приходилось брать каждую в ролик и
 * смотреть. Описание человек уже написал — оно и есть название.
 *
 * ПРАВИЛА, ВЫВЕДЕННЫЕ ИЗ ТОГО, ЧТО ЛЮДИ ПИШУТ В ЭТОМ ПОЛЕ:
 *
 *  • режем по границе СЛОВА, а не по букве: «Красный куб на бел…» читается,
 *    «Красный куб на бе» выглядит как сбой;
 *  • многострочное описание сжимаем в одну строку — в списке всё равно одна;
 *  • пустое описание бывает законно (у «Аватара» вход берётся из прошлых
 *    шагов), и тогда родовое имя честнее выдуманного.
 */
func названиеИзОписания(_ описание: String, иначе запасное: String, предел: Int = 42)
  -> String
{
  let одной = описание
    .replacingOccurrences(of: "\n", with: " ")
    .split(separator: " ", omittingEmptySubsequences: true)
    .joined(separator: " ")
    .trimmingCharacters(in: .whitespacesAndNewlines)
  guard !одной.isEmpty else { return запасное }
  guard одной.count > предел else { return одной }

  // Ищем последний пробел в пределах лимита. Если слово одно и длиннее
  // предела — режем по букве: иначе вернули бы пустую строку.
  let обрезок = String(одной.prefix(предел))
  if let пробел = обрезок.lastIndex(of: " ") {
    let поСлову = обрезок[..<пробел].trimmingCharacters(in: .whitespaces)
    if !поСлову.isEmpty { return поСлову + "…" }
  }
  return обрезок + "…"
}
