import SwiftUI

/**
 * Вход по коду из мини-аппа.
 *
 * ЧТО ЗАМЕНИЛО. Здесь было поле «ключ агента» — длинная строка, которую
 * человек добывал сам и вбивал руками. Это работало ровно один раз и только у
 * того, кто знает, где ключ взять; для всех остальных приложение молча
 * отвечало 401, а агент показывал пустой пузырь.
 *
 * ПОЧЕМУ ШЕСТЬ ЦИФР — ЛУЧШЕЕ, ЧТО ЗДЕСЬ МОЖНО. У приложения нет и не будет
 * подписи Telegram: оно не внутри Telegram. Значит личность обязана прийти с
 * той стороны, где подпись есть. Из трёх способов её перенести —
 *
 *   ссылка   `vibee://…?rt=` — токен оседает в логах и в буфере обмена;
 *   QR-код   — требует второго устройства, а чаще всего оно одно и то же;
 *   код      — проходит через глаза и не оставляет копии нигде,
 *
 * последний единственный не создаёт следа. Так же входят на телевизорах, и
 * ровно по этой причине.
 *
 * ПАЛИТРА — `Тема.Профиль`, а не общая.
 *
 * Этот экран показывается ровно в одном месте: `ProfileScreen.swift:доступ`
 * (проверено `grep -rn SignInView apps/vibee-ios/Vibee/` — два совпадения,
 * объявление и одно применение). То есть человек видит его всегда на фоне
 * профиля, и общая зелёно-серая палитра рядом с золотисто-чёрной читалась бы
 * как чужая вставка. Собственного источника в вебе у этого экрана нет —
 * веб узнаёт человека по подписи Telegram и кода не спрашивает, — поэтому
 * берём палитру того экрана, внутри которого он живёт.
 */
struct SignInView: View {
  /// Зовётся после успешного входа: Профиль перерисовывает себя.
  var вошли: () -> Void

  @State private var код = ""
  @State private var идёт = false
  @State private var ошибка: String?

  @FocusState private var вФокусе: Bool

  private var цифры: String { код.filter(\.isNumber) }
  /*
   * Готовность — по границам, которые знает клиент, а не по точной длине.
   * Точную знает только сервер (`PAIRING.DIGITS`), и попытка держать её копию
   * здесь уже стоила приложению всего входа: цифр стало восемь, а поле
   * принимало шесть.
   */
  private var готов: Bool {
    цифры.count >= Identity.минимумЦифрКода
      && цифры.count <= Identity.максимумЦифрКода
      && !идёт
  }

  var body: some View {
    VStack(alignment: .leading, spacing: Тема.Отступ.пузырьЧата) {
      // Число цифр НЕ называется: оно задано на сервере и уже менялось.
      // Текст, повторяющий его руками, разошёлся бы молча — и разошёлся.
      Text("Откройте бота в Telegram и нажмите «Войти в приложение». "
           + "Он покажет код — введите его здесь.")
        .font(Тема.Шрифт.стиль(.callout))
        // #a39d8d — первая ступень приглушения в профиле, Profile.css:1667.
        .foregroundStyle(Тема.Профиль.текстВторичный)
        .fixedSize(horizontal: false, vertical: true)

      /**
       * Одно поле, а не шесть клеток.
       *
       * Отдельные клетки под каждую цифру выглядят нарядно и ломают три вещи
       * разом: вставку кода целиком, автозаполнение из сообщения и VoiceOver,
       * который читает их как несвязанные поля. `.oneTimeCode` даёт системную
       * подсказку над клавиатурой — это и есть нативность, ради которой всё.
       *
       * ПОДСКАЗКА НЕ ПОКАЗЫВАЕТ ЦИФРЫ. Здесь стояло «000000» — третья копия
       * серверной длины в этом же файле, после `count == 6` и `prefix(6)`.
       * Текстовый сторож её не поймал (это не сравнение и не обрезка), и нашёл
       * её только живой запуск в симуляторе: поле предлагало шесть клеток под
       * восьмизначный код.
       *
       * Клиент этой величины не знает, поэтому подсказка её и не рисует.
       */
      // Коротко: поле свёрстано под цифры с разрядкой `kerning(8)`, и длинная
      // подсказка в нём обрезается — «код из Tele…». Увидел это только на
      // живом запуске: правка текста без запуска даёт другой неверный вид
      // вместо прежнего неверного.
      TextField("код", text: $код)
        .keyboardType(.numberPad)
        .textContentType(.oneTimeCode)
        .font(Тема.Шрифт.моно(Тема.БезИсточника.кегльКодаВхода, .semibold))
        .kerning(8)
        .multilineTextAlignment(.center)
        .focused($вФокусе)
        // Кремовый текст в поле — `color: #e6e0d2`, Profile.css:1721.
        .foregroundStyle(Тема.Профиль.текст)
        /**
         * КАРЕТКА. `.tint` здесь не украшение: цвет мигающей палочки ввода
         * берётся именно отсюда, а не из `.foregroundStyle`.
         *
         * Найдено не глазами, а замером — на скриншоте после первой правки
         * поиск зелёных пикселей дал 127 строк по 6 px шириной на
         * y 574-700 px, ровно по центру поля. Это была единственная зелёная
         * деталь, оставшаяся на золотом экране: подкрасив текст и рамку,
         * каретку легко не заметить, потому что она мигает и на половине
         * кадров её нет.
         */
        .tint(Тема.Профиль.акцент)
        .padding(.vertical, Тема.Отступ.карточкаЛенты)
        /**
         * Поле профиля: фон #050505, рамка #2a2820, радиус 10 —
         * Profile.css:1717-1721 (`.profile-skills__input`).
         *
         * Фон поля СОВПАДАЕТ с фоном страницы (:1114 и :1720 — один и тот же
         * #050505), поэтому поле обозначает себя рамкой, а не заливкой.
         * Скопировано как есть: раньше здесь стояла подложка #1a1a1a общей
         * темы — заметно светлее и на золотисто-чёрном фоне выглядела серой
         * заплаткой.
         */
        .background(
          Тема.Профиль.фон,
          in: RoundedRectangle(cornerRadius: Тема.Профиль.радиусПоля)
        )
        .overlay(
          RoundedRectangle(cornerRadius: Тема.Профиль.радиусПоля)
            .strokeBorder(
              Тема.Профиль.границаЗаметная, lineWidth: Тема.Профиль.толщинаГраницы
            )
        )
        .onChange(of: код) { _, новое in
          // Обрезаем на вводе, а не на отправке: поле, принимающее седьмую
          // цифру и молча её теряющее, выглядит сломанным.
          let только = новое.filter(\.isNumber)
          if только != новое || только.count > Identity.максимумЦифрКода {
            код = String(только.prefix(Identity.максимумЦифрКода))
          }
          /**
           * ОШИБКА ГАСНЕТ ТОЛЬКО ОТ РУКИ ЧЕЛОВЕКА, А НЕ ОТ ЛЮБОЙ ПРАВКИ ПОЛЯ.
           *
           * Здесь стояло `if ошибка != nil { ошибка = nil }` без условия, и
           * это делало КАЖДЫЙ неудачный вход беззвучным. Разбор отказа в
           * `войти()` идёт так: сначала пишется текст ошибки, следом
           * очищается поле — а очистка поля есть изменение `код`, то есть
           * этот самый обработчик, который только что записанную ошибку
           * стирал. Человек видел, как поле опустело, и ни слова о причине.
           *
           * Условие на непустоту разделяет два случая, которые внешне
           * одинаковы: программный сброс кладёт в поле ПУСТО, а живой ввод
           * всегда даёт непустую строку. Так старая жалоба уходит, как
           * только человек набирает новый код, и остаётся, когда её никто не
           * читал.
           */
          if !новое.isEmpty, ошибка != nil { ошибка = nil }
        }
        .accessibilityLabel("Код из шести цифр")

      if let ошибка {
        Label(ошибка, systemImage: "exclamationmark.triangle.fill")
          .font(Тема.Шрифт.стиль(.footnote))
          // Тёплый #ff6b6b нового блока профиля — Profile.css:1733.
          .foregroundStyle(Тема.Профиль.красный)
          .fixedSize(horizontal: false, vertical: true)
      }

      Button {
        Task { await войти() }
      } label: {
        HStack(spacing: Тема.Отступ.sm) {
          if идёт { ProgressView().tint(Тема.Профиль.акцент) }
          Text(идёт ? "Проверяем…" : "Войти")
        }
      }
      /**
       * ЗОЛОТАЯ ПИЛЮЛЯ ВМЕСТО ЗЕЛЁНОЙ ЗАЛИВКИ.
       *
       * Было: `.borderedProminent` с заливкой #00ff88 и чёрной подписью.
       * Чёрный там стоял не для красоты — белый на зелёном нечитаем и
       * вызвал отдельную жалобу (пересчитано здесь: 1.34:1; в комментарии
       * `Тема.Цвет.наАкценте` стоит 1.28:1 — расхождение чужое, не трогаю).
       *
       * Золото ту же ловушку ставит ещё жёстче: белый на #ffd700 — 1.40:1.
       * Но повторять инверсию не пришлось: у нового профиля НИ ОДНОЙ кнопки
       * со сплошной заливкой нет (`grep -n 'background:.*#ffd700\|
       * background:.*vibee-gold' Profile.css` — ноль совпадений). Все четыре
       * его кнопки — рамка плюс подложка 8-10% плюс текст цветом рамки; она
       * же `.profile-skills__save`, Profile.css:1737-1745, и она же основное
       * действие своего блока, как «Войти» здесь.
       *
       * Итог замерен на кадре: подложка кнопки #1e1a05, золотой текст на
       * ней — 12.42:1 против 14.97:1 у чёрного на сплошном золоте. Порог
       * AAA (7:1) пройден вдвое, инверсии подписи больше нет.
       *
       * Высоту 44 задаёт сам стиль — см. `Тема.Пилюля`. Проверено
       * по тому же кадру: золотая рамка занимает строки 773..904 из 2622
       * при масштабе 3x, то есть ровно 44.00 pt.
       */
      .buttonStyle(
        Тема.Пилюля(
          цвет: Тема.Профиль.акцент,
          заливка: Тема.Профиль.заливкаСильная,
          воВсюШирину: true
        )
      )
      // Недоступная кнопка: `opacity: 0.4` — Profile.css:1749, :1774.
      .opacity(готов ? 1 : 0.4)
      .disabled(!готов)
    }
    /**
     * Фокус ставится ЗАДАЧЕЙ, а не в onAppear.
     *
     * `.onAppear` срабатывает до того, как поле попадает в цепочку
     * ответчиков, и присваивание фокуса теряется: экран открывается,
     * клавиатуры нет, набирать некуда, пока не ткнёшь пальцем. Проверено
     * на симуляторе — именно так и было.
     *
     * Один пропущенный кадр — минимальная пауза, после которой поле уже
     * в иерархии. Больше ждать незачем, меньше — не хватает.
     */
    .task {
      try? await Task.sleep(nanoseconds: 50_000_000)
      вФокусе = true
    }
  }

  private func войти() async {
    идёт = true
    ошибка = nil
    do {
      try await Identity.claimPairing(code: цифры)
      вошли()
    } catch {
      ошибка = error.localizedDescription
      // Код одноразовый: после отказа он мёртв в любом случае, и оставлять
      // его в поле значит приглашать нажать «Войти» ещё раз впустую.
      код = ""
      вФокусе = true
    }
    идёт = false
  }
}
