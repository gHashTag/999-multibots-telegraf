import XCTest
@testable import Vibee

/// Тесты названы по тому, чего НЕ должно случиться на экране.
final class ЦенаНажатияTests: XCTestCase {

  func testПосекунднаяСДлительностьюНазываетПОЛНУЮСумму() {
    // 36/с × 10 с = 360. Раньше на кнопке стояло 36, а списывали 360.
    let ц = ЦенаНажатия.посчитать(единица: 36, мера: "с", множитель: 10)
    XCTAssertEqual(ц.всего, 360)
    XCTAssertEqual(ц.подпись, "· 360")
  }

  func testБезДлительностиСуммаНЕВЫДУМЫВАЕТСЯ() {
    // Липсинк: длительность задаёт озвучка, человек её не выбирает.
    let ц = ЦенаНажатия.посчитать(единица: 6, мера: "с", множитель: nil)
    XCTAssertNil(ц.всего)
    XCTAssertEqual(ц.подпись, "· 6/с")
  }

  func testПлоскаяЦенаНеУмножаетсяНиНаЧто() {
    let ц = ЦенаНажатия.посчитать(единица: 11, мера: nil, множитель: 10)
    XCTAssertEqual(ц.всего, 11)
    XCTAssertEqual(ц.подпись, "· 11")
  }

  func testНетЦеныНетПодписи() {
    XCTAssertNil(ЦенаНажатия.посчитать(единица: nil, мера: "с", множитель: 10).подпись)
  }

  func testНольСекундНеДелаетРаботуБесплатной() {
    let ц = ЦенаНажатия.посчитать(единица: 36, мера: "с", множитель: 0)
    XCTAssertNil(ц.всего)
    XCTAssertEqual(ц.подпись, "· 36/с")
  }

  func testЗнакиСчитаютсяТысячамиВВЕРХ() {
    // Озвучка тарифицируется за 1000 знаков. 24 за тысячу, текст на 2400 —
    // это три тысячи, то есть 72. Экран об этом молчал вовсе.
    let ц = ЦенаНажатия.посчитать(единица: 24, мера: "1000 зн.", множитель: 3)
    XCTAssertEqual(ц.всего, 72)
    XCTAssertEqual(ц.подпись, "· 72")
  }

  func testПустойТекстНеОбещаетСуммуНоНазываетМеру() {
    let ц = ЦенаНажатия.посчитать(единица: 24, мера: "1000 зн.", множитель: nil)
    XCTAssertNil(ц.всего)
    XCTAssertEqual(ц.подпись, "· 24/1000 зн.")
  }

  func testРазборДлительности() {
    XCTAssertEqual(секундыИзДлительности("6s"), 6)
    XCTAssertEqual(секундыИзДлительности("10s"), 10)
    // Мусор даёт nil, а не единицу: единица назвала бы сумму вшестеро меньше.
    XCTAssertNil(секундыИзДлительности(""))
    XCTAssertNil(секундыИзДлительности("s"))
    XCTAssertNil(секундыИзДлительности("0s"))
  }
}
