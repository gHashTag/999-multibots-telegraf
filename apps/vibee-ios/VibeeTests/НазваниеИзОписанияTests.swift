import XCTest
@testable import Vibee

/// Тесты названы по тому, чего НЕ должно быть в списке генераций.
final class НазваниеИзОписанияTests: XCTestCase {

  func testКороткоеОписаниеИдётЦеликомБезМноготочия() {
    XCTAssertEqual(названиеИзОписания("Красный куб", иначе: "Фото"), "Красный куб")
  }

  func testПустоеОписаниеНеДаётПустуюСтроку() {
    // У «Аватара» вход берётся из прошлых шагов, и описание бывает пустым.
    XCTAssertEqual(названиеИзОписания("", иначе: "Аватар"), "Аватар")
    XCTAssertEqual(названиеИзОписания("   \n  ", иначе: "Аватар"), "Аватар")
  }

  func testДлинноеРежетсяПоСловуАНеПоБукве() {
    let имя = названиеИзОписания(
      "Красный куб на белом столе в мягком утреннем свете", иначе: "Фото")
    XCTAssertTrue(имя.hasSuffix("…"), имя)
    XCTAssertLessThanOrEqual(имя.count, 43)
    // Обрыв посреди слова читается как сбой приложения.
    XCTAssertFalse(имя.dropLast().hasSuffix(" "), имя)
    XCTAssertTrue(имя.hasPrefix("Красный куб на белом столе"), имя)
  }

  func testОдноДлинноеСловоНеПревращаетсяВПустоту() {
    let имя = названиеИзОписания(String(repeating: "а", count: 100), иначе: "Фото")
    XCTAssertEqual(имя.count, 43)
    XCTAssertTrue(имя.hasSuffix("…"))
  }

  func testПереносыСтрокСжимаютсяВОднуСтроку() {
    let имя = названиеИзОписания("первая\nвторая", иначе: "Фото")
    XCTAssertEqual(имя, "первая вторая")
  }

  func testЛишниеПробелыНеРастягиваютНазвание() {
    XCTAssertEqual(названиеИзОписания("  куб   на    столе ", иначе: "Фото"), "куб на столе")
  }
}
