import XCTest
@testable import Vibee

/// Тесты названы по тому, чего НЕ должно оказаться на вкладке.
final class ИсторияВидаTests: XCTestCase {

  private func актив(вид: String?, дорожка: String) -> Слои.Актив {
    Слои.Актив(дорожка: дорожка, вид: вид, подпись: "x", ссылка: nil,
               текст: nil, когда: "2026-09-05T00:00:00Z", таймированныеПодписи: nil)
  }

  func testРоликСВидеоНеПоказываетсяНаЛипсинке() {
    // Обе вкладки кладут результат на дорожку `video` — отбор по дорожке
    // показывал чужое, и человек мог взять его в ролик.
    let всё = [актив(вид: "видео", дорожка: "video")]
    XCTAssertTrue(
      ИсторияВида.отобрать(всё, вид: "аватар", дорожка: "video").isEmpty)
  }

  func testСвойВидПоказывается() {
    let всё = [актив(вид: "аватар", дорожка: "video")]
    XCTAssertEqual(
      ИсторияВида.отобрать(всё, вид: "аватар", дорожка: "video").count, 1)
  }

  func testСтарыеЗаписиБезВидаНЕТЕРЯЮТСЯ() {
    // Оплаченное, сделанное до появления поля. Выбросить его — потерять то,
    // за что человек заплатил.
    let всё = [актив(вид: nil, дорожка: "video")]
    XCTAssertEqual(
      ИсторияВида.отобрать(всё, вид: "видео", дорожка: "video").count, 1)
  }

  func testСтараяЗаписьЧужойДорожкиНеВсплывает() {
    let всё = [актив(вид: nil, дорожка: "audio")]
    XCTAssertTrue(
      ИсторияВида.отобрать(всё, вид: "видео", дорожка: "video").isEmpty)
  }
}
