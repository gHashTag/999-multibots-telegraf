import XCTest
@testable import Vibee

/**
 * ЧЕМ МЕРЯЕТСЯ ЦЕНА — ВОПРОС К СЕРВЕРУ, А НЕ К СПИСКУ МОДЕЛЕЙ.
 *
 * Тесты названы по тому, чего НЕ должно случиться на экране.
 *
 * Разбор, из которого они выросли. Сервер отдавал `perSecondModels` по одной
 * лишь единице цены, а списывал посекундно только там, где длину задаём мы
 * сами. Восемь видеомоделей ехали с чужой пометкой, и приложение множило цену
 * на выбранную длительность: остаток 20, grok-imagine (5), 6 с — кнопка
 * гасла «нужно 30, есть 20», хотя сервер за то же нажатие берёт 5.
 *
 * Сервер список починили. Но починка вынесла из него липсинк — законно, его
 * длину задаёт присланный звук, — и ранний выход в `посекундная` превратил бы
 * это во вторую ошибку, зеркальную первой: липсинк стал бы «плоским», экран
 * пропустил бы нажатие, за которое возьмут вдесятеро.
 */
final class МераЦеныTests: XCTestCase {

  private func баланс(
    остаток: Int = 100,
    цены: [String: Int] = ["video_generate": 11, "lipsync_generate": 6],
    модели: [String: Int]? = nil,
    посекундныеВиды: [String]? = ["lipsync_generate"],
    посекундныеМодели: [String]? = ["kie/kling/v3-turbo-text-to-video"],
    познаковыеМодели: [String]? = ["kie/elevenlabs/text-to-speech-multilingual-v2"]
  ) -> API.Баланс {
    // Через JSON, а не через инициализатор: так тест проверяет ровно ту
    // форму ответа, которую отдаёт `/api/balance`.
    var о: [String: Any] = ["balance": остаток, "prices": цены]
    if let модели { о["modelPrices"] = модели }
    if let посекундныеВиды { о["perSecond"] = посекундныеВиды }
    if let посекундныеМодели { о["perSecondModels"] = посекундныеМодели }
    if let познаковыеМодели { о["perThousandCharsModels"] = познаковыеМодели }
    let данные = try! JSONSerialization.data(withJSONObject: о)
    return try! JSONDecoder().decode(API.Баланс.self, from: данные)
  }

  func testЛипсинкОстаётсяПосекунднымХотяЕгоМоделиНетВСписке() {
    // Сервер шлёт список моделей БЕЗ липсинка и вид работы С ним. Ранний
    // выход по непустому списку вернул бы nil — и экран сравнил бы остаток с
    // ценой одной секунды при счёте за десять.
    let б = баланс()
    XCTAssertEqual(б.мера("lipsync_generate", модель: "kie/veed/fabric-1"), "с")
    XCTAssertTrue(б.посекундная("lipsync_generate", модель: "kie/veed/fabric-1"))
  }

  func testВидеоНеСтановитсяПосекунднымИзЗаВидаРаботы() {
    // Обратная ошибка: `perSecond` не содержит видео, и модель, которой нет в
    // списке, обязана считаться плоской. Иначе вернётся запрет работы,
    // которую сервер сделал бы за пятёрку.
    let б = баланс()
    XCTAssertNil(б.мера("video_generate", модель: "kie/grok-imagine/text-to-video"))
    XCTAssertFalse(б.посекундная("video_generate", модель: "kie/grok-imagine/text-to-video"))
  }

  func testМодельИзСпискаСчитаетсяПосекундноДажеПриПлоскомВиде() {
    let б = баланс()
    XCTAssertEqual(
      б.мера("video_generate", модель: "kie/kling/v3-turbo-text-to-video"),
      "с"
    )
  }

  func testЗнакиИмеютПреимуществоНадСекундами() {
    // Модель озвучки не должна получить «с» от вида работы: подпись «6/с» у
    // текста ничего не значит, а сумма растёт с длиной.
    let б = баланс()
    XCTAssertEqual(
      б.мера(
        "audio_generate",
        модель: "kie/elevenlabs/text-to-speech-multilingual-v2"
      ),
      "1000 зн."
    )
  }

  func testСтарыйСерверБезСписковНеЛомаетЭкран() {
    // Полей может не быть вовсе — это не повод менять поведение: цена тогда
    // берётся из вида работы, как было до всей этой истории.
    let б = баланс(посекундныеВиды: nil, посекундныеМодели: nil, познаковыеМодели: nil)
    XCTAssertNil(б.мера("lipsync_generate", модель: "kie/veed/fabric-1"))
    XCTAssertFalse(б.посекундная("video_generate", модель: nil))
  }
}
