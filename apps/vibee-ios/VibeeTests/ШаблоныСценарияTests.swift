import XCTest
@testable import Vibee

/// Тесты названы по тому, чего НЕ должно случиться на экране.
final class ШаблоныСценарияTests: XCTestCase {

  private func шаблон(_ имя: String, id: String = "1") -> [ШаблонСценария] {
    ХранилищеШаблонов.добавить(
      [], имя: имя, ниша: "Крипто", стиль: "Обучающий", секунды: 30,
      язык: "Русский", id: id
    )
  }

  func testПустоеИмяНеСоздаётСтрокуБезПодписи() {
    // Строка без имени в списке неотличима от соседней, и человек удалит не ту.
    XCTAssertTrue(шаблон("").isEmpty)
    XCTAssertTrue(шаблон("   ").isEmpty)
    XCTAssertTrue(шаблон("\n").isEmpty)
  }

  func testПробелыПоКраямНеДелаютДваРазныхШаблона() {
    let первый = шаблон("Утро")
    let оба = ХранилищеШаблонов.добавить(
      первый, имя: "  Утро  ", ниша: "Фитнес", стиль: "Энергичный",
      секунды: 60, язык: "English", id: "2"
    )
    XCTAssertEqual(оба.count, 1)
    // Замещение, а не второй с тем же именем: выбор вслепую между двумя
    // одинаковыми подписями хуже, чем потеря старых настроек.
    XCTAssertEqual(оба[0].ниша, "Фитнес")
    XCTAssertEqual(оба[0].секунды, 60)
  }

  func testПовторИмениВДругомРегистреТожеЗамещает() {
    let оба = ХранилищеШаблонов.добавить(
      шаблон("Утро"), имя: "УТРО", ниша: "Еда", стиль: "Спокойный",
      секунды: 15, язык: "Русский", id: "2"
    )
    XCTAssertEqual(оба.count, 1)
    XCTAssertEqual(оба[0].ниша, "Еда")
  }

  func testУдалениеПоIdНеТрогаетСоседей() {
    let первый = шаблон("Утро", id: "a")
    let два = ХранилищеШаблонов.добавить(
      первый, имя: "Вечер", ниша: "Мода", стиль: "Разговорный",
      секунды: 90, язык: "Русский", id: "b"
    )
    let осталось = ХранилищеШаблонов.удалить(два, id: "a")
    XCTAssertEqual(осталось.map(\.имя), ["Вечер"])
  }

  func testУдалениеНесуществующегоНеТеряетНичего() {
    let два = ХранилищеШаблонов.добавить(
      шаблон("Утро", id: "a"), имя: "Вечер", ниша: "Мода", стиль: "Разговорный",
      секунды: 90, язык: "Русский", id: "b"
    )
    XCTAssertEqual(ХранилищеШаблонов.удалить(два, id: "нет").count, 2)
  }

  func testВсеЧетыреНастройкиВозвращаютсяЦеликом() {
    // Шаблон, восстанавливающий три поля из четырёх, хуже отсутствующего:
    // человек считает, что настройки те же, и платит за чужие.
    let т = ХранилищеШаблонов.добавить(
      [], имя: "Про крипту", ниша: "Крипто", стиль: "Профессиональный",
      секунды: 90, язык: "English", id: "x"
    )[0]
    XCTAssertEqual(т.ниша, "Крипто")
    XCTAssertEqual(т.стиль, "Профессиональный")
    XCTAssertEqual(т.секунды, 90)
    XCTAssertEqual(т.язык, "English")
  }

  func testХранилищеПереживаетЗаписьИЧтение() {
    let память = UserDefaults(suiteName: "тест.шаблоны")!
    память.removePersistentDomain(forName: "тест.шаблоны")
    ХранилищеШаблонов.записать(шаблон("Утро"), в: память)
    XCTAssertEqual(ХранилищеШаблонов.прочитать(память).map(\.имя), ["Утро"])
  }

  func testИспорченныеДанныеДаютПустоеАНеСбой() {
    // Старый формат не должен ронять вкладку генерации.
    let память = UserDefaults(suiteName: "тест.мусор")!
    память.removePersistentDomain(forName: "тест.мусор")
    память.set(Data("не json".utf8), forKey: ХранилищеШаблонов.ключ)
    XCTAssertEqual(ХранилищеШаблонов.прочитать(память).count, 0)
  }

  func testСоветыТеЖеЧетыреЧтоВВебе() {
    // Две витрины, советующие разное, хуже одной, не советующей ничего.
    XCTAssertEqual(СоветыСценария.все.count, 4)
    XCTAssertTrue(СоветыСценария.все.allSatisfy { !$0.isEmpty })
  }
}
