import XCTest
@testable import Vibee

/**
 * Согласование числа с существительным.
 *
 * Тесты названы по тому, чего НЕ должно быть на экране. Оба живых
 * потребителя — таймлайн («1 дорожка») и прайс моделей («1 токен») — ломались
 * ровно на единице, самом частом случае.
 */
final class СклонениеTests: XCTestCase {

  func testЕдиницаНеПолучаетФормуМножественного() {
    XCTAssertEqual(склонение(1, "токен", "токена", "токенов"), "1 токен")
    XCTAssertEqual(склонение(1, "дорожка", "дорожки", "дорожек"), "1 дорожка")
  }

  func testДваЧетыреБерутВторуюФормуАНеПервую() {
    XCTAssertEqual(склонение(2, "токен", "токена", "токенов"), "2 токена")
    XCTAssertEqual(склонение(4, "токен", "токена", "токенов"), "4 токена")
  }

  func testОдиннадцатьНеСчитаетсяЕдиницей() {
    // Цена Seedream 5 Lite — ровно 11, и наивная проверка «десяток == 1»
    // дала бы здесь «11 токен».
    XCTAssertEqual(склонение(11, "токен", "токена", "токенов"), "11 токенов")
    XCTAssertEqual(склонение(12, "токен", "токена", "токенов"), "12 токенов")
    XCTAssertEqual(склонение(14, "токен", "токена", "токенов"), "14 токенов")
  }

  func testДвадцатьОдинСноваЕдиница() {
    XCTAssertEqual(склонение(21, "токен", "токена", "токенов"), "21 токен")
    XCTAssertEqual(склонение(22, "токен", "токена", "токенов"), "22 токена")
  }

  func testСотниНеСбиваютФорму() {
    XCTAssertEqual(склонение(101, "токен", "токена", "токенов"), "101 токен")
    XCTAssertEqual(склонение(111, "токен", "токена", "токенов"), "111 токенов")
  }

  func testНольБеретФормуМножественного() {
    XCTAssertEqual(склонение(0, "токен", "токена", "токенов"), "0 токенов")
  }
}
