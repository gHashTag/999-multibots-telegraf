import XCTest

/**
 * Быстрая проверка вкладки «ИИ» — без единой координаты.
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ. Ту же вкладку проверяли руками через тапы по
 * пикселям, и это стоило часа на попадание по одной строке: снимок
 * симулятора идёт в масштабе 2,286, пересчёты мажут, клавиатура симулятора в
 * русской раскладке превращает набранное `vibecoding` в `мшиусщвштп`, а
 * `simctl pbcopy` калечит UTF-8 — вставленная тема приходила как
 * «–T–∞–є–±–Ï–Њ». Проверка, которая сама себе мешает, не проверка.
 *
 * XCUITest берёт элемент по опознавателю и печатает текст через API, минуя и
 * раскладку, и буфер. Опознаватели заданы в `GenerateScreen`: `ии.вид.*`,
 * `ии.модель.*`, `ии.промпт`, `ии.кнопка.текст`.
 *
 * ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ. Ни один тест не нажимает «Сгенерировать»
 * по-настоящему: это стоит денег у провайдера и требует входа. Проверяется
 * то, что ломалось на самом деле и ломалось молча — состав списка, цены,
 * категории и доступность кнопки.
 */
final class ИИЭкранTests: XCTestCase {
  private var app: XCUIApplication!

  override func setUp() {
    continueAfterFailure = false
    app = XCUIApplication()
    /*
     * ОСТАТОК ПОДСТАВЛЯЕТСЯ, иначе цен в списке нет ВООБЩЕ.
     *
     * `ценаМодели` возвращает nil без баланса, а баланс даёт сессия. С тех
     * пор как цены переехали на сервер, `testЦенаВидна` не мог пройти ни при
     * каких условиях — он был красным на `main`, и красным его держало не
     * приложение, а отсутствие входа у проверяющего.
     *
     * Способ тот же, что у `ДеньгиНаЭкранеTests`: аргумент запуска, `#if
     * DEBUG`, задаёт тот, кто запускает процесс.
     */
    app.launchArguments += [
      "-подставнойБаланс",
      #"{"balance":1000,"prices":{"video_generate":11,"image_generate":8,"audio_generate":12,"lipsync_generate":6},"modelPrices":{"kie/kling/v2-1-pro":11}}"#,
    ]
    app.launch()
    app.buttons["ИИ"].firstMatch.tap()
  }

  /// Переключить вид. Опознаватель — rawValue перечисления `Вид`.
  private func вид(_ имя: String) {
    let кнопка = app.buttons["ии.вид.\(имя)"].firstMatch
    XCTAssertTrue(кнопка.waitForExistence(timeout: 5), "нет вкладки «\(имя)»")
    // Вкладки в горизонтальной ленте: дальние не видны без прокрутки, и
    // тап по невидимому элементу XCUITest выполняет «вслепую» — попадая
    // мимо. Прокрутка к элементу дешевле и надёжнее любого свайпа.
    if !кнопка.isHittable { кнопка.scrollToElement() }
    кнопка.tap()
  }

  private func строкаМодели(_ id: String) -> XCUIElement {
    app.descendants(matching: .any)["ии.модель.\(id)"].firstMatch
  }

  func testСценарийПоказываетТекстовыеМоделиАНеВидео() {
    вид("сценарий")
    // Именно это было сломано: вкладка показывала Kling и Grok Imagine —
    // модели, которые снимают ролик, а не пишут текст.
    XCTAssertTrue(строкаМодели("glm-5.3").waitForExistence(timeout: 5))
    XCTAssertTrue(строкаМодели("gpt-5-2").exists)
    XCTAssertFalse(строкаМодели("kling/v2-1-pro").exists,
                   "видеомодель просочилась в сценарий")
  }

  func testКатегорииНеПеремешаны() {
    // Подстрочная эвристика однажды отнесла kling/v2-1-pro к картинкам, а
    // infinitalk — к звуку. Ошибку было видно человеку в готовом списке.
    вид("видео")
    XCTAssertTrue(строкаМодели("kling/v2-1-pro").waitForExistence(timeout: 5))
    вид("аватар")
    XCTAssertTrue(строкаМодели("infinitalk/from-audio").waitForExistence(timeout: 5))
    XCTAssertFalse(строкаМодели("kling/v2-1-pro").exists)
  }

  func testЗвукНеОбъявленСломанным() {
    // Вкладка показывала панель «Звук сейчас не работает» во весь экран и
    // прятала список моделей, хотя озвучка идёт через KieAI.
    вид("звук")
    XCTAssertFalse(app.staticTexts["Звук сейчас не работает"].exists)
    XCTAssertTrue(
      строкаМодели("elevenlabs/text-to-speech-turbo-2-5").waitForExistence(timeout: 5)
    )
  }

  func testЦенаВидна() {
    /*
     * Молчание о цене — не мелочь: человек узнавал её по списанию.
     *
     * Тест искал «от $…» и был КРАСНЫМ на `main`. Долларовый ценник —
     * себестоимость у провайдера, а не то, что платит человек, — убрали
     * намеренно, а тест остался проверять снятое. Ищем то, что показано:
     * цену в токенах.
     *
     * Подпись берётся у строки ЦЕЛИКОМ: строка — это `Button`, и SwiftUI
     * склеивает доступность его содержимого; отдельными элементами
     * внутренние `Text` не находятся.
     */
    вид("видео")
    let строка = строкаМодели("kling/v2-1-pro")
    XCTAssertTrue(строка.waitForExistence(timeout: 5))
    XCTAssertTrue(
      строка.label.contains("токен"),
      "у модели не показана цена в токенах: «\(строка.label)»"
    )
  }

  func testКнопкаНеЖмётсяБезВыбораМодели() {
    // Умолчание не ставится намеренно: подставить первую живую значило бы
    // решить за человека, чем генерировать, и списать за это деньги.
    вид("видео")
    _ = строкаМодели("kling/v2-1-pro").waitForExistence(timeout: 5)
    XCTAssertTrue(app.staticTexts["Выберите модель"].exists)
  }

  /**
   * Этот тест был отложен и ПОЙМАЛ настоящий дефект, когда его починили.
   *
   * Строка модели принимала нажатие только по буквам: фон невыбранной строки
   * — `Color.clear`, а прозрачное SwiftUI не считает попаданием. Тап в центр
   * строки уходил в пустоту между названием и ценой. Лечится
   * `.contentShape` в `СтрокаМоделиKie`.
   */
  func testВыборМоделиИТемыОткрываетКнопку() {
    вид("сценарий")
    let поле = app.textViews["ии.промпт"].firstMatch
    let текстовое = поле.exists ? поле : app.textFields["ии.промпт"].firstMatch
    XCTAssertTrue(текстовое.waitForExistence(timeout: 5))
    текстовое.tap()
    // Печать через API — минует русскую раскладку симулятора, из-за которой
    // ручной ввод превращался в «мшиусщвштп».
    текстовое.typeText("Вайбкодинг")
    // Клавиатуру ОБЯЗАТЕЛЬНО убрать: она закрывает нижнюю треть экрана, и
    // тап по модели уходит в неё — молча, потому что XCUITest считает
    // попадание успешным. Ровно так же мазали и ручные тапы.
    if app.keyboards.count > 0 { app.buttons["Return"].firstMatch.tap() }
    if app.keyboards.count > 0 { app.swipeDown() }

    let модель = строкаМодели("glm-5.3")
    if !модель.isHittable { модель.scrollToElement() }
    модель.tap()

    // Подсказка «выберите модель» должна исчезнуть — значит кнопка живая.
    XCTAssertFalse(app.staticTexts["Выберите модель"].exists)
    XCTAssertFalse(app.staticTexts["Нужно описание"].exists)
  }
}

extension XCUIElement {
  /// Докрутить до себя. XCUITest тапает по невидимому элементу «вслепую»,
  /// и такой тап уходит мимо — молча, что хуже падения.
  func scrollToElement() {
    var попыток = 0
    while !isHittable && попыток < 8 {
      XCUIApplication().swipeUp()
      попыток += 1
    }
  }
}
