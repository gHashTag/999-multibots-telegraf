/**
 * ГРУППЫ ШАБЛОНОВ — ролик снят ПО шаблону, и шаблонов немного.
 *
 * Вкладка «Шаблоны» показывала 46 карточек подряд. Замер по живой ленте: это
 * ТРИ композиции и одна запись без неё —
 *
 *     TrinityBlogReel   43
 *     SplitTalkingHead   2
 *     NoirReel           1
 *     без композиции     1
 *
 * То есть сорок три карточки были одним шаблоном с разным текстом. Владелец
 * назвал это спамом, и он прав: витрина обещает разнообразие, которого нет.
 *
 * Вычисление отдельно от экрана намеренно: здесь живут случаи, которые ломают
 * список, — пустая композиция, незнакомое имя, порядок групп, — и они
 * проверяются значением, а не наблюдением за отрисовкой.
 */
export interface СГруппой {
  compositionId?: string | null
}

export interface Группа<T> {
  /** Ключ композиции; `null` — записи, у которых её нет. */
  ключ: string | null
  /** Человеческое имя. Незнакомую композицию называем её же идентификатором. */
  имя: string
  ролики: T[]
}

/**
 * Человеческие имена трёх наших композиций.
 *
 * Незнакомую НЕ переименовываем в «Другое»: под таким именем сольются разные
 * шаблоны, и группировка снова начнёт врать. Показываем как есть — станет
 * видно, что появился новый, и его можно будет назвать.
 */
const ИМЕНА: Record<string, string> = {
  TrinityBlogReel: 'Блог',
  SplitTalkingHead: 'Сплит',
  NoirReel: 'Нуар',
}

export function имяШаблона(ключ: string | null): string {
  if (!ключ) return 'Без шаблона'
  return ИМЕНА[ключ] ?? ключ
}

/**
 * Разложить ролики по шаблонам, сохранив порядок их появления.
 *
 * Порядок групп — по первому встреченному ролику, а не по размеру: список
 * отсортирован по дате, и «свежее сверху» человек уже прочитал глазами.
 * Пересортировка по количеству переставляла бы группы после каждой
 * генерации.
 */
export function поШаблонам<T extends СГруппой>(ролики: T[]): Группа<T>[] {
  const порядок: (string | null)[] = []
  const по = new Map<string | null, T[]>()
  for (const р of ролики) {
    const ключ = р.compositionId ?? null
    if (!по.has(ключ)) {
      по.set(ключ, [])
      порядок.push(ключ)
    }
    по.get(ключ)!.push(р)
  }
  return порядок.map(ключ => ({
    ключ,
    имя: имяШаблона(ключ),
    ролики: по.get(ключ)!,
  }))
}
