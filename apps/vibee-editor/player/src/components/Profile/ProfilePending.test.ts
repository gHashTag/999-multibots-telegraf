import { describe, it, expect } from 'vitest'
import fs from 'fs'
import path from 'path'

/**
 * РАЗДЕЛ, ГДЕ ОДОБРЯЮТ, — ПРОВОДКА.
 *
 * Скрытая публикация без места, где её одобрить, была бы хуже сегодняшнего:
 * пост исчезал бы совсем (все чтения фильтруют `is_public = TRUE`). Пара
 * обязана быть целой, и проверяется здесь именно это.
 *
 * По исходнику, а не отрисовкой: у веба нет @testing-library, поднимать
 * профиль ради двух условий дорого, а ломается именно проводка — вкладка
 * заведена, а раздел не подключён, или наоборот.
 */
const РАЗДЕЛ = fs.readFileSync(
  path.join(__dirname, 'ProfilePending.tsx'),
  'utf8'
)
const ВКЛАДКИ = fs.readFileSync(
  path.join(__dirname, 'ProfileTabs.tsx'),
  'utf8'
)

describe('раздел «ждут одобрения» подключён, а не только написан', () => {
  it('вкладка есть в порядке СВОЕГО профиля и отрисовывает раздел', () => {
    // Семнадцатое правило: помощник может быть зелёным и не подключённым.
    expect(ВКЛАДКИ).toMatch(/'pending',/)
    expect(ВКЛАДКИ).toContain("id: 'pending' as const")
    expect(ВКЛАДКИ).toContain(
      "{visibleActiveTab === 'pending' && <ProfilePending />}"
    )
  })

  it('раздела нет у ЧУЖОГО профиля', () => {
    // Неодобренное — это черновики, и посторонним там нечего делать.
    const публичные = ВКЛАДКИ.slice(
      ВКЛАДКИ.indexOf('const PUBLIC_TAB_ORDER'),
      ВКЛАДКИ.indexOf(']', ВКЛАДКИ.indexOf('const PUBLIC_TAB_ORDER'))
    )
    expect(публичные).not.toContain('pending')
  })

  it('карточка исчезает только ПОСЛЕ успеха', () => {
    /*
     * Исчезнувшая карточка при неудавшемся одобрении означала бы
     * «опубликовано», когда нет, — и человек не нажал бы второй раз.
     */
    expect(РАЗДЕЛ).toMatch(/if \(!о\.ok\) throw new Error/)
    expect(РАЗДЕЛ).toMatch(/setСписок\(с => \(с \?\? \[\]\)\.filter/)
  })

  it('запросы уходят с личностью', () => {
    /*
     * Маршрут отдаёт ТОЛЬКО свои посты и узнаёт владельца из подписи; без
     * заголовков он ответит 401, и раздел всегда был бы пуст.
     *
     * Считалось число вхождений `authHeaders()` — и это оказалось хрупко и
     * недостаточно: одобрение вызывало её через СПРЕД
     * (`{...authHeaders(), ...}`), спред `Headers` даёт пустой объект, счёт
     * при этом сходился, а запрос уходил без удостоверения.
     *
     * Теперь проверяется суть: оба запроса есть, и НИ ОДИН не собирает
     * заголовки спредом.
     */
    expect(РАЗДЕЛ).toContain('/api/feed/pending')
    expect(РАЗДЕЛ).toContain('/api/feed/approve')
    expect(РАЗДЕЛ).toMatch(/headers: authHeaders\(/)
    expect(РАЗДЕЛ).not.toContain('...authHeaders()')
  })

  it('пустота объяснена словами', () => {
    // Пустой раздел читается как поломка — это уже разбирали на других
    // экранах.
    expect(РАЗДЕЛ).toContain('Нечего одобрять')
  })
})
