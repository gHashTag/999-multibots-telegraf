import { describe, it, expect } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'

/**
 * ПОЛОСА ШАГОВ ИИ ОБЯЗАНА ПОМЕЩАТЬСЯ В ТЕЛЕФОН.
 *
 * Владелец: «в веб версии на многих табах в разделе ИИ вёрстка у кнопок
 * поломана без отступов, криво смотрится».
 *
 * Замерено на живой странице (окно 384px, 06.09.2026): первая вкладка
 * начиналась на −111px от левого края, последняя уходила за правый на +109px.
 * Полоса переполнялась и вставала прокруткой так, что активная вкладка в
 * центре, а крайние обрезаны с обеих сторон. Полоса прокрутки здесь скрыта
 * намеренно, поэтому ничто не подсказывало, что содержимое можно листать —
 * человек видел просто обрубленные слова.
 *
 * Арифметика была против вёрстки:
 *
 *     6 шагов × 92px (min-width) + 5 × 4px (зазор) + 2 × 8px (отступ) = 580px
 *
 * при экране 384px. Никакими отступами это не лечится — не помещается по
 * построению.
 *
 * ПЕРВАЯ ПОПРАВКА БЫЛА ХУЖЕ БОЛЕЗНИ. Разделив ширину поровну, я получил 58px
 * на вкладку и подписи «С…», «Г…», «Ф…», «Л…», «В…», «Р…» — проверено
 * скриншотом. Раньше были нечитаемы две крайние, стало — все шесть. Одна
 * буква с многоточием не называет шаг.
 *
 * Работает третье: на узком экране подпись остаётся у АКТИВНОГО шага,
 * остальные — иконки. «Где я» читается всегда, и всё помещается.
 */
const ИСХОДНИК = fs.readFileSync(path.join(__dirname, 'AiPipelineNav.css'), 'utf8')

/**
 * Правила БЕЗ комментариев.
 *
 * Проверки вида «такого больше нет» ловили мой собственный рассказ о том,
 * почему прежнее правило не работало: комментарий обязан называть снятое
 * `min-width: 92px` и объяснять, почему нельзя `display: none`. Закреплять
 * надо ПОВЕДЕНИЕ, а история должна оставаться рядом с кодом и не ронять
 * прогон. Третий случай этого класса за смену — поэтому вырезаю один раз.
 */
const CSS = ИСХОДНИК.replace(/\/\*[\s\S]*?\*\//g, '')

describe('полоса шагов ИИ', () => {
  it('вкладке разрешено сжиматься', () => {
    /*
     * `flex: 1 0 auto` — «расти можно, сжиматься нельзя». Именно этот запрет
     * вместе с min-width и выталкивал полосу за экран.
     */
    expect(CSS).toContain('flex: 1 1 0')
    expect(CSS).not.toMatch(/min-width:\s*92px/)
  })

  it('на узком экране подпись остаётся у активного шага', () => {
    expect(CSS).toMatch(/@media \(max-width: 480px\)/)
    expect(CSS).toContain(
      '.ai-pipeline__item:not(.is-active) .ai-pipeline__label'
    )
  })

  it('скрытая подпись остаётся доступной для чтения с экрана', () => {
    /*
     * `display: none` убрал бы подпись и из доступного дерева: программе
     * чтения с экрана осталась бы иконка без имени, то есть кнопка «без
     * названия». Поэтому подпись прячется визуально, а не удаляется.
     */
    expect(CSS).toContain('clip-path: inset(50%)')
    expect(CSS).not.toMatch(
      /:not\(\.is-active\) \.ai-pipeline__label \{[^}]*display:\s*none/
    )
  })

  it('шесть шагов при 92px минимума не поместились бы — арифметика записана', () => {
    /*
     * Проверка не CSS, а НАШЕГО ЗНАНИЯ о причине: если кто-то вернёт
     * фиксированный минимум, пусть увидит здесь, почему это не работает.
     */
    const ШАГОВ = 6
    const ЗАЗОР = 4
    const ОТСТУП = 8
    const ЭКРАН = 384
    const прежнийМинимум = 92
    const нужно =
      ШАГОВ * прежнийМинимум + (ШАГОВ - 1) * ЗАЗОР + 2 * ОТСТУП
    expect(нужно).toBeGreaterThan(ЭКРАН)
  })
})
