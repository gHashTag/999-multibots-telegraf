import { describe, it, expect } from 'vitest'
import fs from 'fs'
import path from 'path'

/**
 * ПОЧИНКА ВЫБОРА ГОЛОСА НЕ ДОЛЖНА ОБОЙТИ ВЕРНУВШИХСЯ.
 *
 * Найдено состязательной проверкой СВОЕЙ ЖЕ правки, через час после того, как
 * она была влита. Список голосов заменялся целиком, а сохранённый выбор
 * трогали только когда он ПУСТ. У всех, кто заходил раньше, в хранилище лежит
 * `sarah` или идентификатор ElevenLabs: список приезжает новый, выбор остаётся
 * старый, провайдер снова получает строку, которой не знает.
 *
 * То есть правка «голос доходит до провайдера» не подействовала бы ни на
 * одного вернувшегося — а именно они и есть те, кто уже платил за одинаковые
 * файлы.
 *
 * Проверяем по исходнику: атомы jotai здесь без стора не выполнить, а ломалось
 * ровно условие, а не вычисление.
 */
const ГОЛОСА = fs.readFileSync(path.join(__dirname, 'voices.ts'), 'utf8')
const ПАНЕЛЬ = fs.readFileSync(
  path.join(__dirname, '..', 'components', 'Panels', 'GeneratePanel.tsx'),
  'utf8'
)

describe('сохранённый выбор голоса сверяется со списком', () => {
  it('условие смотрит на членство в новом списке, а не только на пустоту', () => {
    expect(ГОЛОСА).toContain('естьВСписке')
    expect(ГОЛОСА).toMatch(/if \(!currentSelected \|\| !естьВСписке\)/)
  })

  it('запасные голоса — настоящие идентификаторы провайдера', () => {
    // `sarah`/`rachel`/`josh` не были голосами нигде: провайдер их отбрасывал
    // и читал голосом по умолчанию, а человек платил за каждую попытку.
    expect(ГОЛОСА).not.toContain("id: 'sarah'")
    expect(ГОЛОСА).toContain("id: 'Russian_ReliableMan'")
  })
})

describe('голос подписан тем, кто его произносит', () => {
  it('подпись берётся у сервера, а не зашита ElevenLabs', () => {
    // ElevenLabs недоступен (ключ в переменной — идентификатор), читает
    // MiniMax, и он же называет себя в поле `provider` ответа.
    expect(ПАНЕЛЬ).not.toContain("'ElevenLabs voice'")
    expect(ПАНЕЛЬ).toContain('voiceProvider')
    expect(ГОЛОСА).toContain('voiceProviderAtom')
  })
})
