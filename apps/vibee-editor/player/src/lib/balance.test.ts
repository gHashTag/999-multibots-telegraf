import { describe, it, expect } from 'vitest'
import { ценаНажатия, мераЦены, тысячиЗнаковКОплате, type Баланс } from './balance'
import fs from 'fs'
import path from 'path'

/** Исходник читаем текстом: ветка живёт под `import.meta.env.DEV`, и в
 *  тестовой сборке её не исполнить — а ломаться она может только целиком. */
const ИСХОДНИК = fs.readFileSync(path.join(__dirname, 'balance.ts'), 'utf8')

/**
 * ЧИСЛО НА КНОПКЕ ОБЯЗАНО РАВНЯТЬСЯ СПИСАННОМУ.
 *
 * Тестов у денежной математики веба не было ни одного: цена, мера и ворота
 * появились в панели сразу в готовом виде и держались на чтении глазами.
 * Держались плохо — состязательный разбор нашёл здесь два расхождения с
 * сервером, оба в пользу отказа ПОСЛЕ нажатия.
 *
 * Числа взяты из серверного прайса (`billing-shared.ts`), а не выдуманы:
 * сойдутся они или нет — единственное, что здесь проверяется.
 */
const баланс: Баланс = {
  balance: 12,
  prices: {
    audio_generate: 12,
    lipsync_generate: 6,
    video_generate: 11,
  },
  modelPrices: {
    'kie/elevenlabs/text-to-speech-multilingual-v2': 24,
    'kie/kling/v3-turbo-text-to-video': 36,
  },
  perSecond: ['lipsync_generate'],
  perSecondModels: ['kie/kling/v3-turbo-text-to-video'],
  perThousandCharsModels: ['kie/elevenlabs/text-to-speech-multilingual-v2'],
}

describe('счёт озвучки растёт с длиной текста', () => {
  it('начатая тысяча оплачивается целиком', () => {
    expect(тысячиЗнаковКОплате('')).toBe(1)
    expect(тысячиЗнаковКОплате('x')).toBe(1)
    expect(тысячиЗнаковКОплате('x'.repeat(1000))).toBe(1)
    expect(тысячиЗнаковКОплате('x'.repeat(1001))).toBe(2)
  })

  it('2500 знаков по 12 стоят 36, а не 12', () => {
    /*
     * Тот самый отказ после нажатия: остаток 12, кнопка «· 12», счёт 36.
     * Модель по умолчанию (`direct/elevenlabs`) в списке познаковых НЕ
     * значится, а маршрут умножает при любой модели — поэтому множитель
     * считается безусловно.
     */
    const цена = ценаНажатия(баланс, 'audio_generate', 'direct/elevenlabs')
    expect(цена).toBe(12)
    expect(цена! * тысячиЗнаковКОплате('x'.repeat(2500))).toBe(36)
    expect(баланс.balance).toBeLessThan(36)
  })

  it('мегабайтная вставка упирается в тот же потолок, что и сервер', () => {
    // Иначе сервер ответит «invalid billing quantity» вместо счёта, и экран
    // назовёт сумму, которой не бывает.
    expect(тысячиЗнаковКОплате('x'.repeat(9_000_000))).toBe(3600)
  })
})

describe('чем меряется цена', () => {
  it('липсинк остаётся посекундным, хотя его моделей нет в списке', () => {
    /*
     * Сервер шлёт в `perSecondModels` только те модели, счёт за которые сам
     * умножает на длину, заданную НА ЭКРАНЕ. Липсинка там нет: его длину
     * задаёт присланный звук. Признак приходит видом работы — и пока веб его
     * не читал, самая дорогая кнопка панели подписывалась ценой одной
     * секунды: 6 вместо 60 за десять.
     */
    expect(мераЦены(баланс, 'kie/veed/fabric-1', 'lipsync_generate')).toBe('с')
  })

  it('видеомодель вне списка не получает «с» от вида работы', () => {
    // Обратная ошибка: `perSecond` не содержит видео, и модель, которой нет в
    // списке, обязана считаться плоской.
    expect(
      мераЦены(баланс, 'kie/grok-imagine/text-to-video', 'video_generate')
    ).toBeNull()
  })

  it('знаки имеют преимущество над секундами', () => {
    expect(
      мераЦены(
        баланс,
        'kie/elevenlabs/text-to-speech-multilingual-v2',
        'audio_generate'
      )
    ).toBe('1000 зн.')
  })

  it('старый сервер без списков не ломает подпись', () => {
    const без: Баланс = { balance: 100, prices: { lipsync_generate: 6 } }
    expect(мераЦены(без, 'kie/veed/fabric-1', 'lipsync_generate')).toBeNull()
  })
})

describe('цена модели важнее цены вида работы', () => {
  it('берётся цена выбранной модели', () => {
    expect(
      ценаНажатия(баланс, 'video_generate', 'kie/kling/v3-turbo-text-to-video')
    ).toBe(36)
  })

  it('без своей цены модель падает на вид работы', () => {
    expect(ценаНажатия(баланс, 'video_generate', 'veo3-fast')).toBe(11)
  })
})

describe('цены можно увидеть без сессии — но только в сборке разработчика', () => {
  it('подстава читается из адреса и не требует сети', () => {
    /*
     * Та же дыра проверки, что была в приложении: подписи появляются лишь
     * когда сервер ответил остатком, а остаток даёт сессия. Кода авторизации
     * у проверяющего нет, значит цену на кнопке нельзя было увидеть ГЛАЗАМИ
     * ни разу — и долг проверки не гасился никогда.
     */
    expect(ИСХОДНИК).toContain("new URLSearchParams(location.search).get('баланс')")
    expect(ИСХОДНИК).toContain('const свой = подставнойБаланс()')
  })

  it('ветка закрыта проверкой сборки, и Vite её вырежет', () => {
    // `import.meta.env.DEV` в рабочей сборке равен `false`: ветки нет в
    // собранных файлах вовсе. Убери проверку — и остаток можно будет
    // подставить ссылкой у любого посетителя.
    expect(ИСХОДНИК).toMatch(/if \(!import\.meta\.env\.DEV\) return null/)
  })
})
