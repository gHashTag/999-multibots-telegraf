import { API_BASE } from '../config'
import { authHeaders } from './apiFetch'

/**
 * ОСТАТОК И ЦЕНЫ ДЛЯ ВЕБА.
 *
 * Мини-приложение не спрашивало баланс НИ РАЗУ и цен не знало: человек жал
 * «Сгенерировать» и платил, ни разу не увидев суммы. В мобильном приложении
 * этот же дефект чинили всю ночь — здесь он оставался целиком.
 *
 * Цены берём с сервера, а не держим свою таблицу: вторая копия разошлась бы с
 * первой молча, и это уже случалось трижды в этом коде.
 */
export interface Баланс {
  balance: number
  prices: Record<string, number>
  modelPrices?: Record<string, number>
  /**
   * Виды работы, которые сервер считает посекундно, — сегодня один липсинк.
   *
   * Поле сервер отдавал с самого начала (`perSecond`), а веб его не объявлял и
   * не читал: липсинк, единственная посекундная кнопка панели, подписывался
   * плоским числом. Замер: 6 за секунду, десятисекундная озвучка — счёт 60,
   * на кнопке «· 6».
   */
  perSecond?: string[]
  perSecondModels?: string[]
  perThousandCharsModels?: string[]
  /**
   * Какие поля КАЖДАЯ модель действительно получит — пересечение её контракта
   * с тем, что умеет передать маршрут. У десяти видеомоделей из двенадцати
   * контракт — один `prompt`, и чипы «Длительность»/«Соотношение» до
   * провайдера не доходили вовсе.
   */
  modelFields?: Record<string, string[]>
  exempt?: boolean
}

/**
 * ПОДСТАВНОЙ ОСТАТОК ДЛЯ ПРОВЕРКИ — ТОЛЬКО В СБОРКЕ РАЗРАБОТЧИКА.
 *
 * Та же дыра проверки, что была в приложении: денежные подписи появляются
 * лишь когда сервер ответил остатком, а остаток он отдаёт по сессии. Кода
 * авторизации у проверяющего нет — это учётные данные владельца. Значит цену
 * на кнопке, отказ и меру нельзя было увидеть ГЛАЗАМИ ни разу, и долг
 * проверки не закрывался никогда.
 *
 * Значение берётся из строки адреса (`?баланс=<json>`), которую задаёт тот,
 * кто открывает страницу. `import.meta.env.DEV` в рабочей сборке равен
 * `false`, и Vite вырезает эту ветку целиком — в собранных файлах её нет.
 */
function подставнойБаланс(): Баланс | null {
  if (!import.meta.env.DEV) return null
  try {
    const сырое = new URLSearchParams(location.search).get('баланс')
    if (!сырое) return null
    const б = JSON.parse(сырое) as Баланс
    return typeof б?.balance === 'number' ? б : null
  } catch {
    return null
  }
}

export async function загрузитьБаланс(): Promise<Баланс | null> {
  const свой = подставнойБаланс()
  if (свой) return свой
  try {
    const о = await fetch(`${API_BASE}/api/balance`, { headers: authHeaders() })
    if (!о.ok) return null
    const д = (await о.json()) as Баланс & { success?: boolean }
    return typeof д?.balance === 'number' ? д : null
  } catch {
    // Молчим НАМЕРЕННО: цена — не повод ломать экран генерации. Без баланса
    // кнопка просто не называет сумму, как было до этой правки.
    return null
  }
}

/**
 * Сколько спишут за одно нажатие.
 *
 * Цена МОДЕЛИ, а не вида работы: сервер списывает именно её, а вид — лишь
 * запасной вариант, когда у модели своей цены нет. Разошлись бы — человек
 * увидел бы одно, а заплатил другое.
 */
export function ценаНажатия(
  б: Баланс | null,
  операция: string,
  модель: string | undefined
): number | null {
  if (!б) return null
  if (модель && б.modelPrices?.[модель] != null) return б.modelPrices[модель]
  return б.prices?.[операция] ?? null
}

/**
 * Чем меряется цена: «с», «1000 зн.» или ничем (за вызов).
 *
 * Список моделей ДОБАВЛЯЕТ посекундность, а не исчерпывает её. Сервер шлёт в
 * `perSecondModels` только те модели, счёт за которые сам умножает на длину,
 * заданную на экране; липсинка там нет и быть не может — его длину задаёт
 * присланный звук. Посекундность липсинка приходит видом работы, в `perSecond`.
 *
 * Пока эта развилка не читалась, единственная посекундная кнопка панели
 * подписывалась ценой одной секунды: 6 вместо 60 за десять секунд.
 */
export function мераЦены(
  б: Баланс | null,
  модель: string | undefined,
  операция?: string
): string | null {
  if (!б) return null
  if (модель && б.perThousandCharsModels?.includes(модель)) return '1000 зн.'
  if (модель && б.perSecondModels?.includes(модель)) return 'с'
  if (операция && б.perSecond?.includes(операция)) return 'с'
  return null
}

/**
 * Сколько НАЧАТЫХ ТЫСЯЧ знаков оплатят. Зеркало серверной `тысячиЗнаковКОплате`
 * (render/src/agent/billing-shared.ts): та же формула и тот же потолок.
 *
 * Считается БЕЗУСЛОВНО, а не только для моделей из `perThousandCharsModels`:
 * маршрут озвучки умножает счёт на длину при ЛЮБОЙ модели, а модель по
 * умолчанию (`direct/elevenlabs`) в том списке не значится — именно там
 * подпись врала сильнее всего. Замер: остаток 12, текст на 2500 знаков,
 * кнопка «· 12», счёт 36, отказ ПОСЛЕ нажатия.
 *
 * `.length` в обоих местах — единицы UTF-16, счёт сходится знак в знак.
 */
export function тысячиЗнаковКОплате(текст: string): number {
  return Math.min(Math.max(1, Math.ceil(текст.length / 1000)), 3600)
}

/**
 * Доедет ли это поле до провайдера у выбранной модели.
 *
 * Неизвестная модель и старый сервер без списка отвечают ДА: прятать
 * настройку на догадке хуже, чем показать лишнюю — так мы отняли бы
 * работающий выбор. Не-Kie модели (veo3 и прочие) в списке отсутствуют и
 * поэтому сохраняют свои чипы.
 */
export function полеДоходит(
  б: Баланс | null,
  поле: string,
  модель: string | undefined
): boolean {
  if (!б || !модель) return true
  const список = б.modelFields?.[модель]
  return список ? список.includes(поле) : true
}
