import { describe, it, expect } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'

/**
 * Отсутствие модуля не должно выглядеть успехом — issue #960.
 *
 * ПОЧЕМУ ТЕСТ ЧИТАЕТ ИСХОДНИК, А НЕ ЗОВЁТ ФУНКЦИЮ. Проверяемое поведение
 * возникает только когда `import('./src/lib/faceDetection')` падает, то есть
 * когда в образе нет `@tensorflow/tfjs-node`. Здесь он есть, и подделать это
 * можно лишь подменой резолвера модулей — цена такой подмены выше, чем
 * ценность проверки, и она сама становится тем, что придётся сопровождать.
 *
 * Поэтому утверждается СТРУКТУРА: что оба обработчика различают состояние
 * сервиса и событие кадра, и что признак уезжает в задание. Это слабее
 * поведенческого теста и сильнее, чем ничего: удаление ветки роняет прогон.
 */
const источник = fs.readFileSync(
  path.join(__dirname, 'render-server.ts'),
  'utf8'
)

describe('недоступность кадрирования по лицу не молчит', () => {
  it('состояние объявляется ОДИН раз, а не на каждом ролике', () => {
    // Признак разового объявления — проверка флага перед записью.
    expect(источник).toContain('if (!faceApiНедоступен)')
    expect(источник).toMatch(/faceApiНедоступен = String\(e\)/)
  })

  it('оба обработчика различают состояние сервиса и событие кадра', () => {
    // Ровно два места ловят отказ распознавания, и оба обязаны спрашивать,
    // не отсутствует ли модуль вообще, прежде чем молча подставлять нули.
    const развилок = (
      источник.match(/if \(faceCroppingUnavailable\(\)\)/g) || []
    ).length
    expect(развилок).toBe(2)
  })

  it('признак уезжает в задание, а не остаётся в логе', () => {
    // Лог видит только тот, кто в него смотрит. Человек, получивший ролик,
    // должен узнать о недостающем кадрировании из ответа.
    const записей = (
      источник.match(/inputProps\.faceCroppingUnavailable =/g) || []
    ).length
    expect(записей).toBe(2)
  })

  it('разовый сбой распознавания по-прежнему тихий', () => {
    // Обратная сторона: не всякий отказ надо поднимать. Лицо, не найденное
    // на конкретном кадре, — нормальный исход, и ветка else должна остаться.
    expect(источник).toContain("console.warn(`⚠️ Face detection failed:`")
  })
})
