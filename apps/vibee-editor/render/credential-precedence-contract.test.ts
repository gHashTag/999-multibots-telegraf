import fs from 'node:fs'
import path from 'node:path'

/**
 * ДОГОВОР МЕЖДУ КЛИЕНТОМ И СЕРВЕРОМ О ПОРЯДКЕ УДОСТОВЕРЕНИЙ.
 *
 * Заведено 07.09.2026, после того как я СЛОМАЛ ВХОД В МИНИ-АПП.
 *
 * ── ЧТО ПРОИЗОШЛО ──────────────────────────────────────────────────────────
 *
 * Я заставил мини-апп слать подпись Telegram и сессионный токен ОДНОВРЕМЕННО,
 * написав в обосновании: «сервер принимает любое из двух, лишний заголовок
 * ничего не меняет». `authenticate` разбирает ветки ПО ПОРЯДКУ и при отказе
 * НЕ проваливается дальше: присланный Bearer решает исход. Access живёт 600
 * секунд — через десять минут после запуска клиент слал протухший токен с
 * исправной подписью и получал 401 на каждый запрос.
 *
 * ── ПОЧЕМУ ОБЫЧНОГО СТОРОЖА БЫЛО МАЛО ──────────────────────────────────────
 *
 * Свойство сервера БЫЛО закреплено — в `auth-session.test.ts` есть тест с
 * именем «does NOT fall through to the initData branch when Bearer is bad».
 * То есть дело не в отсутствии проверки: я утверждал о чужом коде, не
 * посмотрев на него, при живом тесте с этим самым названием.
 *
 * Чего не было — СВЯЗИ. Серверный тест говорит про сервер, клиентский про
 * клиента, и ничто не соединяло два факта: «сервер предпочтёт Bearer и
 * откажет» и «клиент волен послать Bearer рядом с подписью». Между двумя
 * зелёными наборами тестов лежала дыра, в которую и провалился вход.
 *
 * Этот файл — про СТЫК. Он читает обе стороны и проверяет, что они всё ещё
 * договорены. Сломается он в двух случаях, и оба нужны:
 *
 *   1. клиент снова начал слать два удостоверения сразу;
 *   2. на сервере переставили ветки (например, подпись стала выше сессии) —
 *      тогда правило клиента можно и НУЖНО пересмотреть, и тест об этом
 *      напомнит вместо того, чтобы молча устареть.
 */

const КОРЕНЬ = path.join(__dirname, '..', '..', '..')

const читать = (...ч: string[]) =>
  fs.readFileSync(path.join(КОРЕНЬ, ...ч), 'utf8')

/** Код без комментариев: рассказ о правиле — не правило. */
const безКомментариев = (s: string) =>
  s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

const СЕРВЕР = безКомментариев(
  читать('apps', 'vibee-editor', 'render', 'auth.ts')
)
const КЛИЕНТ = безКомментариев(
  читать('apps', 'vibee-editor', 'player', 'src', 'lib', 'apiFetch.ts')
)

/** Заголовки в том порядке, в каком их спрашивает `authenticate`. */
function порядокНаСервере(): string[] {
  const от = СЕРВЕР.indexOf('export function authenticate')
  expect(от, 'authenticate не найдена — проверка была бы пустой').toBeGreaterThan(0)
  const тело = СЕРВЕР.slice(от)
  const найдено: string[] = []
  for (const м of тело.matchAll(
    /req\.headers\['(x-api-key|x-agent-key|authorization|x-telegram-init-data)'\]/g
  )) {
    if (!найдено.includes(м[1])) найдено.push(м[1])
  }
  return найдено
}

describe('порядок удостоверений на сервере', () => {
  it('разобран — иначе всё ниже проверяет пустоту', () => {
    expect(порядокНаСервере().length).toBeGreaterThanOrEqual(4)
  })

  it('сессия спрашивается РАНЬШЕ подписи', () => {
    /*
     * Это и есть то свойство, из-за незнания которого сломался вход. Пока оно
     * верно, клиент обязан не слать Bearer вместе с подписью.
     */
    const п = порядокНаСервере()
    expect(п.indexOf('authorization')).toBeLessThan(
      п.indexOf('x-telegram-init-data')
    )
  })

  it('отказ по Bearer НЕ проваливается в проверку подписи', () => {
    /*
     * Проверяется по коду, а не по комментарию: в ветке Bearer есть `return`
     * до того, как дело дойдёт до заголовка подписи.
     */
    const от = СЕРВЕР.indexOf("req.headers['authorization']")
    const до = СЕРВЕР.indexOf("req.headers['x-telegram-init-data']", от)
    expect(от).toBeGreaterThan(0)
    expect(до).toBeGreaterThan(от)
    const ветка = СЕРВЕР.slice(от, до)
    expect(ветка).toContain('catch')
    expect(ветка).toMatch(/catch[\s\S]*return/)
  })
})

describe('клиент считается с этим порядком', () => {
  it('при подписи Bearer НЕ ставится', () => {
    /*
     * ГЛАВНАЯ СТРОКА ФАЙЛА. Ровно это я и сломал: два удостоверения сразу,
     * первое — протухшее.
     */
    const от = КЛИЕНТ.indexOf('if (initData) {')
    expect(от, 'ветку подписи не нашли').toBeGreaterThan(0)
    const ветка = КЛИЕНТ.slice(от, КЛИЕНТ.indexOf('} else {', от))
    expect(ветка).toContain("h.set('X-Telegram-Init-Data', initData)")
    expect(ветка).not.toContain('Authorization')
  })

  it('без подписи Bearer ставится — опора, без неё правило пустое', () => {
    // «Не слать Bearer» не должно означать «не слать никогда»: вебу и
    // нативному приложению больше нечем представиться.
    const от = КЛИЕНТ.indexOf('} else {', КЛИЕНТ.indexOf('if (initData) {'))
    expect(КЛИЕНТ.slice(от, от + 300)).toContain('Authorization')
  })
})

describe('договор проверяется целиком, а не по половине', () => {
  it('правило клиента ОБОСНОВАНО текущим порядком сервера', () => {
    /*
     * Смысл этой связки: если завтра на сервере поставят подпись выше сессии,
     * запрет клиенту станет лишним — и этот тест упадёт, требуя пересмотреть
     * правило, вместо того чтобы молча устареть.
     *
     * Ровно этой связи не хватало 07.09.2026: серверный тест «Bearer не
     * проваливается» и клиентские тесты были зелёные ОБА, а вход был сломан,
     * потому что никто не смотрел на стык.
     */
    const п = порядокНаСервере()
    const сессияРаньшеПодписи =
      п.indexOf('authorization') < п.indexOf('x-telegram-init-data')

    const от = КЛИЕНТ.indexOf('if (initData) {')
    const клиентМолчитОBearer = !КЛИЕНТ.slice(
      от,
      КЛИЕНТ.indexOf('} else {', от)
    ).includes('Authorization')

    expect(
      сессияРаньшеПодписи && клиентМолчитОBearer,
      сессияРаньшеПодписи
        ? 'сервер предпочитает сессию, значит клиент НЕ должен слать её вместе с подписью'
        : 'порядок на сервере изменился — пересмотрите правило клиента и этот тест'
    ).toBe(true)
  })
})
