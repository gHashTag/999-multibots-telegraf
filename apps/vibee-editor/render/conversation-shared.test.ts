/**
 * ОДИН РАЗГОВОР НА ОБЕ ПОВЕРХНОСТИ.
 *
 * Владелец: «чат бота и чат в мини аппе в агента должен быть
 * синхронизирован». Синхронизировать было нечего — хранилища не существовало:
 *
 *  - переписка мини-аппа жила ЦЕЛИКОМ в localStorage, потолок 100 сообщений,
 *    при переполнении молча выбрасывалось НАЧАЛО разговора;
 *  - сервер не хранил ничего: клиент присылал весь транскрипт каждым
 *    запросом;
 *  - таблицы сообщений не было.
 *
 * Человек видел это так: почистил браузер или открыл из другого клиента —
 * разговора нет, и никто на сервере не знает, что он был.
 */

/** Поддельный пул: проверяем логику, не поднимая Postgres. */
function поддельныйПул() {
  const строки: any[] = []
  let n = 0
  const пул: Пул = {
    async query(sql: string, params: unknown[] = []) {
      if (/^(CREATE|ALTER)/i.test(sql.trim())) return { rows: [] }
      if (/^INSERT INTO agent_messages/i.test(sql.trim())) {
        строки.push({
          id: ++n,
          telegram_id: params[0],
          role: params[1],
          content: params[2],
          surface: params[3],
          thread: params[4] ?? 'self',
          created_at: '2026-09-06T00:00:00Z',
        })
        return { rows: [] }
      }
      if (/^DELETE FROM agent_messages/i.test(sql.trim())) {
        /*
         * ПОДДЕЛКА ПОДЧИНЯЕТСЯ WHERE, А НЕ ДОГАДЫВАЕТСЯ О НЁМ.
         *
         * Сначала она сама решала, «по id это или по владельцу», и снятие
         * условия `AND telegram_id = $2` в настоящем коде НЕ роняло тест:
         * подделка всё равно фильтровала по владельцу. Проверка сверяла
         * подделку с подделкой — ровно как было с ORDER BY выше.
         *
         * Теперь распознаются ровно две формы запроса, а любая третья —
         * ошибка. Неузнанный WHERE не должен вести себя как правильный:
         * именно так дыра и осталась бы незамеченной.
         */
        const текст = sql.replace(/\s+/g, ' ').trim()
        const было = строки.length
        let оставить: any[] | null = null
        // Since 2026-09-13 both forms are scoped to a thread as well (spec
        // crm-client-workspace.t27): the fake still refuses any third shape.
        if (
          /WHERE id = \$1 AND telegram_id = \$2 AND thread = \$3$/.test(текст)
        ) {
          оставить = строки.filter(
            с =>
              !(
                с.id === params[0] &&
                с.telegram_id === params[1] &&
                с.thread === params[2]
              )
          )
        } else if (/WHERE telegram_id = \$1 AND thread = \$2$/.test(текст)) {
          оставить = строки.filter(
            с => !(с.telegram_id === params[0] && с.thread === params[1])
          )
        }
        if (оставить === null) {
          throw new Error(
            `подделка не узнала условие удаления: ${текст} — ` +
              'проверь, не сняли ли привязку к владельцу'
          )
        }
        строки.length = 0
        строки.push(...оставить)
        return { rows: [], rowCount: было - строки.length } as any
      }
      if (/^SELECT/i.test(sql.trim())) {
        const свои = строки.filter(
          с => с.telegram_id === params[0] && с.thread === (params[2] ?? 'self')
        )
        const предел = Number(params[1])
        /*
         * ПОДДЕЛКА ПОДЧИНЯЕТСЯ ЗАПРОСУ, А НЕ ПОВТОРЯЕТ ОЖИДАЕМЫЙ ОТВЕТ.
         *
         * Сначала здесь стояло `свои.slice(-предел).reverse()` — то есть
         * хвост отдавался ВСЕГДА, чем бы ни был настоящий SQL. Проверка
         * «отдаётся хвост, а не начало» проходила и с `ORDER BY id ASC`:
         * она сверяла подделку с подделкой. Поймано мутацией — заменил
         * DESC на ASC, и ничего не покраснело.
         *
         * Теперь направление читается из самого запроса, и подмена
         * сортировки меняет ответ, как в настоящей базе.
         */
        const поУбыванию = /ORDER BY\s+id\s+DESC/i.test(sql)
        const упорядочено = [...свои].sort((a, b) =>
          поУбыванию ? b.id - a.id : a.id - b.id
        )
        return { rows: упорядочено.slice(0, предел) }
      }
      return { rows: [] }
    },
  }
  return { пул, строки }
}

describe('разговор хранится на сервере', () => {
  beforeEach(() => забытьТаблицу())

  it('записанное читается в хронологическом порядке', async () => {
    const { пул } = поддельныйПул()
    await записатьРеплику(пул, '1', {
      role: 'user',
      content: 'первое',
      surface: 'bot',
    })
    await записатьРеплику(пул, '1', {
      role: 'assistant',
      content: 'второе',
      surface: 'bot',
    })
    const р = await прочитатьРазговор(пул, '1')
    expect(р.map(x => x.content)).toEqual(['первое', 'второе'])
  })

  it('отдаётся ХВОСТ разговора, а не начало', async () => {
    /*
     * `ORDER BY id ASC LIMIT N` вернул бы первые реплики — то есть ровно не
     * то, что нужно, чтобы продолжить разговор. Ошибка тихая: данные есть,
     * они просто не те.
     */
    const { пул } = поддельныйПул()
    for (let i = 1; i <= 10; i++) {
      await записатьРеплику(пул, '1', {
        role: 'user',
        content: `реплика ${i}`,
        surface: 'bot',
      })
    }
    const р = await прочитатьРазговор(пул, '1', 3)
    expect(р.map(x => x.content)).toEqual([
      'реплика 8',
      'реплика 9',
      'реплика 10',
    ])
  })

  it('чужой разговор не отдаётся', async () => {
    const { пул } = поддельныйПул()
    await записатьРеплику(пул, '1', {
      role: 'user',
      content: 'моё',
      surface: 'bot',
    })
    await записатьРеплику(пул, '2', {
      role: 'user',
      content: 'чужое',
      surface: 'bot',
    })
    const р = await прочитатьРазговор(пул, '2')
    expect(р.map(x => x.content)).toEqual(['чужое'])
  })

  it('номер реплики доходит до клиента — иначе удалить её нечем', async () => {
    /*
     * Маршрут удаления принимает `?id=`, но история его не возвращала:
     * возможность была написана, покрыта тестами и НЕДОСТИЖИМА. Найдено при
     * попытке убрать собственные проверочные реплики из разговора владельца
     * — то есть первым же реальным применением.
     */
    const { пул } = поддельныйПул()
    await записатьРеплику(пул, '1', {
      role: 'user',
      content: 'первое',
      surface: 'bot',
    })
    const р = await прочитатьРазговор(пул, '1')
    expect(р[0].id).toBe(1)
  })

  it('поверхность сохраняется — видно, где человек писал', async () => {
    const { пул, строки } = поддельныйПул()
    await записатьРеплику(пул, '1', {
      role: 'user',
      content: 'из бота',
      surface: 'bot',
    })
    expect(строки[0].surface).toBe('bot')
  })

  it('пустая реплика не пишется', async () => {
    // Агент иногда заканчивает ход одними вызовами инструментов. Пустая
    // строка в истории выглядела бы молчанием в ответ на вопрос.
    const { пул, строки } = поддельныйПул()
    expect(
      await записатьРеплику(пул, '1', {
        role: 'assistant',
        content: '   ',
        surface: 'bot',
      })
    ).toBe(false)
    expect(строки.length).toBe(0)
  })
})

describe('ответ собирается из потока', () => {
  it('склеивает куски текста', () => {
    expect(
      собратьОтвет([
        { тип: 'текст', текст: 'при' },
        { тип: 'текст', текст: 'вет' },
      ])
    ).toBe('привет')
  })

  it('размышление в историю НЕ идёт', () => {
    /*
     * Черновик мысли — не сказанное человеку. Записав его, следующий виток
     * прочитал бы его как слова агента и начал бы на них опираться.
     */
    expect(
      собратьОтвет([
        { тип: 'размышление', текст: 'сначала посмотрю ленту' },
        { тип: 'текст', текст: 'готово' },
      ])
    ).toBe('готово')
  })

  it('ошибка не записывается ответом', () => {
    expect(собратьОтвет([{ тип: 'ошибка', текст: 'провайдер молчит' }])).toBe('')
  })
})

describe('маршрут истории достижим', () => {
  it('пропущен общим гвардом — иначе 401 до обработчика', () => {
    /*
     * В этом файле уже трижды случалось, что написанный и покрытый тестами
     * маршрут возвращал 401, ни разу не дойдя до обработчика: пары, карточка
     * агента, /api/feed/pending. Проверка стоит рядом с маршрутом, чтобы
     * четвёртого раза не было.
     */
    expect(
      isPublic({
        url: '/api/agent/history?limit=50',
        method: 'GET',
        headers: {},
      } as any)
    ).toBe(true)
  })

  it('личность берётся из проверенной, а не из запроса', () => {
    const сервер = fs.readFileSync(
      path.join(__dirname, 'render-server.ts'),
      'utf8'
    )
    const кусок = сервер.slice(
      сервер.indexOf("'/api/agent/history'"),
      сервер.indexOf("'/api/agent/history'") + 1200
    )
    expect(кусок).toContain('await resolveIdentity(req, getPool)')
    expect(кусок).toContain('handleAgentHistory(req, res, String(who), getPool)')
  })

  it('чат записывает обе стороны разговора', () => {
    const маршруты = fs.readFileSync(
      path.join(__dirname, 'src', 'agent', 'routes.ts'),
      'utf8'
    )
    expect(маршруты).toContain("role: 'user'")
    expect(маршруты).toContain("role: 'assistant'")
    // Пишем ПОСЛЕДНЮЮ реплику, а не всю присланную историю: клиент шлёт весь
    // транскрипт каждым запросом, и запись целиком дублировала бы разговор.
    expect(маршруты).toContain('const последняя = history[history.length - 1]')
  })
})

describe('переписку можно править — но только свою', () => {
  beforeEach(() => забытьТаблицу())

  it('своя реплика удаляется', async () => {
    const { пул } = поддельныйПул()
    await записатьРеплику(пул, '1', { role: 'user', content: 'а', surface: 'bot' })
    await записатьРеплику(пул, '1', { role: 'user', content: 'б', surface: 'bot' })
    expect(await удалитьРеплику(пул, '1', 1)).toBe(1)
    expect((await прочитатьРазговор(пул, '1')).map(x => x.content)).toEqual(['б'])
  })

  it('ЧУЖАЯ реплика не удаляется, даже зная её номер', async () => {
    /*
     * Условие по telegram_id не для красоты: без него знание чужого id
     * означало бы право стирать чужую переписку. Номера реплик сквозные.
     */
    const { пул } = поддельныйПул()
    await записатьРеплику(пул, '2', { role: 'user', content: 'чужое', surface: 'bot' })
    expect(await удалитьРеплику(пул, '1', 1)).toBe(0)
    expect((await прочитатьРазговор(пул, '2')).length).toBe(1)
  })

  it('«начать заново» стирает ТОЛЬКО свой разговор', async () => {
    const { пул } = поддельныйПул()
    await записатьРеплику(пул, '1', { role: 'user', content: 'моё', surface: 'bot' })
    await записатьРеплику(пул, '2', { role: 'user', content: 'чужое', surface: 'bot' })
    expect(await очиститьРазговор(пул, '1')).toBe(1)
    expect((await прочитатьРазговор(пул, '1')).length).toBe(0)
    expect((await прочитатьРазговор(пул, '2')).length).toBe(1)
  })

  it('несуществующий номер отличим от удалённого', async () => {
    // 0 удалённых строк — не то же самое, что успех: маршрут отвечает 404,
    // иначе опечатка в номере выглядела бы как «готово».
    const { пул } = поддельныйПул()
    expect(await удалитьРеплику(пул, '1', 999)).toBe(0)
  })
})

describe('кнопка «Новый разговор» чистит и сервер', () => {
  it('маршрут удаления смонтирован и опознаёт так же, как чтение', () => {
    const сервер = fs.readFileSync(path.join(__dirname, 'render-server.ts'), 'utf8')
    /*
     * Якорь — по ПУТИ, а не по первому `req.method === 'DELETE'` в файле:
     * таких маршрутов несколько, и первый попавшийся относится к ленте.
     * Тот же промах, что уже был со списком импортов вместо списка сцен.
     */
    // Ещё точнее: `'/api/agent/history' &&` встречается и у GET-маршрута
    // строкой выше. Ищем именно ветку DELETE.
    const начало = сервер.indexOf(
      "'/api/agent/history' &&\n    req.method === 'DELETE'"
    )
    expect(начало).toBeGreaterThan(0)
    const кусок = сервер.slice(начало, начало + 1200)
    expect(кусок).toContain('await resolveIdentity(req, getPool)')
    expect(кусок).toContain('handleAgentHistoryDelete')
  })
})
