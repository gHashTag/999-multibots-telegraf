import { describe, it, expect, beforeEach } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'
import {
  записатьРеплику,
  прочитатьРазговор,
  собратьОтвет,
  забытьТаблицу,
  type Пул,
} from './src/agent/conversation'
import { isPublic } from './auth'

/**
 * ОДИН РАЗГОВОР НА ОБЕ ПОВЕРХНОСТИ.
 *
 * Владелец: «чат бота и чат в мини аппе в агента должен быть
 * синхронизирован». Синхронизировать было нечего — хранилища не существовало:
 *
 *  - переписка мини-аппа жила ЦЕЛИКОМ в localStorage, потолок 100 сообщений,
 *    при переполнении молча выбрасывалось НАЧАЛО разговора;
 *  - сервер не хранил ничего: клиент присылал весь транскрипт каждым
 *    запросом;
 *  - таблицы сообщений не было.
 *
 * Человек видел это так: почистил браузер или открыл из другого клиента —
 * разговора нет, и никто на сервере не знает, что он был.
 */

/** Поддельный пул: проверяем логику, не поднимая Postgres. */
function поддельныйПул() {
  const строки: any[] = []
  let n = 0
  const пул: Пул = {
    async query(sql: string, params: unknown[] = []) {
      if (/^CREATE/i.test(sql.trim())) return { rows: [] }
      if (/^INSERT INTO agent_messages/i.test(sql.trim())) {
        строки.push({
          id: ++n,
          telegram_id: params[0],
          role: params[1],
          content: params[2],
          surface: params[3],
          created_at: '2026-09-06T00:00:00Z',
        })
        return { rows: [] }
      }
      if (/^SELECT/i.test(sql.trim())) {
        const свои = строки.filter(с => с.telegram_id === params[0])
        const предел = Number(params[1])
        /*
         * ПОДДЕЛКА ПОДЧИНЯЕТСЯ ЗАПРОСУ, А НЕ ПОВТОРЯЕТ ОЖИДАЕМЫЙ ОТВЕТ.
         *
         * Сначала здесь стояло `свои.slice(-предел).reverse()` — то есть
         * хвост отдавался ВСЕГДА, чем бы ни был настоящий SQL. Проверка
         * «отдаётся хвост, а не начало» проходила и с `ORDER BY id ASC`:
         * она сверяла подделку с подделкой. Поймано мутацией — заменил
         * DESC на ASC, и ничего не покраснело.
         *
         * Теперь направление читается из самого запроса, и подмена
         * сортировки меняет ответ, как в настоящей базе.
         */
        const поУбыванию = /ORDER BY\s+id\s+DESC/i.test(sql)
        const упорядочено = [...свои].sort((a, b) =>
          поУбыванию ? b.id - a.id : a.id - b.id
        )
        return { rows: упорядочено.slice(0, предел) }
      }
      return { rows: [] }
    },
  }
  return { пул, строки }
}

describe('разговор хранится на сервере', () => {
  beforeEach(() => забытьТаблицу())

  it('записанное читается в хронологическом порядке', async () => {
    const { пул } = поддельныйПул()
    await записатьРеплику(пул, '1', {
      role: 'user',
      content: 'первое',
      surface: 'bot',
    })
    await записатьРеплику(пул, '1', {
      role: 'assistant',
      content: 'второе',
      surface: 'bot',
    })
    const р = await прочитатьРазговор(пул, '1')
    expect(р.map(x => x.content)).toEqual(['первое', 'второе'])
  })

  it('отдаётся ХВОСТ разговора, а не начало', async () => {
    /*
     * `ORDER BY id ASC LIMIT N` вернул бы первые реплики — то есть ровно не
     * то, что нужно, чтобы продолжить разговор. Ошибка тихая: данные есть,
     * они просто не те.
     */
    const { пул } = поддельныйПул()
    for (let i = 1; i <= 10; i++) {
      await записатьРеплику(пул, '1', {
        role: 'user',
        content: `реплика ${i}`,
        surface: 'bot',
      })
    }
    const р = await прочитатьРазговор(пул, '1', 3)
    expect(р.map(x => x.content)).toEqual([
      'реплика 8',
      'реплика 9',
      'реплика 10',
    ])
  })

  it('чужой разговор не отдаётся', async () => {
    const { пул } = поддельныйПул()
    await записатьРеплику(пул, '1', {
      role: 'user',
      content: 'моё',
      surface: 'bot',
    })
    await записатьРеплику(пул, '2', {
      role: 'user',
      content: 'чужое',
      surface: 'bot',
    })
    const р = await прочитатьРазговор(пул, '2')
    expect(р.map(x => x.content)).toEqual(['чужое'])
  })

  it('поверхность сохраняется — видно, где человек писал', async () => {
    const { пул, строки } = поддельныйПул()
    await записатьРеплику(пул, '1', {
      role: 'user',
      content: 'из бота',
      surface: 'bot',
    })
    expect(строки[0].surface).toBe('bot')
  })

  it('пустая реплика не пишется', async () => {
    // Агент иногда заканчивает ход одними вызовами инструментов. Пустая
    // строка в истории выглядела бы молчанием в ответ на вопрос.
    const { пул, строки } = поддельныйПул()
    expect(
      await записатьРеплику(пул, '1', {
        role: 'assistant',
        content: '   ',
        surface: 'bot',
      })
    ).toBe(false)
    expect(строки.length).toBe(0)
  })
})

describe('ответ собирается из потока', () => {
  it('склеивает куски текста', () => {
    expect(
      собратьОтвет([
        { тип: 'текст', текст: 'при' },
        { тип: 'текст', текст: 'вет' },
      ])
    ).toBe('привет')
  })

  it('размышление в историю НЕ идёт', () => {
    /*
     * Черновик мысли — не сказанное человеку. Записав его, следующий виток
     * прочитал бы его как слова агента и начал бы на них опираться.
     */
    expect(
      собратьОтвет([
        { тип: 'размышление', текст: 'сначала посмотрю ленту' },
        { тип: 'текст', текст: 'готово' },
      ])
    ).toBe('готово')
  })

  it('ошибка не записывается ответом', () => {
    expect(собратьОтвет([{ тип: 'ошибка', текст: 'провайдер молчит' }])).toBe('')
  })
})

describe('маршрут истории достижим', () => {
  it('пропущен общим гвардом — иначе 401 до обработчика', () => {
    /*
     * В этом файле уже трижды случалось, что написанный и покрытый тестами
     * маршрут возвращал 401, ни разу не дойдя до обработчика: пары, карточка
     * агента, /api/feed/pending. Проверка стоит рядом с маршрутом, чтобы
     * четвёртого раза не было.
     */
    expect(
      isPublic({
        url: '/api/agent/history?limit=50',
        method: 'GET',
        headers: {},
      } as any)
    ).toBe(true)
  })

  it('личность берётся из проверенной, а не из запроса', () => {
    const сервер = fs.readFileSync(
      path.join(__dirname, 'render-server.ts'),
      'utf8'
    )
    const кусок = сервер.slice(
      сервер.indexOf("'/api/agent/history'"),
      сервер.indexOf("'/api/agent/history'") + 1200
    )
    expect(кусок).toContain('await resolveIdentity(req, getPool)')
    expect(кусок).toContain('handleAgentHistory(req, res, String(who), getPool)')
  })

  it('чат записывает обе стороны разговора', () => {
    const маршруты = fs.readFileSync(
      path.join(__dirname, 'src', 'agent', 'routes.ts'),
      'utf8'
    )
    expect(маршруты).toContain("role: 'user'")
    expect(маршруты).toContain("role: 'assistant'")
    // Пишем ПОСЛЕДНЮЮ реплику, а не всю присланную историю: клиент шлёт весь
    // транскрипт каждым запросом, и запись целиком дублировала бы разговор.
    expect(маршруты).toContain('const последняя = history[history.length - 1]')
  })
})
