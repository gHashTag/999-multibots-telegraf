/**
 * УДАЛЕНИЕ СВОЕГО ФОТО ИЗ ПРОФИЛЯ АВАТАРА.
 *
 * Вынесено из `render-server.ts` 07.09.2026, и вот почему.
 *
 * `DELETE /api/assets` удаляет файлы людей, и вся защита от «удалить чужое» —
 * это одно условие в запросе: `AND telegram_id = $2`. Рядом лежал текстовый
 * сторож `assets-identity-order.test.ts`, который честно писал о себе:
 * «проверяет ПОРЯДОК — личность устанавливается раньше тела и базы; НЕ
 * проверяет, что функция личности верна».
 *
 * То есть порядок был закреплён, а само свойство «чужое не удаляется» — нет.
 * Исполнить его было нечем: `render-server.ts` не импортирует ни один тест,
 * потому что импорт поднимает сервер.
 *
 * Поэтому здесь ровно та часть, которая защищает, — и ничего больше. HTTP
 * остаётся снаружи, а условие можно запустить и сломать в тесте.
 *
 * ── ПОЧЕМУ УСЛОВИЙ ТРИ, А НЕ ОДНО ──────────────────────────────────────────
 *
 *   id            — что удаляем;
 *   telegram_id   — ЧЬЁ. Без него любой номер id удаляет чужой файл;
 *   type          — только фото профиля аватара. Иначе тем же маршрутом
 *                   вычищаются генерации, договоры и всё, что когда-нибудь
 *                   ляжет в `assets` с другим типом.
 *
 * Ноль удалённых строк — это НЕ успех. Клиент, услышавший «удалено» про
 * несуществующее или чужое, поверит и покажет человеку исчезнувший файл,
 * которого никто не трогал.
 */

/** Минимум, который нужен от пула: выполнить запрос и сказать число строк. */
export interface ПулДляУдаления {
  query(
    sql: string,
    params: unknown[]
  ): Promise<{ rowCount?: number | null }>
}

export type ИтогУдаления = 'удалено' | 'не найдено'

/**
 * Удалить фото по id — но ТОЛЬКО своё и только фото профиля аватара.
 *
 * `кто` обязан приходить из проверенной личности, а НЕ из запроса: id в
 * строке запроса называет файл, а не владельца.
 */
export async function удалитьСвоёФото(
  pool: ПулДляУдаления,
  { кто, id }: { кто: string; id: number }
): Promise<ИтогУдаления> {
  const r = await pool.query(
    `DELETE FROM assets
      WHERE id = $1 AND telegram_id = $2 AND type = 'avatar_photo'`,
    [id, String(кто)]
  )
  return (r.rowCount ?? 0) > 0 ? 'удалено' : 'не найдено'
}
