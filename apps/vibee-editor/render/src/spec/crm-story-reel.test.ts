/**
 * THE STORY REEL IS WRITTEN IN t27 FIRST (owner, 2026-09-27: "t27 is our
 * language; everything is to be rewritten in it in the end").
 *
 * gHashTag/t27 specs/automation/crm-story-reel.t27 is the spec of record. It
 * is vendored here byte for byte, beside its `t27c gen-ts` output, and the
 * host imports its numbers from that output. Three things are pinned:
 *
 *   1. the generated module IS the spec -- every `pub const` of the .t27 has
 *      the same value there, and nothing else is declared;
 *   2. the host restates none of the spec's numbers -- they are imported;
 *   3. the spec's own test vectors hold against the HOST: a spec can only be
 *      the source of truth if the code does what its tests say.
 *
 * Refresh: node scripts/sync-t27-spec.mjs <t27 checkout> automation/crm-story-reel
 */
const HERE = __dirname
const specText = readFileSync(join(HERE, 'crm-story-reel.t27'), 'utf8')
const genText = readFileSync(join(HERE, 'crm-story-reel.gen.ts'), 'utf8')

/** `pub const NAME : TYPE = VALUE;` of the spec, read as values. */
function specConsts(): Map<string, unknown> {
  const out = new Map<string, unknown>()
  const re = /^\s*pub const (\w+)\s*:\s*(\w+)\s*=\s*(.+?);/gm
  for (const m of specText.matchAll(re)) {
    const [, name, type, raw] = m
    const value =
      type === 'str'
        ? JSON.parse(raw.trim())
        : type === 'bool'
          ? raw.trim() === 'true'
          : Number(raw.trim())
    out.set(name, value)
  }
  return out
}

describe('the generated module is the spec', () => {
  const consts = specConsts()

  it('reads the spec: it has constants, and the negative control works', () => {
    expect(consts.size).toBeGreaterThan(50)
    expect(consts.get('PRICE_ESTIMATE_TOKENS')).toBe(270)
    expect(consts.get('SENT_WITHOUT_PRESS')).toBe(false)
    expect(consts.get('COMPOSITION')).toBe('StoryReel')
  })

  it('every constant of the spec has the same value in the generated module', () => {
    const gen = SPEC as unknown as Record<string, unknown>
    for (const [name, value] of consts) expect(gen[name], name).toBe(value)
  })

  it('the generated module declares nothing the spec does not', () => {
    const declared = [...SPEC.__DECL_ORDER__].filter(
      n => !(SPEC.__STRUCT_ORDER__ as readonly string[]).includes(n)
    )
    expect(declared).toEqual([...consts.keys()])
    expect(SPEC.__NOT_EMITTED__).toEqual([])
  })

  it('is the compiler output, marked as such, and names its spec', () => {
    expect(
      genText.startsWith(
        '// Generated by `t27c gen-ts` from crm-story-reel.t27. Do not edit.'
      )
    ).toBe(true)
    expect(specText).toContain('module automation::crm_story_reel')
    expect(SPEC.ID).toBe('crm-story-reel')
    expect(SPEC.REPO).toBe('999-multibots-telegraf')
  })
})

describe('the host restates none of the spec numbers', () => {
  const src = (f: string) => readFileSync(join(HERE, '..', 'agent', f), 'utf8')

  it.each([
    [
      'story-template.ts',
      [
        'JOB_ATTEMPTS',
        'BEAT_MS',
        'DEAD_MS',
        'SWEEP_MS',
        'ABANDON_MINUTES',
        'START_PARAM',
        'TOPIC_MAX',
        'SCENES',
        'BILLED_SECONDS',
      ],
    ],
    [
      'story-reel-tool.ts',
      ['SCENES_MIN', 'SCENES_MAX', 'PAUSE_SEC', 'STILL_WAIT_MS'],
    ],
  ])('%s takes its STORY_* constants from the spec', (file, names) => {
    const text = src(file)
    for (const n of names) {
      const m = new RegExp(`export const STORY_${n} = (.+)`).exec(text)
      expect(m, `STORY_${n} in ${file}`).not.toBeNull()
      expect(m![1], `STORY_${n}`).toMatch(/^SPEC\./)
    }
  })

  it('and the values it exports are the spec values', () => {
    expect(STORY_JOB_ATTEMPTS).toBe(SPEC.JOB_ATTEMPTS)
    expect(STORY_BEAT_MS).toBe(SPEC.BEAT_MS)
    expect(STORY_DEAD_MS).toBe(SPEC.DEAD_MS)
    expect(STORY_SWEEP_MS).toBe(SPEC.SWEEP_MS)
    expect(STORY_ABANDON_MINUTES).toBe(SPEC.ABANDON_MINUTES)
    expect(STORY_START_PARAM).toBe(SPEC.START_PARAM)
    expect(STORY_TOPIC_MAX).toBe(SPEC.TOPIC_MAX)
    expect(STORY_SCENES).toBe(SPEC.SCENES_DEFAULT)
    expect(STORY_BILLED_SECONDS).toBe(SPEC.BILLED_SECONDS)
    expect(STORY_SCENES_MIN).toBe(SPEC.SCENES_MIN)
    expect(STORY_SCENES_MAX).toBe(SPEC.SCENES_MAX)
    expect(STORY_PAUSE_SEC).toBe(SPEC.PAUSE_SEC)
    expect(STORY_BREATH_SEC * 1000).toBe(SPEC.BREATH_MS)
    expect(STORY_STILL_WAIT_MS).toBe(SPEC.STILL_WAIT_MS)
    expect(storyTurn(7)).toBe(`${SPEC.CARD_TURN_PREFIX}7`)
  })
})

/*
 * The spec's `test` blocks, run against the host. Each block below names the
 * block of crm-story-reel.t27 it mirrors; its inputs and answers are the
 * spec's, the function under test is the one production runs.
 */
describe("the spec's tests hold against the host", () => {
  it('the estimate is three stills, three lines, thirteen seconds of lip-sync and one cut', () => {
    expect(TOKEN_PRICES.image_edit).toBe(SPEC.TOKENS_PER_STILL)
    expect(TOKEN_PRICES.audio_generate).toBe(SPEC.TOKENS_PER_LINE)
    expect(TOKEN_PRICES.lipsync_generate).toBe(SPEC.TOKENS_PER_LIPSYNC_SEC)
    expect(TOKEN_PRICES.reel_render).toBe(SPEC.TOKENS_PER_ASSEMBLY)
    expect(storyPriceEstimate()).toBe(SPEC.PRICE_ESTIMATE_TOKENS)
  })

  it('the voice is her own, cloned once per seller, and only Replicate can speak it', () => {
    expect(VOICE_CLONE_MODEL).toBe(SPEC.CLONE_MODEL)
    expect(`minimax/${VOICE_CLONE_TTS_MODEL}`).toBe(SPEC.VOICE_MODEL)
    expect(VOICE_CLONE_USD).toBe(Number(SPEC.CLONE_COST_USD))
    expect(LEAD_VOICE_MIN_SECONDS).toBe(SPEC.CLONE_MIN_SECONDS)
    expect(LEAD_VOICE_GOOD_SECONDS).toBe(SPEC.CLONE_GOOD_SECONDS)
    expect(LEAD_VOICE_MAX_SECONDS).toBe(SPEC.CLONE_MAX_SECONDS)
  })

  it('the stills and the lip-sync are the models the spec names', () => {
    expect(EDIT_MODEL).toBe(SPEC.STILL_MODEL)
    expect(LIPSYNC_DEFAULT_MODEL).toBe(SPEC.LIPSYNC_MODEL)
  })

  it('a script of one to four scenes is made as given; five is refused', () => {
    const scene = { setting: 'a room', line: 'Hello.' }
    const of = (n: number) => scenesOf(Array.from({ length: n }, () => scene))
    expect(Array.isArray(of(SPEC.SCENES_DEFAULT))).toBe(true)
    expect(Array.isArray(of(1))).toBe(true)
    expect(Array.isArray(of(4))).toBe(true)
    expect(typeof of(0)).toBe('string')
    expect(typeof of(5)).toBe('string')
  })

  it('the pause stays between one and four seconds, three by default', () => {
    expect(pauseOf(SPEC.PAUSE_SEC)).toBe(3)
    expect(pauseOf(0)).toBe(1)
    expect(pauseOf(9)).toBe(4)
    expect(pauseOf(undefined)).toBe(SPEC.PAUSE_SEC)
  })

  it('the card never displaces one the owner has not answered, and fits Telegram', () => {
    const id = 'abc123abc123'
    const secret = 's'.repeat(32)
    for (const b of cardButtons(id, secret).flat())
      expect(Buffer.byteLength(b.callback_data)).toBeLessThanOrEqual(
        SPEC.CALLBACK_BYTES_MAX
      )
    expect(SPEC.CARD_DISPLACES_UNANSWERED).toBe(false)
    expect(SPEC.PRESSABLE_CARDS_PER_PERSON).toBe(1)
  })

  it('a render asked for by the service waits for approval in the feed', () => {
    expect(
      renderFeedEntry({ viaServiceKey: true, renderId: 'aaaaaaaa' }).isPublic
    ).toBe(SPEC.SERVICE_RENDER_FEED_PUBLIC)
  })

  it('the one-press links are the spec routes', () => {
    expect(SPEC.START_PARAM).toBe('reel')
    expect(isAppRoute(SPEC.PAGE_ROUTE)).toBe(true)
  })
})
