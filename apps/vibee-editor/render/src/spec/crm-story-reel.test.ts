/** `pub const NAME : TYPE = VALUE;` of the spec, read as values. */
function specConsts(): Map<string, unknown> {
  const out = new Map<string, unknown>()
  const re = /^\s*pub const (\w+)\s*:\s*(\w+)\s*=\s*(.+?);/gm
  for (const m of specText.matchAll(re)) {
    const [, name, type, raw] = m
    const value =
      type === 'str'
        ? JSON.parse(raw.trim())
        : type === 'bool'
          ? raw.trim() === 'true'
          : Number(raw.trim())
    out.set(name, value)
  }
  return out
}

