/**
 * THE STORY REEL IS WRITTEN IN t27 FIRST (owner, 2026-09-27: "t27 is our
 * language; everything is to be rewritten in it in the end").
 *
 * gHashTag/t27 specs/automation/crm-story-reel.t27 is the spec of record. It
 * is vendored here byte for byte, beside its `t27c gen-ts` output, and the
 * host imports its numbers from that output. Three things are pinned:
 *
 *   1. the generated module IS the spec -- every `pub const` of the .t27 has
 *      the same value there, and nothing else is declared;
 *   2. the host restates none of the spec's numbers -- they are imported;
 *   3. the spec's own test vectors hold against the HOST: a spec can only be
 *      the source of truth if the code does what its tests say.
 *
 * Refresh: node scripts/sync-t27-spec.mjs <t27 checkout> automation/crm-story-reel
 */
