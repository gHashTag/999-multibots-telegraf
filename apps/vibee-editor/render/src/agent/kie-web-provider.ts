export const KIE_WEB_MODELS: Record<
  KieWebMediaKind,
  ReadonlySet<string>
> = (() => {
  const из: Record<KieWebMediaKind, Set<string>> = {
    image: new Set(),
    video: new Set(),
    audio: new Set(),
    lipsync: new Set(),
  }
  for (const м of KIE_MODELS) {
    if (м.state !== 'live') continue
    const видимое = ВИДИМЫЕ_ИМЕНА[м.id]
    if (!видимое || видимое.опасная === true) continue
    const kind = ВИД_К_KIND[видимое.вид]
    if (!kind) continue
    if (priceForKieModel(м.id) == null) continue
    /**
     * 4. КОНТРАКТ ИЗВЕСТЕН. Без него заявку не собрать: часть моделей
     *    отвечает «This field is required», НЕ НАЗЫВАЯ поле — ни пустая
     *    проба, ни прайс, ни исходник документации его не выдают (схема на
     *    docs.kie.ai грузится отдельным запросом). Допустить такую модель
     *    значит показать её в списке и гарантированно отказать после
     *    нажатия — то самое обещание, которого никто не исполнит.
     *
     *    Как только контракт измерен и записан в `needs`, модель попадает
     *    в список сама, без правки этого файла.
     */
    if (!м.needs || м.needs.length === 0) continue
    /**
     * 5. ВХОД, КОТОРЫЙ МЫ МОЖЕМ ДАТЬ. Модель, просящая картинку, видео или
     *    звук, которых маршрут не передаёт, не сработает НИКОГДА: сборщик
     *    входа вернёт null, а до него человек уже нажал и заплатил (деньги
     *    вернутся, время нет).
     *
     *    Замер: таких моделей было семь, по одной-две на каждой платной
     *    вкладке. Приложение честно писало «нужно: картинку» — и отправляло
     *    запрос без неё, потому что загрузки на этих экранах просто нет.
     *
     *    Это ВРЕМЕННО и обратимо: как только экран научится передавать
     *    вход, добавьте поле в ПОЛЯ_МАРШРУТА — и модели вернутся сами,
     *    без правки этого условия.
     */
    const умеем = ПОЛЯ_МАРШРУТА[kind]
    if (м.needs.some(поле => !умеем.includes(поле))) continue
    из[kind].add(м.id)
  }
  return из
})()

/**
 * КАКИЕ ПОЛЯ ЭТА МОДЕЛЬ ДЕЙСТВИТЕЛЬНО ПОЛУЧИТ. Для `/api/balance`.
 *
 * Пересечение контракта модели с тем, что умеет передать маршрут: ровно те
 * поля, которые `kieInputFor` оставит в заявке.
 *
 * Сегодня пересечение не срезает НИЧЕГО — допуск выше не пускает модель, чьё
 * поле маршрут передать не умеет. Отсечение стоит здесь не «на всякий
 * случай», а чтобы сужение `ПОЛЯ_МАРШРУТА` не начало молча отнимать у модели
 * поля, оставляя её в витрине; тест проверяет обе стороны.
 *
 * Замер, ради которого это заведено: у ДЕСЯТИ видеомоделей из двенадцати
 * контракт — один `prompt`, а экран показывает чипы «Длительность» и «Кадр».
 * Человек выбирает 9:16 для рилса и получает то, что модель решила сама.
 * Настройка, ни на что не влияющая, — это обещание не того; правило уже
 * записано в приложении, но выполнялось на глаз, по виду работы.
 *
 * Клиенты спрашивают сервер, а не заводят четвёртую копию контрактов.
 */
export function поляМоделей(): Record<string, string[]> {
  const из: Record<string, string[]> = {}
  for (const kind of Object.keys(KIE_WEB_MODELS) as KieWebMediaKind[]) {
    const умеем = ПОЛЯ_МАРШРУТА[kind]
    for (const id of KIE_WEB_MODELS[kind]) {
      const контракт =
        KIE_MODELS.find((м: { id: string; needs?: string[] }) => м.id === id)
          ?.needs ?? []
      из[`kie/${id}`] = контракт.filter(поле => умеем.includes(поле))
    }
  }
  return из
}

export function reviewedKieModel(
  kind: KieWebMediaKind,
  requested: unknown
): string | null {
  if (typeof requested !== 'string' || !requested.startsWith('kie/')) {
    return null
  }
  const model = requested.slice(4)
  if (!KIE_WEB_MODELS[kind].has(model)) {
    throw new Error(`Kie.ai model is not enabled for ${kind}`)
  }
  return model
}

/**
 * Вход для KieAI, собранный ПО КОНТРАКТУ КОНКРЕТНОЙ МОДЕЛИ.
 *
 * Раньше на весь вид шла одна форма — та, что подходит одной допущенной
 * модели. Пока модель была одна, это работало. Как только допущены все,
 * форма начала не совпадать: `google/imagen4` отвечает
 * «aspect_ratio cannot be empty», а мы слали только `prompt`; человек видел
 * отказ там, где модель исправна и готова работать.
 *
 * Контракт берётся из `needs` каталога — это ДОСЛОВНЫЕ ответы KieAI на пробу,
 * а не наши догадки о том, что модель хочет. Поле, которого модель не просила,
 * не отправляется: лишнее поле у части моделей само по себе повод для отказа.
 *
 * Чего эта функция НЕ делает: не выдумывает значения. Если контракт требует
 * поле, которого у нас нет (`speakers` у многоголосого TTS), заявка не
 * собирается и вызывающий получает null — отказать до траты честнее, чем
 * послать заведомо неполный запрос и заплатить за отказ.
 */
export function kieInputFor(
  modelId: string,
  доступно: Record<string, unknown>
): Record<string, unknown> | null {
  const м = KIE_MODELS.find(x => x.id === modelId)
  const контракт = м?.needs ?? []
  // Контракт неизвестен (проба не назвала полей) — шлём то, что есть, и
  // позволяем провайдеру ответить. Пустая заявка хуже: она точно не сработает.
  if (!контракт.length) return { ...доступно }

  const вход: Record<string, unknown> = {}
  for (const поле of контракт) {
    const v = доступно[поле]
    if (v === undefined || v === null || v === '') return null
    вход[поле] = v
  }
  // Необязательные, но осмысленные для вида: отправляем только те, что
  // модель уже назвала в контракте, — см. выше про лишние поля.
  return вход
}
