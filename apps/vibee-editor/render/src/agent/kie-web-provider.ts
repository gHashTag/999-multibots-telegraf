export type KieWebMediaKind = 'image' | 'video' | 'audio' | 'lipsync'

const ВИД_К_KIND: Record<string, KieWebMediaKind> = {
  картинка: 'image',
  видео: 'video',
  звук: 'audio',
  липсинк: 'lipsync',
}

/**
 * ВСЕ модели KieAI, допущенные к оплате — а не одна на вид.
 *
 * Здесь стояла ровно одна проверенная модель на каждый вид. Это защищало от
 * траты на непроверенном пути, но ценой продукта: каталог показывал 45 живых
 * моделей, сервер выполнял 4, и выбор был обещанием, которого никто не
 * собирался исполнять.
 *
 * Теперь допущено всё, что удовлетворяет ТРЁМ условиям, и каждое из них —
 * про деньги или про честность, а не про вкус:
 *
 *   1. `live` у провайдера. Приостановленная модель заберёт деньги и не
 *      вернёт результат.
 *   2. ЦЕНА ИЗВЕСТНА. Пять моделей из сорока восьми провайдер не оценил
 *      вовсе; взять с человека неизвестно сколько нельзя, а назвать сумму до
 *      нажатия — нечем.
 *   3. НЕ помечена опасной. `grok-imagine/image-to-video` создаёт ПЛАТНОЕ
 *      задание даже на пустой запрос — разведка по ней стоила денег дважды.
 *      Такую нельзя допускать к оплате ни при каком балансе.
 */
/**
 * Поля, которые маршрут КАЖДОГО вида физически передаёт модели.
 *
 * Списки взяты ИЗ ВЫЗОВОВ, не из памяти, и рядом стоит файл со строкой.
 * Проверка, написанная по памяти, обвинила шесть исправных моделей: маршруты
 * подставляют `quality`, `mode` и `resolution` сами.
 *
 * Место одно НАМЕРЕННО: по этому списку и допускается модель, и проверяется
 * конвейер (`scripts/pipeline-check.ts`). Две копии разошлись бы на первой же
 * правке, и допуск начал бы расходиться с проверкой — то есть проверка
 * замолчала бы ровно там, где нужна.
 */
/**
 * Разрешение, которое маршрут видео просит у провайдера.
 *
 * Живёт здесь, а не строкой внутри обработчика, потому что от него зависит
 * ЦЕНА: у grok-imagine 480p и 720p стоят по-разному, и цена в каталоге
 * привязана к конкретной строке прайса. Тест сверяет одно с другим.
 */
export const РАЗРЕШЕНИЕ_ВИДЕО = '480p'

/**
 * Разрешение, которое маршрут ЛИПСИНКА просит у провайдера.
 *
 * Та же причина, что у видео, и та же ошибка, не исправленная здесь: цена
 * модели в каталоге — САМАЯ ДЕШЁВАЯ строка прайса (kie-prices.generated.ts
 * это прямо объявляет), а маршрут пересылал разрешение, пришедшее от клиента.
 *
 * Замер по живому прайсу KieAI (`model-pricing/page`): у InfiniteTalk ДВЕ
 * строки — «up to 15 seconds-480p» за $0.015 в секунду и «…-720p» за $0.06,
 * вчетверо дороже. Цена в каталоге взята с первой; веб же слал 720p ПО
 * УМОЛЧАНИЮ, а приложение — 480p. То есть за одну и ту же секунду мы платили
 * вчетверо больше в зависимости от того, откуда пришёл человек, а брали
 * одинаково.
 *
 * Пин, а не новая цена: разрешение выбирает тот, кто назначает цену. Продавать
 * 720p отдельной строкой — решение владельца, и оно требует своей цены, а не
 * молчаливого списания по ставке 480p.
 */
export const РАЗРЕШЕНИЕ_ЛИПСИНКА = '480p'

