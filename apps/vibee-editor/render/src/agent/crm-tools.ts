/**
 * CRM НА ДАННЫХ, КОТОРЫЕ У НАС УЖЕ ЕСТЬ.
 *
 * Владелец попросил CRM и «предложение горячих лидов». Первым делом я назвал
 * препятствие: контакты Telegram боту недоступны, для них нужен вход
 * владельца, которого агент выполнить не может. Это по-прежнему верно.
 *
 * Но ждать этого входа незачем: аудитория УЖЕ есть и она немаленькая. Замер
 * 06.09.2026: 2380 человек в `users`, 1510 завершённых входящих платежей в
 * `payments_v2`. Это люди, которые сами пришли к ботам владельца, — то есть
 * самая тёплая база, какая бывает, и её не надо ниоткуда выкачивать.
 *
 * ── ЧТО ЗДЕСЬ СЧИТАЕТСЯ ЛИДОМ ───────────────────────────────────────────────
 *
 * Не «похожий на клиента», а измеримое поведение:
 *
 *   ГОРЯЧИЙ  — заходил недавно, но НИ РАЗУ не платил. Интерес есть, барьер
 *              не пройден: ему нужен повод, а не знакомство.
 *   ВЕРНУТЬ  — платил раньше и замолчал. Дороже всего терять именно этих:
 *              они уже доказали, что готовы платить.
 *   ЖИВЫЕ    — платил и заходит. Их не трогают предложениями, им дают
 *              работать.
 *
 * ── ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ ─────────────────────────────────────────────────
 *
 * Нет рассылки. Инструменты только ПОКАЗЫВАЮТ, кому имеет смысл написать.
 * Массовая отправка — необратимое действие в адрес живых людей, и оно должно
 * начинаться с решения человека, а не с решения модели. Тот же принцип, что и
 * у telegram-tools: читать можно, действовать наружу — по подтверждению.
 *
 * Нет никаких «скорингов» с придуманными коэффициентами: число, которое
 * нельзя объяснить, в продаже хуже отсутствия числа.
 */
import type { AgentTool, ToolContext } from './tools'

/**
 * ЭТО ЧУЖИЕ ЛЮДИ, А НЕ ПРОСТО СТРОКИ.
 *
 * Здесь отдаются имена и идентификаторы посторонних. Открыть это «любому
 * опознанному» значит отдать базу клиентов каждому, кто открыл мини-апп:
 * подпись мини-аппа есть у всех пользователей платформы.
 *
 * КАЖДЫЙ ВИДИТ ТОЛЬКО СВОЮ АУДИТОРИЮ. Первая версия пускала одного владельца
 * платформы — безопасно, но бесполезно для остальных пятнадцати
 * ботовладельцев. Теперь граница проходит по `bot_name`: чьи боты — того и
 * люди. Владение берётся из `avatars` (таблица, на которой уже стоит
 * `getOwnedBots` в сервисе бота), а не из нового списка: второй источник
 * владения разошёлся бы с первым.
 *
 * Fail-closed: не удалось определить, чьи боты, — отказ, а не «покажем всё».
 */
const OWNER_TELEGRAM_ID = (process.env.OWNER_TELEGRAM_ID || '144022504').trim()

/** Боты, которыми человек владеет. Пустой список — значит показывать нечего. */
async function моиБоты(telegramId: string): Promise<string[]> {
  const строки = await запрос<{ bot_name: string | null }>(
    `avatars?select=bot_name&telegram_id=eq.${encodeURIComponent(telegramId)}`
  )
  return строки.map(с => (с.bot_name || '').trim()).filter(Boolean)
}

/**
 * Чью аудиторию показываем.
 *
 * `null` означает «все боты» и достаётся ТОЛЬКО владельцу платформы: он
 * отвечает за платформу целиком, и разбивка по ботам в сводке — его рабочий
 * инструмент. Всем остальным возвращается конкретный список их ботов.
 */
async function областьВидимости(ctx?: ToolContext): Promise<string[] | null> {
  const кто = ctx ? String(ctx.telegramId ?? '') : ''
  if (!кто) {
    throw new Error(
      'CRM показывает данные других людей и требует подтверждённой личности'
    )
  }
  if (кто === OWNER_TELEGRAM_ID) return null
  const боты = await моиБоты(кто)
  if (!боты.length) {
    throw new Error(
      'CRM показывает аудиторию ВАШИХ ботов, а за вами ботов не числится. ' +
        'Если бот ваш — он должен быть записан на вас в avatars.'
    )
  }
  return боты
}

const noArgs = { type: 'object', properties: {} } as const

/** Сколько людей отдаём списком. Больше — не список, а выгрузка. */
const ПОТОЛОК_СПИСКА = 50

function настройки(): { url: string; key: string } {
  const url = (process.env.SUPABASE_URL || '').replace(/\/+$/, '')
  const key = process.env.SUPABASE_SERVICE_KEY || ''
  if (!url || !key) {
    throw new Error(
      'CRM не настроен: нужны SUPABASE_URL и SUPABASE_SERVICE_KEY на сервисе рендера'
    )
  }
  return { url, key }
}

/**
 * Сколько строк отдаёт Supabase за один запрос.
 *
 * PostgREST режет выдачу СВОИМ потолком (db-max-rows), и `limit` в адресе
 * его не отменяет. Поэтому читаем страницами через заголовок Range.
 */
const СТРАНИЦА = 1000

/**
 * ЧИТАЕМ ВСЮ БАЗУ, А НЕ ПЕРВУЮ СТРАНИЦУ.
 *
 * Первая версия слала один запрос и считала, что получила всех. Спросил
 * живой сервис 06.09.2026 — и он ответил:
 *
 *     всего_людей: 1000    при 2380 в таблице
 *     пришли_за_7_дней: 0  свежие просто не попали в срез
 *
 * Худшая форма ошибки: ответ выглядит уверенно и неверен. Владелец прочитал
 * бы «роста нет» и «платящих 5.6%» и принял бы решения по обоим.
 *
 * Пагинация идёт до КОРОТКОЙ страницы: ждать пустую — лишний запрос, а
 * «до потолка попыток» молча обрезало бы базу ровно так же, как PostgREST.
 */
async function запрос<T>(путь: string): Promise<T[]> {
  const { url, key } = настройки()
  const всё: T[] = []
  for (let начало = 0; ; начало += СТРАНИЦА) {
    const о = await fetch(`${url}/rest/v1/${путь}`, {
      headers: {
        apikey: key,
        Authorization: `Bearer ${key}`,
        Range: `${начало}-${начало + СТРАНИЦА - 1}`,
        'Range-Unit': 'items',
      },
    })
    if (!о.ok && о.status !== 206) {
      throw new Error(
        `Supabase ответил ${о.status}: ${(await о.text()).slice(0, 200)}`
      )
    }
    const кусок = (await о.json()) as T[]
    всё.push(...кусок)
    if (кусок.length < СТРАНИЦА) return всё
    /*
     * Предохранитель ГРОМКИЙ: молчаливая остановка вернула бы нас ровно к
     * той ошибке, которую эта функция и чинит.
     */
    if (всё.length > 200_000) {
      throw new Error(
        `чтение ${путь} не закончилось на 200000 строк — проверьте Range`
      )
    }
  }
}

interface Человек {
  telegram_id: string | number
  username: string | null
  first_name: string | null
  bot_name: string | null
  created_at: string | null
  updated_at: string | null
  language_code: string | null
}

/** Дней с последнего появления. null — если даты нет. */
function днейНазад(дата: string | null): number | null {
  if (!дата) return null
  const t = Date.parse(дата)
  if (!Number.isFinite(t)) return null
  return Math.floor((Date.now() - t) / 86_400_000)
}

/**
 * Кто вообще платил.
 *
 * Считаем ТОЛЬКО завершённые входящие: незавершённая попытка — это не
 * покупатель, а как раз горячий лид, и путать их значит терять самых
 * перспективных.
 */
async function платившие(): Promise<Set<string>> {
  const строки = await запрос<{ telegram_id: string | number }>(
    'payments_v2?select=telegram_id&status=eq.COMPLETED&type=eq.MONEY_INCOME'
  )
  return new Set(строки.map(с => String(с.telegram_id)))
}

async function люди(область: string[] | null): Promise<Человек[]> {
  const поля =
    'telegram_id,username,first_name,bot_name,created_at,updated_at,language_code'
  /*
   * Фильтруем НА СТОРОНЕ БАЗЫ, а не после выборки: тянуть всю платформу,
   * чтобы отдать владельцу одного бота его сотню, — это и лишний трафик, и
   * лишний риск, что отфильтровать забудут.
   */
  const фильтр = область
    ? `&bot_name=in.(${область.map(b => `"${b.replace(/"/g, '')}"`).join(',')})`
    : ''
  return запрос<Человек>(`users?select=${поля}${фильтр}`)
}

/** То, что можно показать владельцу: имя, ссылка, давность. Без лишнего. */
function карточка(ч: Человек) {
  return {
    telegram_id: String(ч.telegram_id),
    имя: ч.first_name || null,
    ссылка: ч.username ? `https://t.me/${ч.username}` : null,
    бот: ч.bot_name || null,
    молчит_дней: днейНазад(ч.updated_at),
    с_нами_дней: днейНазад(ч.created_at),
  }
}

