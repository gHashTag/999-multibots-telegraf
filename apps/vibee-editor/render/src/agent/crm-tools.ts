/**
 * Доля платящих отдельной функцией, чтобы деление на ноль было видно глазами,
 * а не пряталось внутри строки форматирования.
 */
function долюПлатящих(платящих: number, всего: number): number {
  return всего > 0 ? платящих / всего : 0
}
