import { describe, it, expect } from 'vitest'
import { reviewedKieModel } from './kie-web-provider'
import { KIE_WEB_MODELS as ВИТРИНА } from '../../../player/src/lib/kieProvider'

/**
 * МОДЕЛЬ, ПРЕДЛОЖЕННАЯ В ВЕБЕ, ОБЯЗАНА ПРОХОДИТЬ ДОПУСК СЕРВЕРА.
 *
 * Два списка одного и того же — что человек выбирает и что сервер исполняет —
 * жили порознь и разошлись молча.
 *
 * Замер, ради которого тест написан. Вкладка «Липсинк» предлагала ровно одну
 * модель, `kie/veed/fabric-1`, и сервер отвергал её ВСЕГДА: допуск отсеивает
 * всё, чему KieAI не назвал себестоимость, а семейство veed в прайсе
 * отсутствует целиком. Порядок на маршруте такой:
 *
 *     мерим длину звука → заводим задачу → СПИСЫВАЕМ → reviewedKieModel
 *     бросает «Kie.ai model is not enabled for lipsync» → возврат → 500
 *
 * То есть липсинк из веба не работал ни разу, а на экран приходила фраза, из
 * которой не следует ни одного действия. Ни один тест этого не ловил: обе
 * стороны по отдельности были верны.
 *
 * Тест смотрит НА ОБА списка сразу — единственное место, где расхождение
 * вообще видно.
 */
describe('витрина веба и допуск сервера — про одни и те же модели', () => {
  const виды = ['image', 'video', 'audio', 'lipsync'] as const

  for (const вид of виды) {
    for (const м of ВИТРИНА[вид]) {
      it(`${вид}: ${м.id} допущена сервером`, () => {
        // `reviewedKieModel` БРОСАЕТ, а не возвращает null: в маршруте её
        // результат идёт через `!`, и исключение улетает в общий catch уже
        // ПОСЛЕ списания.
        expect(() => reviewedKieModel(вид, м.id)).not.toThrow()
        expect(reviewedKieModel(вид, м.id)).toBe(м.id.slice(4))
      })
    }
  }

  it('витрина не пуста ни на одной вкладке', () => {
    // Пустой список сделал бы тесты выше зелёными, ничего не проверив: вкладка
    // без моделей — та же неработающая вкладка, только молча.
    for (const вид of виды) expect(ВИТРИНА[вид].length).toBeGreaterThan(0)
  })
})
