import { describe, it, expect } from 'vitest'
import fs from 'fs'
import path from 'path'
import { reviewedKieModel, type KieWebMediaKind } from './kie-web-provider'
import { СЕБЕСТОИМОСТЬ_USD } from './kie-prices.generated'

/**
 * ВИТРИНА ПРИЛОЖЕНИЯ ОБЯЗАНА ПРОХОДИТЬ ДОПУСК СЕРВЕРА.
 *
 * Ровно этот тест веб получил после того, как расхождение стоило целой
 * вкладки: там предлагали модель, которую сервер отвергает всегда, — списание
 * проходило, следом летел отказ, возврат и 500. У приложения такого теста не
 * было, и совпадение держалось на руках: `KieModels.swift` пишет генератор,
 * но запускают его не при каждой правке, а список моделей на сервере живёт
 * своей жизнью.
 *
 * Свифт читаем текстом: поднимать Swift из vitest нечем, а ломается здесь
 * СПИСОК, а не вычисление.
 */
const СВИФТ = fs.readFileSync(
  path.join(
    __dirname, '..', '..', '..', '..', 'vibee-ios', 'Vibee', 'KieModels.swift'
  ),
  'utf8'
)

interface Строка {
  id: string
  вид: string
  живая: boolean
  опасная: boolean
  ценаЕсть: boolean
  входИзвне: boolean
}

/** Разбор одной строки `Модель(...)` — тех полей, по которым экран фильтрует. */
function модели(): Строка[] {
  // Построчно, а не одним выражением на всю запись: поля со значением по
  // умолчанию (`входИзвне`) в строке могут отсутствовать, и жёсткий шаблон
  // молча находил бы НОЛЬ моделей — то есть проверка была бы зелёной и пустой.
  return СВИФТ.split('\n')
    .filter(строка => строка.includes('Модель(id: "'))
    .map(строка => {
      const поле = (имя: string) =>
        строка.match(new RegExp(`${имя}: ([^,)]+)`))?.[1]?.trim()
      return {
        id: строка.match(/Модель\(id: "([^"]+)"/)![1],
        вид: (поле('вид') ?? '').replace(/^\./, ''),
        живая: поле('живая') === 'true',
        опасная: поле('опасная') === 'true',
        ценаЕсть: (поле('ценаUSD') ?? 'nil') !== 'nil',
        входИзвне: поле('входИзвне') === 'true',
      }
    })
}

/** `сервернаяOK` из GenerateScreen.swift, слово в слово. */
function показываетЭкран(м: Строка): boolean {
  if (м.вид === 'сценарий') return true
  return м.живая && !м.опасная && м.ценаЕсть && !м.входИзвне
}

const ВИД_К_KIND: Record<string, KieWebMediaKind | undefined> = {
  картинка: 'image',
  видео: 'video',
  звук: 'audio',
  липсинк: 'lipsync',
}

describe('модель, которую показывает приложение, сервер обслуживает', () => {
  it('разбор нашёл каталог, а не пустоту', () => {
    // Пустой список сделал бы проверку ниже зелёной, не проверив ничего —
    // ровно тот способ, которым уже замолкала проверка скриптов.
    expect(модели().length).toBeGreaterThan(30)
  })

  it('каждая показанная платная модель проходит допуск', () => {
    const отвергнутые: string[] = []
    for (const м of модели()) {
      if (!показываетЭкран(м)) continue
      const kind = ВИД_К_KIND[м.вид]
      // Сценарий идёт другим маршрутом, без допуска KieAI.
      if (!kind) continue
      try {
        reviewedKieModel(kind, `kie/${м.id}`)
      } catch {
        отвергнутые.push(`${м.вид}/${м.id}`)
      }
    }
    expect(отвергнутые).toEqual([])
  })

  it('цена в приложении не расходится с серверной себестоимостью', () => {
    /*
     * Число на кнопке считается из `ценаUSD`, скопированной в Swift. Разойдись
     * она с `СЕБЕСТОИМОСТЬ_USD` — и экран назовёт одну сумму, а сервер
     * спишет другую: тот самый класс, из-за которого цены и переехали на
     * сервер.
     */
    const расхождения: string[] = []
    const цены = СВИФТ.matchAll(
      /Модель\(id: "([^"]+)"[^)]*?ценаUSD: ([^,]+),/g
    )
    for (const [, id, сырое] of цены) {
      const вСвифте = сырое.trim() === 'nil' ? null : Number(сырое)
      const наСервере = СЕБЕСТОИМОСТЬ_USD[id] ?? null
      if (вСвифте !== наСервере) {
        расхождения.push(`${id}: приложение ${вСвифте} ≠ сервер ${наСервере}`)
      }
    }
    expect(расхождения).toEqual([])
  })
})

const ГЕНЕРАТОР = fs.readFileSync(
  path.join(__dirname, '..', '..', 'scripts', 'gen-kie-swift.ts'),
  'utf8'
)

describe('генератор выдаёт то, что компилируется', () => {
  it('структура объявляет каждое поле, которое передаёт вызов', () => {
    /*
     * Генератор — документированный и закреплённый тестом способ обновить
     * каталог приложения, и он выдавал Swift, который НЕ СОБИРАЕТСЯ: в
     * структуре не хватало трёх свойств, которые перечисляет вызов
     * `Модель(...)`. Хуже несобираемости то, ЧЕГО не хватало: `входИзвне` —
     * признак, по которому экран прячет модели без пригодного входа, то есть
     * ровно то, что держит витрину внутри допуска сервера.
     *
     * Значит, первая же попытка обновить каталог либо сломала бы сборку, либо
     * (после «починки» удалением поля) вернула бы в приложение семь моделей,
     * которые не работают никогда.
     */
    const вызов =
      ГЕНЕРАТОР.split('\n').find(с => с.includes('Модель(id: "${')) ?? ''
    expect(вызов).not.toBe('')
    const поля = [...вызов.matchAll(/(?:\(|, )(\p{L}[\p{L}\d]*): /gu)].map(
      м => м[1]
    )
    expect(поля.length).toBeGreaterThan(5)
    for (const поле of поля) {
      expect(
        new RegExp(`(let|var) ${поле}:`).test(ГЕНЕРАТОР),
        `структура не объявляет «${поле}», который передаёт вызов`
      ).toBe(true)
    }
  })
})
