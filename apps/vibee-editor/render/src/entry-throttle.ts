/**
 * ТОРМОЗ НА ДВЕРЯХ ВХОДА.
 *
 * Найдено при разборе входа в приложение 07.09.2026.
 *
 * `POST /api/auth/pair/claim` принимает шестизначный код и не требует
 * личности — и не может требовать: смысл кода в том, что у входящего ещё
 * ничего нет. Защита от перебора была построена так: промах засчитывается в
 * счётчик попыток, пять попыток — код гасится.
 *
 * Промах при этом засчитывался запросом БЕЗ ФИЛЬТРА ПО ВЛАДЕЛЬЦУ:
 *
 *     UPDATE app_pairing_codes SET attempts = attempts + 1
 *      WHERE consumed_at IS NULL AND expires_at > now()
 *
 * то есть каждый мимо-удар гасил живые коды ВСЕХ людей платформы. Комментарий
 * рядом описывал это как «жжёт коды жертвы — заметно и неприятно». На деле
 * жертва тут не одна: пять запросов в секунду с любого адреса делают вход по
 * коду невозможным для всех и навсегда, ценой копеек.
 *
 * ── ПОЧЕМУ ИМЕННО ТОРМОЗ, А НЕ ЧТО-ТО УМНОЕ ────────────────────────────────
 *
 * Убрать начисление промахов нельзя: вернётся перебор. Начислять «только
 * атакующему» невозможно: он неопознан, в этом вся суть двери.
 *
 * Но перебор бессмыслен, если попытки ограничены по источнику. Код живёт 120
 * секунд, пространство — миллион. При десяти попытках в минуту на адрес за всю
 * жизнь кода приходится двадцать догадок против миллиона: вероятность
 * попадания 1 к 50 000 за окно, и она не накапливается — код сменится.
 *
 * Тогда начисление промахов «всем живым кодам» становится не нужным вовсе, и
 * отказ в обслуживании исчезает вместе с ним.
 *
 * ── ЧЕСТНО О ГРАНИЦАХ ──────────────────────────────────────────────────────
 *
 * Счётчик в памяти процесса. При нескольких копиях сервиса злоумышленник
 * получит по лимиту с каждой — но это по-прежнему на порядки меньше, чем
 * ничего, и совпадает с тем, как в этом сервисе уже сделан список отозванных
 * сессий. Заводить общий кэш ради этого — отдельная работа с отдельными
 * отказами.
 *
 * Адрес берётся из соединения, а не из заголовков: `X-Forwarded-For`
 * подделывается тем же, кто стучится, и тормоз, который можно обойти сменой
 * заголовка, — это не тормоз.
 */

/** Сколько попыток на источник в окне. */
export const ПОПЫТОК_В_ОКНЕ = 10

/** Длина окна. Кратна времени жизни кода (120 с), чтобы считалось просто. */
export const ОКНО_МС = 60_000

/**
 * Сколько источников помним. Больше — не память, а способ её исчерпать:
 * атакующий с миллионом адресов не должен ронять сервис через наш же счётчик.
 */
const МАКС_ИСТОЧНИКОВ = 10_000

interface Окно {
  счёт: number
  началось: number
}

const окна = new Map<string, Окно>()

/** Только для проверок. */
export function забытьОкна(): void {
  окна.clear()
}

export function числоОкон(): number {
  return окна.size
}

/**
 * Можно ли пустить ещё одну попытку с этого источника.
 *
 * Возвращает, сколько секунд ждать, если нельзя, — человеку и клиенту нужно
 * знать «когда», а не только «нет».
 */
export function пуститьПопытку(
  источник: string,
  сейчас = Date.now()
): { можно: true } | { можно: false; ждатьСекунд: number } {
  const ключ = источник || 'неизвестный'

  // Чистим протухшие окна лениво: отдельный таймер ради этого — лишняя
  // движущаяся часть, а карта и так ограничена сверху.
  if (окна.size > МАКС_ИСТОЧНИКОВ) {
    for (const [k, о] of окна) {
      if (сейчас - о.началось > ОКНО_МС) окна.delete(k)
    }
    // Если и после чистки тесно — карта заполнена живыми окнами: значит идёт
    // распределённый перебор, и новый источник ждёт вместе со всеми.
    if (окна.size > МАКС_ИСТОЧНИКОВ && !окна.has(ключ)) {
      return { можно: false, ждатьСекунд: Math.ceil(ОКНО_МС / 1000) }
    }
  }

  const о = окна.get(ключ)
  if (!о || сейчас - о.началось >= ОКНО_МС) {
    окна.set(ключ, { счёт: 1, началось: сейчас })
    return { можно: true }
  }
  if (о.счёт >= ПОПЫТОК_В_ОКНЕ) {
    const осталось = ОКНО_МС - (сейчас - о.началось)
    return { можно: false, ждатьСекунд: Math.max(1, Math.ceil(осталось / 1000)) }
  }
  о.счёт += 1
  return { можно: true }
}

/**
 * Адрес источника — из СОЕДИНЕНИЯ.
 *
 * `X-Forwarded-For` подделывает тот же, кто стучится; тормоз, обходимый сменой
 * заголовка, тормозом не является. Railway ставит соединение через свой
 * прокси, поэтому адрес будет общим для всех за ним — и это осознанная плата:
 * лучше грубое ограничение, чем никакого.
 */
export function источникЗапроса(req: {
  socket?: { remoteAddress?: string }
}): string {
  return req.socket?.remoteAddress || 'неизвестный'
}
