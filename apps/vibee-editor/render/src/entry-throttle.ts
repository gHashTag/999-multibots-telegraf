/**
 * ТОРМОЗ НА ДВЕРЯХ ВХОДА.
 *
 * Найдено при разборе входа в приложение 07.09.2026.
 *
 * `POST /api/auth/pair/claim` принимает код и не требует личности — и не может
 * требовать: смысл кода в том, что у входящего ещё ничего нет. Защита от
 * перебора была построена так: промах засчитывается в счётчик попыток, пять
 * попыток — код гасится.
 *
 * Промах при этом засчитывался запросом БЕЗ ФИЛЬТРА ПО ВЛАДЕЛЬЦУ:
 *
 *     UPDATE app_pairing_codes SET attempts = attempts + 1
 *      WHERE consumed_at IS NULL AND expires_at > now()
 *
 * то есть каждый мимо-удар гасил живые коды ВСЕХ людей платформы. Комментарий
 * рядом описывал это как «жжёт коды жертвы — заметно и неприятно». На деле
 * жертва тут не одна: пять запросов в секунду с любого адреса делают вход по
 * коду невозможным для всех и навсегда, ценой копеек.
 *
 * ── ПОЧЕМУ ИМЕННО ТОРМОЗ, А НЕ ЧТО-ТО УМНОЕ ────────────────────────────────
 *
 * Убрать начисление промахов нельзя: вернётся перебор. Начислять «только
 * атакующему» невозможно: он неопознан, в этом вся суть двери.
 *
 * Но перебор бессмыслен, если попытки ограничены. Код живёт 120 секунд,
 * пространство — сто миллионов (восемь цифр). Даже при потолке всего канала
 * на жизнь кода приходится тысяча догадок против ста миллионов.
 *
 * Тогда начисление промахов «всем живым кодам» становится не нужным вовсе, и
 * отказ в обслуживании исчезает вместе с ним.
 *
 * ── ДВА УРОВНЯ, И ПОЧЕМУ ОДНОГО МАЛО ───────────────────────────────────────
 *
 * Первая версия считала попытки ТОЛЬКО по адресу соединения, с пояснением:
 * «X-Forwarded-For подделывает тот же, кто стучится». Это верно про заголовок
 * и неверно про последствия. Railway обрывает TLS на своём крае и идёт в
 * контейнер сам, поэтому `remoteAddress` — адрес ПРОКСИ, один и тот же для
 * всех людей платформы. Десять попыток в минуту на такой ключ — это не тормоз
 * для злоумышленника, а запрет входа для всех сразу: ровно тот отказ в
 * обслуживании, который здесь чинили.
 *
 * Поэтому ключей два:
 *
 *   КЛИЕНТ (левый адрес из `X-Forwarded-For`, иначе соединение) — узкий лимит.
 *     Подделывается сменой заголовка, и это честно записано ниже. Его работа —
 *     развести обычных людей, чтобы сосед за тем же прокси не запирал дверь.
 *
 *   КАНАЛ (всегда соединение) — широкий потолок. Подделать нельзя: адрес берётся
 *     из сокета. Его работа — ограничить поток целиком, включая того, кто
 *     крутит заголовок.
 *
 * Потолок канала выбран так, чтобы сегодняшняя живая нагрузка его не касалась,
 * а перебор — упирался. Порядок величин: тысяча попыток в минуту против ста
 * миллионов кодов даёт шанс 1 к 50 000 за всю жизнь кода, и он не копится —
 * код сменится.
 *
 * ── ЧЕСТНО О ГРАНИЦАХ ──────────────────────────────────────────────────────
 *
 * Счётчик в памяти процесса. При нескольких копиях сервиса злоумышленник
 * получит по лимиту с каждой — но это по-прежнему на порядки меньше, чем
 * ничего, и совпадает с тем, как в этом сервисе уже сделан список отозванных
 * сессий. Заводить общий кэш ради этого — отдельная работа с отдельными
 * отказами.
 */

/** Сколько попыток на клиента в окне. Узкий лимит, ключ подделываемый. */
export const ПОПЫТОК_В_ОКНЕ = 10

/**
 * Потолок на всё соединение (значит — на весь трафик из-за прокси Railway).
 *
 * Живой вход стоит одной-двух попыток на человека; обновление сессии — раз в
 * десять минут. Тысяча в минуту на всю платформу не задевает никого из живых
 * и при этом кладёт предел перебору, который крутит заголовок.
 */
export const ПОТОЛОК_КАНАЛА = 1000

/** Длина окна. Кратна времени жизни кода (120 с), чтобы считалось просто. */
export const ОКНО_МС = 60_000

/**
 * Сколько источников помним. Больше — не память, а способ её исчерпать:
 * атакующий с миллионом адресов не должен ронять сервис через наш же счётчик.
 */
const МАКС_ИСТОЧНИКОВ = 10_000

interface Окно {
  счёт: number
  началось: number
}

const окна = new Map<string, Окно>()

/** Только для проверок. */
export function забытьОкна(): void {
  окна.clear()
}

export function числоОкон(): number {
  return окна.size
}

/**
 * Можно ли пустить ещё одну попытку с этого источника.
 *
 * Возвращает, сколько секунд ждать, если нельзя, — человеку и клиенту нужно
 * знать «когда», а не только «нет».
 */
export function пуститьПопытку(
  источник: string,
  сейчас = Date.now(),
  предел = ПОПЫТОК_В_ОКНЕ
): { можно: true } | { можно: false; ждатьСекунд: number } {
  const ключ = источник || 'неизвестный'

  // Чистим протухшие окна лениво: отдельный таймер ради этого — лишняя
  // движущаяся часть, а карта и так ограничена сверху.
  if (окна.size > МАКС_ИСТОЧНИКОВ) {
    for (const [k, о] of окна) {
      if (сейчас - о.началось > ОКНО_МС) окна.delete(k)
    }
    // Если и после чистки тесно — карта заполнена живыми окнами: значит идёт
    // распределённый перебор, и новый источник ждёт вместе со всеми.
    if (окна.size > МАКС_ИСТОЧНИКОВ && !окна.has(ключ)) {
      return { можно: false, ждатьСекунд: Math.ceil(ОКНО_МС / 1000) }
    }
  }

  const о = окна.get(ключ)
  if (!о || сейчас - о.началось >= ОКНО_МС) {
    окна.set(ключ, { счёт: 1, началось: сейчас })
    return { можно: true }
  }
  if (о.счёт >= предел) {
    const осталось = ОКНО_МС - (сейчас - о.началось)
    return { можно: false, ждатьСекунд: Math.max(1, Math.ceil(осталось / 1000)) }
  }
  о.счёт += 1
  return { можно: true }
}

interface ЗапросСАдресом {
  socket?: { remoteAddress?: string }
  headers?: Record<string, string | string[] | undefined>
}

/**
 * Адрес соединения — НЕПОДДЕЛЫВАЕМЫЙ ключ.
 *
 * За прокси Railway он общий для всех, поэтому годится только под широкий
 * потолок канала, а не под лимит на человека.
 */
export function источникЗапроса(req: ЗапросСАдресом): string {
  return req.socket?.remoteAddress || 'неизвестный'
}

/**
 * Кто стучится, по мнению прокси, — ПОДДЕЛЫВАЕМЫЙ ключ.
 *
 * Берём левый адрес из `X-Forwarded-For`: край Railway ставит туда клиента.
 * Значение можно подделать сменой заголовка, и на нём НЕЛЬЗЯ строить защиту —
 * оно нужно, чтобы люди за одним прокси не мешали друг другу.
 */
export function клиентЗапроса(req: ЗапросСАдресом): string {
  const сырой = req.headers?.['x-forwarded-for']
  const строка = Array.isArray(сырой) ? сырой[0] : сырой
  const левый = String(строка ?? '')
    .split(',')[0]
    .trim()
  return левый || источникЗапроса(req)
}

/**
 * Тормоз для двери входа: узкий лимит на клиента И широкий потолок на канал.
 *
 * Оба счётчика заряжаются на каждом вызове — иначе тот, кто уже упёрся в один,
 * бесплатно копил бы попытки в другом.
 */
export function пуститьВход(
  req: ЗапросСАдресом,
  сейчас = Date.now()
): { можно: true } | { можно: false; ждатьСекунд: number } {
  const канал = пуститьПопытку(
    `кан:${источникЗапроса(req)}`,
    сейчас,
    ПОТОЛОК_КАНАЛА
  )
  const клиент = пуститьПопытку(`кли:${клиентЗапроса(req)}`, сейчас)
  if (!канал.можно) return канал
  return клиент
}
