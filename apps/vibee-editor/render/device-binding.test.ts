import { describe, it, expect } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'

/**
 * ОБЕЩАНИЕ ЗАЩИТЫ, КОТОРОЙ НЕТ, ОПАСНЕЕ ЕЁ ОТСУТСТВИЯ.
 *
 * В токене доступа лежит `dkt` — отпечаток ключа устройства, — и комментарий
 * рядом утверждал: «привязывает токен к одному устройству». Проверено
 * 07.09.2026:
 *
 *   verifyAppSession сверяет форму, алгоритм, подпись, срок и отзыв — и ни
 *   разу не смотрит на dkt;
 *   ни один клиент не отправляет device_pubkey: поиск по всему репозиторию
 *   (мини-апп, iOS) не находит ни одной отправки;
 *   значит поле пусто в каждом выданном токене.
 *
 * То есть свойство было объявлено и не выполнялось нигде. На такие
 * утверждения опираются: «токен привязан к устройству» меняет решение о том,
 * сколько он живёт и что делать при краже.
 */
const ЧИТАТЬ = (о: string) =>
  fs.readFileSync(path.join(__dirname, о), 'utf8')
/** Без комментариев: рассказ о снятом обещании обязан остаться в коде. */
const БЕЗ_ПРОЗЫ = (s: string) =>
  s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

describe('токен не притворяется привязанным к устройству', () => {
  it('комментарий больше не обещает привязку', () => {
    const s = ЧИТАТЬ('session.ts')
    expect(s).not.toContain('Binds the token to one device')
    expect(s).toContain('ЗАРЕЗЕРВИРОВАН, А НЕ РАБОТАЕТ')
  })

  it('проверка токена по-прежнему НЕ смотрит на dkt — и это сказано вслух', () => {
    /*
     * Проверка фиксирует ФАКТ, а не желаемое. Если однажды dkt начнут
     * сверять при использовании токена, этот тест покраснеет и заставит
     * переписать и его, и комментарий — то есть заметить изменение свойства,
     * а не тихо его приобрести.
     */
    const код = БЕЗ_ПРОЗЫ(ЧИТАТЬ('session.ts'))
    const проверка = код.slice(
      код.indexOf('export function verifyAppSession'),
      код.indexOf('export function verifyAppSession') + 2500
    )
    expect(проверка).not.toContain('dkt')
  })
})

describe('записанный ключ устройства теперь работает', () => {
  const МАРШРУТЫ = ЧИТАТЬ('session-routes.ts')
  const БЛОК = МАРШРУТЫ.slice(
    МАРШРУТЫ.indexOf("path === '/api/auth/refresh'"),
    МАРШРУТЫ.indexOf("path === '/api/auth/logout'")
  )

  it('обмен требует совпадения, если ключ у сессии записан', () => {
    expect(БЛОК).toContain('const записанный = String(s.device_pubkey ?? \'\')')
    expect(БЛОК).toMatch(/if \(записанный\)/)
    expect(БЛОК).toContain('deviceThumbprint(body)')
  })

  it('несовпадение — отказ, а не тихий пропуск', () => {
    expect(БЛОК).toMatch(/предъявленный !== записанный/)
    expect(БЛОК).toContain('выдан другому устройству')
  })

  it('правило ОДНОСТОРОННЕЕ: без записанного ключа ничего не требуем', () => {
    /*
     * Сегодня ключ не присылает никто. Потребуй мы его у всех — вход
     * сломался бы для всех ради защиты, которую они не могут предложить.
     * Ровно об этом писал автор deviceThumbprint.
     */
    const внутри = БЛОК.slice(БЛОК.indexOf('const записанный'))
    // Проверка обязана стоять ВНУТРИ `if (записанный)`, а не снаружи.
    expect(внутри.indexOf('if (записанный)')).toBeLessThan(
      внутри.indexOf('предъявленный !== записанный')
    )
  })

  it('честно назван предел: это не доказательство владения', () => {
    // Предъявленный ключ — такой же предъявляемый секрет, как и сам токен.
    // Красть теперь нужно оба; выдавать это за криптографию нельзя.
    expect(МАРШРУТЫ).toContain('не криптографическое доказательство владения')
  })
})
