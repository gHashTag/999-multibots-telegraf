/**
 * Таблица цен для человека: модель, токены, посекундность, единица прайса.
 *
 * Жила встроенной строкой внутри `bin/tri`, и это ломало проверку скриптов:
 * кириллица, законная в TypeScript, выглядела для неё ошибкой bash. Файл с
 * кодом на своём языке — и честнее, и проверяется своим инструментом.
 */
import { модельныеЦены, посекунднаяМодель } from '../src/agent/billing-shared'
import { ЕДИНИЦА_ЦЕНЫ } from '../src/agent/kie-prices.generated'

const цены = модельныеЦены()
const строки = Object.entries(цены).sort((a, b) => a[1] - b[1])
console.log('моделей с ценой:', строки.length)
for (const [ид, токены] of строки) {
  const единица = (ЕДИНИЦА_ЦЕНЫ as Record<string, string>)[ид.replace('kie/', '')] ?? ''
  console.log(
    String(токены).padStart(5),
    посекунднаяМодель(ид) ? '/с' : '  ',
    ид.padEnd(42),
    единица
  )
}
