/**
 * ПРОВЕРКА ВСЕГО КОНВЕЙЕРА, КОТОРАЯ НЕ ТРАТИТ КРЕДИТЫ.
 *
 * Зачем. Ломается конвейер не там, где видно: модель допущена, но её контракт
 * не совпадает с тем, что шлёт экран; цена названа в единице, которую не
 * перевести в вызов; модель есть в каталоге, но сервер её не включил. Каждый
 * такой случай ловился ТОЛЬКО живой генерацией — то есть деньгами и минутами.
 *
 * Здесь всё это проверяется на данных, которые уже лежат в репозитории:
 * контракты (`needs` — дословные ответы KieAI на пробу), цены и единицы из
 * прайса, поля, которые маршрут физически способен передать. Ноль вызовов
 * провайдера, ноль списаний.
 *
 * Запуск:
 *   npx tsx scripts/pipeline-check.ts
 *
 * Код возврата 1, если хоть одна проверка не прошла — годится для CI.
 */
import { KIE_MODELS } from '../src/agent/kie-models'
import { ВИДИМЫЕ_ИМЕНА } from '../src/agent/kie-display-names'
import { ПОЛЯ_МАРШРУТА, KIE_WEB_MODELS } from '../src/agent/kie-web-provider'
import { ЕДИНИЦА_ЦЕНЫ } from '../src/agent/kie-prices.generated'
import {
  priceForKieModel,
  посекунднаяМодель,
  TOKEN_PRICES,
} from '../src/agent/billing-shared'

/**
 * Поля маршрутов берутся ИЗ ДОПУСКА, а не из своей копии.
 *
 * Здесь стоял второй такой же список. Копия и допуск разошлись бы на первой
 * правке, и проверка замолчала бы ровно там, где нужна: модель, которой
 * маршрут перестал слать поле, осталась бы «в порядке».
 */
const ЧТО_ШЛЁТ_ЭКРАН: Record<string, string[]> = {
  картинка: ПОЛЯ_МАРШРУТА.image,
  видео: ПОЛЯ_МАРШРУТА.video,
  звук: ПОЛЯ_МАРШРУТА.audio,
  липсинк: ПОЛЯ_МАРШРУТА.lipsync,
}

/** Единицы, которые мы умеем превратить в счёт за один вызов. */
const ПОНЯТНЫЕ_ЕДИНИЦЫ = new Set([
  'за картинку',
  'за запрос',
  'за ролик',
  'за секунду',
  'за мегапиксель',
  'за 1000 знаков',
])

type Беда = { модель: string; что: string }
const беды: Беда[] = []
const пусто: string[] = []

for (const м of KIE_MODELS as any[]) {
  if (м.state !== 'live') continue
  const видимое = (ВИДИМЫЕ_ИМЕНА as any)[м.id]
  if (!видимое) {
    беды.push({ модель: м.id, что: 'нет видимого имени — не покажем человеку' })
    continue
  }
  const вид = видимое.вид
  if (вид === 'сценарий') continue // не тарифицируется и идёт мимо KieAI

  const цена = priceForKieModel(м.id)
  const умеем = ЧТО_ШЛЁТ_ЭКРАН[вид] ?? []
  const нехватка = ((м.needs ?? []) as string[]).filter(п => !умеем.includes(п))

  /*
   * ИСТОЧНИК ПРАВДЫ О ТОМ, ЧТО ПРЕДЛАГАЮТ, — САМ ДОПУСК.
   *
   * Раньше здесь считалась своя «продаваемость» по цене и контракту. Она
   * повторяла условия допуска и разошлась бы с ним: после того как допуск
   * научился отсеивать модели без передаваемого входа, проверка продолжала
   * звать их бедой, хотя человек их уже не видит.
   */
  const kind = { картинка: 'image', видео: 'video', звук: 'audio', липсинк: 'lipsync' }[
    вид as 'картинка' | 'видео' | 'звук' | 'липсинк'
  ]
  const предлагается = kind ? (KIE_WEB_MODELS as any)[kind].has(м.id) : false
  if (!предлагается) {
    пусто.push(
      `${м.id} (${вид}) — не предлагаем: ${
        цена == null
          ? 'цены нет'
          : видимое.опасная
            ? 'опасная'
            : !(м.needs?.length ?? 0)
              ? 'контракт неизвестен'
              : нехватка.length
                ? `экран не шлёт ${нехватка.join(', ')}`
                : 'сервер не включил'
      }`
    )
    continue
  }

  // 1. КОНТРАКТ ПРОТИВ ЭКРАНА. Модель, ПРЕДЛОЖЕННУЮ человеку и просящую поле,
  //    которого экран не шлёт, ждёт отказ ПОСЛЕ нажатия — и после списания.
  if (нехватка.length) {
    беды.push({
      модель: м.id,
      что: `просит ${нехватка.join(', ')}, а экран «${вид}» такого не шлёт`,
    })
  }

  // 2. ЕДИНИЦА ЦЕНЫ. Непонятная единица означает, что сумму до нажатия назвать
  //    нечем — такую модель продавать нельзя (см. Gemini TTS за 280 токенов).
  const ед = (ЕДИНИЦА_ЦЕНЫ as any)[м.id]
  if (ед && !ПОНЯТНЫЕ_ЕДИНИЦЫ.has(ед)) {
    беды.push({ модель: м.id, что: `единица «${ед}» не переводится в цену вызова` })
  }

  // 3. ПОСЕКУНДНОСТЬ. Если модель считается по секундам, вид работы обязан
  //    уметь передать длительность — иначе спишем за одну секунду.
  if (посекунднаяМодель(м.id) && !умеем.includes('duration') && вид !== 'липсинк') {
    беды.push({ модель: м.id, что: 'посекундная, но длительность экраном не передаётся' })
  }
}

// 4. КАЖДЫЙ ВИД ДОЛЖЕН ЧТО-ТО ПРЕДЛАГАТЬ. Пустая вкладка — это конвейер,
//    оборванный молча.
for (const вид of Object.keys(ЧТО_ШЛЁТ_ЭКРАН)) {
  const есть = (KIE_MODELS as any[]).some(м => {
    const в = (ВИДИМЫЕ_ИМЕНА as any)[м.id]
    return (
      м.state === 'live' &&
      в?.вид === вид &&
      !в.опасная &&
      (м.needs?.length ?? 0) > 0 &&
      priceForKieModel(м.id) != null
    )
  })
  if (!есть) беды.push({ модель: `вид:${вид}`, что: 'ни одной продаваемой модели' })
}

// 5. ЦЕНА ВИДА. Без неё запасной путь спишет ноль — то есть отдаст работу даром.
for (const [вид, оп] of Object.entries({
  картинка: 'image_generate',
  видео: 'video_generate',
  звук: 'audio_generate',
  липсинк: 'lipsync_generate',
})) {
  if (!TOKEN_PRICES[оп]) беды.push({ модель: `вид:${вид}`, что: `нет цены «${оп}»` })
}

console.log('— не продаётся (это не ошибка, но человек их не увидит) —')
for (const с of пусто) console.log('  ', с)
console.log(`\n— проверено видов: ${Object.keys(ЧТО_ШЛЁТ_ЭКРАН).length}, бед: ${беды.length} —`)
for (const б of беды) console.log(`  ✗ ${б.модель}: ${б.что}`)
if (!беды.length) console.log('  ✓ конвейер сходится: контракты, цены и единицы согласованы')
process.exit(беды.length ? 1 : 0)
