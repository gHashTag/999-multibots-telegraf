import { describe, it, expect } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'
import { PAIRING } from './session-store'

/**
 * ДЛИНУ КОДА ВХОДА ЗНАЕТ СЕРВЕР. КЛИЕНТЫ НЕ ДОЛЖНЫ ЕЁ ПОВТОРЯТЬ.
 *
 * Найдено 07.09.2026, и это регрессия, внесённая мной же.
 *
 * Пятью итерациями раньше длина кода поднялась с шести цифр до восьми ради
 * стойкости: миллион вариантов против ста миллионов. Правка была серверной,
 * покрыта тестом и доказана мутацией — тестом на то, что верхняя граница
 * ВЫВОДИТСЯ из `PAIRING.DIGITS`, а не задана числом рядом.
 *
 * Клиенты никто не посмотрел. А там:
 *
 *  - `SignIn.swift` обрезал ввод на шестой цифре и включал кнопку только при
 *    ровно шести — то есть ВОСЬМИЗНАЧНЫЙ КОД НЕВОЗМОЖНО БЫЛО НАБРАТЬ. Вход в
 *    приложение на iOS не работал вовсе;
 *  - `Identity.claimPairing` отказывал до запроса: «Нужны шесть цифр»;
 *  - мини-апп писал «Введите эти 6 цифр», показывая восемь, и резал их как
 *    «123 45678»;
 *  - кнопка обещала «Показать 6-значный код»;
 *  - английский текст бота обещал «six-digit code» — при том что русский рядом
 *    длину не называл, и комментарий над ним объяснял, ПОЧЕМУ не называет.
 *
 * Лечится не сверкой чисел — сверка чисел и есть болезнь. Клиент не может
 * знать эту величину, поэтому он её больше не утверждает: iOS принимает
 * диапазон и отдаёт решение серверу, мини-апп берёт число ИЗ САМОГО КОДА,
 * тексты не называют его вовсе.
 *
 * Этот файл сторожит именно отсутствие копий.
 */

const КОРЕНЬ = path.join(__dirname, '..', '..', '..')

const читать = (...ч: string[]) => fs.readFileSync(path.join(КОРЕНЬ, ...ч), 'utf8')

/** Код без комментариев: рассказ о правиле — не правило. */
const безКомментариев = (s: string) =>
  s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

const IOS_ВХОД = безКомментариев(читать('apps', 'vibee-ios', 'Vibee', 'SignIn.swift'))
const IOS_ЛИЧНОСТЬ = безКомментариев(
  читать('apps', 'vibee-ios', 'Vibee', 'Identity.swift')
)
const МИНИАПП = безКомментариев(
  читать('apps', 'vibee-editor', 'player', 'src', 'components', 'Profile', 'PairWithApp.tsx')
)
const БОТ = безКомментариев(читать('src', 'commands', 'appLoginCommand.ts'))

describe('клиенты не держат собственную копию длины кода', () => {
  it('файлы прочитаны, а не пусты', () => {
    // Пустая строка прошла бы каждое `not.toMatch` ниже.
    for (const [имя, текст] of [
      ['SignIn.swift', IOS_ВХОД],
      ['Identity.swift', IOS_ЛИЧНОСТЬ],
      ['PairWithApp.tsx', МИНИАПП],
      ['appLoginCommand.ts', БОТ],
    ] as const) {
      expect(текст.length, имя).toBeGreaterThan(500)
    }
  })

  it('iOS не сверяет ввод с точным числом цифр', () => {
    /*
     * Именно `count == 6` закрыл вход целиком. Любое точное число здесь — это
     * копия серверной величины, которая разойдётся при следующей же правке.
     */
    expect(IOS_ВХОД).not.toMatch(/цифры\.count == \d+/)
    expect(IOS_ЛИЧНОСТЬ).not.toMatch(/цифры\.count == \d+/)
  })

  it('iOS не обрезает ввод по числу, взятому из воздуха', () => {
    expect(IOS_ВХОД).not.toMatch(/prefix\(\d+\)/)
    expect(IOS_ВХОД).toContain('Identity.максимумЦифрКода')
  })

  it('границы iOS шире серверной длины — иначе код снова не набрать', () => {
    /*
     * ЭТО ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ДВА МИРА СРАВНИВАЮТСЯ ЧИСЛАМИ. Оно и должно
     * быть одно: не «клиент знает длину», а «клиент допускает её с запасом».
     */
    const мин = Number(/минимумЦифрКода = (\d+)/.exec(IOS_ЛИЧНОСТЬ)?.[1])
    const макс = Number(/максимумЦифрКода = (\d+)/.exec(IOS_ЛИЧНОСТЬ)?.[1])
    expect(Number.isFinite(мин) && Number.isFinite(макс), 'границы не найдены').toBe(true)
    expect(PAIRING.DIGITS).toBeGreaterThanOrEqual(мин)
    expect(PAIRING.DIGITS).toBeLessThanOrEqual(макс)
  })

  it('мини-апп берёт число цифр из самого кода', () => {
    expect(МИНИАПП).toContain('code.length')
    expect(МИНИАПП).not.toMatch(/эти \d+ цифр/)
    expect(МИНИАПП).not.toMatch(/\d+-значный/)
  })

  it('мини-апп группирует код по его длине, а не по тройкам', () => {
    // `code.slice(0, 3)` резал восьмизначный код как «123 45678» — вид
    // опечатки, а не группировки.
    expect(МИНИАПП).not.toMatch(/code\.slice\(0, \d+\)/)
  })

  it('тексты бота не называют число цифр ни на одном языке', () => {
    expect(БОТ).not.toMatch(/six-digit|eight-digit|\d-digit/i)
    expect(БОТ).not.toMatch(/шестизначн|восьмизначн|\d+ цифр/i)
  })
})
