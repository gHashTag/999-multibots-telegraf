import { describe, it, expect } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'
import {
  ценаТокенов,
  ПАКЕТЫ,
  МАКС_ЗВЁЗД,
  названиеСчёта,
} from './src/agent/token-packs'

/**
 * ЧЕК НА ЛЮБОЕ КОЛИЧЕСТВО НЕ ДОЛЖЕН ПОРОДИТЬ ВТОРУЮ ПРАВДУ О ЦЕНЕ.
 *
 * Пакеты были заданы тремя парами прямо в обработчике: 10→15, 50→65, 150→175.
 * Цена нелинейна — это скидка за объём. Стоило бы посчитать произвольную сумму
 * по одной плоской ставке, и человек, попросивший «чек на 150», заплатил бы
 * больше, чем за такой же пакет рядом. Для покупателя это не «особенность
 * тарификации», а обман.
 *
 * Поэтому проверка ниже — главная в файле: КАЖДЫЙ прежний пакет обязан выйти
 * из новой шкалы ТОЧНО.
 */
describe('пакеты выводятся из шкалы, а не живут рядом с ней', () => {
  const ПРЕЖНИЕ: Record<number, number> = { 10: 15, 50: 65, 150: 175 }

  it.each(ПАКЕТЫ)('пакет %i стоит столько же, сколько стоил', токенов => {
    expect(ценаТокенов(токенов).звёзд).toBe(ПРЕЖНИЕ[токенов])
  })

  it('витрина и шкала описывают одни и те же пакеты', () => {
    // Пустая витрина сделала бы проверку выше бессодержательной.
    expect([...ПАКЕТЫ]).toEqual([10, 50, 150])
  })
})

describe('скидка за объём сохраняется', () => {
  it('токен дешевеет с ростом количества', () => {
    const мало = ценаТокенов(10).звёздЗаТокен
    const средне = ценаТокенов(50).звёздЗаТокен
    const много = ценаТокенов(150).звёздЗаТокен
    expect(средне).toBeLessThan(мало)
    expect(много).toBeLessThan(средне)
  })

  it('больше токенов никогда не стоит меньше звёзд', () => {
    /*
     * Ступенчатая шкала легко даёт разрыв: на границе ступени большая покупка
     * может оказаться ДЕШЕВЛЕ меньшей, и тогда выгодно покупать лишнее. Идём
     * по всей области и проверяем монотонность.
     */
    let прежняя = 0
    for (let n = 1; n <= 600; n++) {
      const звёзд = ценаТокенов(n).звёзд
      expect(звёзд).toBeGreaterThanOrEqual(прежняя)
      прежняя = звёзд
    }
  })

  it('на границе ступени цена не подскакивает выше соседней', () => {
    // 149 по ставке 1.3 против 150 по ставке 175/150.
    expect(ценаТокенов(150).звёзд).toBeLessThanOrEqual(
      ценаТокенов(149).звёзд + 2
    )
  })
})

describe('границы названы, а не подразумеваются', () => {
  it('ноль и отрицательное отвергаются', () => {
    expect(() => ценаТокенов(0)).toThrow()
    expect(() => ценаТокенов(-5)).toThrow()
  })

  it('дробное количество не создаёт дробных звёзд', () => {
    expect(ценаТокенов(10.9).токенов).toBe(10)
  })

  it('слишком большой счёт отказывается ПОНЯТНО, а не ошибкой Telegram', () => {
    /*
     * Telegram не примет счёт выше своего предела и ответит собственным
     * текстом, которого человек не поймёт. Свой отказ раньше — честнее, чем
     * пересказ чужого.
     */
    let сообщение = ''
    try {
      ценаТокенов(1_000_000)
    } catch (e) {
      сообщение = String(e)
    }
    expect(сообщение).toContain(String(МАКС_ЗВЁЗД))
    expect(сообщение).toMatch(/несколько счетов|меньше/)
  })

  it('название счёта одно на всех', () => {
    expect(названиеСчёта(42)).toBe('42 токенов Trinity')
  })
})

describe('ставка верхней ступени записана дробью', () => {
  it('в исходнике нет десятичного приближения 1.16', () => {
    /*
     * 1.1667 на 150 токенах даёт 176 звёзд — пакет дорожает на ровном месте.
     * Дробь 175/150 даёт ровно 175. Расхождение в деньгах — это расхождение
     * между обещанным и списанным, а не «копейка».
     */
    const исходник = fs.readFileSync(
      path.join(__dirname, 'src', 'agent', 'token-packs.ts'),
      'utf8'
    )
    // Закрепляется САМА ШКАЛА, а не текст рядом: рассказ о том, почему
    // приближение вредно, должен остаться в комментарии и не ронять прогон.
    const шкала = исходник.slice(
      исходник.indexOf('export const СТУПЕНИ'),
      исходник.indexOf(']', исходник.indexOf('export const СТУПЕНИ'))
    )
    expect(шкала).not.toMatch(/\d\.\d+/)
    expect(шкала).toContain('числитель: 175, знаменатель: 150')
  })
})
