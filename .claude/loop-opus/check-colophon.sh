#!/bin/bash
# Автопроверка вёрстки колофона в готовом mp4.
#
# Зачем: 24.08.2026 сервис рендера перезапустился на УСТАРЕВШЕМ образе и за
# несколько минут испёк один ролик старым бандлом — уже после того, как фикс
# был в main и проверен живым рендером. Код был прав, а ролик вышел кривой.
# Поймать такое можно только по самому файлу.
#
# Как отличаем: в сломанной вёрстке лента прижата к левому краю и заходит за
# декоративную рамку (inset 54px). В починенной левее x=159 текста нет вовсе.
# Значит достаточно посмотреть на яркость узкой полосы у левого края в полосе
# колофона: есть светлые пиксели — вёрстка старая.
#
#   ./check-colophon.sh <файл.mp4|файл.png> [порог]
#
# Выход 0 — вёрстка в порядке. Выход 1 — похоже на старую вёрстку.

set -u
FILE="${1:?укажи mp4 или png}"
# Порог выбран ПО ЗАМЕРУ на эталонах, а не на глаз:
#   кривой ролик (09:45 24.08.2026)  YAVG = 31.02
#   верный  (перерендер и контроль)  YAVG = 25.45   (совпали до сотых)
# 28 лежит ровно между. Если разделение когда-нибудь исчезнет — значит
# поменялась вёрстка или полоса кадра, и порог надо пересчитать, а не двигать.
THRESH="${2:-28}"

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

if [[ "$FILE" == *.mp4 ]]; then
  DUR=$(ffprobe -v error -show_entries format=duration -of default=nw=1:nk=1 "$FILE")
  AT=$(awk -v d="$DUR" 'BEGIN{printf "%.2f", d*0.985}')
  ffmpeg -v error -ss "$AT" -i "$FILE" -frames:v 1 -y "$TMP/f.png" || exit 2
  FRAME="$TMP/f.png"
else
  FRAME="$FILE"
fi

# Полоса шириной 150px у левого края, по вертикали — зона колофона.
#
# ВАЖНО про -v error: metadata=print пишет на уровне info, и `-v error` его
# ГЛУШИТ. Первая версия скрипта именно из-за этого не измеряла ничего — и,
# что хуже, выглядела рабочей. Уровень логов здесь трогать нельзя.
YAVG=$(ffmpeg -i "$FRAME" -vf "crop=150:260:0:800,signalstats,metadata=print:key=lavfi.signalstats.YAVG" -f null - 2>&1 \
       | sed -n 's/.*YAVG=\([0-9.]*\).*/\1/p' | head -1)

if [ -z "$YAVG" ]; then
  echo "НЕ ИЗМЕРЕНО: ffmpeg не отдал YAVG — проверка недействительна"
  exit 2      # НЕ 0: молчаливый успех здесь хуже отказа
fi

echo "YAVG левой полосы: $YAVG (порог $THRESH)"
if awk -v y="$YAVG" -v t="$THRESH" 'BEGIN{exit !(y > t)}'; then
  echo "ПОДОЗРЕНИЕ: текст заходит за левую рамку — похоже на старую вёрстку"
  exit 1
fi
echo "OK: у левого края пусто, вёрстка новая"
exit 0
