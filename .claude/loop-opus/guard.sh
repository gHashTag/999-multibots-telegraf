#!/bin/bash
# Страж итерации цикла opus-improvements.
#
# Зачем: в этом репозитории ОДНОВРЕМЕННО работает второй автономный агент
# (ветка loop/agent-improvements, каталог loop/). Он коммитит и мержит каждые
# несколько минут. Без стража два цикла дерутся за рабочее дерево и ломают
# работу друг друга — это ровно то, чего просили не допустить.
#
# Выход 0 — можно работать. Выход 1 — итерацию пропустить.

set -u
DIR="$(cd "$(dirname "$0")" && pwd)"

# Лок ЖИВЁТ ВОЗЛЕ ОСНОВНОГО .git, а не возле этой копии скрипта.
#
# ЗАЧЕМ. Оснастку цикла внесли в git, и у неё стало ДВЕ копии: в основном
# чекауте и в рабочем дереве worktree. Каждая считала $DIR от себя, то есть
# у каждой был СВОЙ лок. Команда release, случайно запущенная из worktree,
# сняла лок, которого там не было, — `rm -f` на несуществующем файле выходит
# с нулём, — и напечатала «OK: лок освобождён». Настоящий лок остался, и
# следующая итерация встала на 30 минут.
#
# git rev-parse --git-common-dir из worktree отдаёт .git ОСНОВНОГО чекаута,
# поэтому обе копии сходятся в одну точку.
COMMON="$(git rev-parse --git-common-dir 2>/dev/null || true)"
if [ -n "$COMMON" ]; then
  LOCKDIR="$(cd "$COMMON" && pwd)"
else
  # Не репозиторий — работаем по-старому, но громко: молчаливый откат к
  # локальному локу это ровно тот случай, из-за которого правка и появилась.
  echo "WARN: git не отвечает, лок будет локальным для $DIR" >&2
  LOCKDIR="$DIR"
fi
LOCK="$LOCKDIR/loop-opus.lock"
NOW=$(date +%s)

# Освобождение лока по завершении итерации: guard.sh release
#
# Без этого лок живёт до истечения 30 минут и глушит ДВА следующих такта
# крона — то есть удачно завершённая итерация наказывала цикл простоем.
# Протухание остаётся страховкой на случай смерти процесса, а не штатным
# способом снять лок.
if [ "${1:-}" = "release" ]; then
  if [ -f "$LOCK" ]; then
    rm -f "$LOCK"
    echo "OK: лок освобождён ($LOCK)"
  else
    # Ровно этот молчаливый «успех» и стоил получаса простоя: release из
    # другого каталога снимал НЕ ТОТ лок и всё равно рапортовал об успехе.
    # «Освобождать нечего» и «освобождено» — разные исходы, и печатать их
    # надо разными словами.
    echo "WARN: лока не было — освобождать нечего." >&2
    echo "      Ожидался: $LOCK" >&2
    echo "      Проверьте, что release идёт из того же репозитория, что acquire." >&2
  fi
  exit 0
fi

# 0. Рабочее дерево — ВНЕ /tmp.
#
#    Целый цикл ушёл на разбор завала: worktree жил в scratchpad под /tmp,
#    система его стёрла вместе с кешами, и дальше каждый мерж спотыкался о
#    незакоммиченные файлы в основном дереве. Каталог, который ОС вправе
#    очистить, — плохое место для ветки, где идёт работа.
#
#    Постоянное место: ~/.vibee-worktrees/opus. Если его нет — говорим об
#    этом громко, а не создаём молча во временном.
WT_HOME="$HOME/.vibee-worktrees/opus"
if [ ! -d "$WT_HOME" ]; then
  echo "WARN: рабочего дерева нет в $WT_HOME" >&2
  echo "      создать: git worktree add -f $WT_HOME -b wt/opus-base origin/main" >&2
  echo "      НЕ создавайте его под /tmp — оттуда его сотрёт чистка." >&2
fi

# 1. Лок от наложения собственных итераций.
#
#    Порог 30 минут = ДВА пропущенных такта крона, а не один. Первая версия
#    стояла на 14 минутах — меньше самого такта, — и первая же итерация шла
#    дольше: следующее срабатывание сочло бы лок протухшим и вошло бы
#    параллельно. То есть защита от наложения сама создавала наложение.
#
#    Порог обязан быть БОЛЬШЕ типичной итерации, иначе он бесполезен; и
#    конечным, иначе умерший процесс останавливает цикл навсегда.
if [ -f "$LOCK" ]; then
  AGE=$(( NOW - $(cat "$LOCK" 2>/dev/null || echo 0) ))
  if [ "$AGE" -lt 1800 ]; then
    echo "SKIP: предыдущая итерация ещё идёт (${AGE}с назад)"
    exit 1
  fi
  echo "WARN: протухший лок (${AGE}с), перехватываю"
fi
echo "$NOW" > "$LOCK"

# 2. Не лезть, если рабочее дерево занято чужими правками вне моего пространства.
#    Мои файлы — только .claude/loop-opus/**. Всё остальное незакоммиченное
#    принадлежит второму агенту, и трогать его нельзя.
FOREIGN=$(git status --porcelain 2>/dev/null | grep -v '^?? ' | grep -vc 'loop-opus' || echo 0)
echo "INFO: чужих незакоммиченных файлов: $FOREIGN"

# 3. Ветка. Если мы на чужой ветке — это нормально для чтения, но коммитить
#    туда нельзя. Просто сообщаем.
echo "INFO: текущая ветка: $(git rev-parse --abbrev-ref HEAD)"
echo "INFO: последний коммит агента: $(git log -1 --format='%ar | %s' 2>/dev/null)"
echo "OK: можно работать"
exit 0
