#!/bin/bash
# Страж итерации цикла opus-improvements.
#
# Зачем: в этом репозитории ОДНОВРЕМЕННО работает второй автономный агент
# (ветка loop/agent-improvements, каталог loop/). Он коммитит и мержит каждые
# несколько минут. Без стража два цикла дерутся за рабочее дерево и ломают
# работу друг друга — это ровно то, чего просили не допустить.
#
# Выход 0 — можно работать. Выход 1 — итерацию пропустить.

set -u
DIR="$(cd "$(dirname "$0")" && pwd)"
LOCK="$DIR/.lock"
NOW=$(date +%s)

# Освобождение лока по завершении итерации: guard.sh release
#
# Без этого лок живёт до истечения 30 минут и глушит ДВА следующих такта
# крона — то есть удачно завершённая итерация наказывала цикл простоем.
# Протухание остаётся страховкой на случай смерти процесса, а не штатным
# способом снять лок.
if [ "${1:-}" = "release" ]; then
  rm -f "$LOCK"
  echo "OK: лок освобождён"
  exit 0
fi

# 1. Лок от наложения собственных итераций.
#
#    Порог 30 минут = ДВА пропущенных такта крона, а не один. Первая версия
#    стояла на 14 минутах — меньше самого такта, — и первая же итерация шла
#    дольше: следующее срабатывание сочло бы лок протухшим и вошло бы
#    параллельно. То есть защита от наложения сама создавала наложение.
#
#    Порог обязан быть БОЛЬШЕ типичной итерации, иначе он бесполезен; и
#    конечным, иначе умерший процесс останавливает цикл навсегда.
if [ -f "$LOCK" ]; then
  AGE=$(( NOW - $(cat "$LOCK" 2>/dev/null || echo 0) ))
  if [ "$AGE" -lt 1800 ]; then
    echo "SKIP: предыдущая итерация ещё идёт (${AGE}с назад)"
    exit 1
  fi
  echo "WARN: протухший лок (${AGE}с), перехватываю"
fi
echo "$NOW" > "$LOCK"

# 2. Не лезть, если рабочее дерево занято чужими правками вне моего пространства.
#    Мои файлы — только .claude/loop-opus/**. Всё остальное незакоммиченное
#    принадлежит второму агенту, и трогать его нельзя.
FOREIGN=$(git status --porcelain 2>/dev/null | grep -v '^?? ' | grep -vc 'loop-opus' || echo 0)
echo "INFO: чужих незакоммиченных файлов: $FOREIGN"

# 3. Ветка. Если мы на чужой ветке — это нормально для чтения, но коммитить
#    туда нельзя. Просто сообщаем.
echo "INFO: текущая ветка: $(git rev-parse --abbrev-ref HEAD)"
echo "INFO: последний коммит агента: $(git log -1 --format='%ar | %s' 2>/dev/null)"
echo "OK: можно работать"
exit 0
