#!/bin/bash
# Проверка САМОГО инструмента, а не продукта.
#
# ПОЧЕМУ ОНА СУЩЕСТВУЕТ. free-disk.sh дважды содержал кириллические имена там,
# где bash требует [A-Za-z_][A-Za-z0-9_]*: сначала в арифметике
# (`$(( после - до ))`), потом в переменной цикла (`for корень in …`). Оба раза
# скрипт печатал ошибку и ШЁЛ ДАЛЬШЕ: порог «мало места» не срабатывал,
# сборочные выходы не удалялись. Код возврата оставался нулевым — то есть всё,
# чем я скрипт проверял, говорило «в порядке».
#
# Имена здесь ЛАТИНИЦЕЙ намеренно: первая версия этой проверки была написана
# кириллицей и упала той же ошибкой, которую ищет. Комментарии по-русски —
# они bash'у не видны.
set -u
# ПРОВЕРЯЕТСЯ НЕ ОДИН ФАЙЛ, А ВСЕ НАШИ СКРИПТЫ.
#
# Была привязка к free-disk.sh — и ровно в тот день, когда появился bin/tri,
# он был написан кириллицей и упал на `local тут там`. Проверка существовала,
# знала этот класс наизусть и молчала, потому что смотрела в другой файл.
# Инструмент, который проверяет только то, что уже починено, бесполезен.
here="$(cd "$(dirname "$0")/../.." && pwd)"
targets=("$(dirname "$0")/free-disk.sh" "$here/bin/tri")
[ $# -gt 0 ] && targets=("$@")
bad=0

for target in "${targets[@]}"; do
  [ -f "$target" ] || continue
  echo "── $(basename "$target") ──"

bash -n "$target" || { echo "✗ синтаксис не разбирается"; bad=1; }

# Присваивания и переменные циклов — только латиницей.
if grep -nE "^[[:space:]]*(for|while)[[:space:]]+[^A-Za-z_[:space:]]" "$target" \
   | grep -v "^[0-9]*:[[:space:]]*#"; then
  echo "✗ не-ASCII имя переменной цикла: bash его не примет"
  bad=1
fi

# Арифметика: внутри $(( )) не должно быть ничего, кроме ASCII.
# Комментарии исключаются ДО поиска: в free-disk.sh стоит пояснение, дословно
# приводящее сломанное `$(( после - до ))`. Без этого проверка ловила бы текст,
# объясняющий ошибку, вместо самой ошибки — и была бы вечно красной.
if grep -v "^[[:space:]]*#" "$target" | grep -oE '\$\(\([^)]*\)\)' | LC_ALL=C grep -q '[^ -~]'; then
  echo "✗ не-ASCII внутри \$(( )) — арифметика упадёт"
  bad=1
fi

# И главное: запуск не должен печатать ни одной ошибки bash.
out=$(bash "$target" 2>&1)
if echo "$out" | grep -qiE "not a valid identifier|syntax error|integer expression expected|unbound variable"; then
  echo "✗ запуск печатает ошибку bash:"
  echo "$out" | grep -iE "not a valid identifier|syntax error|integer expression|unbound" | head -3
  bad=1
fi

  # Не-ASCII в объявлении переменной: `local тут` и `x=1` одинаково падают.
  #
  # РЕЗУЛЬТАТ БЕРЁТСЯ ИЗ ТЕКСТА, А НЕ ИЗ КОДА ВОЗВРАТА КОНВЕЙЕРА. Первая
  # версия кончалась на `| head -3`, а `head` успешен и без единого
  # совпадения — то есть условие было истинно ВСЕГДА, и проверка ругалась на
  # заведомо здоровый free-disk.sh. Ровно тот класс, который она ищет:
  # инструмент, чей ответ не зависит от того, что он проверяет.
  # `[^ -~]` в локали C — это «байт вне печатного ASCII». `\x00-\x7F` тут не
  # работает: grep -E принимает это за набор литералов 'x','0','7','F','-',
  # и под правило попадали чистые ASCII-имена вроде `here=`. Проверка ругалась
  # на то, что сама же и починила минуту назад.
  hits=$(LC_ALL=C grep -nE "^[[:space:]]*(local |declare |export )?[^=]*[^ -~][^=]*=" "$target" \
         | grep -v "^[0-9]*:[[:space:]]*#" || true)
  # ОБЪЯВЛЕНИЕ БЕЗ ПРИСВАИВАНИЯ — отдельная форма, и именно она меня сломала:
  # `local здесь там` не содержит `=`, поэтому правило выше его пропускало.
  # Проверено мутацией: без этой строки проверка молчит на том самом дефекте,
  # ради которого написана. Запуск её тоже не ловит — `tri` без аргументов
  # печатает справку и до функции не доходит, то есть «прогнать и посмотреть»
  # покрывает лишь путь по умолчанию.
  decls=$(LC_ALL=C grep -nE "^[[:space:]]*(local|declare|export|readonly)[[:space:]]+[^=]*[^ -~]" "$target" \
          | grep -v "^[0-9]*:[[:space:]]*#" || true)
  hits="$hits$decls"

  if [ -n "$hits" ]; then
    echo "✗ не-ASCII имя переменной: bash его не примет"
    echo "$hits" | head -3
    bad=1
  fi
done

if [ "$bad" -eq 0 ]; then echo "✓ скрипты здоровы"; else exit 1; fi
