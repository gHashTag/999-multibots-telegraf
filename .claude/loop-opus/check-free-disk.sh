#!/bin/bash
# Проверка САМОГО инструмента, а не продукта.
#
# ПОЧЕМУ ОНА СУЩЕСТВУЕТ. free-disk.sh дважды содержал кириллические имена там,
# где bash требует [A-Za-z_][A-Za-z0-9_]*: сначала в арифметике
# (`$(( после - до ))`), потом в переменной цикла (`for корень in …`). Оба раза
# скрипт печатал ошибку и ШЁЛ ДАЛЬШЕ: порог «мало места» не срабатывал,
# сборочные выходы не удалялись. Код возврата оставался нулевым — то есть всё,
# чем я скрипт проверял, говорило «в порядке».
#
# Имена здесь ЛАТИНИЦЕЙ намеренно: первая версия этой проверки была написана
# кириллицей и упала той же ошибкой, которую ищет. Комментарии по-русски —
# они bash'у не видны.
set -u
target="$(dirname "$0")/free-disk.sh"
bad=0

bash -n "$target" || { echo "✗ синтаксис не разбирается"; bad=1; }

# Присваивания и переменные циклов — только латиницей.
if grep -nE "^[[:space:]]*(for|while)[[:space:]]+[^A-Za-z_[:space:]]" "$target" \
   | grep -v "^[0-9]*:[[:space:]]*#"; then
  echo "✗ не-ASCII имя переменной цикла: bash его не примет"
  bad=1
fi

# Арифметика: внутри $(( )) не должно быть ничего, кроме ASCII.
# Комментарии исключаются ДО поиска: в free-disk.sh стоит пояснение, дословно
# приводящее сломанное `$(( после - до ))`. Без этого проверка ловила бы текст,
# объясняющий ошибку, вместо самой ошибки — и была бы вечно красной.
if grep -v "^[[:space:]]*#" "$target" | grep -oE '\$\(\([^)]*\)\)' | LC_ALL=C grep -q '[^ -~]'; then
  echo "✗ не-ASCII внутри \$(( )) — арифметика упадёт"
  bad=1
fi

# И главное: запуск не должен печатать ни одной ошибки bash.
out=$(bash "$target" 2>&1)
if echo "$out" | grep -qiE "not a valid identifier|syntax error|integer expression expected|unbound variable"; then
  echo "✗ запуск печатает ошибку bash:"
  echo "$out" | grep -iE "not a valid identifier|syntax error|integer expression|unbound" | head -3
  bad=1
fi

if [ "$bad" -eq 0 ]; then echo "✓ free-disk.sh здоров"; else exit 1; fi
