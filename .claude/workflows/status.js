export const meta = {
  name: 'status',
  description:
    'Замерить состояние продакшена, проверить находки состязательно и переписать дашборд',
  whenToUse:
    'После каждой итерации работ, перед докладом владельцу и перед любым «готово». ' +
    'Отвечает на вопрос «что сейчас реально работает», а не «что должно работать».',
  phases: [
    { title: 'Замер' },
    { title: 'Разведка' },
    { title: 'Опровержение' },
    { title: 'Пробелы' },
    { title: 'Дашборд' },
  ],
}

// ─────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ЭТОТ ВОРКФЛОУ УСТРОЕН ИМЕННО ТАК
//
// В этом репозитории уже были: дашборд, печатавший шесть шаблонов при одном
// существующем; лендинг, показывавший «0 CREATORS» при трёх записях; хук,
// печатавший «✅ все проверки пройдены», не выполнив ни одной; маршруты
// ленты, отдававшие 200 со списком вместо действия. Все они ВЫГЛЯДЕЛИ
// рабочими. Поэтому здесь:
//
//   1. Сначала машинный замер (детерминированный, без модели), потом агенты.
//      Агент не должен «выяснять» то, что можно измерить командой.
//   2. Каждая находка идёт на ОПРОВЕРЖЕНИЕ разными линзами. Одна линза видит
//      один класс ошибок; мёртвый код, перекрытый каскад и недостижимый
//      маршрут ловятся разными вопросами.
//   3. Отдельная фаза ищет ПРОБЕЛЫ: что не проверено вовсе. Непроверенное
//      никогда не засчитывается как успех — это главное правило файла.
//   4. Ничего не редактируется. Воркфлоу только измеряет и докладывает.
// ─────────────────────────────────────────────────────────────────────────

const REPO = '.' // the workflow runs in the repo root; agents run commands in cwd
const RENDER = 'https://vibee-render-production.up.railway.app'
const PLAYER = 'https://vibee-editor-production.up.railway.app'

const RULES = `
РАБОТАЕШЬ В ${REPO}. ТОЛЬКО ЧИТАЕШЬ И ПРОВЕРЯЕШЬ — ничего не правь, не коммить,
не деплой.

ПЯТЬ ПРАВИЛ, каждое оплачено ошибкой в этом же проекте:

1. ЗЕЛЁНАЯ СБОРКА НЕ ДОКАЗЫВАЕТ НИЧЕГО. Проверяй живым запросом:
   рендер ${RENDER}, мини-апп ${PLAYER}. Деплой был SUCCESS, пока домен
   отдавал 502.

2. КОД 200 — ТОЖЕ НЕ ДОКАЗАТЕЛЬСТВО. Маршруты ленты отдавали 200 со всем
   списком вместо действия, потому что попадали в префиксный матчер. Проверяй
   ФОРМУ ответа, а не только код.

3. ПРЕЖДЕ ЧЕМ ОБЪЯСНЯТЬ ПОВЕДЕНИЕ ЧЕРЕЗ ФУНКЦИЮ — УБЕДИСЬ, ЧТО ОНА
   ВЫЗЫВАЕТСЯ. Здесь AssetBrowser не импортирован нигде, 16 из 23
   Inngest-функций недостижимы, а рендер ходил по сети к самому себе на
   мёртвый хост.

4. ЧТО НЕ ИЗМЕРЕНО — ТАК И ПИШИ. «Не проверено» это отдельный исход, а не
   разновидность «ок». Пустой вывод grep -c даёт 0, неотличимо от «чисто»:
   смотри код возврата. Для tsc всегда --pretty false, иначе grep по
   «error TS» молча не совпадает на цветном выводе.

5. СЕКРЕТЫ НЕ ПЕЧАТАЙ. Только имя файла, строка и первые 6 символов.

Пиши по-русски. Числа — измеренные, а не оценённые.
`

const FINDINGS = {
  type: 'object',
  required: ['findings', 'summary'],
  properties: {
    summary: { type: 'string' },
    findings: {
      type: 'array',
      items: {
        type: 'object',
        required: ['title', 'severity', 'evidence', 'verified_how'],
        properties: {
          title: { type: 'string' },
          severity: { type: 'string', enum: ['блокер', 'важное', 'мелочь'] },
          file: { type: 'string' },
          evidence: {
            type: 'string',
            description: 'команда и её вывод, номера строк',
          },
          verified_how: {
            type: 'string',
            enum: ['живой запрос', 'чтение кода', 'и то и другое'],
          },
          fix: { type: 'string' },
        },
      },
    },
  },
}

// ─────────────────────────────────────────────────────────────────────────
phase('Замер')
// Детерминированная часть. Скрипт сам помечает непроверенное.
const measured = await agent(
  `${RULES}

Запусти машинный замер и верни его результат БЕЗ интерпретации:

    cd ${REPO} && npm run dashboard

Скрипт опрашивает живые службы, проверяет форму ответов ленты, считает линт,
типы и секреты, и пишет docs/dashboard/status.json.

Верни:
1. Полное содержимое docs/dashboard/status.json.
2. Отдельным списком — всё, что скрипт пометил «не проверено», с причиной.
   Это не мелочь: непроверенная проверка выглядит как пройденная, и именно
   так в этом репозитории жили сломанные ворота.
Ничего не додумывай и не чини.`,
  { label: 'замер', phase: 'Замер' }
)

// ─────────────────────────────────────────────────────────────────────────
phase('Разведка')
// Разные линзы, а не разные копии одного вопроса: каждая видит свой класс.
const LENSES = [
  {
    label: 'деньги',
    p: `Проверь ДЕНЕЖНЫЙ контур.
1. Списывается ли баланс при генерации из мини-аппа. Ищи balance/deduct/stars
   в ${REPO}/apps/vibee-editor/render/render-server.ts и приведи вывод grep.
2. Достижимы ли платные маршруты /api/generate/* без подписи — живым запросом.
3. ГЛАВНОЕ: если они закрыты только 401, то починка аутентификации ОТКРОЕТ
   бесплатный доступ к платным провайдерам. Скажи об этом прямо и оцени, что
   именно станет бесплатным.
4. Сверься с тем, как списывает бот: ${REPO}/src/core/supabase/updateUserBalance.ts.`,
  },
  {
    label: 'мёртвый-код',
    p: `Найди код, на который опирается работа, но который НЕ ВЫЗЫВАЕТСЯ.
Для каждого подозрительного модуля: grep импортов вне его собственной папки,
и подтверждение, что элемент есть в живом DOM или маршрут отвечает.
Начни с того, что уже ловили: AssetBrowser, VerticalFeed, TemplateService,
src/factory/, player/src/api/renderApi.ts, Inngest-функции без отправителя
(npm run check:events).`,
  },
  {
    label: 'пайплайн',
    p: `Проверь цепочку create → рендер → публикация → лента ЦЕЛИКОМ.
1. Что отдаёт ${RENDER}/compositions и совпадает ли с ${RENDER}/templates.
2. Есть ли в ленте записи, СОЗДАННЫЕ рендером (у них videoUrl указывает на
   бакет рендера, а не на storage Supabase). Приведи ${RENDER}/api/feed.
3. Заполнены ли assets и tracks — без них Remix открывает пустой редактор.
4. Есть ли в записи поле под текст поста с хештегами.`,
  },
  {
    label: 'мобилка',
    p: `Проверь мини-апп на ширине 375px браузерными инструментами.
Измеряй getBoundingClientRect, а не смотри на скриншот.
1. Есть ли кнопки ниже 44px по высоте — назови поимённо.
2. Нижняя панель: сколько вкладок видно целиком, шаг между ними.
3. Лента: object-fit у видео и у постера, обрезается ли кадр.
4. Не перекрывает ли что-нибудь главную кнопку генерации.`,
  },
  {
    label: 'секреты',
    p: `Проверь секреты в ОТСЛЕЖИВАЕМЫХ файлах поиском по ФОРМЕ И ЭНТРОПИИ,
а не по списку известных шаблонов — прошлая чистка так и пропустила учётку
Infisical. Ищи длинные hex 32/64, base64-подобные 40+, «ИМЯ=длинное».
Отдельно скажи, какие формы детекторы НЕ покрывают.
ЗНАЧЕНИЯ НЕ ПЕЧАТАЙ.`,
  },
]

const scouted = await parallel(
  LENSES.map(
    l => () =>
      agent(`${RULES}\n\n${l.p}`, {
        label: l.label,
        phase: 'Разведка',
        schema: FINDINGS,
      })
  )
)

// ─────────────────────────────────────────────────────────────────────────
phase('Опровержение')
// Барьер здесь ОПРАВДАН: дедупликация нужна по всему набору сразу, иначе одна
// и та же поломка уедет на тройную проверку из трёх линз.
const all = scouted.filter(Boolean).flatMap(r => r.findings || [])
const seen = new Set()
const unique = all.filter(f => {
  const k = `${f.file || ''}|${(f.title || '').slice(0, 60)}`
  if (seen.has(k)) return false
  seen.add(k)
  return true
})
log(
  `Находок ${all.length}, после дедупликации ${unique.length}. Отправляю опровергать.`
)

const VERDICT = {
  type: 'object',
  required: ['refuted', 'reason'],
  properties: {
    refuted: { type: 'boolean' },
    reason: { type: 'string' },
    correction: { type: 'string' },
  },
}

// Три РАЗНЫЕ линзы опровержения. Три одинаковых скептика ловят один класс.
const REFUTERS = [
  [
    'живость',
    'Проверь, вызывается ли этот код вообще и достижим ли маршрут. Если код мёртвый — находка пустая.',
  ],
  [
    'воспроизведение',
    'Воспроизведи живым запросом или замером в браузере. Если не воспроизводится — находка пустая.',
  ],
  [
    'важность',
    'Проверь по данным, а не по коду: выполнялся ли этот путь хоть раз, есть ли строки в базе. Латентный дефект — не активная утечка.',
  ],
]

const judged = await parallel(
  unique.map(
    f => () =>
      parallel(
        REFUTERS.map(
          ([lens, ask]) =>
            () =>
              agent(
                `${RULES}

ТВОЯ ЗАДАЧА — ОПРОВЕРГНУТЬ. Ищи причины, по которым утверждение неверно или
неважно. Сомневаешься — ставь refuted=true.

Линза «${lens}»: ${ask}

Утверждение: ${f.title}
Файл: ${f.file || 'не указан'}
Доказательство автора: ${f.evidence}
Как проверял: ${f.verified_how}`,
                {
                  label: `${lens}:${(f.title || '').slice(0, 22)}`,
                  phase: 'Опровержение',
                  schema: VERDICT,
                }
              )
        )
      ).then(vs => {
        const v = vs.filter(Boolean)
        // Выживает при большинстве НЕ опровергнувших. Пустой набор голосов —
        // это «не проверено», а не «подтверждено»: считаем опровергнутым.
        const alive = v.filter(x => !x.refuted).length
        return {
          ...f,
          голоса: v.length,
          за: alive,
          выжила: v.length > 0 && alive > v.length / 2,
          вердикты: v,
        }
      })
  )
)

const confirmed = judged.filter(Boolean).filter(f => f.выжила)
const killed = judged.filter(Boolean).filter(f => !f.выжила)
log(`Подтверждено ${confirmed.length}, отброшено ${killed.length}.`)

// ─────────────────────────────────────────────────────────────────────────
phase('Пробелы')
// Критик полноты. Без него отчёт читается как «проверено всё», хотя проверено
// только то, о чём догадались спросить.
const gaps = await agent(
  `${RULES}

Ты ищешь ПРОБЕЛЫ, а не дефекты. Вопрос один: чего в этой проверке НЕ БЫЛО?

Машинный замер:
${String(measured).slice(0, 20000)}

Подтверждённые находки:
${JSON.stringify(
  confirmed.map(f => ({ t: f.title, s: f.severity })),
  null,
  1
).slice(0, 10000)}

Отброшенные:
${JSON.stringify(
  killed.map(f => ({ t: f.title, за: f.за, голосов: f.голоса })),
  null,
  1
).slice(0, 6000)}

Назови:
1. Какие части системы не проверялись ВООБЩЕ ни одной линзой.
2. Какие утверждения приняты по чтению кода, но не подтверждены запуском.
3. Что помечено «не проверено» в машинном замере и почему это опасно.
4. Какая проверка могла ОТРАБОТАТЬ ВПУСТУЮ и выдать зелёный результат
   (пустой ввод, несовпавший grep, пропущенный код возврата).

Это станет списком работ на следующий заход. Не выдумывай дефекты — называй
только незакрытые области.`,
  { label: 'пробелы', phase: 'Пробелы' }
)

// ─────────────────────────────────────────────────────────────────────────
phase('Дашборд')
const written = await agent(
  `${RULES}

Собери итог для владельца и обнови дашборд.

Машинный замер: ${String(measured).slice(0, 20000)}
Подтверждено: ${JSON.stringify(confirmed, null, 1).slice(0, 30000)}
Пробелы: ${String(gaps).slice(0, 12000)}

Сделай ДВЕ вещи:

А. Допиши в ${REPO}/docs/dashboard/STATUS.md разделы (сам файл уже создан
   машинным замером, НЕ переписывай его целиком — только допиши в конец):
   «## Подтверждённые дефекты» — таблица: что, где, чем проверено, severity;
   «## Не проверено» — список из фазы пробелов, отдельной таблицей;
   «## Что требует владельца» — только то, чего не может сделать агент:
   перевыпуск ключей, доступы, деньги, продуктовые решения.

Б. Верни короткий текст для владельца:
   - что изменилось с прошлого замера, если это видно;
   - три самые тяжёлые вещи сейчас, по убыванию последствий;
   - что делать следующим шагом.

Без маркетинга и без «возможно». Числа измеренные. Если чего-то не знаешь —
так и напиши.`,
  { label: 'дашборд', phase: 'Дашборд' }
)

return {
  замер: measured,
  подтверждено: confirmed.map(f => ({ ...f, вердикты: undefined })),
  отброшено: killed.map(f => ({ title: f.title, за: f.за, голосов: f.голоса })),
  пробелы: gaps,
  итог: written,
}
